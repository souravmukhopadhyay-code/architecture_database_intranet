-- Tree shape by level, per-level attributes, routes of the tree's own
-- domain, and no moving a node once tickets were raised under it.
CREATE OR REPLACE FUNCTION tms.ticket_category_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_level ref.tms_category_level; v_parent_depth smallint; v_root_depth smallint; v_dom smallint;
BEGIN
  SELECT * INTO v_level FROM ref.tms_category_level WHERE id = NEW.category_level_id;
  IF NEW.parent_id IS NULL THEN
    SELECT CASE WHEN uses_kra_type THEN 0 ELSE 1 END INTO v_root_depth FROM ref.tms_ticket_domain WHERE id = NEW.ticket_domain_id;
    IF v_level.depth <> v_root_depth THEN
      RAISE EXCEPTION 'tms.ticket_category: a tree of this domain starts at level depth %, not at %', v_root_depth, v_level.code
        USING ERRCODE = 'check_violation';
    END IF;
    v_dom := NEW.ticket_domain_id;
  ELSE
    SELECT l.depth INTO v_parent_depth FROM tms.ticket_category c JOIN ref.tms_category_level l ON l.id = c.category_level_id
    WHERE c.id = NEW.parent_id;
    IF v_level.depth <> v_parent_depth + 1 THEN
      RAISE EXCEPTION 'tms.ticket_category: a % must sit directly under the level above it', v_level.code USING ERRCODE = 'check_violation';
    END IF;
    SELECT ticket_domain_id INTO v_dom FROM tms.v_ticket_category WHERE category_id = NEW.parent_id;
  END IF;
  IF (v_level.code = 'MASTER') <> (NEW.category_type_id IS NOT NULL) THEN
    RAISE EXCEPTION 'tms.ticket_category: the category type is set on the master level, and only there' USING ERRCODE = 'check_violation';
  END IF;
  IF v_level.is_leaf <> (NEW.priority_id IS NOT NULL) THEN
    RAISE EXCEPTION 'tms.ticket_category: the priority is set on the leaf level, and only there' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.route_id IS NOT NULL AND (SELECT ticket_domain_id FROM tms.ticket_route WHERE id = NEW.route_id) IS DISTINCT FROM v_dom THEN
    RAISE EXCEPTION 'tms.ticket_category: the route belongs to the other domain' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'UPDATE'
     AND (NEW.parent_id IS DISTINCT FROM OLD.parent_id OR NEW.category_level_id <> OLD.category_level_id
          OR NEW.ticket_domain_id IS DISTINCT FROM OLD.ticket_domain_id)
     AND EXISTS (SELECT 1 FROM tms.category_subtree(OLD.id) s
                 WHERE EXISTS (SELECT 1 FROM tms.ticket t WHERE t.raised_category_id = s.category_id)
                    OR EXISTS (SELECT 1 FROM tms.ticket_event e WHERE e.category_id = s.category_id)) THEN
    RAISE EXCEPTION 'tms.ticket_category: % cannot be moved — tickets were raised under it (deactivate it and create a new one)', OLD.name
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

