  FOR EACH ROW EXECUTE FUNCTION tms.ticket_route_level_validate();

-- A redressal forum: a committee (an academic body of a type: SGRC, ICC,
-- anti-ragging committee …) or a position (Ombudsperson). The body / holder
-- that hears a ticket is the nearest one above the requester's unit (of
-- anchor_org_unit_type, if given) — one SGRC for the university, or one per
-- school, is configuration. Time limit, whether its decision must be a
-- resolution of a quorate meeting, where an appeal goes and within how long,
-- and whether its cases are confidential.
CREATE TABLE tms.redressal_forum (
  id                       smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                     citext NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]{1,60}$'),
  label                    text NOT NULL CHECK (btrim(label) <> ''),
  academic_body_type_id    smallint REFERENCES ref.academic_body_type(id),
  position_type_id         smallint REFERENCES org.position_type(id),
  anchor_org_unit_type_id  smallint REFERENCES ref.org_unit_type(id),
  decision_within_days     smallint NOT NULL CHECK (decision_within_days > 0),     -- POLICY
  counts_office_days       boolean NOT NULL DEFAULT false,                         -- business days instead of calendar days
  needs_resolution         boolean NOT NULL DEFAULT false,
  appeal_forum_id          smallint REFERENCES tms.redressal_forum(id),
  appeal_window_days       smallint CHECK (appeal_window_days > 0),                -- POLICY
  compliance_within_days   smallint CHECK (compliance_within_days > 0),            -- a decision in the requester's favour is carried out within this (NULL = not tracked)
  next_forum_id            smallint REFERENCES tms.redressal_forum(id),             -- where the forum forwards a case by default (squad → committee)
  first_action_within_hours smallint CHECK (first_action_within_hours > 0),        -- the forum's first action on a case it receives (NULL = the category's / priority's first-response hours)
  alert_position_type_id   smallint REFERENCES org.position_type(id),               -- who is alerted when that first action is late (e.g. the head of the institution)
