-- =============================================================================
-- 12_tms.sql — Helpdesk & student grievance redressal (schema: tms)
--
-- A module on top of the foundation (runs after 00–11). Rebuilt from the old
-- SGT UMS TMS (backend/src/modules/tms), keeping its behaviour, fixing its
-- known faults, and raised to the UGC (Redress of Grievances of Students)
-- Regulations, 2023 on the student side: a helpdesk ladder first, then the
-- Students' Grievance Redressal Committee, then the Ombudsperson; ragging and
-- sexual-harassment complaints go straight to their statutory committees,
-- confidentially. The full design, flows and policy table are in
-- docs/tms/tms-design.md. Everything the foundation already knows is referenced,
-- never copied:
--
--   who raises / handles     iam.user_account, people.employee, people.student
--                            (contact = the requester's own pii.person_phone)
--   the requester's unit     people.v_person_principal_kind (home unit when raised)
--   mentor / manager         people.student_mentor, people.employee_reporting_line
--   HOD, Dean, Dean Acad.,   org.appointment (position × unit) — found relative
--   Registrar, VC            to the requester's unit, the category's unit, or fixed
--   committees (SGRC, ICC,   academic.academic_body (+ members, meetings and
--   anti-ragging, EOC)       quorum-checked resolutions); Ombudsperson = a position
--   holidays                 academic.calendar_event (types in helpdesk_closure_type)
--   academic context         academic.batch / academic_term / course
--   attachments              people.file_object
--   permissions              authz (module tms), checked with has_permission()
--
--   CONFIGURATION  helpdesk_setting (one row of policy), helpdesk_weekday,
--                  helpdesk_closure_type, helpdesk_declaration (dated text the
--                  requester accepts), ticket_route + ticket_route_level (the
--                  ladder: handler pool, category owner, mentor, manager, a
--                  position relative to the requester / category / a fixed
--                  unit, a named person), redressal_forum (committee or
--                  position; time limit; appeal forum), ticket_category (tree;
--                  route, forum, confidentiality … inherited down the tree),
--                  ticket_category_owner, ticket_category_handler (pool,
--                  optionally per unit), ticket_notice_rule
--   TICKETS        ticket (the raised facts, immutable, TMS-YYYY-NNNNN),
--                  ticket_academic_context, ticket_respondent (complaint
--                  against a person), ticket_event (append-only timeline —
--                  status, assignee, level, forum, clock, rating DERIVED:
--                  v_ticket_state), ticket_event_file, ticket_notification
--   CLOCK          business_deadline(), business_minutes_between(),
--                  deadline_after(), days_after() — office or calendar time
--   ENTRY POINTS   INSERT tms.ticket (routing + CREATED by trigger),
--                  INSERT tms.ticket_event (every later action, validated
--                  against ref.tms_event_allowed_status and the actor rules),
--                  INSERT tms.ticket_respondent (recusal by trigger),
--                  run_scheduler() (hourly job), can_view(), can_act(),
--                  is_forum_member(), requester_shown_to(), next_escalation()
-- =============================================================================

SET client_encoding = 'UTF8';   -- files are UTF-8; psql on Windows may default to WIN1252

CREATE SCHEMA IF NOT EXISTS tms;   -- helpdesk tickets, routes, redressal forums, SLA clock
SET search_path = tms, org, people, academic, iam, authz, pii, ref, public;

-- ################################################################### LOOKUPS ##

-- Who may raise a ticket of this domain, and whether its category tree starts
-- at a KRA type. The three permission ids are filled once the permissions
-- exist (below) and then made mandatory.
CREATE TABLE ref.tms_ticket_domain (
  id                     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                   citext NOT NULL UNIQUE,
  label                  text   NOT NULL,
  principal_kind_id      smallint NOT NULL REFERENCES ref.principal_kind(id),   -- who may raise
  uses_kra_type          boolean NOT NULL,                                     -- tree root = KRA type (depth 0) or master (depth 1)
  context_must_be_own    boolean NOT NULL DEFAULT false,                       -- academic context = one of the requester's own batches
  create_permission_id   int REFERENCES authz.permission(id),
  view_permission_id     int REFERENCES authz.permission(id),
  update_permission_id   int REFERENCES authz.permission(id),
  is_active              boolean NOT NULL DEFAULT true,
  sort_order             smallint NOT NULL DEFAULT 0
);
-- The levels of the category tree. Labels differ by domain (the employee side
-- calls them KRA / KPI / measurement criteria).
CREATE TABLE ref.tms_category_level (
  id              smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            citext NOT NULL UNIQUE,
  label           text   NOT NULL,
  depth           smallint NOT NULL UNIQUE CHECK (depth BETWEEN 0 AND 3),
  student_label   text,
  employee_label  text NOT NULL,
  is_leaf         boolean NOT NULL,              -- tickets, priority and handlers live on the leaf
  is_active       boolean NOT NULL DEFAULT true,
  sort_order      smallint NOT NULL DEFAULT 0
);
CREATE TABLE ref.tms_category_type    (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL, is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
-- Priority = the SLA terms: resolution hours per level, first-response hours,
-- and whether the clock counts office hours only or runs round the clock.
CREATE TABLE ref.tms_priority (
  id                    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                  citext NOT NULL UNIQUE,
  label                 text NOT NULL,
  sla_hours             smallint NOT NULL CHECK (sla_hours > 0),                   -- per level (POLICY)
  first_response_hours  smallint CHECK (first_response_hours > 0),                 -- NULL = not tracked (POLICY)
  office_hours_only     boolean,                                                   -- NULL = the helpdesk-wide default; false = wall-clock hours (24 × 7)
  is_active             boolean NOT NULL DEFAULT true,
  sort_order            smallint NOT NULL DEFAULT 0,
  CHECK (first_response_hours IS NULL OR first_response_hours <= sla_hours)
);
-- is_grievance = may go to a redressal forum (UGC); requires_relief = the
-- requester must state the relief sought.
CREATE TABLE ref.tms_message_type (
  id               smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             citext NOT NULL UNIQUE,
  label            text NOT NULL,
  for_student      boolean NOT NULL,
  for_employee     boolean NOT NULL,
  is_grievance     boolean NOT NULL DEFAULT false,
  requires_relief  boolean NOT NULL DEFAULT false,
  is_active        boolean NOT NULL DEFAULT true,
  sort_order       smallint NOT NULL DEFAULT 0
);
CREATE TABLE ref.tms_ticket_status (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              citext NOT NULL UNIQUE,
  label             text NOT NULL,
  is_closed         boolean NOT NULL,
  awaits_requester  boolean NOT NULL DEFAULT false,   -- RESOLVED: the requester accepts, reopens, refers or appeals
  is_with_forum     boolean NOT NULL DEFAULT false,
  is_active         boolean NOT NULL DEFAULT true,
  sort_order        smallint NOT NULL DEFAULT 0
);
CREATE TABLE ref.tms_assignment_basis (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                       is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
-- Why a ticket ended. is_ratable: the requester may rate the handling;
-- is_reopenable: the requester may reopen it within the reopen window.
CREATE TABLE ref.tms_closure_reason (
  id             smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           citext NOT NULL UNIQUE,
  label          text NOT NULL,
  is_ratable     boolean NOT NULL,
  is_reopenable  boolean NOT NULL,
  is_active      boolean NOT NULL DEFAULT true,
  sort_order     smallint NOT NULL DEFAULT 0
);
-- Who may record an event: the requester, someone who can act on the ticket
-- (tms.can_act), either of them, a member of the forum hearing it, or the
-- scheduled job only.
CREATE TABLE ref.tms_event_actor (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                  is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
-- What an event does to the derived state. Exactly the flags v_ticket_state
-- reads; the event-specific checks are in ticket_event_validate(), the
-- statuses it may happen in are ref.tms_event_allowed_status.
CREATE TABLE ref.tms_event_type (
  id                    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                  citext NOT NULL UNIQUE,
  label                 text   NOT NULL,
  event_actor_id        smallint NOT NULL REFERENCES ref.tms_event_actor(id),
  sets_status_id        smallint REFERENCES ref.tms_ticket_status(id),   -- NULL = status unchanged
  sets_assignee         boolean NOT NULL DEFAULT false,                  -- carries the (new) assignee, level or forum
  starts_clock          boolean NOT NULL DEFAULT false,                  -- carries a new due time
  pauses_clock          boolean NOT NULL DEFAULT false,                  -- carries the minutes left
  stops_clock           boolean NOT NULL DEFAULT false,
  needs_remark          boolean NOT NULL DEFAULT false,
  needs_remark_or_file  boolean NOT NULL DEFAULT false,                  -- checked at commit (files are added after the event)
  closure_reason_id     smallint REFERENCES ref.tms_closure_reason(id),  -- resolving / closing event: why (NULL on CONFIRMED / AUTO_CLOSED = the resolution's)
  counts_as_response    boolean NOT NULL DEFAULT false,                  -- first response to the requester
  allows_files          boolean NOT NULL DEFAULT false,
  shown_to_requester    boolean NOT NULL DEFAULT true,                   -- internal events stay off the requester's timeline
  is_active             boolean NOT NULL DEFAULT true,
  sort_order            smallint NOT NULL DEFAULT 0,
  CHECK (starts_clock::int + pauses_clock::int + stops_clock::int <= 1),
  CHECK (NOT (needs_remark AND needs_remark_or_file))
);
-- The ticket lifecycle as data: in which statuses each event may be recorded.
CREATE TABLE ref.tms_event_allowed_status (
  event_type_id     smallint NOT NULL REFERENCES ref.tms_event_type(id) ON DELETE CASCADE,
  ticket_status_id  smallint NOT NULL REFERENCES ref.tms_ticket_status(id),
  PRIMARY KEY (event_type_id, ticket_status_id)
);
CREATE TABLE ref.tms_route_level_kind  (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                        is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
CREATE TABLE ref.tms_anchor_base       (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                        is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
CREATE TABLE ref.tms_redressal_outcome (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                        is_in_favour boolean NOT NULL, is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
-- How a ticket reached the helpdesk; only a self-service channel is used by
-- the requester directly, every other one is recorded by an intake desk.
CREATE TABLE ref.tms_intake_channel    (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                        is_self_service boolean NOT NULL, is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
-- Grievance heads for reporting — the kinds of grievance the UGC regulations
-- list (is_ugc_listed), plus the statutory channels and "other".
CREATE TABLE ref.tms_grievance_head    (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                        is_ugc_listed boolean NOT NULL, is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
-- What academic context a category's tickets carry.
CREATE TABLE ref.tms_academic_context_rule (
  id             smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           citext NOT NULL UNIQUE,
  label          text NOT NULL,
  needs_context  boolean NOT NULL,     -- batch, term and semester
  needs_course   boolean NOT NULL,     -- … and the course
  is_active      boolean NOT NULL DEFAULT true,
  sort_order     smallint NOT NULL DEFAULT 0,
  CHECK (NOT needs_course OR needs_context)
);
-- Why a ticket is on hold (the clock paused while someone outside the
-- handling side is awaited).
CREATE TABLE ref.tms_hold_reason       (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                        is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
CREATE TABLE ref.tms_notice_recipient   (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                         is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);
CREATE TABLE ref.tms_notification_status (id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code citext NOT NULL UNIQUE, label text NOT NULL,
                                          is_final boolean NOT NULL, is_active boolean NOT NULL DEFAULT true, sort_order smallint NOT NULL DEFAULT 0);

