-- Module settings: one row of policy. All "days" are calendar days; office
-- hours and time zone drive the SLA clock.
CREATE TABLE tms.helpdesk_setting (
  id                              boolean PRIMARY KEY DEFAULT true CHECK (id),
  auto_escalation_enabled         boolean  NOT NULL DEFAULT true,
  reopen_window_days              smallint NOT NULL DEFAULT 7  CHECK (reopen_window_days BETWEEN 1 AND 90),
  max_reopens                     smallint NOT NULL DEFAULT 2  CHECK (max_reopens BETWEEN 0 AND 10),
  confirmation_window_days        smallint NOT NULL DEFAULT 3  CHECK (confirmation_window_days BETWEEN 1 AND 30),   -- a resolution not contested closes after this
  rating_window_days              smallint NOT NULL DEFAULT 15 CHECK (rating_window_days BETWEEN 1 AND 90),
  clarification_reminder_days     smallint DEFAULT 2 CHECK (clarification_reminder_days >= 1),   -- NULL = no reminder
  clarification_expiry_days       smallint DEFAULT 7 CHECK (clarification_expiry_days >= 1),     -- NULL = waits for ever
  requester_may_escalate_overdue  boolean  NOT NULL DEFAULT true,
  requester_refer_after_days      smallint DEFAULT 7  CHECK (requester_refer_after_days >= 0),   -- NULL = only once resolved
  auto_refer_after_days           smallint DEFAULT 15 CHECK (auto_refer_after_days >= 1),        -- NULL = no automatic referral
  max_files_per_event             smallint NOT NULL DEFAULT 5 CHECK (max_files_per_event BETWEEN 0 AND 20),
  max_file_bytes                  int      NOT NULL DEFAULT 5242880 CHECK (max_file_bytes > 0),          -- 5 MB (old: PDF / PNG / JPEG ≤ 5 MB)
  duplicate_window_seconds        smallint NOT NULL DEFAULT 10 CHECK (duplicate_window_seconds BETWEEN 0 AND 3600),   -- same requester, leaf and text = a duplicate (0 = off)
  sla_warning_percent             smallint NOT NULL DEFAULT 25 CHECK (sla_warning_percent BETWEEN 1 AND 99),         -- attention tier WARNING at or below this share of the SLA left
  on_hold_enabled                 boolean  NOT NULL DEFAULT true,
  max_hold_days                   smallint DEFAULT 10 CHECK (max_hold_days >= 1),               -- a hold is released automatically after this (NULL = never)
  notice_max_attempts             smallint NOT NULL DEFAULT 3 CHECK (notice_max_attempts BETWEEN 1 AND 20),          -- a notice failing this often is given up
  scheduler_office_hours_only     boolean  NOT NULL DEFAULT true,                               -- false = the job also runs nights and holidays (24 × 7 priorities)
  office_hours_only               boolean  NOT NULL DEFAULT true,                               -- the default for every SLA clock: count office hours only (false = count every hour); a priority or a category may override it
  count_holidays                  boolean  NOT NULL DEFAULT false,                              -- true = holidays count as working days (the clock does not stop for them)
  student_tms_enabled             boolean  NOT NULL DEFAULT false,
  student_tms_locked              boolean  NOT NULL DEFAULT false,                              -- deployment lock: Student TMS cannot be switched on (old STUDENT_TMS_FORCE_DISABLED); not updatable by the app role
  employee_tms_enabled            boolean  NOT NULL DEFAULT true,                               -- old EMPLOYEE_TMS_ENABLED, now enforced
  business_day_start              time NOT NULL DEFAULT '09:00',
  business_day_end                time NOT NULL DEFAULT '17:00',
  time_zone                       text NOT NULL DEFAULT 'Asia/Kolkata',
  updated_by_account_id           uuid REFERENCES iam.user_account(id),
  created_at                      timestamptz NOT NULL DEFAULT now(),
  updated_at                      timestamptz NOT NULL DEFAULT now(),
  CHECK (business_day_end > business_day_start),
  CHECK (clarification_expiry_days IS NULL OR clarification_reminder_days IS NULL OR clarification_expiry_days > clarification_reminder_days)
);
SELECT util.attach_updated_at('tms.helpdesk_setting');

CREATE OR REPLACE FUNCTION tms.helpdesk_setting_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'tms.helpdesk_setting: the settings row cannot be deleted' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_timezone_names WHERE name = NEW.time_zone) THEN
    RAISE EXCEPTION 'tms.helpdesk_setting: unknown time zone %', NEW.time_zone USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.student_tms_locked AND NEW.student_tms_enabled THEN
    RAISE EXCEPTION 'tms.helpdesk_setting: Student TMS is locked off for this deployment' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_helpdesk_setting_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.helpdesk_setting
  FOR EACH ROW EXECUTE FUNCTION tms.helpdesk_setting_validate();

CREATE OR REPLACE FUNCTION tms.config()
RETURNS tms.helpdesk_setting LANGUAGE sql STABLE AS $$ SELECT * FROM tms.helpdesk_setting WHERE id $$;

-- Days of the week the helpdesk works (ISO: 1 = Monday), each with its own
-- hours if they differ from the default (a Saturday half day).
CREATE TABLE tms.helpdesk_weekday (
  iso_dow    smallint PRIMARY KEY CHECK (iso_dow BETWEEN 1 AND 7),
  day_start  time,                                   -- NULL = helpdesk_setting.business_day_start
  day_end    time,                                   -- NULL = helpdesk_setting.business_day_end
  CHECK ((day_start IS NULL) = (day_end IS NULL)),
  CHECK (day_end > day_start)
);

-- One date that differs from the weekly pattern and the calendar: open on a
-- holiday or a weekly off (exam-time Saturday, fee deadline day), or closed
-- on a normal day (strike, election, power shutdown) — with the reason, and
-- optionally its own hours. Wins over everything else.
CREATE TABLE tms.helpdesk_day_override (
  on_date                date PRIMARY KEY,
  is_working             boolean NOT NULL,
  day_start              time,
  day_end                time,
  note                   text NOT NULL CHECK (length(btrim(note)) BETWEEN 3 AND 256),
  created_by_account_id  uuid REFERENCES iam.user_account(id),
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  CHECK ((day_start IS NULL) = (day_end IS NULL)),
  CHECK (day_end > day_start),
  CHECK (is_working OR day_start IS NULL)
);
SELECT util.attach_updated_at('tms.helpdesk_day_override');
-- Which academic-calendar event types close the offices (a HOLIDAY does; a
