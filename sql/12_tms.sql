-- The knowledge-base articles a requester sees for a leaf: published ones
-- on the leaf, on any node above it, or for the whole domain.
CREATE OR REPLACE FUNCTION tms.kb_articles_for(p_leaf uuid)
RETURNS SETOF tms.kb_article LANGUAGE sql STABLE AS $$
  SELECT k.* FROM tms.kb_article k
  WHERE k.published @> current_date
    AND k.ticket_domain_id = (SELECT ticket_domain_id FROM tms.v_ticket_category WHERE category_id = p_leaf)
    AND (k.category_id IS NULL OR k.category_id IN (SELECT category_id FROM tms.category_ancestors(p_leaf)))
  ORDER BY k.category_id NULLS LAST, k.sort_order, k.title;
$$;

-- How useful each article is: answers, and the share that needed no ticket.
CREATE OR REPLACE VIEW tms.v_kb_article_stats AS
SELECT k.id AS kb_article_id, k.ticket_domain_id, k.category_id, k.title,
       count(f.id) AS answers, count(f.id) FILTER (WHERE f.was_helpful) AS helpful,
       round(100.0 * count(f.id) FILTER (WHERE f.was_helpful) / NULLIF(count(f.id), 0), 1) AS deflection_percent
FROM tms.kb_article k LEFT JOIN tms.kb_feedback f ON f.kb_article_id = k.id
GROUP BY k.id, k.ticket_domain_id, k.category_id, k.title;

