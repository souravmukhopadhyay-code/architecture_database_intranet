-- Whether and when the helpdesk works on a date, and why — everything an
-- administrator configures, in this order:
--   1. a dated override (open on a holiday / weekly off, or closed on a normal
--      day, with its own hours if given);
--   2. the weekly pattern (helpdesk_weekday: which days, each day's hours);
--   3. holidays — the academic calendar's university-wide events of the types
--      in helpdesk_closure_type — close the day, unless count_holidays is on;
--   4. otherwise open, with the weekday's hours or the default hours.
-- opens / closes NULL = closed.
CREATE OR REPLACE FUNCTION tms.day_hours(p_date date)
RETURNS TABLE (opens time, closes time, reason text) LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE c tms.helpdesk_setting := tms.config(); o tms.helpdesk_day_override; w tms.helpdesk_weekday; v_holiday text;
BEGIN
  SELECT * INTO o FROM tms.helpdesk_day_override d WHERE d.on_date = p_date;
  SELECT * INTO w FROM tms.helpdesk_weekday d WHERE d.iso_dow = extract(isodow FROM p_date);
  IF o.on_date IS NOT NULL THEN
    IF o.is_working THEN
      opens := COALESCE(o.day_start, w.day_start, c.business_day_start);
      closes := COALESCE(o.day_end, w.day_end, c.business_day_end);
    END IF;
    reason := 'Override: ' || o.note;
  ELSIF w.iso_dow IS NULL THEN
    reason := 'Weekly off';
  ELSE
    SELECT ce.name INTO v_holiday FROM academic.calendar_event ce
    JOIN tms.helpdesk_closure_type oc ON oc.calendar_event_type_id = ce.calendar_event_type_id
    WHERE ce.org_unit_id IS NULL AND ce.period @> p_date LIMIT 1;
    IF v_holiday IS NOT NULL AND NOT c.count_holidays THEN
      reason := 'Holiday: ' || v_holiday;
    ELSE
      opens := COALESCE(w.day_start, c.business_day_start);
      closes := COALESCE(w.day_end, c.business_day_end);
      reason := CASE WHEN v_holiday IS NOT NULL THEN 'Holiday counted as a working day: ' || v_holiday ELSE 'Working day' END;
    END IF;
  END IF;
  RETURN NEXT;
END $$;

CREATE OR REPLACE FUNCTION tms.is_business_day(p_date date)
RETURNS boolean LANGUAGE sql STABLE AS $$ SELECT h.opens IS NOT NULL FROM tms.day_hours(p_date) h $$;

-- The helpdesk calendar between two dates, as the admin screen shows it.
CREATE OR REPLACE FUNCTION tms.helpdesk_calendar(p_from date, p_to date)
RETURNS TABLE (on_date date, is_working boolean, opens time, closes time, reason text) LANGUAGE sql STABLE AS $$
  SELECT d::date, h.opens IS NOT NULL, h.opens, h.closes, h.reason
  FROM generate_series(p_from, p_to, interval '1 day') d CROSS JOIN LATERAL tms.day_hours(d::date) h
  ORDER BY 1;
$$;

CREATE OR REPLACE FUNCTION tms.is_business_moment(p_at timestamptz)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE c tms.helpdesk_setting := tms.config(); v_local timestamp; h record;
BEGIN
  v_local := p_at AT TIME ZONE c.time_zone;
  SELECT * INTO h FROM tms.day_hours(v_local::date);
  RETURN h.opens IS NOT NULL AND v_local::time >= h.opens AND v_local::time < h.closes;
END $$;

-- p_minutes of office time after p_start: a start outside office hours moves
-- to the next opening; each working day contributes its own hours.
CREATE OR REPLACE FUNCTION tms.business_deadline(p_start timestamptz, p_minutes int)
RETURNS timestamptz LANGUAGE plpgsql STABLE AS $$
DECLARE c tms.helpdesk_setting := tms.config(); v_cur timestamp; v_left int := GREATEST(p_minutes, 0); v_avail int; i int := 0; h record;
BEGIN
  v_cur := p_start AT TIME ZONE c.time_zone;
  LOOP
    i := i + 1;
    IF i > 4000 THEN
      RAISE EXCEPTION 'tms.business_deadline: no working day found — check the weekdays, closures and overrides' USING ERRCODE = 'data_exception';
    END IF;
    SELECT * INTO h FROM tms.day_hours(v_cur::date);
    IF h.opens IS NULL OR v_cur::time >= h.closes THEN
      v_cur := (v_cur::date + 1)::timestamp;
      CONTINUE;
    END IF;
    IF v_cur::time < h.opens THEN
      v_cur := v_cur::date + h.opens;
    END IF;
    v_avail := floor(extract(epoch FROM (v_cur::date + h.closes) - v_cur) / 60)::int;
    IF v_left <= v_avail THEN
      RETURN (v_cur + make_interval(mins => v_left)) AT TIME ZONE c.time_zone;
    END IF;
    v_left := v_left - v_avail;
    v_cur := (v_cur::date + 1)::timestamp;
  END LOOP;
END $$;

-- Office minutes between two instants (0 if p_to <= p_from).
CREATE OR REPLACE FUNCTION tms.business_minutes_between(p_from timestamptz, p_to timestamptz)
RETURNS int LANGUAGE plpgsql STABLE AS $$
DECLARE c tms.helpdesk_setting := tms.config(); v_a timestamp; v_b timestamp; v_d date; v_s timestamp; v_e timestamp; v_total numeric := 0; h record;
BEGIN
  IF p_to IS NULL OR p_from IS NULL OR p_to <= p_from THEN RETURN 0; END IF;
  v_a := p_from AT TIME ZONE c.time_zone;
  v_b := p_to AT TIME ZONE c.time_zone;
  v_d := v_a::date;
  WHILE v_d <= v_b::date LOOP
    SELECT * INTO h FROM tms.day_hours(v_d);
    IF h.opens IS NOT NULL THEN
      v_s := GREATEST(v_a, v_d + h.opens);
      v_e := LEAST(v_b, v_d + h.closes);
      IF v_e > v_s THEN v_total := v_total + extract(epoch FROM v_e - v_s) / 60; END IF;
    END IF;
    v_d := v_d + 1;
  END LOOP;
  RETURN floor(v_total)::int;
END $$;

-- The same in either kind of time: office minutes, or plain minutes (24 × 7).
CREATE OR REPLACE FUNCTION tms.deadline_after(p_start timestamptz, p_minutes int, p_office boolean)
RETURNS timestamptz LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN p_office THEN tms.business_deadline(p_start, p_minutes)
              ELSE p_start + make_interval(mins => GREATEST(p_minutes, 0)) END;
$$;
CREATE OR REPLACE FUNCTION tms.minutes_left(p_from timestamptz, p_to timestamptz, p_office boolean)
RETURNS int LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN p_office THEN tms.business_minutes_between(p_from, p_to)
              ELSE GREATEST(floor(extract(epoch FROM p_to - p_from) / 60), 0)::int END;
$$;

-- p_days after p_start: the close of office on the p_days-th working day
-- after it, or p_days calendar days later (a forum's time limit).
CREATE OR REPLACE FUNCTION tms.days_after(p_start timestamptz, p_days int, p_office boolean)
RETURNS timestamptz LANGUAGE plpgsql STABLE AS $$
DECLARE c tms.helpdesk_setting := tms.config(); v_d date; n int := 0; i int := 0;
BEGIN
  IF NOT p_office THEN RETURN p_start + make_interval(days => p_days); END IF;
  v_d := (p_start AT TIME ZONE c.time_zone)::date;
  WHILE n < p_days LOOP
    v_d := v_d + 1; i := i + 1;
    IF i > 4000 THEN
      RAISE EXCEPTION 'tms.days_after: no working day found — check the weekdays, closures and overrides' USING ERRCODE = 'data_exception';
    END IF;
    IF tms.is_business_day(v_d) THEN n := n + 1; END IF;
  END LOOP;
  RETURN (v_d + (SELECT h.closes FROM tms.day_hours(v_d) h)) AT TIME ZONE c.time_zone;
END $$;

-- The SLA of a level for a ticket in a category: the route level's own
-- hours, else the category's (category-wise SLA, inherited down the tree),
-- else the priority's.
CREATE OR REPLACE FUNCTION tms.level_sla_minutes(p_priority smallint, p_level smallint, p_category uuid)
RETURNS int LANGUAGE sql STABLE AS $$
  SELECT COALESCE((SELECT sla_hours FROM tms.ticket_route_level WHERE id = p_level),
                  (SELECT sla_hours FROM tms.v_ticket_category WHERE category_id = p_category),
                  (SELECT sla_hours FROM ref.tms_priority WHERE id = p_priority)) * 60;
$$;
-- Whether the clock counts office hours only: the category's choice, else
-- the priority's, else the helpdesk-wide default (helpdesk_setting.office_hours_only).
CREATE OR REPLACE FUNCTION tms.sla_office(p_priority smallint, p_category uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT COALESCE((SELECT sla_office_hours_only FROM tms.v_ticket_category WHERE category_id = p_category),
                  (SELECT office_hours_only FROM ref.tms_priority WHERE id = p_priority),
                  (SELECT office_hours_only FROM tms.helpdesk_setting WHERE id));
$$;

