-- The declaration a requester accepts when raising a ticket of a domain
-- ("the information is true; the matter is not before a court; I read the
-- relevant notices first"). Dated: one in force per domain at a time; the
-- ticket records the version accepted.
CREATE TABLE tms.helpdesk_declaration (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_domain_id  smallint NOT NULL REFERENCES ref.tms_ticket_domain(id),
  body              text NOT NULL CHECK (length(btrim(body)) BETWEEN 10 AND 4000),
  valid             daterange NOT NULL DEFAULT daterange(current_date, NULL),
  created_at        timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  CONSTRAINT helpdesk_declaration_one_at_a_time EXCLUDE USING gist (ticket_domain_id WITH =, valid WITH &&)
);

