CREATE OR REPLACE FUNCTION tms.redressal_forum_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.appeal_forum_id IS NOT NULL AND EXISTS (
       WITH RECURSIVE ch AS (SELECT NEW.appeal_forum_id AS id, 1 AS n
                             UNION ALL
                             SELECT f.appeal_forum_id, ch.n + 1 FROM tms.redressal_forum f JOIN ch ON f.id = ch.id
                             WHERE f.appeal_forum_id IS NOT NULL AND ch.n < 50)
       SELECT 1 FROM ch WHERE ch.id = NEW.id) THEN
    RAISE EXCEPTION 'tms.redressal_forum %: the appeal chain would come back to this forum', NEW.code USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.position_type_id IS NOT NULL AND NEW.anchor_org_unit_type_id IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM org.position_type_unit_type WHERE position_type_id = NEW.position_type_id AND org_unit_type_id = NEW.anchor_org_unit_type_id) THEN
    RAISE EXCEPTION 'tms.redressal_forum %: that position does not exist for that type of unit', NEW.code USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
