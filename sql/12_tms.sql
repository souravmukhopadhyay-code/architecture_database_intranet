  updated_at               timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(academic_body_type_id, position_type_id) = 1),
  CHECK ((appeal_forum_id IS NULL) = (appeal_window_days IS NULL)),
  CHECK (NOT needs_resolution OR academic_body_type_id IS NOT NULL),
  CHECK (appeal_forum_id IS DISTINCT FROM id),
  CHECK (next_forum_id IS DISTINCT FROM id)
);
