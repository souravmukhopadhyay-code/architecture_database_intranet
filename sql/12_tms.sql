-- SLA facts per ticket: first-response target and when the first response
-- came, and the office time from raising to resolution.
CREATE OR REPLACE VIEW tms.v_ticket_sla AS
SELECT s.ticket_id, s.priority_id, s.ticket_domain, s.category_id,
       CASE WHEN COALESCE(vc.first_response_hours, p.first_response_hours) IS NOT NULL
            THEN tms.deadline_after(s.created_at, COALESCE(vc.first_response_hours, p.first_response_hours) * 60,
                                    tms.sla_office(p.id, vc.category_id)) END AS first_response_due_at,
       fr.first_responded_at,
       COALESCE(COALESCE(vc.first_response_hours, p.first_response_hours) IS NOT NULL
                AND COALESCE(fr.first_responded_at, CASE WHEN s.is_closed THEN NULL ELSE now() END)
                    > tms.deadline_after(s.created_at, COALESCE(vc.first_response_hours, p.first_response_hours) * 60,
                                         tms.sla_office(p.id, vc.category_id)), false) AS first_response_breached,
       CASE WHEN s.resolved_at IS NOT NULL THEN tms.business_minutes_between(s.created_at, s.resolved_at) END AS office_minutes_to_resolution,
       pz.paused_office_minutes,
       lf.percent_left AS sla_percent_left,
       CASE WHEN s.is_closed OR s.awaits_requester THEN NULL
            WHEN s.clock_state = 'PAUSED' THEN 'PAUSED'
            WHEN s.clock_state <> 'RUNNING' THEN NULL
            WHEN s.is_overdue OR lf.percent_left <= 0 THEN 'CRITICAL'
            WHEN lf.percent_left <= (SELECT sla_warning_percent FROM tms.helpdesk_setting WHERE id) THEN 'WARNING'
            ELSE 'NORMAL' END AS attention
FROM tms.v_ticket_state s
JOIN ref.tms_priority p ON p.id = s.priority_id
JOIN tms.v_ticket_category vc ON vc.category_id = s.category_id
LEFT JOIN LATERAL (SELECT min(e.occurred_at) AS first_responded_at FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.counts_as_response
                   WHERE e.ticket_id = s.ticket_id AND e.actor_account_id IS DISTINCT FROM s.requester_account_id) fr ON true
-- office time spent paused (clarifications and holds), each pause up to the clock event that ended it
LEFT JOIN LATERAL (SELECT COALESCE(sum(tms.business_minutes_between(pe.occurred_at, COALESCE(nx.occurred_at, now()))), 0)::int AS paused_office_minutes
                   FROM tms.ticket_event pe
                   JOIN ref.tms_event_type pt ON pt.id = pe.event_type_id AND pt.pauses_clock
                   LEFT JOIN LATERAL (SELECT min(x.occurred_at) AS occurred_at FROM tms.ticket_event x
                                      JOIN ref.tms_event_type xt ON xt.id = x.event_type_id AND (xt.starts_clock OR xt.stops_clock OR xt.pauses_clock)
                                      WHERE x.ticket_id = pe.ticket_id AND x.id > pe.id) nx ON true
                   WHERE pe.ticket_id = s.ticket_id) pz ON true
-- share of the current clock's time still left
LEFT JOIN LATERAL (SELECT CASE WHEN s.clock_state = 'RUNNING' AND s.due_at IS NOT NULL
                                    AND tms.minutes_left(s.clock_since, s.due_at, s.clock_is_office) > 0
                               THEN round(100.0 * tms.minutes_left(now(), s.due_at, s.clock_is_office)
                                          / tms.minutes_left(s.clock_since, s.due_at, s.clock_is_office), 1) END AS percent_left) lf ON true;

-- Per handler: tickets with them now, overdue, waiting for clarification;
-- tickets they resolved, the average rating and how many came back.
CREATE OR REPLACE VIEW tms.v_ticket_handler_stats AS
WITH cur AS (
  SELECT s.assignee_employee_id AS employee_id,
         count(*) FILTER (WHERE NOT s.is_closed AND NOT s.awaits_requester) AS open_tickets,
         count(*) FILTER (WHERE s.is_overdue) AS overdue_tickets,
         count(*) FILTER (WHERE s.clock_state = 'PAUSED' AND NOT s.is_closed) AS awaiting_clarification
  FROM tms.v_ticket_state s WHERE s.assignee_employee_id IS NOT NULL
  GROUP BY s.assignee_employee_id),
res AS (
  SELECT em.id AS employee_id, count(DISTINCT e.ticket_id) AS resolved_tickets
  FROM tms.ticket_event e
  JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code IN ('RESOLVED', 'REJECTED')
  JOIN iam.user_account a    ON a.id = e.actor_account_id
  JOIN people.employee em    ON em.person_id = a.person_id
  GROUP BY em.id),
rat AS (
  SELECT em.id AS employee_id, round(avg(s.rating), 2) AS avg_rating, sum(s.reopen_count) AS reopened
  FROM tms.v_ticket_state s
  JOIN iam.user_account a ON a.id = s.resolved_by_account_id
  JOIN people.employee em ON em.person_id = a.person_id
  GROUP BY em.id),
ever AS (
  SELECT e.assignee_employee_id AS employee_id, count(DISTINCT e.ticket_id) AS ever_assigned
  FROM tms.ticket_event e WHERE e.assignee_employee_id IS NOT NULL
  GROUP BY e.assignee_employee_id)
SELECT ever.employee_id,
       ever.ever_assigned,
       COALESCE(cur.open_tickets, 0) AS open_tickets, COALESCE(cur.overdue_tickets, 0) AS overdue_tickets,
       COALESCE(cur.awaiting_clarification, 0) AS awaiting_clarification,
       COALESCE(res.resolved_tickets, 0) AS resolved_tickets, rat.avg_rating, COALESCE(rat.reopened, 0) AS reopened
FROM ever
LEFT JOIN cur ON cur.employee_id = ever.employee_id
LEFT JOIN res ON res.employee_id = ever.employee_id
LEFT JOIN rat ON rat.employee_id = ever.employee_id;

-- Per current category: volume by status, overdue, first responses late,
-- escalations, reopens, referrals, rating and mean resolution time (office hours).
CREATE OR REPLACE VIEW tms.v_ticket_category_stats AS
SELECT s.category_id, s.ticket_domain, s.category_type, s.responsible_org_unit_id,
       count(*) AS tickets,
       count(*) FILTER (WHERE s.status = 'OPEN') AS open_tickets,
       count(*) FILTER (WHERE s.status = 'ESCALATED') AS escalated_tickets,
       count(*) FILTER (WHERE s.status = 'WITH_FORUM') AS with_forum_tickets,
       count(*) FILTER (WHERE s.status = 'RESOLVED') AS resolved_tickets,
       count(*) FILTER (WHERE s.is_closed) AS closed_tickets,
       count(*) FILTER (WHERE s.is_overdue) AS overdue_tickets,
