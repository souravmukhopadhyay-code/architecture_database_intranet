-- What the account may record on the ticket now — the buttons a screen
-- shows (the old canReopen, for every action). Mirrors the checks of
-- ticket_event_validate; the insert itself stays the authority.
CREATE OR REPLACE FUNCTION tms.available_actions(p_account uuid, p_ticket uuid)
RETURNS TABLE (event_code text, label text) LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE s record; c tms.helpdesk_setting := tms.config(); r record; v_t tms.ticket; v_person uuid;
        v_req boolean; v_acts boolean; v_forum boolean; v_comp boolean; v_ok boolean; v_reason ref.tms_closure_reason; v_f tms.redressal_forum;
BEGIN
  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = p_ticket;
  IF NOT FOUND OR NOT tms.domain_is_open(s.ticket_domain_id) OR NOT tms.can_login(p_account) THEN RETURN; END IF;
  SELECT * INTO v_t FROM tms.ticket WHERE id = p_ticket;
  v_person := tms.person_of_account(p_account);
  IF tms.is_respondent(p_ticket, v_person) THEN RETURN; END IF;
  v_req := v_person = tms.person_of_account(v_t.requester_account_id);
  v_acts := tms.can_act(p_account, p_ticket);
  v_forum := tms.is_forum_member(p_account, p_ticket);
  v_comp := tms.can_report_compliance(p_account, p_ticket);
  SELECT * INTO v_reason FROM ref.tms_closure_reason WHERE id = COALESCE(s.closure_reason_id, s.resolution_reason_id);
  SELECT * INTO v_f FROM tms.redressal_forum WHERE id = s.forum_id;
  FOR r IN SELECT et.code, et.label, ea.code AS actor
           FROM ref.tms_event_type et
           JOIN ref.tms_event_actor ea ON ea.id = et.event_actor_id AND ea.code <> 'SYSTEM'
           JOIN ref.tms_event_allowed_status a ON a.event_type_id = et.id
           JOIN ref.tms_ticket_status st ON st.id = a.ticket_status_id AND st.code = s.status
           WHERE et.is_active ORDER BY et.sort_order LOOP
    v_ok := CASE r.actor WHEN 'REQUESTER' THEN v_req WHEN 'HANDLER' THEN v_acts WHEN 'REQUESTER_OR_HANDLER' THEN v_req OR v_acts
                         WHEN 'FORUM' THEN v_forum WHEN 'RESPONSIBLE_OFFICE' THEN v_comp
                         WHEN 'CONSULTEE' THEN EXISTS (SELECT 1 FROM tms.ticket_event q JOIN ref.tms_event_type qt ON qt.id = q.event_type_id AND qt.code = 'CONSULTATION_REQUESTED'
                                                        WHERE q.ticket_id = p_ticket AND tms.person_of_employee(q.consulted_employee_id) = v_person
                                                          AND NOT EXISTS (SELECT 1 FROM tms.ticket_event x WHERE x.reply_to_event_id = q.id))
                         ELSE false END;
    IF v_ok THEN
      v_ok := CASE r.code
        WHEN 'CLARIFICATION_REQUESTED' THEN s.clock_state <> 'PAUSED'
        WHEN 'PUT_ON_HOLD' THEN c.on_hold_enabled AND s.clock_state <> 'PAUSED'
        WHEN 'CLARIFICATION_PROVIDED' THEN s.clock_state = 'PAUSED' AND s.clock_event = 'CLARIFICATION_REQUESTED'
        WHEN 'HOLD_RELEASED' THEN s.clock_state = 'PAUSED' AND s.clock_event = 'PUT_ON_HOLD'
        WHEN 'ESCALATED' THEN (v_acts OR (c.requester_may_escalate_overdue AND s.is_overdue)) AND EXISTS (SELECT 1 FROM tms.next_escalation(p_ticket))
        WHEN 'RECUSED' THEN false
        WHEN 'REASSIGNED' THEN EXISTS (SELECT 1 FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id AND k.code = 'HANDLER_POOL'
                                       WHERE rl.id = s.level_id)
        WHEN 'REFERRED' THEN s.is_grievance AND s.referral_count = 0 AND s.category_forum_id IS NOT NULL
                             AND ((v_acts AND NOT v_req AND s.status <> 'RESOLVED')
                                  OR (v_req AND (s.status = 'RESOLVED'
                                                 OR (c.requester_refer_after_days IS NOT NULL AND now() >= v_t.created_at + make_interval(days => c.requester_refer_after_days)))))
        WHEN 'APPEALED' THEN s.resolution_event = 'FORUM_DECIDED' AND v_f.appeal_forum_id IS NOT NULL
                             AND now() <= s.resolved_at + make_interval(days => v_f.appeal_window_days)
        WHEN 'RESOLVED' THEN NOT v_req
        WHEN 'REJECTED' THEN NOT v_req
        WHEN 'MERGED' THEN NOT s.is_confidential
        WHEN 'CONSULTATION_REQUESTED' THEN NOT s.is_confidential
        WHEN 'REOPENED' THEN s.forum_id IS NULL AND s.reopen_count < c.max_reopens
                             AND (NOT s.is_closed OR (COALESCE(v_reason.is_reopenable, false) AND now() <= s.closed_at + make_interval(days => c.reopen_window_days)))
        WHEN 'RATED' THEN s.rating IS NULL AND s.resolved_at IS NOT NULL AND COALESCE(v_reason.is_ratable, false)
                          AND now() <= s.resolved_at + make_interval(days => c.rating_window_days)
        WHEN 'ACTION_TAKEN' THEN s.resolution_event = 'FORUM_DECIDED' AND v_f.compliance_within_days IS NOT NULL
                                 AND (SELECT is_in_favour FROM ref.tms_redressal_outcome WHERE id = s.redressal_outcome_id)
                                 AND NOT EXISTS (SELECT 1 FROM tms.ticket_event x JOIN ref.tms_event_type xt ON xt.id = x.event_type_id AND xt.code = 'ACTION_TAKEN'
                                                 WHERE x.ticket_id = p_ticket AND x.occurred_at >= s.resolved_at)
        ELSE true END;
    END IF;
    IF COALESCE(v_ok, false) THEN
      event_code := r.code; label := r.label;
      RETURN NEXT;
    END IF;
  END LOOP;
END $$;

-- The accounts a notice rule's recipient means for an event:
--   REQUESTER          the requester
--   ASSIGNEE           the assignee after the event
--   PREVIOUS_ASSIGNEE  the assignee before it, if it changed
--   FORUM_MEMBERS      the current members of the committee hearing it (or the holder)
--   FOLLOWERS          requesters of tickets merged into this one
-- Never a respondent.
CREATE OR REPLACE FUNCTION tms.notice_accounts(p_code text, p_ticket uuid, p_event bigint)
RETURNS SETOF uuid LANGUAGE plpgsql STABLE AS $$
DECLARE s record; v_prev uuid;
BEGIN
  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = p_ticket;
  CASE p_code
    WHEN 'REQUESTER' THEN
      RETURN NEXT s.requester_account_id;
    WHEN 'ASSIGNEE' THEN
      IF s.assignee_employee_id IS NOT NULL THEN RETURN NEXT tms.account_of_employee(s.assignee_employee_id); END IF;
    WHEN 'PREVIOUS_ASSIGNEE' THEN
      SELECT e.assignee_employee_id INTO v_prev FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.sets_assignee
      WHERE e.ticket_id = p_ticket AND e.id < p_event ORDER BY e.id DESC LIMIT 1;
      IF v_prev IS NOT NULL AND v_prev IS DISTINCT FROM s.assignee_employee_id
         AND NOT tms.is_respondent(p_ticket, tms.person_of_employee(v_prev)) THEN
        RETURN NEXT tms.account_of_employee(v_prev);
      END IF;
    WHEN 'FORUM_MEMBERS' THEN
      IF s.forum_id IS NOT NULL AND s.academic_body_id IS NOT NULL THEN
        RETURN QUERY SELECT a.id FROM academic.academic_body_member m
                     LEFT JOIN people.employee e ON e.id = m.employee_id
                     JOIN iam.user_account a ON a.person_id = COALESCE(m.external_person_id, e.person_id)
                     WHERE m.academic_body_id = s.academic_body_id AND m.valid @> current_date
                       AND NOT tms.is_respondent(p_ticket, a.person_id);
      ELSIF s.forum_id IS NOT NULL AND s.assignee_employee_id IS NOT NULL THEN
        RETURN NEXT tms.account_of_employee(s.assignee_employee_id);
      END IF;
    WHEN 'FOLLOWERS' THEN
      RETURN QUERY SELECT DISTINCT t.requester_account_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'MERGED'
                   JOIN tms.ticket t ON t.id = e.ticket_id
                   WHERE e.related_ticket_id = p_ticket;
    WHEN 'CONSULTEE' THEN
      RETURN QUERY SELECT tms.account_of_employee(e.consulted_employee_id) FROM tms.ticket_event e
                   WHERE e.id = p_event AND e.consulted_employee_id IS NOT NULL;
    WHEN 'CONSULT_ASKER' THEN
      RETURN QUERY SELECT q.actor_account_id FROM tms.ticket_event e JOIN tms.ticket_event q ON q.id = e.reply_to_event_id
                   WHERE e.id = p_event;
    WHEN 'FORUM_ALERT' THEN
      RETURN QUERY SELECT tms.account_of_employee(ap.employee_id)
                   FROM tms.redressal_forum f
                   CROSS JOIN LATERAL org.ancestors(COALESCE(s.requester_org_unit_id, s.responsible_org_unit_id)) a
                   JOIN org.appointment ap ON ap.org_unit_id = a.org_unit_id AND ap.position_type_id = f.alert_position_type_id
                                          AND ap.valid @> current_date
                   WHERE f.id = s.forum_id AND NOT tms.is_respondent(p_ticket, tms.person_of_employee(ap.employee_id))
                   ORDER BY a.depth LIMIT 1;
    WHEN 'LAST_HANDLER' THEN
      SELECT e.assignee_employee_id INTO v_prev FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.sets_assignee
      WHERE e.ticket_id = p_ticket AND e.forum_id IS NULL AND e.assignee_employee_id IS NOT NULL ORDER BY e.id DESC LIMIT 1;
      IF v_prev IS NOT NULL AND NOT tms.is_respondent(p_ticket, tms.person_of_employee(v_prev)) THEN
        RETURN NEXT tms.account_of_employee(v_prev);
      END IF;
    ELSE NULL;
  END CASE;
END $$;

-- Queue the notices the event causes, per notice_rule. Nobody is told about
-- their own action, unless the rule is a receipt (notify_actor).
CREATE OR REPLACE FUNCTION tms.ticket_event_notify()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_dom smallint;
BEGIN
  SELECT ticket_domain_id INTO v_dom FROM tms.v_ticket_state WHERE ticket_id = NEW.ticket_id;
  INSERT INTO tms.ticket_notification (ticket_event_id, recipient_account_id, contact_channel_id, notification_status_id)
  SELECT NEW.id, x.account_id, r.contact_channel_id, ref.id_of('tms_notification_status', 'PENDING')
  FROM tms.ticket_notice_rule r
  JOIN ref.tms_notice_recipient nr ON nr.id = r.notice_recipient_id
  JOIN tms.helpdesk_channel hc ON hc.contact_channel_id = r.contact_channel_id AND hc.is_enabled
  CROSS JOIN LATERAL tms.notice_accounts(nr.code, NEW.ticket_id, NEW.id) AS x(account_id)
  WHERE r.event_type_id = NEW.event_type_id
    AND (r.ticket_domain_id IS NULL OR r.ticket_domain_id = v_dom)
    AND x.account_id IS NOT NULL
    AND (r.notify_actor OR x.account_id IS DISTINCT FROM NEW.actor_account_id)
    AND (r.is_mandatory OR NOT EXISTS (SELECT 1 FROM tms.notice_opt_out o
                                       WHERE o.account_id = x.account_id AND o.contact_channel_id = r.contact_channel_id))
  ON CONFLICT DO NOTHING;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_ticket_event_notify AFTER INSERT ON tms.ticket_event
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_event_notify();

-- The sender records the outcome; a final status is final.
CREATE OR REPLACE FUNCTION tms.ticket_notification_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'tms.ticket_notification: the delivery log is kept' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF (SELECT is_final FROM ref.tms_notification_status WHERE id = OLD.notification_status_id) THEN
      RAISE EXCEPTION 'tms.ticket_notification: % is final', (SELECT code FROM ref.tms_notification_status WHERE id = OLD.notification_status_id)
        USING ERRCODE = 'check_violation';
    END IF;
    IF (NEW.ticket_event_id, NEW.recipient_account_id, NEW.contact_channel_id, NEW.created_at)
       IS DISTINCT FROM (OLD.ticket_event_id, OLD.recipient_account_id, OLD.contact_channel_id, OLD.created_at) THEN
      RAISE EXCEPTION 'tms.ticket_notification: only the delivery outcome changes' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  IF (SELECT code FROM ref.tms_notification_status WHERE id = NEW.notification_status_id) = 'SENT' AND NEW.sent_at IS NULL THEN
    NEW.sent_at := now();
  END IF;
  IF (SELECT code FROM ref.tms_notification_status WHERE id = NEW.notification_status_id) = 'FAILED'
     AND NEW.attempt_count >= (tms.config()).notice_max_attempts THEN
    NEW.notification_status_id := ref.id_of('tms_notification_status', 'GAVE_UP');   -- no endless retries
  END IF;
  IF TG_OP = 'UPDATE' AND NEW.attempt_count <> OLD.attempt_count THEN
    NEW.last_attempt_at := now();
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ticket_notification_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.ticket_notification
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_notification_validate();

