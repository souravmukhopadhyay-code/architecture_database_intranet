-- The grievance register (UGC): one row per stage a case spends with a
-- forum — referred, appealed, or forwarded by another committee: when it
-- arrived, when the forum first acted (urgent cases: within hours), its time
-- limit, how the stage ended (decided or forwarded), whether in time, the
-- compliance of a decision in the requester's favour, and the academic year.
CREATE OR REPLACE VIEW tms.v_grievance_register AS
SELECT e.id AS referral_event_id, e.ticket_id, t.request_no, s.ticket_domain, s.is_confidential,
       s.grievance_head_id, gh.code AS grievance_head,
       e.forum_id, f.code AS forum, e.academic_body_id,
       (et.code = 'APPEALED') AS is_appeal, (et.code = 'AUTO_REFERRED') AS is_automatic, (et.code = 'FORUM_FORWARDED') AS is_forwarded_in,
       e.occurred_at AS referred_at, e.due_at,
       fa.occurred_at AS first_action_at, fa.action_due AS first_action_due_at,
       (fa.occurred_at IS NOT NULL AND (fa.action_due IS NULL OR fa.occurred_at <= fa.action_due)) AS first_action_in_time,
       d.occurred_at AS decided_at,
       CASE WHEN d.code = 'FORUM_FORWARDED' THEN 'FORWARDED' ELSE ro.code END AS outcome, ro.is_in_favour,
       (d.occurred_at IS NOT NULL AND d.occurred_at <= e.due_at) AS decided_in_time,
       CASE WHEN d.code = 'FORUM_DECIDED' THEN 'DECIDED'
            WHEN d.code = 'FORUM_FORWARDED' THEN 'FORWARDED'
            WHEN s.is_closed THEN 'CLOSED_UNDECIDED'
            ELSE 'PENDING' END AS register_status,
       (d.occurred_at IS NULL AND NOT s.is_closed AND e.due_at < now()) AS is_overdue,
       CASE WHEN ro.is_in_favour AND f.compliance_within_days IS NOT NULL THEN d.occurred_at + make_interval(days => f.compliance_within_days) END AS compliance_due_at,
       cp.occurred_at AS complied_at,
       (ro.is_in_favour AND f.compliance_within_days IS NOT NULL AND cp.occurred_at IS NULL
        AND d.occurred_at + make_interval(days => f.compliance_within_days) < now()) AS compliance_overdue,
       ay.id AS academic_year_id
FROM tms.ticket_event e
JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code IN ('REFERRED', 'AUTO_REFERRED', 'APPEALED', 'FORUM_FORWARDED')
JOIN tms.ticket t ON t.id = e.ticket_id
JOIN tms.v_ticket_state s ON s.ticket_id = e.ticket_id
JOIN tms.v_ticket_category vc ON vc.category_id = s.category_id
JOIN ref.tms_priority p ON p.id = s.priority_id
JOIN tms.redressal_forum f ON f.id = e.forum_id
LEFT JOIN ref.tms_grievance_head gh ON gh.id = s.grievance_head_id
-- how the stage ended: the forum's decision, or its forwarding to another forum
LEFT JOIN LATERAL (SELECT x.id AS decision_id, x.occurred_at, x.redressal_outcome_id, xt.code FROM tms.ticket_event x
                   JOIN ref.tms_event_type xt ON xt.id = x.event_type_id AND xt.code IN ('FORUM_DECIDED', 'FORUM_FORWARDED')
                   WHERE x.ticket_id = e.ticket_id AND x.id > e.id ORDER BY x.id LIMIT 1) d ON true
LEFT JOIN ref.tms_redressal_outcome ro ON ro.id = d.redressal_outcome_id AND d.code = 'FORUM_DECIDED'
-- the forum's first action in the stage (anything recorded by someone other than the requester)
LEFT JOIN LATERAL (SELECT (SELECT min(x.occurred_at) FROM tms.ticket_event x
                           WHERE x.ticket_id = e.ticket_id AND x.id > e.id AND x.actor_account_id IS NOT NULL
                             AND x.actor_account_id <> t.requester_account_id
                             AND (d.decision_id IS NULL OR x.id <= d.decision_id)) AS occurred_at,
                          CASE WHEN COALESCE(f.first_action_within_hours, vc.first_response_hours, p.first_response_hours) IS NOT NULL
                               THEN tms.deadline_after(e.occurred_at, COALESCE(f.first_action_within_hours, vc.first_response_hours, p.first_response_hours) * 60,
                                                       tms.sla_office(p.id, vc.category_id)) END AS action_due) fa ON true
LEFT JOIN LATERAL (SELECT min(x.occurred_at) AS occurred_at FROM tms.ticket_event x
                   JOIN ref.tms_event_type xt ON xt.id = x.event_type_id AND xt.code = 'ACTION_TAKEN'
                   WHERE d.code = 'FORUM_DECIDED' AND x.ticket_id = e.ticket_id AND x.id > d.decision_id
                     AND NOT EXISTS (SELECT 1 FROM tms.ticket_event n JOIN ref.tms_event_type nt ON nt.id = n.event_type_id AND nt.code = 'FORUM_DECIDED'
                                     WHERE n.ticket_id = e.ticket_id AND n.id > d.decision_id AND n.id < x.id)) cp ON true
LEFT JOIN academic.academic_year ay ON ay.period @> (e.occurred_at AT TIME ZONE (SELECT time_zone FROM tms.helpdesk_setting WHERE id))::date;

-- The register summed up per academic year, forum and grievance head — the
-- figures for the UGC / NAAC return (received, decided, in time, pending …).
CREATE OR REPLACE VIEW tms.v_grievance_summary AS
SELECT r.academic_year_id, r.ticket_domain, r.forum_id, r.forum, r.grievance_head,
       count(*) AS received,
       count(*) FILTER (WHERE r.register_status = 'DECIDED') AS decided,
       count(*) FILTER (WHERE r.decided_in_time) AS decided_in_time,
       count(*) FILTER (WHERE r.register_status = 'PENDING') AS pending,
       count(*) FILTER (WHERE r.is_overdue) AS pending_overdue,
       count(*) FILTER (WHERE r.register_status = 'CLOSED_UNDECIDED') AS closed_undecided,
       count(*) FILTER (WHERE r.is_in_favour) AS decided_in_favour,
       count(*) FILTER (WHERE r.is_appeal) AS appeals,
       count(*) FILTER (WHERE r.register_status = 'FORWARDED') AS forwarded,
       count(*) FILTER (WHERE r.first_action_in_time) AS acted_on_in_time,
       round(avg(extract(epoch FROM r.decided_at - r.referred_at) / 86400) FILTER (WHERE r.decided_at IS NOT NULL)::numeric, 1) AS avg_days_to_decision
