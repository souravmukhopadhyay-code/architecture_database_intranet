-- A node and every node below it.
CREATE OR REPLACE FUNCTION tms.category_subtree(p_category uuid)
RETURNS TABLE (category_id uuid, depth int) LANGUAGE sql STABLE AS $$
  WITH RECURSIVE d AS (
    SELECT id, 0 AS depth FROM tms.ticket_category WHERE id = p_category
    UNION ALL
    SELECT c.id, d.depth + 1 FROM tms.ticket_category c JOIN d ON c.parent_id = d.id)
  SELECT id, depth FROM d;
$$;

-- A node and every node above it (depth 0 = the node itself).
CREATE OR REPLACE FUNCTION tms.category_ancestors(p_category uuid)
RETURNS TABLE (category_id uuid, depth int) LANGUAGE sql STABLE AS $$
  WITH RECURSIVE u AS (
    SELECT id, parent_id, 0 AS depth FROM tms.ticket_category WHERE id = p_category
    UNION ALL
    SELECT c.id, c.parent_id, u.depth + 1 FROM tms.ticket_category c JOIN u ON c.id = u.parent_id)
  SELECT id, depth FROM u;
$$;

-- Every node with what it inherits from above.
CREATE OR REPLACE VIEW tms.v_ticket_category AS
WITH RECURSIVE t AS (
  SELECT c.id, c.id AS root_id, c.ticket_domain_id, c.org_unit_id AS responsible_org_unit_id,
         c.category_type_id, c.academic_context_rule_id, c.route_id, c.redressal_forum_id,
         COALESCE(c.direct_to_forum, false) AS direct_to_forum, COALESCE(c.is_confidential, false) AS is_confidential,
         COALESCE(c.allows_anonymous, false) AS allows_anonymous, COALESCE(c.allows_respondent, false) AS allows_respondent,
         COALESCE(c.requires_incident_date, false) AS requires_incident_date, COALESCE(c.allows_raising, true) AS allows_raising,
         c.sla_hours, c.first_response_hours, c.sla_office_hours_only,
         c.grievance_head_id, c.is_active AS effective_active,
         CASE WHEN l.code = 'KRA_TYPE' THEN c.id END AS kra_type_id,
         CASE WHEN l.code = 'MASTER' THEN c.id END AS master_id,
         c.name::text AS path, l.depth, l.is_leaf
  FROM tms.ticket_category c JOIN ref.tms_category_level l ON l.id = c.category_level_id
  WHERE c.parent_id IS NULL
  UNION ALL
  SELECT c.id, t.root_id, t.ticket_domain_id, COALESCE(c.org_unit_id, t.responsible_org_unit_id),
         COALESCE(c.category_type_id, t.category_type_id), COALESCE(c.academic_context_rule_id, t.academic_context_rule_id),
         COALESCE(c.route_id, t.route_id), COALESCE(c.redressal_forum_id, t.redressal_forum_id),
         COALESCE(c.direct_to_forum, t.direct_to_forum), COALESCE(c.is_confidential, t.is_confidential),
         COALESCE(c.allows_anonymous, t.allows_anonymous), COALESCE(c.allows_respondent, t.allows_respondent),
         COALESCE(c.requires_incident_date, t.requires_incident_date), COALESCE(c.allows_raising, t.allows_raising),
         COALESCE(c.sla_hours, t.sla_hours), COALESCE(c.first_response_hours, t.first_response_hours),
         COALESCE(c.sla_office_hours_only, t.sla_office_hours_only),
         COALESCE(c.grievance_head_id, t.grievance_head_id), t.effective_active AND c.is_active,
         t.kra_type_id, CASE WHEN l.code = 'MASTER' THEN c.id ELSE t.master_id END,
