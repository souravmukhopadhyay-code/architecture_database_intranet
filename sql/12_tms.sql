-- A route = the ladder a ticket climbs. Levels are tried in order; a level
-- whose person is missing, cannot work now, is the requester, is the current
-- assignee or is named in the complaint is skipped.
CREATE TABLE tms.ticket_route (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              citext NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]{1,60}$'),
  label             text NOT NULL CHECK (btrim(label) <> ''),
  ticket_domain_id  smallint NOT NULL REFERENCES ref.tms_ticket_domain(id),
  is_active         boolean NOT NULL DEFAULT true,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);
SELECT util.attach_updated_at('tms.ticket_route');

-- One level of a route — everything about it is configuration:
--   HANDLER_POOL       round-robin among the leaf's handlers serving the requester's unit
--   CATEGORY_OWNER     the owner of the ticket's category node at category_level
--   MENTOR             the requester's current mentor (students)
--   REPORTING_MANAGER  the requester's manager, manager_level up (employees)
--   POSITION           the holder of position_type at: the requester's unit, the
--                      category's responsible unit, or a fixed unit — or at the
--                      nearest unit of anchor_org_unit_type above it (HOD =
--                      HEAD at DEPARTMENT, Dean = DEAN at SCHOOL, VC = at UNIVERSITY)
--   NAMED              one employee
-- sla_hours overrides the priority's hours at this level; oversees = the
-- holder may act on the ticket at any time, not only when it reaches them.
CREATE TABLE tms.ticket_route_level (
  id                        smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  route_id                  smallint NOT NULL REFERENCES tms.ticket_route(id) ON DELETE CASCADE,
  seq                       smallint NOT NULL CHECK (seq >= 1),
  label                     text NOT NULL CHECK (btrim(label) <> ''),
  route_level_kind_id       smallint NOT NULL REFERENCES ref.tms_route_level_kind(id),
  category_level_id         smallint REFERENCES ref.tms_category_level(id),
  position_type_id          smallint REFERENCES org.position_type(id),
  anchor_base_id            smallint REFERENCES ref.tms_anchor_base(id),
  anchor_org_unit_type_id   smallint REFERENCES ref.org_unit_type(id),
  org_unit_id               uuid REFERENCES org.org_unit(id),
  reporting_line_type_id    smallint REFERENCES ref.reporting_line_type(id),
  manager_level             smallint CHECK (manager_level BETWEEN 1 AND 5),
  employee_id               uuid REFERENCES people.employee(id),
  sla_hours                 smallint CHECK (sla_hours > 0),
  oversees                  boolean NOT NULL DEFAULT false,
  created_at                timestamptz NOT NULL DEFAULT now(),
  updated_at                timestamptz NOT NULL DEFAULT now(),
  UNIQUE (route_id, seq)
);
CREATE INDEX ticket_route_level_employee_idx ON tms.ticket_route_level (employee_id);
SELECT util.attach_updated_at('tms.ticket_route_level');

CREATE OR REPLACE FUNCTION tms.ticket_route_level_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_kind text; v_base text; v_type smallint;
BEGIN
  SELECT code INTO v_kind FROM ref.tms_route_level_kind WHERE id = NEW.route_level_kind_id;
  SELECT code INTO v_base FROM ref.tms_anchor_base WHERE id = NEW.anchor_base_id;
  IF v_kind = 'POSITION' THEN
    IF NEW.position_type_id IS NULL OR NEW.anchor_base_id IS NULL THEN
      RAISE EXCEPTION 'tms.ticket_route_level %: a POSITION level needs the position and where to look for it', NEW.label USING ERRCODE = 'check_violation';
    END IF;
    IF (v_base = 'FIXED_UNIT') <> (NEW.org_unit_id IS NOT NULL) THEN
      RAISE EXCEPTION 'tms.ticket_route_level %: a unit is given exactly when the level looks at a fixed unit', NEW.label USING ERRCODE = 'check_violation';
    END IF;
    v_type := COALESCE(NEW.anchor_org_unit_type_id, (SELECT org_unit_type_id FROM org.org_unit WHERE id = NEW.org_unit_id));
    IF v_type IS NOT NULL AND NOT EXISTS (SELECT 1 FROM org.position_type_unit_type WHERE position_type_id = NEW.position_type_id AND org_unit_type_id = v_type) THEN
      RAISE EXCEPTION 'tms.ticket_route_level %: that position does not exist for that type of unit', NEW.label USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.position_type_id IS NOT NULL OR NEW.anchor_base_id IS NOT NULL OR NEW.anchor_org_unit_type_id IS NOT NULL OR NEW.org_unit_id IS NOT NULL THEN
    RAISE EXCEPTION 'tms.ticket_route_level %: position settings on a % level', NEW.label, v_kind USING ERRCODE = 'check_violation';
  END IF;
  IF (v_kind = 'CATEGORY_OWNER') <> (NEW.category_level_id IS NOT NULL) THEN
    RAISE EXCEPTION 'tms.ticket_route_level %: a category level is given exactly on a CATEGORY_OWNER level', NEW.label USING ERRCODE = 'check_violation';
  END IF;
  IF v_kind = 'CATEGORY_OWNER' AND (SELECT is_leaf FROM ref.tms_category_level WHERE id = NEW.category_level_id) THEN
    RAISE EXCEPTION 'tms.ticket_route_level %: a leaf has handlers, not an owner — use a HANDLER_POOL level', NEW.label USING ERRCODE = 'check_violation';
  END IF;
  IF v_kind = 'REPORTING_MANAGER' THEN
    NEW.reporting_line_type_id := COALESCE(NEW.reporting_line_type_id, ref.id_of('reporting_line_type', 'REPORTING'));
    NEW.manager_level := COALESCE(NEW.manager_level, 1);
  ELSIF NEW.reporting_line_type_id IS NOT NULL OR NEW.manager_level IS NOT NULL THEN
    RAISE EXCEPTION 'tms.ticket_route_level %: manager settings on a % level', NEW.label, v_kind USING ERRCODE = 'check_violation';
  END IF;
  IF (v_kind = 'NAMED') <> (NEW.employee_id IS NOT NULL) THEN
    RAISE EXCEPTION 'tms.ticket_route_level %: a person is named exactly on a NAMED level', NEW.label USING ERRCODE = 'check_violation';
  END IF;
  IF v_kind = 'HANDLER_POOL' AND NEW.oversees THEN
    RAISE EXCEPTION 'tms.ticket_route_level %: a handler pool does not oversee', NEW.label USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
