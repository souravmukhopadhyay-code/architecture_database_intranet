-- ################################################################ SCHEDULER ##

-- The hourly job (app.system_job = on). During office hours (or when forced):
--   1. grievances the helpdesk has not settled within auto_refer_after_days
--      go to their category's forum (AUTO_REFERRED);
--   2. every running clock past its due time: at the helpdesk, escalated one
--      level (AUTO_ESCALATED) or — nobody left — stopped (ESCALATION_EXHAUSTED);
--      with auto-escalation off, and always at a forum, one OVERDUE_NOTICE
--      per overdue spell;
--   3. clarifications not answered: a reminder, then — after the expiry —
--      closed for no response;
--   4. resolutions neither accepted nor contested within the confirmation
--      window (a forum decision: within the appeal window) are closed.
-- Also: holds past max_hold_days are released, one compliance reminder per
-- decision not carried out in time, and one alert (members and the forum's
-- alert position) per forum stage without a first action in time.
-- p_now judges "due"; new due times always count from the real clock.
CREATE OR REPLACE FUNCTION tms.run_scheduler(p_now timestamptz DEFAULT now(), p_force boolean DEFAULT false)
RETURNS TABLE (auto_referred int, escalated int, exhausted int, overdue_notices int, reminders int, expired int, auto_closed int,
               holds_released int, compliance_reminders int, forum_action_alerts int)
LANGUAGE plpgsql AS $$
DECLARE c tms.helpdesk_setting := tms.config(); r record; v_next record; v_seat record; v_window int;
BEGIN
  IF current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'tms.run_scheduler: runs as a system job only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  auto_referred := 0; escalated := 0; exhausted := 0; overdue_notices := 0; reminders := 0; expired := 0; auto_closed := 0;
  holds_released := 0; compliance_reminders := 0; forum_action_alerts := 0;
  -- one instance at a time (old advisory lock 7358291); a second run returns at once
  IF NOT pg_try_advisory_xact_lock(7358291) THEN
    RETURN NEXT; RETURN;
  END IF;
  IF NOT p_force AND c.scheduler_office_hours_only AND NOT tms.is_business_moment(p_now) THEN
    RETURN NEXT; RETURN;
  END IF;

  IF c.auto_refer_after_days IS NOT NULL THEN
    FOR r IN SELECT s.ticket_id, s.category_forum_id, COALESCE(s.requester_org_unit_id, s.responsible_org_unit_id) AS unit
             FROM tms.v_ticket_state s
             WHERE s.status IN ('OPEN', 'ESCALATED') AND s.is_grievance AND s.category_forum_id IS NOT NULL AND s.referral_count = 0
               AND s.created_at + make_interval(days => c.auto_refer_after_days) <= p_now AND tms.domain_is_open(s.ticket_domain_id)
             ORDER BY s.created_at LOOP
      SELECT * INTO v_seat FROM tms.forum_seat(r.category_forum_id, r.unit);
      IF v_seat.academic_body_id IS NOT NULL OR v_seat.employee_id IS NOT NULL THEN
        INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
        VALUES (r.ticket_id, ref.id_of('tms_event_type', 'AUTO_REFERRED'),
                format('Not settled within %s days of being raised', c.auto_refer_after_days));
        auto_referred := auto_referred + 1;
      END IF;
    END LOOP;
  END IF;

  FOR r IN SELECT s.ticket_id, s.forum_id, s.clock_event_id FROM tms.v_ticket_state s
           WHERE NOT s.is_closed AND s.clock_state = 'RUNNING' AND s.due_at <= p_now AND tms.domain_is_open(s.ticket_domain_id)
           ORDER BY s.due_at LOOP
    IF r.forum_id IS NULL AND c.auto_escalation_enabled THEN
      SELECT * INTO v_next FROM tms.next_escalation(r.ticket_id);
      IF v_next.employee_id IS NOT NULL THEN
        INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
        VALUES (r.ticket_id, ref.id_of('tms_event_type', 'AUTO_ESCALATED'), 'Not resolved within the SLA');
        escalated := escalated + 1;
      ELSE
        INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
        VALUES (r.ticket_id, ref.id_of('tms_event_type', 'ESCALATION_EXHAUSTED'), 'The highest level has been reached; the ticket stays where it is');
        exhausted := exhausted + 1;
      END IF;
    ELSIF NOT EXISTS (SELECT 1 FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'OVERDUE_NOTICE'
                      WHERE e.ticket_id = r.ticket_id AND e.id > r.clock_event_id) THEN
      INSERT INTO tms.ticket_event (ticket_id, event_type_id) VALUES (r.ticket_id, ref.id_of('tms_event_type', 'OVERDUE_NOTICE'));
      overdue_notices := overdue_notices + 1;
    END IF;
  END LOOP;

  -- a forum that has not acted on a case it received within its first-action
  -- time (urgent cases: hours): its members and the alert position are told, once
  FOR r IN SELECT x.ticket_id, x.stage_event_id
           FROM (SELECT s.ticket_id, st.id AS stage_event_id,
                        tms.deadline_after(st.occurred_at,
                                           COALESCE(f.first_action_within_hours, vc.first_response_hours, p.first_response_hours) * 60,
                                           tms.sla_office(p.id, vc.category_id)) AS action_due,
                        s.requester_account_id
                 FROM tms.v_ticket_state s
                 JOIN tms.redressal_forum f ON f.id = s.forum_id
                 JOIN tms.v_ticket_category vc ON vc.category_id = s.category_id
                 JOIN ref.tms_priority p ON p.id = s.priority_id
                 CROSS JOIN LATERAL (SELECT e.id, e.occurred_at FROM tms.ticket_event e
                                     WHERE e.ticket_id = s.ticket_id AND e.forum_id IS NOT NULL ORDER BY e.id DESC LIMIT 1) st
                 WHERE s.status = 'WITH_FORUM' AND tms.domain_is_open(s.ticket_domain_id)
                   AND COALESCE(f.first_action_within_hours, vc.first_response_hours, p.first_response_hours) IS NOT NULL) x
           WHERE x.action_due <= p_now
             AND NOT EXISTS (SELECT 1 FROM tms.ticket_event a WHERE a.ticket_id = x.ticket_id AND a.id > x.stage_event_id
                               AND a.actor_account_id IS NOT NULL AND a.actor_account_id <> x.requester_account_id)
             AND NOT EXISTS (SELECT 1 FROM tms.ticket_event a JOIN ref.tms_event_type at2 ON at2.id = a.event_type_id AND at2.code = 'FORUM_ACTION_OVERDUE'
                             WHERE a.ticket_id = x.ticket_id AND a.id > x.stage_event_id) LOOP
    INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
    VALUES (r.ticket_id, ref.id_of('tms_event_type', 'FORUM_ACTION_OVERDUE'), 'The forum has not acted on the case within its first-action time');
    forum_action_alerts := forum_action_alerts + 1;
  END LOOP;

  FOR r IN SELECT s.ticket_id, s.clock_since FROM tms.v_ticket_state s
           WHERE NOT s.is_closed AND s.clock_state = 'PAUSED' AND s.clock_event = 'PUT_ON_HOLD' AND tms.domain_is_open(s.ticket_domain_id)
             AND c.max_hold_days IS NOT NULL AND s.clock_since + make_interval(days => c.max_hold_days) <= p_now LOOP
    INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
    VALUES (r.ticket_id, ref.id_of('tms_event_type', 'HOLD_EXPIRED'), format('On hold for %s days: the clock runs again', c.max_hold_days));
    holds_released := holds_released + 1;
  END LOOP;

  FOR r IN SELECT s.ticket_id, s.resolved_at, f.compliance_within_days FROM tms.v_ticket_state s
           JOIN tms.redressal_forum f ON f.id = s.forum_id AND f.compliance_within_days IS NOT NULL
           JOIN ref.tms_redressal_outcome o ON o.id = s.redressal_outcome_id AND o.is_in_favour
           WHERE s.resolution_event = 'FORUM_DECIDED' AND tms.domain_is_open(s.ticket_domain_id)
             AND s.resolved_at + make_interval(days => f.compliance_within_days) <= p_now
             AND NOT EXISTS (SELECT 1 FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id
                             AND et.code IN ('ACTION_TAKEN', 'COMPLIANCE_REMINDER')
                             WHERE e.ticket_id = s.ticket_id AND e.occurred_at >= s.resolved_at) LOOP
    INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
    VALUES (r.ticket_id, ref.id_of('tms_event_type', 'COMPLIANCE_REMINDER'),
            format('The decision was to be carried out within %s days', r.compliance_within_days));
    compliance_reminders := compliance_reminders + 1;
  END LOOP;

  FOR r IN SELECT s.ticket_id, s.clock_since, s.clock_event_id FROM tms.v_ticket_state s
           WHERE NOT s.is_closed AND s.clock_state = 'PAUSED' AND s.clock_event = 'CLARIFICATION_REQUESTED' AND tms.domain_is_open(s.ticket_domain_id) LOOP
    IF c.clarification_expiry_days IS NOT NULL AND r.clock_since + make_interval(days => c.clarification_expiry_days) <= p_now THEN
      INSERT INTO tms.ticket_event (ticket_id, event_type_id, remarks)
      VALUES (r.ticket_id, ref.id_of('tms_event_type', 'CLARIFICATION_EXPIRED'),
              format('No reply to the request for clarification within %s days', c.clarification_expiry_days));
      expired := expired + 1;
    ELSIF c.clarification_reminder_days IS NOT NULL AND r.clock_since + make_interval(days => c.clarification_reminder_days) <= p_now
          AND NOT EXISTS (SELECT 1 FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'CLARIFICATION_REMINDER'
                          WHERE e.ticket_id = r.ticket_id AND e.id > r.clock_event_id) THEN
      INSERT INTO tms.ticket_event (ticket_id, event_type_id) VALUES (r.ticket_id, ref.id_of('tms_event_type', 'CLARIFICATION_REMINDER'));
      reminders := reminders + 1;
    END IF;
  END LOOP;

  FOR r IN SELECT s.ticket_id, s.resolved_at, s.resolution_event, s.forum_id FROM tms.v_ticket_state s
           WHERE s.status = 'RESOLVED' AND tms.domain_is_open(s.ticket_domain_id) LOOP
    v_window := CASE WHEN r.resolution_event = 'FORUM_DECIDED'
                     THEN COALESCE((SELECT appeal_window_days FROM tms.redressal_forum WHERE id = r.forum_id), c.confirmation_window_days)
                     ELSE c.confirmation_window_days END;
    IF r.resolved_at + make_interval(days => v_window) <= p_now THEN
      INSERT INTO tms.ticket_event (ticket_id, event_type_id) VALUES (r.ticket_id, ref.id_of('tms_event_type', 'AUTO_CLOSED'));
      auto_closed := auto_closed + 1;
    END IF;
  END LOOP;
  RETURN NEXT;
END $$;

