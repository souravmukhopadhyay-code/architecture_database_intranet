-- The category tree. Employee domain: KRA type (0) → master / KRA (1) →
-- category / KPI (2) → leaf / measurement criteria (3). Student domain starts
-- at the master (1). The domain and the responsible unit are set on the root;
-- the unit can be narrowed further down. The category type (academic /
-- non-academic / examination) is set on the master; priority (and so the
-- SLA) on the leaf. Every other setting — route, redressal forum, straight
-- to the forum, confidential, anonymous allowed, complaint against a person
-- allowed, incident date required, grievance head, academic context — is
-- NULL = "as the parent" and is resolved down the tree (v_ticket_category).
CREATE TABLE tms.ticket_category (
  id                         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  parent_id                  uuid REFERENCES tms.ticket_category(id) ON DELETE RESTRICT,
  category_level_id          smallint NOT NULL REFERENCES ref.tms_category_level(id),
  ticket_domain_id           smallint REFERENCES ref.tms_ticket_domain(id),     -- root only
  org_unit_id                uuid REFERENCES org.org_unit(id),                  -- responsible unit: required on a root, optional override below
  category_type_id           smallint REFERENCES ref.tms_category_type(id),     -- master level only
  priority_id                smallint REFERENCES ref.tms_priority(id),          -- leaf only
  academic_context_rule_id   smallint REFERENCES ref.tms_academic_context_rule(id),
  route_id                   smallint REFERENCES tms.ticket_route(id),
  redressal_forum_id         smallint REFERENCES tms.redressal_forum(id),
  direct_to_forum            boolean,
  is_confidential            boolean,
  allows_anonymous           boolean,
  allows_respondent          boolean,
  requires_incident_date     boolean,
  allows_raising             boolean,                                           -- false = internal only: reachable by transfer, not offered to requesters
  sla_hours                  smallint CHECK (sla_hours > 0),                    -- category-wise SLA per level (NULL = as the parent, at the top: the priority's)
  first_response_hours       smallint CHECK (first_response_hours > 0),         -- category-wise first-response target (same inheritance)
  sla_office_hours_only      boolean,                                           -- false = the clock runs round the clock (NULL = as the parent / the priority)
  grievance_head_id          smallint REFERENCES ref.tms_grievance_head(id),
  name                       citext NOT NULL CHECK (btrim(name) <> '' AND length(name) <= 256),
  description                text CHECK (description IS NULL OR length(description) <= 512),
  sort_order                 smallint NOT NULL DEFAULT 0,
  is_active                  boolean NOT NULL DEFAULT true,
  created_at                 timestamptz NOT NULL DEFAULT now(),
  updated_at                 timestamptz NOT NULL DEFAULT now(),
  CHECK (parent_id IS DISTINCT FROM id),
  CHECK ((parent_id IS NULL) = (ticket_domain_id IS NOT NULL)),
  CHECK (parent_id IS NOT NULL OR org_unit_id IS NOT NULL),
  CHECK (first_response_hours IS NULL OR sla_hours IS NULL OR first_response_hours <= sla_hours)
);
