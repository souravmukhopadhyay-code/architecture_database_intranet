  FROM tms.ticket_category c JOIN t ON c.parent_id = t.id JOIN ref.tms_category_level l ON l.id = c.category_level_id)
SELECT t.id AS category_id, t.root_id, t.ticket_domain_id, d.code AS ticket_domain, t.responsible_org_unit_id,
