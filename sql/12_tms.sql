-- The state of every ticket, from the latest event of each kind:
--   classification  the last transfer, else as raised (category, priority, route)
--   status          last event that sets a status
--   assignee        last event that (re)assigns: person, route level, or forum
--   clock           last event that starts / pauses / stops the clock:
--                   RUNNING (a due time), PAUSED (minutes left), STOPPED
--   resolution      last event (since the last reopen) that awaits the requester
--   closure reason  of the closing event, else of the resolution it closed
--   rating          a rating given after the last reopen
CREATE OR REPLACE VIEW tms.v_ticket_state AS
SELECT t.id AS ticket_id, t.request_no, t.requester_account_id, t.requester_org_unit_id, t.raised_by_account_id, t.is_anonymous,
       t.created_at, t.raised_category_id,
       COALESCE(tr.category_id, t.raised_category_id) AS category_id,
       COALESCE(tr.priority_id, t.priority_id) AS priority_id,
       CASE WHEN tr.category_id IS NOT NULL THEN tr.route_id ELSE t.route_id END AS route_id,
       t.message_type_id, mt.is_grievance,
       vc.ticket_domain_id, vc.ticket_domain, vc.category_type_id, vc.category_type, vc.responsible_org_unit_id,
       vc.root_id, vc.kra_type_id, vc.master_id, vc.grievance_head_id, vc.redressal_forum_id AS category_forum_id,
       (vc.is_confidential OR COALESCE(fx.any_confidential, false)) AS is_confidential,
       (t.requested_assignee_employee_id IS NOT NULL) AS is_manual_assignment,
       ts.code AS status, COALESCE(ts.is_closed, false) AS is_closed, COALESCE(ts.awaits_requester, false) AS awaits_requester,
       st.occurred_at AS status_since,
       asg.assignee_employee_id, asg.level_id, asg.level_category_id, asg.forum_id, asg.academic_body_id,
       CASE WHEN ck.pauses_clock THEN 'PAUSED'
            WHEN ck.starts_clock AND ck.due_at IS NOT NULL THEN 'RUNNING'
            ELSE 'STOPPED' END AS clock_state,
       ck.id AS clock_event_id, ck.code AS clock_event, ck.occurred_at AS clock_since,
       CASE WHEN ck.starts_clock THEN ck.due_at END AS due_at,
       CASE WHEN ck.pauses_clock THEN ck.sla_remaining_minutes END AS paused_remaining_minutes,
       CASE WHEN asg.forum_id IS NOT NULL THEN f.counts_office_days ELSE tms.sla_office(p.id, vc.category_id) END AS clock_is_office,
       COALESCE(NOT ts.is_closed AND ck.starts_clock AND ck.due_at <= now(), false) AS is_overdue,
       rs.occurred_at AS resolved_at, rs.actor_account_id AS resolved_by_account_id, rs.code AS resolution_event,
       rs.closure_reason_id AS resolution_reason_id, rs.redressal_outcome_id,
       CASE WHEN ts.is_closed THEN st.occurred_at END AS closed_at,
       CASE WHEN ts.is_closed THEN COALESCE(st.closure_reason_id, rs.closure_reason_id) END AS closure_reason_id,
       rt.rating,
       COALESCE(n.escalation_count, 0) AS escalation_count, COALESCE(n.reopen_count, 0) AS reopen_count,
       COALESCE(fx.referral_count, 0) AS referral_count,
       mg.related_ticket_id AS merged_into_ticket_id,
       n.last_event_at
FROM tms.ticket t
JOIN ref.tms_message_type mt ON mt.id = t.message_type_id
LEFT JOIN LATERAL (SELECT e.category_id, e.priority_id, e.route_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'TRANSFERRED'
                   WHERE e.ticket_id = t.id ORDER BY e.id DESC LIMIT 1) tr ON true
JOIN tms.v_ticket_category vc ON vc.category_id = COALESCE(tr.category_id, t.raised_category_id)
JOIN ref.tms_priority p ON p.id = COALESCE(tr.priority_id, t.priority_id)
LEFT JOIN LATERAL (SELECT e.occurred_at, et.sets_status_id, et.closure_reason_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.sets_status_id IS NOT NULL
                   WHERE e.ticket_id = t.id ORDER BY e.id DESC LIMIT 1) st ON true
LEFT JOIN ref.tms_ticket_status ts ON ts.id = st.sets_status_id
LEFT JOIN LATERAL (SELECT e.assignee_employee_id, e.level_id, e.level_category_id, e.forum_id, e.academic_body_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.sets_assignee
                   WHERE e.ticket_id = t.id ORDER BY e.id DESC LIMIT 1) asg ON true
LEFT JOIN tms.redressal_forum f ON f.id = asg.forum_id
LEFT JOIN LATERAL (SELECT e.id, et.code, e.occurred_at, e.due_at, e.sla_remaining_minutes, et.starts_clock, et.pauses_clock, et.stops_clock FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND (et.starts_clock OR et.pauses_clock OR et.stops_clock)
                   WHERE e.ticket_id = t.id ORDER BY e.id DESC LIMIT 1) ck ON true
LEFT JOIN LATERAL (SELECT max(e.id) AS reopened_event_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'REOPENED'
                   WHERE e.ticket_id = t.id) ro ON true
LEFT JOIN LATERAL (SELECT e.occurred_at, e.actor_account_id, et.code, et.closure_reason_id, e.redressal_outcome_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id
                   JOIN ref.tms_ticket_status s2 ON s2.id = et.sets_status_id AND s2.awaits_requester
                   WHERE e.ticket_id = t.id AND e.id > COALESCE(ro.reopened_event_id, 0)
                   ORDER BY e.id DESC LIMIT 1) rs ON true
LEFT JOIN LATERAL (SELECT e.rating FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'RATED'
                   WHERE e.ticket_id = t.id AND e.id > COALESCE(ro.reopened_event_id, 0)
                   ORDER BY e.id DESC LIMIT 1) rt ON true
LEFT JOIN LATERAL (SELECT count(*) AS referral_count, bool_or(rf.is_confidential) AS any_confidential FROM tms.ticket_event e
                   JOIN tms.redressal_forum rf ON rf.id = e.forum_id
                   WHERE e.ticket_id = t.id) fx ON true
LEFT JOIN LATERAL (SELECT count(*) FILTER (WHERE et.code IN ('ESCALATED', 'AUTO_ESCALATED')) AS escalation_count,
                          count(*) FILTER (WHERE et.code = 'REOPENED') AS reopen_count,
                          max(e.occurred_at) AS last_event_at
                   FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id
                   WHERE e.ticket_id = t.id) n ON true
LEFT JOIN LATERAL (SELECT e.related_ticket_id FROM tms.ticket_event e
                   JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'MERGED'
                   WHERE e.ticket_id = t.id ORDER BY e.id DESC LIMIT 1) mg ON true;

-- ################################################################ ROUTING ##

-- Round-robin: among the leaf's active, workable handlers serving the
-- requester's unit (the most specific scope that has anyone), never the
-- requester or a respondent, the next one after whoever got the leaf's last
-- round-robin ticket in that pool. Serialised per leaf (row lock).
CREATE OR REPLACE FUNCTION tms.round_robin(p_leaf uuid, p_ticket uuid)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE v_unit uuid; v_req uuid; v_pool uuid[]; v_last uuid; v_idx int;
BEGIN
  SELECT t.requester_org_unit_id, tms.person_of_account(t.requester_account_id) INTO v_unit, v_req FROM tms.ticket t WHERE t.id = p_ticket;
  PERFORM 1 FROM tms.ticket_category WHERE id = p_leaf FOR UPDATE;
  WITH c AS (
    SELECT h.employee_id, h.sort_order, CASE WHEN h.org_unit_id IS NULL THEN 32767 ELSE a.depth END AS dist
    FROM tms.ticket_category_handler h
    JOIN people.employee e ON e.id = h.employee_id
    LEFT JOIN org.ancestors(v_unit) a ON a.org_unit_id = h.org_unit_id
    WHERE h.category_id = p_leaf AND h.is_active AND (h.org_unit_id IS NULL OR a.org_unit_id IS NOT NULL)
      AND tms.is_workable(h.employee_id) AND e.person_id IS DISTINCT FROM v_req
      AND NOT tms.is_respondent(p_ticket, e.person_id))
  SELECT array_agg(c.employee_id ORDER BY c.sort_order, c.employee_id) INTO v_pool
  FROM c WHERE c.dist = (SELECT min(c2.dist) FROM c c2);
  IF v_pool IS NULL THEN RETURN NULL; END IF;
  SELECT e.assignee_employee_id INTO v_last FROM tms.ticket_event e
  WHERE e.level_category_id = p_leaf AND e.assignment_basis_id = ref.id_of('tms_assignment_basis', 'ROUND_ROBIN')
    AND e.assignee_employee_id = ANY (v_pool)
  ORDER BY e.id DESC LIMIT 1;
  v_idx := array_position(v_pool, v_last);
  RETURN v_pool[CASE WHEN v_idx IS NULL THEN 1 ELSE v_idx % array_length(v_pool, 1) + 1 END];
END $$;

-- Who holds a (non-pool) route level for a ticket in a leaf, before the
-- workable / requester / respondent filters. For a pool level: the leaf.
CREATE OR REPLACE FUNCTION tms.level_holder(p_ticket uuid, p_level smallint, p_leaf uuid)
RETURNS TABLE (employee_id uuid, category_id uuid) LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE l record; v_req uuid; v_unit uuid; v_base uuid; v_emp uuid; v_cat uuid; i int;
BEGIN
  SELECT rl.*, k.code AS kind, b.code AS base INTO l
  FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id
  LEFT JOIN ref.tms_anchor_base b ON b.id = rl.anchor_base_id
  WHERE rl.id = p_level;
  SELECT tms.person_of_account(t.requester_account_id), t.requester_org_unit_id INTO v_req, v_unit FROM tms.ticket t WHERE t.id = p_ticket;
  CASE l.kind
    WHEN 'HANDLER_POOL' THEN
      v_cat := p_leaf;
    WHEN 'CATEGORY_OWNER' THEN
      SELECT a.category_id INTO v_cat FROM tms.category_ancestors(p_leaf) a JOIN tms.ticket_category c ON c.id = a.category_id
      WHERE c.category_level_id = l.category_level_id LIMIT 1;
      SELECT o.employee_id INTO v_emp FROM tms.ticket_category_owner o WHERE o.category_id = v_cat AND o.valid @> current_date;
    WHEN 'MENTOR' THEN
      SELECT sm.employee_id INTO v_emp FROM people.student_mentor sm JOIN people.student s ON s.id = sm.student_id
      WHERE s.person_id = v_req AND sm.valid @> current_date LIMIT 1;
    WHEN 'REPORTING_MANAGER' THEN
      SELECT e.id INTO v_emp FROM people.employee e WHERE e.person_id = v_req LIMIT 1;
      FOR i IN 1 .. l.manager_level LOOP
        EXIT WHEN v_emp IS NULL;
        SELECT r.manager_employee_id INTO v_emp FROM people.employee_reporting_line r
        WHERE r.employee_id = v_emp AND r.reporting_line_type_id = l.reporting_line_type_id AND r.valid @> current_date;
      END LOOP;
    WHEN 'POSITION' THEN
      v_base := CASE l.base WHEN 'REQUESTER_UNIT' THEN v_unit
                            WHEN 'CATEGORY_UNIT'  THEN (SELECT vc.responsible_org_unit_id FROM tms.v_ticket_category vc WHERE vc.category_id = p_leaf)
                            ELSE l.org_unit_id END;
      IF l.anchor_org_unit_type_id IS NOT NULL THEN
        SELECT a.org_unit_id INTO v_base FROM org.ancestors(v_base) a JOIN org.org_unit u ON u.id = a.org_unit_id
        WHERE u.org_unit_type_id = l.anchor_org_unit_type_id ORDER BY a.depth LIMIT 1;
      END IF;
      SELECT ap.employee_id INTO v_emp FROM org.appointment ap
      WHERE ap.org_unit_id = v_base AND ap.position_type_id = l.position_type_id AND ap.valid @> current_date;
    WHEN 'NAMED' THEN
      v_emp := l.employee_id;
    ELSE NULL;
  END CASE;
  employee_id := v_emp; category_id := v_cat;
  RETURN NEXT;
END $$;

-- The person a level would give the ticket to now: the pool's next handler,
-- or the holder if they can work, are not the requester and are not named
-- in the complaint. No row / NULL = the level is skipped.
CREATE OR REPLACE FUNCTION tms.level_candidate(p_ticket uuid, p_level smallint, p_leaf uuid)
RETURNS TABLE (employee_id uuid, category_id uuid) LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE h record; v_req uuid;
BEGIN
  SELECT * INTO h FROM tms.level_holder(p_ticket, p_level, p_leaf);
  IF (SELECT k.code FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id WHERE rl.id = p_level) = 'HANDLER_POOL' THEN
    employee_id := tms.round_robin(h.category_id, p_ticket); category_id := h.category_id;
    RETURN NEXT; RETURN;
  END IF;
  SELECT tms.person_of_account(t.requester_account_id) INTO v_req FROM tms.ticket t WHERE t.id = p_ticket;
  IF h.employee_id IS NOT NULL AND tms.is_workable(h.employee_id)
     AND tms.person_of_employee(h.employee_id) IS DISTINCT FROM v_req
     AND NOT tms.is_respondent(p_ticket, tms.person_of_employee(h.employee_id)) THEN
    employee_id := h.employee_id; category_id := h.category_id;
    RETURN NEXT;
  END IF;
END $$;

-- The first level of a route after p_after_seq that gives the ticket to
-- someone (other than p_skip_employee). No row = nobody left on the route.
CREATE OR REPLACE FUNCTION tms.walk_route(p_ticket uuid, p_route smallint, p_leaf uuid, p_after_seq smallint, p_skip_employee uuid)
RETURNS TABLE (employee_id uuid, level_id smallint, level_category_id uuid) LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE r record; c record; v_skip uuid := tms.person_of_employee(p_skip_employee);
BEGIN
  FOR r IN SELECT rl.id FROM tms.ticket_route_level rl WHERE rl.route_id = p_route AND rl.seq > COALESCE(p_after_seq, 0) ORDER BY rl.seq LOOP
    SELECT * INTO c FROM tms.level_candidate(p_ticket, r.id, p_leaf);
    IF c.employee_id IS NOT NULL AND (v_skip IS NULL OR tms.person_of_employee(c.employee_id) <> v_skip) THEN
      employee_id := c.employee_id; level_id := r.id; level_category_id := c.category_id;
      RETURN NEXT; RETURN;
    END IF;
  END LOOP;
END $$;

-- Where an escalation takes the ticket: the next level of its route above
-- the current one that gives it to someone else.
CREATE OR REPLACE FUNCTION tms.next_escalation(p_ticket uuid)
RETURNS TABLE (employee_id uuid, level_id smallint, level_category_id uuid) LANGUAGE plpgsql AS $$
#variable_conflict use_column
DECLARE s record; v_seq smallint;
BEGIN
  SELECT st.route_id, st.category_id, st.level_id, st.assignee_employee_id INTO s FROM tms.v_ticket_state st WHERE st.ticket_id = p_ticket;
  SELECT rl.seq INTO v_seq FROM tms.ticket_route_level rl WHERE rl.id = s.level_id AND rl.route_id = s.route_id;
  RETURN QUERY SELECT w.employee_id, w.level_id, w.level_category_id
               FROM tms.walk_route(p_ticket, s.route_id, s.category_id, COALESCE(v_seq, 0)::smallint, s.assignee_employee_id) w;
END $$;

-- The route level a manually chosen assignee stands at: a handler of the
-- leaf serving the requester's unit → the route's first pool level; the
-- owner of a node above → the CATEGORY_OWNER level for that node's level.
CREATE OR REPLACE FUNCTION tms.manual_level(p_route smallint, p_leaf uuid, p_unit uuid, p_employee uuid)
RETURNS TABLE (level_id smallint, category_id uuid) LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE v_level smallint; v_cat uuid;
BEGIN
  IF EXISTS (SELECT 1 FROM tms.ticket_category_handler h LEFT JOIN org.ancestors(p_unit) a ON a.org_unit_id = h.org_unit_id
             WHERE h.category_id = p_leaf AND h.employee_id = p_employee AND h.is_active
               AND (h.org_unit_id IS NULL OR a.org_unit_id IS NOT NULL)) THEN
    SELECT rl.id INTO v_level FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id AND k.code = 'HANDLER_POOL'
    WHERE rl.route_id = p_route ORDER BY rl.seq LIMIT 1;
    v_cat := p_leaf;
  ELSE
    SELECT rl.id, a.category_id INTO v_level, v_cat
    FROM tms.category_ancestors(p_leaf) a
    JOIN tms.ticket_category c ON c.id = a.category_id
    JOIN tms.ticket_category_owner o ON o.category_id = c.id AND o.valid @> current_date AND o.employee_id = p_employee
    JOIN tms.ticket_route_level rl ON rl.route_id = p_route AND rl.category_level_id = c.category_level_id
    JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id AND k.code = 'CATEGORY_OWNER'
    ORDER BY a.depth, rl.seq LIMIT 1;
  END IF;
  IF v_level IS NOT NULL THEN
    level_id := v_level; category_id := v_cat;
    RETURN NEXT;
  END IF;
END $$;

-- ################################################################# FORUMS ##

-- The body or holder of a forum that hears a requester of p_unit: the
-- nearest active body of the forum's type (or appointed holder of its
-- position) at the unit or above it — at a unit of the anchor type, if set.
CREATE OR REPLACE FUNCTION tms.forum_seat(p_forum smallint, p_unit uuid)
RETURNS TABLE (academic_body_id uuid, employee_id uuid) LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE f tms.redressal_forum; v_body uuid; v_emp uuid;
BEGIN
  SELECT * INTO f FROM tms.redressal_forum WHERE id = p_forum;
  IF f.academic_body_type_id IS NOT NULL THEN
    SELECT b.id INTO v_body FROM org.ancestors(p_unit) a
    JOIN org.org_unit u ON u.id = a.org_unit_id
    JOIN academic.academic_body b ON b.org_unit_id = a.org_unit_id AND b.academic_body_type_id = f.academic_body_type_id AND b.is_active
    WHERE f.anchor_org_unit_type_id IS NULL OR u.org_unit_type_id = f.anchor_org_unit_type_id
    ORDER BY a.depth LIMIT 1;
    IF v_body IS NOT NULL THEN academic_body_id := v_body; employee_id := NULL; RETURN NEXT; END IF;
  ELSE
    SELECT ap.employee_id INTO v_emp FROM org.ancestors(p_unit) a
    JOIN org.org_unit u ON u.id = a.org_unit_id
    JOIN org.appointment ap ON ap.org_unit_id = a.org_unit_id AND ap.position_type_id = f.position_type_id AND ap.valid @> current_date
    WHERE f.anchor_org_unit_type_id IS NULL OR u.org_unit_type_id = f.anchor_org_unit_type_id
    ORDER BY a.depth LIMIT 1;
    IF v_emp IS NOT NULL AND tms.is_workable(v_emp) THEN academic_body_id := NULL; employee_id := v_emp; RETURN NEXT; END IF;
  END IF;
END $$;

-- Is the account a current member of the committee (or the holder) the
-- ticket is with — and not named in the complaint?
CREATE OR REPLACE FUNCTION tms.is_forum_member(p_account uuid, p_ticket uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE s record; v_person uuid;
BEGIN
  SELECT forum_id, academic_body_id, assignee_employee_id INTO s FROM tms.v_ticket_state WHERE ticket_id = p_ticket;
  IF s.forum_id IS NULL OR NOT tms.can_login(p_account) THEN RETURN false; END IF;
  v_person := tms.person_of_account(p_account);
  IF tms.is_respondent(p_ticket, v_person) THEN RETURN false; END IF;
  IF s.academic_body_id IS NOT NULL THEN
    RETURN EXISTS (SELECT 1 FROM academic.academic_body_member m LEFT JOIN people.employee e ON e.id = m.employee_id
                   WHERE m.academic_body_id = s.academic_body_id AND m.valid @> current_date
                     AND COALESCE(m.external_person_id, e.person_id) = v_person);
  END IF;
  RETURN v_person = tms.person_of_employee(s.assignee_employee_id);
END $$;

-- ################################################################# ACCESS ##

-- The domain's switch: student tickets exist only while Student TMS is on,
-- employee tickets while Employee TMS is on.
CREATE OR REPLACE FUNCTION tms.domain_is_open(p_domain smallint)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT CASE d.code WHEN 'STUDENT'  THEN (SELECT student_tms_enabled FROM tms.helpdesk_setting WHERE id)
                     WHEN 'EMPLOYEE' THEN (SELECT employee_tms_enabled FROM tms.helpdesk_setting WHERE id)
                     ELSE true END
  FROM ref.tms_ticket_domain d WHERE d.id = p_domain;
$$;

-- May this account act on the ticket (reply, note, ask for clarification,
-- escalate, reassign, transfer, refer, resolve)?
--   with a forum   its members (or holder) alone
--   otherwise      the current assignee; and — unless the ticket is
--                  confidential — a holder of the domain's update permission
--                  at the responsible unit or the requester's unit, the KRA
--                  head of the ticket's tree, an overseeing level's holder.
-- Never a person named in the complaint.
CREATE OR REPLACE FUNCTION tms.can_act(p_account uuid, p_ticket uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE s record; v_person uuid; v_perm text;
BEGIN
  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = p_ticket;
  IF NOT FOUND OR NOT tms.domain_is_open(s.ticket_domain_id) OR NOT tms.can_login(p_account) THEN RETURN false; END IF;
  v_person := tms.person_of_account(p_account);
  IF tms.is_respondent(p_ticket, v_person) THEN RETURN false; END IF;
  IF s.forum_id IS NOT NULL THEN RETURN tms.is_forum_member(p_account, p_ticket); END IF;
  IF v_person = tms.person_of_employee(s.assignee_employee_id) THEN RETURN true; END IF;
  IF s.is_confidential THEN RETURN false; END IF;
  SELECT pc.code INTO v_perm FROM ref.tms_ticket_domain d JOIN authz.v_permission_code pc ON pc.permission_id = d.update_permission_id
  WHERE d.id = s.ticket_domain_id;
  RETURN authz.has_permission(p_account, v_perm, s.responsible_org_unit_id)
      OR (s.requester_org_unit_id IS NOT NULL AND authz.has_permission(p_account, v_perm, s.requester_org_unit_id))
      OR (s.kra_type_id IS NOT NULL AND EXISTS (
            SELECT 1 FROM tms.ticket_category_owner o JOIN people.employee e ON e.id = o.employee_id
            WHERE o.category_id = s.kra_type_id AND o.valid @> current_date AND e.person_id = v_person))
      OR EXISTS (SELECT 1 FROM tms.ticket_route_level l
                 CROSS JOIN LATERAL tms.level_holder(p_ticket, l.id, s.category_id) h
                 WHERE l.route_id = s.route_id AND l.oversees AND tms.person_of_employee(h.employee_id) = v_person);
END $$;

-- May this account see the ticket? Never a respondent. The requester; anyone
-- who may act; anyone who took part (acted, was assigned, sat on a forum
-- that heard it); the requester of a ticket merged into it. Beyond those, a
-- confidential ticket only with tms.confidential_ticket.view; any other with
-- the domain's view permission at the responsible or the requester's unit,
-- as the owner of a node above it, or as the holder of a level of its route.
CREATE OR REPLACE FUNCTION tms.can_view(p_account uuid, p_ticket uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE s record; v_person uuid; v_perm text;
BEGIN
  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = p_ticket;
  IF NOT FOUND OR NOT tms.domain_is_open(s.ticket_domain_id) THEN RETURN false; END IF;
  v_person := tms.person_of_account(p_account);
  IF tms.is_respondent(p_ticket, v_person) THEN RETURN false; END IF;
  IF s.requester_account_id = p_account OR tms.can_act(p_account, p_ticket)
     OR EXISTS (SELECT 1 FROM tms.ticket_event e
                LEFT JOIN people.employee em ON em.id = e.assignee_employee_id
                LEFT JOIN people.employee ce ON ce.id = e.consulted_employee_id
                WHERE e.ticket_id = p_ticket AND (e.actor_account_id = p_account OR em.person_id = v_person OR ce.person_id = v_person))
     OR EXISTS (SELECT 1 FROM tms.ticket_event e
                JOIN academic.academic_body_member m ON m.academic_body_id = e.academic_body_id AND m.valid @> current_date
                LEFT JOIN people.employee em ON em.id = m.employee_id
                WHERE e.ticket_id = p_ticket AND COALESCE(m.external_person_id, em.person_id) = v_person)
     OR EXISTS (SELECT 1 FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.code = 'MERGED'
                JOIN tms.ticket t ON t.id = e.ticket_id
                WHERE e.related_ticket_id = p_ticket AND t.requester_account_id = p_account) THEN
    RETURN true;
  END IF;
  IF s.is_confidential THEN
    RETURN authz.has_permission(p_account, 'tms.confidential_ticket.view', NULL);
  END IF;
  SELECT pc.code INTO v_perm FROM ref.tms_ticket_domain d JOIN authz.v_permission_code pc ON pc.permission_id = d.view_permission_id
  WHERE d.id = s.ticket_domain_id;
  RETURN authz.has_permission(p_account, v_perm, s.responsible_org_unit_id)
      OR (s.requester_org_unit_id IS NOT NULL AND authz.has_permission(p_account, v_perm, s.requester_org_unit_id))
      OR EXISTS (SELECT 1 FROM tms.category_ancestors(s.category_id) a
                 JOIN tms.ticket_category_owner o ON o.category_id = a.category_id AND o.valid @> current_date
                 JOIN people.employee e ON e.id = o.employee_id
                 WHERE e.person_id = v_person)
      OR EXISTS (SELECT 1 FROM tms.ticket_route_level l
                 CROSS JOIN LATERAL tms.level_holder(p_ticket, l.id, s.category_id) h
                 WHERE l.route_id = s.route_id AND tms.person_of_employee(h.employee_id) = v_person);
END $$;

-- May this account see who raised the ticket? Always, unless it was raised
-- anonymously — then only the requester and holders of tms.anonymous_identity.view.
CREATE OR REPLACE FUNCTION tms.requester_shown_to(p_account uuid, p_ticket uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT NOT t.is_anonymous OR t.requester_account_id = p_account
         OR authz.has_permission(p_account, 'tms.anonymous_identity.view', NULL)
  FROM tms.ticket t WHERE t.id = p_ticket;
$$;

-- Who reports that a forum's decision has been carried out: a member of the
-- forum that decided, the last helpdesk assignee (the office that handled
-- it), or a holder of the domain's update permission at the responsible unit.
CREATE OR REPLACE FUNCTION tms.can_report_compliance(p_account uuid, p_ticket uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE s record; v_person uuid; v_perm text; v_last uuid;
BEGIN
  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = p_ticket;
  IF NOT FOUND OR NOT tms.domain_is_open(s.ticket_domain_id) OR NOT tms.can_login(p_account) THEN RETURN false; END IF;
  v_person := tms.person_of_account(p_account);
  IF tms.is_respondent(p_ticket, v_person) OR v_person = tms.person_of_account(s.requester_account_id) THEN RETURN false; END IF;
  IF tms.is_forum_member(p_account, p_ticket) THEN RETURN true; END IF;
  SELECT e.assignee_employee_id INTO v_last FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id AND et.sets_assignee
  WHERE e.ticket_id = p_ticket AND e.forum_id IS NULL AND e.assignee_employee_id IS NOT NULL ORDER BY e.id DESC LIMIT 1;
  IF v_person = tms.person_of_employee(v_last) THEN RETURN true; END IF;
  SELECT pc.code INTO v_perm FROM ref.tms_ticket_domain d JOIN authz.v_permission_code pc ON pc.permission_id = d.update_permission_id
  WHERE d.id = s.ticket_domain_id;
  RETURN authz.has_permission(p_account, v_perm, s.responsible_org_unit_id);
END $$;

-- May the account download this file? It must be attached to a ticket the
-- account can see; a requester (or follower) who cannot act sees only the
-- files of entries shown to the requester, never those of internal notes.
CREATE OR REPLACE FUNCTION tms.can_download(p_account uuid, p_file uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE r record;
BEGIN
  FOR r IN SELECT e.ticket_id, et.shown_to_requester, t.requester_account_id
           FROM tms.ticket_event_file f
           JOIN tms.ticket_event e ON e.id = f.ticket_event_id
           JOIN ref.tms_event_type et ON et.id = e.event_type_id
           JOIN tms.ticket t ON t.id = e.ticket_id
           WHERE f.file_object_id = p_file LOOP
    IF tms.can_view(p_account, r.ticket_id)
       AND (r.shown_to_requester
            OR tms.can_act(p_account, r.ticket_id)
            OR (p_account <> r.requester_account_id
                AND NOT EXISTS (SELECT 1 FROM tms.ticket_event m JOIN ref.tms_event_type mt ON mt.id = m.event_type_id AND mt.code = 'MERGED'
                                JOIN tms.ticket mt2 ON mt2.id = m.ticket_id
                                WHERE m.related_ticket_id = r.ticket_id AND mt2.requester_account_id = p_account))) THEN
      RETURN true;
    END IF;
  END LOOP;
  RETURN false;
END $$;

-- Who may be chosen as the assignee of a ticket in a leaf for a requester
-- (the old assignee search): handlers of the leaf serving the requester's
-- unit and owners on the leaf's route, able to work, not the requester.
CREATE OR REPLACE FUNCTION tms.eligible_assignees(p_leaf uuid, p_requester_account uuid)
RETURNS TABLE (employee_id uuid, level_id smallint, level_category_id uuid) LANGUAGE plpgsql STABLE AS $$
#variable_conflict use_column
DECLARE v_unit uuid; v_route smallint; v_req uuid := tms.person_of_account(p_requester_account);
BEGIN
  SELECT vc.route_id INTO v_route FROM tms.v_ticket_category vc WHERE vc.category_id = p_leaf;
  SELECT k.home_org_unit_id INTO v_unit FROM people.v_person_principal_kind k
  JOIN ref.tms_ticket_domain d ON d.principal_kind_id = k.principal_kind_id
  JOIN tms.v_ticket_category vc ON vc.ticket_domain_id = d.id AND vc.category_id = p_leaf
  WHERE k.person_id = v_req LIMIT 1;
  RETURN QUERY
  SELECT c.emp, m.level_id, m.category_id
  FROM (SELECT h.employee_id AS emp FROM tms.ticket_category_handler h WHERE h.category_id = p_leaf AND h.is_active
        UNION
        SELECT o.employee_id FROM tms.category_ancestors(p_leaf) a JOIN tms.ticket_category_owner o ON o.category_id = a.category_id
        WHERE o.valid @> current_date AND a.depth > 0) c
  CROSS JOIN LATERAL tms.manual_level(v_route, p_leaf, v_unit, c.emp) m
  WHERE tms.is_workable(c.emp) AND tms.person_of_employee(c.emp) IS DISTINCT FROM v_req
  ORDER BY m.level_id, c.emp;
END $$;

-- ###################################################### TICKET VALIDATION ##

-- Raising: the leaf is active and configured (a route, or straight to a
-- forum), the requester is a current principal of the domain with its create
-- permission (or an intake desk records it for them with tms.intake.create at
-- their unit), the message type fits, and every field the category, the
-- message type and the domain's declaration require is there. Number,
-- priority, route and the requester's unit are filled in. Tickets never change.
CREATE OR REPLACE FUNCTION tms.ticket_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_cat record; v_dom ref.tms_ticket_domain; v_person uuid; v_msg ref.tms_message_type; v_chan ref.tms_intake_channel;
        v_decl uuid; c tms.helpdesk_setting := tms.config(); v_route tms.ticket_route; v_dup citext; v_year smallint; v_no int;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'tms.ticket: a raised ticket is never edited or deleted — record what happens as a ticket_event'
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO v_cat FROM tms.v_ticket_category WHERE category_id = NEW.raised_category_id;
  IF NOT v_cat.is_leaf THEN
    RAISE EXCEPTION 'tms.ticket: raise the ticket under a leaf category' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT v_cat.effective_active THEN
    RAISE EXCEPTION 'tms.ticket: the category is inactive' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT v_cat.allows_raising THEN
    RAISE EXCEPTION 'tms.ticket: the category is for internal use (reached by transfer), not for raising tickets' USING ERRCODE = 'check_violation';
  END IF;
  SELECT * INTO v_dom FROM ref.tms_ticket_domain WHERE id = v_cat.ticket_domain_id;
  IF NOT tms.domain_is_open(v_dom.id) THEN
    RAISE EXCEPTION 'tms.ticket: Student TMS is switched off' USING ERRCODE = 'insufficient_privilege';
  END IF;
  v_person := tms.person_of_account(NEW.requester_account_id);
  SELECT k.home_org_unit_id INTO NEW.requester_org_unit_id FROM people.v_person_principal_kind k
  WHERE k.person_id = v_person AND k.principal_kind_id = v_dom.principal_kind_id ORDER BY k.home_org_unit_id NULLS LAST LIMIT 1;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'tms.ticket: only a current % may raise a % ticket', lower((SELECT code FROM ref.principal_kind WHERE id = v_dom.principal_kind_id)), lower(v_dom.code)
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NOT authz.has_permission(NEW.requester_account_id, (SELECT code FROM authz.v_permission_code WHERE permission_id = v_dom.create_permission_id), NULL) THEN
    RAISE EXCEPTION 'tms.ticket: the account may not raise % tickets', lower(v_dom.code) USING ERRCODE = 'insufficient_privilege';
  END IF;
  -- intake
  NEW.intake_channel_id := COALESCE(NEW.intake_channel_id, ref.id_of('tms_intake_channel', 'PORTAL'));
  SELECT * INTO v_chan FROM ref.tms_intake_channel WHERE id = NEW.intake_channel_id;
  IF NEW.raised_by_account_id IS NULL AND NOT v_chan.is_self_service THEN
    RAISE EXCEPTION 'tms.ticket: a ticket received by % is recorded by the intake desk (raised_by)', lower(v_chan.label) USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.raised_by_account_id IS NOT NULL THEN
    IF v_chan.is_self_service THEN
      RAISE EXCEPTION 'tms.ticket: an intake desk records walk-in, phone, e-mail or letter tickets, not portal ones' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT tms.can_login(NEW.raised_by_account_id)
       OR NOT authz.has_permission(NEW.raised_by_account_id, 'tms.intake.create', NEW.requester_org_unit_id) THEN
      RAISE EXCEPTION 'tms.ticket: the account may not record tickets for this requester' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  -- what is being raised
  SELECT * INTO v_msg FROM ref.tms_message_type WHERE id = NEW.message_type_id;
  IF (v_dom.code = 'STUDENT' AND NOT v_msg.for_student) OR (v_dom.code = 'EMPLOYEE' AND NOT v_msg.for_employee) THEN
    RAISE EXCEPTION 'tms.ticket: message type % is not used for % tickets', v_msg.code, lower(v_dom.code) USING ERRCODE = 'check_violation';
  END IF;
  IF v_cat.direct_to_forum THEN
    IF v_cat.redressal_forum_id IS NULL THEN
      RAISE EXCEPTION 'tms.ticket: the category goes straight to a forum but none is configured' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT v_msg.is_grievance THEN
      RAISE EXCEPTION 'tms.ticket: a complaint filed with % must be a grievance', (SELECT label FROM tms.redressal_forum WHERE id = v_cat.redressal_forum_id)
        USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.requested_assignee_employee_id IS NOT NULL THEN
      RAISE EXCEPTION 'tms.ticket: nobody is chosen for a complaint that goes to a forum' USING ERRCODE = 'check_violation';
    END IF;
  ELSE
    SELECT * INTO v_route FROM tms.ticket_route WHERE id = v_cat.route_id;
    IF NOT FOUND OR NOT v_route.is_active THEN
      RAISE EXCEPTION 'tms.ticket: no active route is configured for this category' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  IF NEW.is_anonymous AND NOT v_cat.allows_anonymous THEN
    RAISE EXCEPTION 'tms.ticket: this category does not take anonymous tickets' USING ERRCODE = 'check_violation';
  END IF;
  IF v_msg.requires_relief AND COALESCE(btrim(NEW.relief_sought), '') = '' THEN
    RAISE EXCEPTION 'tms.ticket: a % states the relief sought', lower(v_msg.label) USING ERRCODE = 'check_violation';
  END IF;
  IF v_cat.requires_incident_date AND NEW.incident_on IS NULL THEN
    RAISE EXCEPTION 'tms.ticket: this category needs the date of the incident' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.incident_on > (clock_timestamp() AT TIME ZONE c.time_zone)::date THEN
    RAISE EXCEPTION 'tms.ticket: the incident date is in the future' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.contact_phone_id IS NULL OR NOT EXISTS (SELECT 1 FROM pii.person_phone WHERE id = NEW.contact_phone_id AND person_id = v_person) THEN
    RAISE EXCEPTION 'tms.ticket: the contact number must be one of the requester''s own phone numbers' USING ERRCODE = 'check_violation';
  END IF;
  SELECT d.id INTO v_decl FROM tms.helpdesk_declaration d WHERE d.ticket_domain_id = v_dom.id AND d.valid @> (clock_timestamp() AT TIME ZONE c.time_zone)::date;
  IF NEW.declaration_id IS DISTINCT FROM v_decl THEN
    RAISE EXCEPTION 'tms.ticket: %', CASE WHEN v_decl IS NULL THEN 'no declaration is in force for this domain'
                                          ELSE 'the requester must accept the declaration in force' END
      USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.requested_assignee_employee_id IS NOT NULL THEN
    IF NOT authz.has_permission(NEW.requester_account_id, 'tms.employee_ticket.assign', NULL) OR v_dom.code <> 'EMPLOYEE' THEN
      RAISE EXCEPTION 'tms.ticket: the requester may not choose the assignee' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF tms.person_of_employee(NEW.requested_assignee_employee_id) = v_person THEN
      RAISE EXCEPTION 'tms.ticket: a ticket cannot be assigned to its own requester' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT tms.is_workable(NEW.requested_assignee_employee_id) THEN
      RAISE EXCEPTION 'tms.ticket: the chosen assignee cannot take tickets now' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM tms.manual_level(v_cat.route_id, NEW.raised_category_id, NEW.requester_org_unit_id, NEW.requested_assignee_employee_id)) THEN
      RAISE EXCEPTION 'tms.ticket: the chosen assignee is neither a handler of this category nor an owner on its route' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  NEW.created_at := clock_timestamp();
  -- no subject given: the start of the description (old employee form)
  NEW.subject := COALESCE(NULLIF(btrim(NEW.subject), ''), left(regexp_replace(btrim(NEW.description), '\s+', ' ', 'g'), 256));
  -- the same requester, leaf and text within a few seconds is a double submission
  IF c.duplicate_window_seconds > 0 THEN
    SELECT t.request_no INTO v_dup FROM tms.ticket t
    WHERE t.requester_account_id = NEW.requester_account_id AND t.raised_category_id = NEW.raised_category_id
      AND btrim(t.description) = btrim(NEW.description)
      AND t.created_at > NEW.created_at - make_interval(secs => c.duplicate_window_seconds)
    ORDER BY t.created_at DESC LIMIT 1;
    IF v_dup IS NOT NULL THEN
      RAISE EXCEPTION 'tms.ticket: a duplicate of % submitted moments ago', v_dup USING ERRCODE = 'unique_violation';
    END IF;
  END IF;
  NEW.priority_id := (SELECT priority_id FROM tms.ticket_category WHERE id = NEW.raised_category_id);
  NEW.route_id := CASE WHEN v_cat.direct_to_forum THEN NULL ELSE v_cat.route_id END;
  v_year := extract(year FROM NEW.created_at AT TIME ZONE c.time_zone)::smallint;
  INSERT INTO tms.ticket_number_counter AS n (year, last_no) VALUES (v_year, 1)
  ON CONFLICT (year) DO UPDATE SET last_no = n.last_no + 1
  RETURNING last_no INTO v_no;
  NEW.request_no := format('TMS-%s-%s', v_year, lpad(v_no::text, 5, '0'));
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ticket_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.ticket
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_validate();

-- Open the ticket. Straight-to-forum categories: raised, then filed with the
-- forum (REFERRED by the requester). Otherwise: the requester's choice, else
-- the first level of the route that gives it to someone (round-robin at a
-- pool), else unassigned at the start of the route — the clock still runs,
-- and the ticket shows in the unrouted queue.
CREATE OR REPLACE FUNCTION tms.ticket_open()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_cat record; v_emp uuid; v_level smallint; v_level_cat uuid; v_basis smallint; m record; w record;
BEGIN
  SELECT * INTO v_cat FROM tms.v_ticket_category WHERE category_id = NEW.raised_category_id;
  IF v_cat.direct_to_forum THEN
    INSERT INTO tms.ticket_event (ticket_id, event_type_id, actor_account_id)
    VALUES (NEW.id, ref.id_of('tms_event_type', 'CREATED'), COALESCE(NEW.raised_by_account_id, NEW.requester_account_id));
    INSERT INTO tms.ticket_event (ticket_id, event_type_id, actor_account_id, remarks)
    VALUES (NEW.id, ref.id_of('tms_event_type', 'REFERRED'), NEW.requester_account_id,
            'Filed with ' || (SELECT label FROM tms.redressal_forum WHERE id = v_cat.redressal_forum_id));
    RETURN NULL;
  END IF;
  IF NEW.requested_assignee_employee_id IS NOT NULL THEN
    SELECT * INTO m FROM tms.manual_level(NEW.route_id, NEW.raised_category_id, NEW.requester_org_unit_id, NEW.requested_assignee_employee_id);
    v_emp := NEW.requested_assignee_employee_id; v_level := m.level_id; v_level_cat := m.category_id;
    v_basis := ref.id_of('tms_assignment_basis', 'MANUAL');
  ELSE
    SELECT * INTO w FROM tms.walk_route(NEW.id, NEW.route_id, NEW.raised_category_id, 0::smallint, NULL);
    v_emp := w.employee_id; v_level := w.level_id; v_level_cat := w.level_category_id;
    IF v_emp IS NOT NULL THEN
      v_basis := CASE WHEN (SELECT k.code FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id
                            WHERE rl.id = v_level) = 'HANDLER_POOL'
                      THEN ref.id_of('tms_assignment_basis', 'ROUND_ROBIN') ELSE ref.id_of('tms_assignment_basis', 'ROUTE') END;
    END IF;
  END IF;
  INSERT INTO tms.ticket_event (ticket_id, event_type_id, actor_account_id, assignee_employee_id, assignment_basis_id,
                                level_id, level_category_id, due_at)
  VALUES (NEW.id, ref.id_of('tms_event_type', 'CREATED'), COALESCE(NEW.raised_by_account_id, NEW.requester_account_id),
          v_emp, v_basis, v_level, v_level_cat,
          tms.deadline_after(NEW.created_at, tms.level_sla_minutes(NEW.priority_id, v_level, NEW.raised_category_id),
                             tms.sla_office(NEW.priority_id, NEW.raised_category_id)));
  RETURN NULL;
END $$;
CREATE TRIGGER trg_ticket_open AFTER INSERT ON tms.ticket
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_open();

-- A category that needs academic context gets it in the same transaction.
CREATE OR REPLACE FUNCTION tms.ticket_context_required()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT needs_context FROM tms.v_ticket_category WHERE category_id = NEW.raised_category_id)
     AND NOT EXISTS (SELECT 1 FROM tms.ticket_academic_context WHERE ticket_id = NEW.id) THEN
    RAISE EXCEPTION 'tms.ticket %: this category needs the academic context (batch, term, semester)', NEW.request_no
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_ticket_context_required AFTER INSERT ON tms.ticket
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION tms.ticket_context_required();

-- The context belongs to the ticket's category, is given when the ticket is
-- raised, and is consistent: the course is there when the category's rule
-- needs it, the batch is the requester's own on a domain that says so, the
-- term is of the programme's calendar type, and the semester is within the
-- programme and (semester programmes) matches the term's odd / even cycle.
CREATE OR REPLACE FUNCTION tms.ticket_academic_context_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_cat record; v_prog record; v_cycle record; v_t tms.ticket;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: the context of a raised ticket is never edited' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO v_t FROM tms.ticket WHERE id = NEW.ticket_id;
  SELECT vc.*, d.context_must_be_own INTO v_cat FROM tms.v_ticket_category vc JOIN ref.tms_ticket_domain d ON d.id = vc.ticket_domain_id
  WHERE vc.category_id = v_t.raised_category_id;
  IF NOT v_cat.needs_context THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: the ticket''s category does not take academic context' USING ERRCODE = 'check_violation';
  END IF;
  IF v_cat.needs_course AND NEW.course_id IS NULL THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: this category needs the course' USING ERRCODE = 'check_violation';
  END IF;
  IF (SELECT count(*) FROM tms.ticket_event WHERE ticket_id = NEW.ticket_id) > 1 THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: give the context when raising the ticket' USING ERRCODE = 'check_violation';
  END IF;
  IF v_cat.context_must_be_own AND NOT EXISTS (
       SELECT 1 FROM academic.student_enrollment se JOIN people.student s ON s.id = se.student_id
       WHERE se.batch_id = NEW.batch_id AND s.person_id = tms.person_of_account(v_t.requester_account_id)) THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: the batch is not one the requester is or was enrolled in' USING ERRCODE = 'check_violation';
  END IF;
  SELECT p.academic_calendar_type_id, p.duration_terms, ct.code AS calendar, p.is_active INTO v_prog
  FROM academic.batch b JOIN academic.program p ON p.id = b.program_id JOIN ref.academic_calendar_type ct ON ct.id = p.academic_calendar_type_id
  WHERE b.id = NEW.batch_id;
  IF NOT v_prog.is_active THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: the batch''s programme is not active' USING ERRCODE = 'check_violation';
  END IF;
  SELECT tc.academic_calendar_type_id, tc.code, tc.position INTO v_cycle
  FROM academic.academic_term t JOIN ref.term_cycle tc ON tc.id = t.term_cycle_id WHERE t.id = NEW.academic_term_id;
  IF v_cycle.academic_calendar_type_id <> v_prog.academic_calendar_type_id THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: the term is not of the programme''s calendar type' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.term_no > v_prog.duration_terms THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: term % is beyond the programme''s % terms', NEW.term_no, v_prog.duration_terms USING ERRCODE = 'check_violation';
  END IF;
  IF v_prog.calendar = 'SEMESTER' AND NEW.term_no % 2 <> v_cycle.position % 2 THEN
    RAISE EXCEPTION 'tms.ticket_academic_context: semester % does not run in an % term', NEW.term_no, v_cycle.code USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ticket_academic_context_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.ticket_academic_context
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_academic_context_validate();

-- Every event after CREATED, one at a time per ticket (row lock): allowed in
-- the current status (ref.tms_event_allowed_status), by the right kind of
-- actor (ref.tms_event_type.event_actor_id), and checked against the state
-- it changes; derived values (next assignee, forum, due time, minutes left)
-- are computed here, never taken from the caller.
CREATE OR REPLACE FUNCTION tms.ticket_event_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_t tms.ticket; v_et ref.tms_event_type; v_kind text; s record; c tms.helpdesk_setting := tms.config();
        v_requester uuid; v_actor uuid; v_is_requester boolean; v_acts boolean; v_next record; v_leaf record;
        v_now timestamptz := clock_timestamp(); v_forum tms.redressal_forum; v_seat record; v_rel record;
        v_reason ref.tms_closure_reason; v_office boolean;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'tms.ticket_event: the timeline is append-only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO v_t FROM tms.ticket WHERE id = NEW.ticket_id FOR UPDATE;
  SELECT * INTO v_et FROM ref.tms_event_type WHERE id = NEW.event_type_id;
  SELECT code INTO v_kind FROM ref.tms_event_actor WHERE id = v_et.event_actor_id;
  NEW.occurred_at := v_now;
  IF v_kind = 'SYSTEM' THEN
    IF current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN
      RAISE EXCEPTION 'tms.ticket_event: % is recorded by the scheduled job only', v_et.code USING ERRCODE = 'insufficient_privilege';
    END IF;
    NEW.actor_account_id := NULL;
  ELSIF NEW.actor_account_id IS NULL THEN
    RAISE EXCEPTION 'tms.ticket_event: % needs the acting account', v_et.code USING ERRCODE = 'check_violation';
  END IF;
  IF v_et.code = 'CREATED' THEN
    IF EXISTS (SELECT 1 FROM tms.ticket_event WHERE ticket_id = NEW.ticket_id) THEN
      RAISE EXCEPTION 'tms.ticket_event: a ticket is created once' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  -- values that belong to one kind of event only
  IF NEW.rating IS NOT NULL AND v_et.code <> 'RATED' THEN
    RAISE EXCEPTION 'tms.ticket_event: a rating belongs to a RATED event' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.category_id IS NOT NULL AND v_et.code <> 'TRANSFERRED' THEN
    RAISE EXCEPTION 'tms.ticket_event: a new category belongs to a TRANSFERRED event' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.related_ticket_id IS NOT NULL AND v_et.code <> 'MERGED' THEN
    RAISE EXCEPTION 'tms.ticket_event: a related ticket belongs to a MERGED event' USING ERRCODE = 'check_violation';
  END IF;
  IF (NEW.redressal_outcome_id IS NOT NULL OR NEW.body_resolution_id IS NOT NULL) AND v_et.code <> 'FORUM_DECIDED' THEN
    RAISE EXCEPTION 'tms.ticket_event: an outcome belongs to a FORUM_DECIDED event' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.forum_id IS NOT NULL AND v_et.code NOT IN ('REFERRED', 'FORUM_FORWARDED') THEN
    RAISE EXCEPTION 'tms.ticket_event: a forum is chosen only when referring or forwarding' USING ERRCODE = 'check_violation';
  END IF;
  IF (NEW.consulted_employee_id IS NOT NULL) <> (v_et.code = 'CONSULTATION_REQUESTED')
     OR (NEW.reply_to_event_id IS NOT NULL) <> (v_et.code = 'CONSULTATION_ANSWERED') THEN
    RAISE EXCEPTION 'tms.ticket_event: a consultation names who is asked, and its answer the request it answers' USING ERRCODE = 'check_violation';
  END IF;
  IF (NEW.hold_reason_id IS NOT NULL) <> (v_et.code = 'PUT_ON_HOLD') THEN
    RAISE EXCEPTION 'tms.ticket_event: a hold states what is awaited (and only a hold)' USING ERRCODE = 'check_violation';
  END IF;
  IF v_et.needs_remark AND COALESCE(btrim(NEW.remarks), '') = '' THEN
    RAISE EXCEPTION 'tms.ticket_event: % needs remarks', v_et.code USING ERRCODE = 'check_violation';
  END IF;

  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = NEW.ticket_id;
  IF NOT tms.domain_is_open(s.ticket_domain_id) THEN
    RAISE EXCEPTION 'tms.ticket_event: Student TMS is switched off' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM ref.tms_event_allowed_status a JOIN ref.tms_ticket_status st ON st.id = a.ticket_status_id
                 WHERE a.event_type_id = v_et.id AND st.code = s.status) THEN
    RAISE EXCEPTION 'tms.ticket_event: "%" is not possible while % is %', v_et.label, v_t.request_no, lower(s.status)
      USING ERRCODE = 'check_violation';
  END IF;

  -- who
  v_requester := tms.person_of_account(v_t.requester_account_id);
  v_actor := tms.person_of_account(NEW.actor_account_id);
  v_is_requester := v_actor IS NOT NULL AND v_actor = v_requester;
  v_acts := v_kind IN ('HANDLER', 'REQUESTER_OR_HANDLER') AND tms.can_act(NEW.actor_account_id, NEW.ticket_id);
  IF (v_kind = 'REQUESTER' AND NOT v_is_requester)
     OR (v_kind = 'HANDLER' AND NOT v_acts)
     OR (v_kind = 'REQUESTER_OR_HANDLER' AND NOT v_is_requester AND NOT v_acts)
     OR (v_kind = 'FORUM' AND NOT tms.is_forum_member(NEW.actor_account_id, NEW.ticket_id))
     OR (v_kind = 'RESPONSIBLE_OFFICE' AND NOT tms.can_report_compliance(NEW.actor_account_id, NEW.ticket_id))
     OR (v_kind = 'CONSULTEE' AND NOT EXISTS (
           SELECT 1 FROM tms.ticket_event q WHERE q.id = NEW.reply_to_event_id AND q.ticket_id = NEW.ticket_id
             AND tms.person_of_employee(q.consulted_employee_id) = v_actor)) THEN
    RAISE EXCEPTION 'tms.ticket_event: the account may not record "%" on % (%)', v_et.label, v_t.request_no, lower(v_kind)
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  v_office := s.clock_is_office;

  CASE v_et.code
    WHEN 'REPLIED', 'REMARKED', 'REQUESTER_COMMENTED', 'CONFIRMED', 'AUTO_CLOSED', 'WITHDRAWN' THEN
      NULL;
    WHEN 'CLARIFICATION_REQUESTED' THEN
      IF s.clock_state = 'PAUSED' THEN
        RAISE EXCEPTION 'tms.ticket_event: a clarification is already pending' USING ERRCODE = 'check_violation';
      END IF;
      NEW.sla_remaining_minutes := CASE WHEN s.due_at IS NULL THEN NULL ELSE tms.minutes_left(v_now, s.due_at, v_office) END;
    WHEN 'CLARIFICATION_PROVIDED', 'HOLD_RELEASED', 'HOLD_EXPIRED' THEN
      IF s.clock_state <> 'PAUSED'
         OR s.clock_event <> (CASE v_et.code WHEN 'CLARIFICATION_PROVIDED' THEN 'CLARIFICATION_REQUESTED' ELSE 'PUT_ON_HOLD' END) THEN
        RAISE EXCEPTION 'tms.ticket_event: %', CASE v_et.code WHEN 'CLARIFICATION_PROVIDED' THEN 'no clarification is pending'
                                                                ELSE 'the ticket is not on hold' END
          USING ERRCODE = 'check_violation';
      END IF;
      NEW.due_at := CASE WHEN s.paused_remaining_minutes IS NULL THEN NULL
                         ELSE tms.deadline_after(v_now, GREATEST(s.paused_remaining_minutes, 1), v_office) END;
    WHEN 'CLARIFICATION_REMINDER', 'CLARIFICATION_EXPIRED' THEN
      IF s.clock_state <> 'PAUSED' OR s.clock_event <> 'CLARIFICATION_REQUESTED' THEN
        RAISE EXCEPTION 'tms.ticket_event: % applies to a pending clarification only', v_et.code USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'PUT_ON_HOLD' THEN
      IF NOT c.on_hold_enabled THEN
        RAISE EXCEPTION 'tms.ticket_event: holds are switched off' USING ERRCODE = 'check_violation';
      END IF;
      IF s.clock_state = 'PAUSED' THEN
        RAISE EXCEPTION 'tms.ticket_event: the clock is already paused (%)', lower(s.clock_event) USING ERRCODE = 'check_violation';
      END IF;
      NEW.sla_remaining_minutes := CASE WHEN s.due_at IS NULL THEN NULL ELSE tms.minutes_left(v_now, s.due_at, v_office) END;
    WHEN 'CONSULTATION_REQUESTED' THEN
      IF s.is_confidential THEN
        RAISE EXCEPTION 'tms.ticket_event: a confidential ticket is not shown to people outside it' USING ERRCODE = 'check_violation';
      END IF;
      IF NOT tms.is_workable(NEW.consulted_employee_id)
         OR tms.person_of_employee(NEW.consulted_employee_id) IN (v_requester, v_actor)
         OR tms.person_of_employee(NEW.consulted_employee_id) IS NOT DISTINCT FROM tms.person_of_employee(s.assignee_employee_id)
         OR tms.is_respondent(NEW.ticket_id, tms.person_of_employee(NEW.consulted_employee_id)) THEN
        RAISE EXCEPTION 'tms.ticket_event: consult someone who can work and is not the requester, the assignee, yourself or a respondent'
          USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'CONSULTATION_ANSWERED' THEN
      IF NOT EXISTS (SELECT 1 FROM tms.ticket_event q JOIN ref.tms_event_type qt ON qt.id = q.event_type_id AND qt.code = 'CONSULTATION_REQUESTED'
                     WHERE q.id = NEW.reply_to_event_id AND q.ticket_id = NEW.ticket_id)
         OR EXISTS (SELECT 1 FROM tms.ticket_event a WHERE a.reply_to_event_id = NEW.reply_to_event_id) THEN
        RAISE EXCEPTION 'tms.ticket_event: answer an open consultation of this ticket, once' USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'ACTION_TAKEN', 'COMPLIANCE_REMINDER' THEN
      IF s.resolution_event IS DISTINCT FROM 'FORUM_DECIDED'
         OR NOT (SELECT is_in_favour FROM ref.tms_redressal_outcome WHERE id = s.redressal_outcome_id)
         OR (SELECT compliance_within_days FROM tms.redressal_forum WHERE id = s.forum_id) IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: % follows a forum decision in the requester''s favour whose compliance is tracked', v_et.code
          USING ERRCODE = 'check_violation';
      END IF;
      IF EXISTS (SELECT 1 FROM tms.ticket_event a JOIN ref.tms_event_type at2 ON at2.id = a.event_type_id AND at2.code = 'ACTION_TAKEN'
                 WHERE a.ticket_id = NEW.ticket_id AND a.id > (SELECT max(d.id) FROM tms.ticket_event d JOIN ref.tms_event_type dt ON dt.id = d.event_type_id
                                                               AND dt.code = 'FORUM_DECIDED' WHERE d.ticket_id = NEW.ticket_id)) THEN
        RAISE EXCEPTION 'tms.ticket_event: the action taken on this decision is reported already' USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'ESCALATED', 'AUTO_ESCALATED' THEN
      IF v_et.code = 'ESCALATED' AND NOT v_acts AND (NOT c.requester_may_escalate_overdue OR NOT s.is_overdue) THEN
        RAISE EXCEPTION 'tms.ticket_event: the requester may escalate only a ticket that is overdue' USING ERRCODE = 'insufficient_privilege';
      END IF;
      SELECT * INTO v_next FROM tms.next_escalation(NEW.ticket_id);
      IF v_next.employee_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: nobody above the current level — the ticket cannot be escalated further' USING ERRCODE = 'check_violation';
      END IF;
      NEW.assignee_employee_id := v_next.employee_id;
      NEW.assignment_basis_id := ref.id_of('tms_assignment_basis', 'ESCALATION');
      NEW.level_id := v_next.level_id;
      NEW.level_category_id := v_next.level_category_id;
      NEW.due_at := tms.deadline_after(v_now, tms.level_sla_minutes(s.priority_id, v_next.level_id, s.category_id), tms.sla_office(s.priority_id, s.category_id));
    WHEN 'RECUSED' THEN
      IF s.assignee_employee_id IS NULL OR NOT tms.is_respondent(NEW.ticket_id, tms.person_of_employee(s.assignee_employee_id)) THEN
        RAISE EXCEPTION 'tms.ticket_event: only an assignee named in the complaint is recused' USING ERRCODE = 'check_violation';
      END IF;
      SELECT * INTO v_next FROM tms.next_escalation(NEW.ticket_id);
      NEW.assignee_employee_id := v_next.employee_id;
      NEW.assignment_basis_id := ref.id_of('tms_assignment_basis', 'RECUSAL');
      NEW.level_id := COALESCE(v_next.level_id, s.level_id);
      NEW.level_category_id := CASE WHEN v_next.level_id IS NULL THEN s.level_category_id ELSE v_next.level_category_id END;
      NEW.due_at := tms.deadline_after(v_now, tms.level_sla_minutes(s.priority_id, NEW.level_id, s.category_id), tms.sla_office(s.priority_id, s.category_id));
    WHEN 'ESCALATION_EXHAUSTED', 'OVERDUE_NOTICE' THEN
      IF s.clock_state <> 'RUNNING' THEN
        RAISE EXCEPTION 'tms.ticket_event: % applies to a running clock only', v_et.code USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'REASSIGNED' THEN
      IF NOT EXISTS (SELECT 1 FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id AND k.code = 'HANDLER_POOL'
                     WHERE rl.id = s.level_id) THEN
        RAISE EXCEPTION 'tms.ticket_event: reassign only at the handler level — escalate or transfer instead' USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.assignee_employee_id IS NULL
         OR NOT EXISTS (SELECT 1 FROM tms.ticket_category_handler h LEFT JOIN org.ancestors(s.requester_org_unit_id) a ON a.org_unit_id = h.org_unit_id
                        WHERE h.category_id = s.category_id AND h.employee_id = NEW.assignee_employee_id AND h.is_active
                          AND (h.org_unit_id IS NULL OR a.org_unit_id IS NOT NULL))
         OR NOT tms.is_workable(NEW.assignee_employee_id) THEN
        RAISE EXCEPTION 'tms.ticket_event: reassign to an active handler of the same category who serves this requester' USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.assignee_employee_id IS NOT DISTINCT FROM s.assignee_employee_id THEN
        RAISE EXCEPTION 'tms.ticket_event: the ticket is already with that handler' USING ERRCODE = 'check_violation';
      END IF;
      IF tms.person_of_employee(NEW.assignee_employee_id) = v_requester
         OR tms.is_respondent(NEW.ticket_id, tms.person_of_employee(NEW.assignee_employee_id)) THEN
        RAISE EXCEPTION 'tms.ticket_event: a ticket cannot go to its requester or to a person named in it' USING ERRCODE = 'check_violation';
      END IF;
      NEW.assignment_basis_id := ref.id_of('tms_assignment_basis', 'REASSIGNMENT');
      NEW.level_id := s.level_id;
      NEW.level_category_id := s.category_id;
    WHEN 'TRANSFERRED' THEN
      SELECT * INTO v_leaf FROM tms.v_ticket_category WHERE category_id = NEW.category_id;
      IF NOT FOUND OR NOT v_leaf.is_leaf OR NOT v_leaf.effective_active THEN
        RAISE EXCEPTION 'tms.ticket_event: transfer to an active leaf category' USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.category_id = s.category_id THEN
        RAISE EXCEPTION 'tms.ticket_event: the ticket is already in that category' USING ERRCODE = 'check_violation';
      END IF;
      IF v_leaf.ticket_domain_id <> s.ticket_domain_id THEN
        RAISE EXCEPTION 'tms.ticket_event: a ticket stays in its domain' USING ERRCODE = 'check_violation';
      END IF;
      IF v_leaf.direct_to_forum THEN
        RAISE EXCEPTION 'tms.ticket_event: that category goes to a forum — refer the ticket to the forum instead' USING ERRCODE = 'check_violation';
      END IF;
      IF v_leaf.route_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: that category has no route' USING ERRCODE = 'check_violation';
      END IF;
      IF (v_leaf.needs_context AND NOT EXISTS (SELECT 1 FROM tms.ticket_academic_context WHERE ticket_id = NEW.ticket_id))
         OR (v_leaf.needs_course AND NOT EXISTS (SELECT 1 FROM tms.ticket_academic_context WHERE ticket_id = NEW.ticket_id AND course_id IS NOT NULL)) THEN
        RAISE EXCEPTION 'tms.ticket_event: that category needs academic context this ticket does not have' USING ERRCODE = 'check_violation';
      END IF;
      NEW.route_id := v_leaf.route_id;
      NEW.priority_id := (SELECT priority_id FROM tms.ticket_category WHERE id = NEW.category_id);
      SELECT * INTO v_next FROM tms.walk_route(NEW.ticket_id, NEW.route_id, NEW.category_id, 0::smallint, NULL);
      IF v_next.employee_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: nobody on that category''s route can take the ticket' USING ERRCODE = 'check_violation';
      END IF;
      NEW.assignee_employee_id := v_next.employee_id;
      NEW.assignment_basis_id := CASE WHEN (SELECT k.code FROM tms.ticket_route_level rl JOIN ref.tms_route_level_kind k ON k.id = rl.route_level_kind_id
                                            WHERE rl.id = v_next.level_id) = 'HANDLER_POOL'
                                      THEN ref.id_of('tms_assignment_basis', 'ROUND_ROBIN') ELSE ref.id_of('tms_assignment_basis', 'ROUTE') END;
      NEW.level_id := v_next.level_id;
      NEW.level_category_id := v_next.level_category_id;
      NEW.due_at := tms.deadline_after(v_now, tms.level_sla_minutes(NEW.priority_id, v_next.level_id, NEW.category_id), tms.sla_office(NEW.priority_id, NEW.category_id));
    WHEN 'REFERRED', 'AUTO_REFERRED', 'APPEALED' THEN
      IF NOT s.is_grievance THEN
        RAISE EXCEPTION 'tms.ticket_event: only a grievance goes to a redressal forum' USING ERRCODE = 'check_violation';
      END IF;
      IF v_et.code = 'APPEALED' THEN
        IF s.resolution_event IS DISTINCT FROM 'FORUM_DECIDED' THEN
          RAISE EXCEPTION 'tms.ticket_event: only a forum''s decision can be appealed' USING ERRCODE = 'check_violation';
        END IF;
        SELECT * INTO v_forum FROM tms.redressal_forum WHERE id = s.forum_id;
        IF v_forum.appeal_forum_id IS NULL THEN
          RAISE EXCEPTION 'tms.ticket_event: the decision of % has no appeal forum here', v_forum.label USING ERRCODE = 'check_violation';
        END IF;
        IF v_now > s.resolved_at + make_interval(days => v_forum.appeal_window_days) THEN
          RAISE EXCEPTION 'tms.ticket_event: the appeal window of % days has passed', v_forum.appeal_window_days USING ERRCODE = 'check_violation';
        END IF;
        NEW.forum_id := v_forum.appeal_forum_id;
        SELECT * INTO v_forum FROM tms.redressal_forum WHERE id = NEW.forum_id;   -- from here on: the appellate forum
      ELSE
        IF s.referral_count > 0 THEN
          RAISE EXCEPTION 'tms.ticket_event: the grievance was referred already — appeal the decision instead' USING ERRCODE = 'check_violation';
        END IF;
        IF NEW.forum_id IS NOT NULL AND NEW.forum_id IS DISTINCT FROM s.category_forum_id AND NOT v_acts THEN
          RAISE EXCEPTION 'tms.ticket_event: only the handling side may refer to a forum other than the category''s' USING ERRCODE = 'insufficient_privilege';
        END IF;
        IF v_et.code = 'REFERRED' AND NOT v_acts
           AND s.status <> 'RESOLVED'
           AND NOT (SELECT direct_to_forum FROM tms.v_ticket_category WHERE category_id = s.category_id)
           AND (c.requester_refer_after_days IS NULL OR v_now < v_t.created_at + make_interval(days => c.requester_refer_after_days)) THEN
          RAISE EXCEPTION 'tms.ticket_event: the requester may refer the grievance once it is resolved%',
            CASE WHEN c.requester_refer_after_days IS NULL THEN '' ELSE format(' or % days after raising it', c.requester_refer_after_days) END
            USING ERRCODE = 'check_violation';
        END IF;
        IF s.status = 'RESOLVED' AND v_acts AND NOT v_is_requester THEN
          RAISE EXCEPTION 'tms.ticket_event: a resolved ticket is referred by its requester (the handling side reopens nothing)' USING ERRCODE = 'check_violation';
        END IF;
        NEW.forum_id := COALESCE(NEW.forum_id, s.category_forum_id);
        IF NEW.forum_id IS NULL THEN
          RAISE EXCEPTION 'tms.ticket_event: no redressal forum is configured for this category' USING ERRCODE = 'check_violation';
        END IF;
        SELECT * INTO v_forum FROM tms.redressal_forum WHERE id = NEW.forum_id;
      END IF;
      IF NOT v_forum.is_active THEN
        RAISE EXCEPTION 'tms.ticket_event: % is not active', v_forum.label USING ERRCODE = 'check_violation';
      END IF;
      SELECT * INTO v_seat FROM tms.forum_seat(NEW.forum_id, COALESCE(v_t.requester_org_unit_id, s.responsible_org_unit_id));
      IF v_seat.academic_body_id IS NULL AND v_seat.employee_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: no % is constituted for this requester', v_forum.label USING ERRCODE = 'check_violation';
      END IF;
      NEW.academic_body_id := v_seat.academic_body_id;
      NEW.assignee_employee_id := v_seat.employee_id;
      NEW.assignment_basis_id := ref.id_of('tms_assignment_basis', 'REFERRAL');
      NEW.level_id := NULL;
      NEW.level_category_id := NULL;
      NEW.due_at := tms.days_after(v_now, v_forum.decision_within_days, v_forum.counts_office_days);
    WHEN 'FORUM_FORWARDED' THEN
      -- one committee hands the case, with its report, to another (the squad's
      -- inquiry to the anti-ragging committee; a grievance that is really
      -- discrimination to the equal opportunity cell)
      SELECT * INTO v_forum FROM tms.redressal_forum WHERE id = s.forum_id;
      NEW.forum_id := COALESCE(NEW.forum_id, v_forum.next_forum_id);
      IF NEW.forum_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: % forwards nowhere by default — name the forum', v_forum.label USING ERRCODE = 'check_violation';
      END IF;
      IF NEW.forum_id = s.forum_id THEN
        RAISE EXCEPTION 'tms.ticket_event: the case is with that forum already' USING ERRCODE = 'check_violation';
      END IF;
      SELECT * INTO v_forum FROM tms.redressal_forum WHERE id = NEW.forum_id;
      IF NOT v_forum.is_active THEN
        RAISE EXCEPTION 'tms.ticket_event: % is not active', v_forum.label USING ERRCODE = 'check_violation';
      END IF;
      SELECT * INTO v_seat FROM tms.forum_seat(NEW.forum_id, COALESCE(v_t.requester_org_unit_id, s.responsible_org_unit_id));
      IF v_seat.academic_body_id IS NULL AND v_seat.employee_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: no % is constituted for this requester', v_forum.label USING ERRCODE = 'check_violation';
      END IF;
      NEW.academic_body_id := v_seat.academic_body_id;
      NEW.assignee_employee_id := v_seat.employee_id;
      NEW.assignment_basis_id := ref.id_of('tms_assignment_basis', 'REFERRAL');
      NEW.level_id := NULL;
      NEW.level_category_id := NULL;
      NEW.due_at := tms.days_after(v_now, v_forum.decision_within_days, v_forum.counts_office_days);
    WHEN 'FORUM_DECIDED' THEN
      IF NEW.redressal_outcome_id IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: a decision states its outcome' USING ERRCODE = 'check_violation';
      END IF;
      SELECT * INTO v_forum FROM tms.redressal_forum WHERE id = s.forum_id;
      IF (v_forum.needs_resolution AND NEW.body_resolution_id IS NULL)
         OR (NEW.body_resolution_id IS NOT NULL AND NOT EXISTS (
               SELECT 1 FROM academic.body_resolution r JOIN academic.body_meeting m ON m.id = r.body_meeting_id
               WHERE r.id = NEW.body_resolution_id AND m.academic_body_id = s.academic_body_id)) THEN
        RAISE EXCEPTION 'tms.ticket_event: the decision of % is a resolution passed at a meeting of that committee', v_forum.label
          USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'RESOLVED', 'REJECTED' THEN
      IF v_is_requester THEN
        RAISE EXCEPTION 'tms.ticket_event: the requester cannot resolve their own ticket' USING ERRCODE = 'insufficient_privilege';
      END IF;
    WHEN 'MERGED' THEN
      SELECT * INTO v_rel FROM tms.v_ticket_state WHERE ticket_id = NEW.related_ticket_id;
      IF NOT FOUND OR v_rel.is_closed OR v_rel.ticket_domain_id <> s.ticket_domain_id THEN
        RAISE EXCEPTION 'tms.ticket_event: merge into an open ticket of the same domain' USING ERRCODE = 'check_violation';
      END IF;
      IF v_rel.is_confidential OR s.is_confidential THEN
        RAISE EXCEPTION 'tms.ticket_event: confidential tickets are never merged' USING ERRCODE = 'check_violation';
      END IF;
    WHEN 'REOPENED' THEN
      IF s.forum_id IS NOT NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: a ticket that went to a redressal forum is appealed, not reopened' USING ERRCODE = 'check_violation';
      END IF;
      IF s.is_closed THEN
        SELECT * INTO v_reason FROM ref.tms_closure_reason WHERE id = s.closure_reason_id;
        IF NOT COALESCE(v_reason.is_reopenable, false) THEN
          RAISE EXCEPTION 'tms.ticket_event: a ticket closed as "%" cannot be reopened', lower(v_reason.label) USING ERRCODE = 'check_violation';
        END IF;
        IF v_now > s.closed_at + make_interval(days => c.reopen_window_days) THEN
          RAISE EXCEPTION 'tms.ticket_event: the reopen window of % days has passed', c.reopen_window_days USING ERRCODE = 'check_violation';
        END IF;
      END IF;
      IF s.reopen_count >= c.max_reopens THEN
        RAISE EXCEPTION 'tms.ticket_event: reopened % time(s) already — refer the grievance to the redressal forum instead', s.reopen_count
          USING ERRCODE = 'check_violation';
      END IF;
      NEW.due_at := tms.deadline_after(v_now, tms.level_sla_minutes(s.priority_id, s.level_id, s.category_id), tms.sla_office(s.priority_id, s.category_id));
    WHEN 'RATED' THEN
      IF NEW.rating IS NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: a rating (1–5) is required' USING ERRCODE = 'check_violation';
      END IF;
      IF s.rating IS NOT NULL THEN
        RAISE EXCEPTION 'tms.ticket_event: the ticket is already rated' USING ERRCODE = 'check_violation';
      END IF;
      SELECT * INTO v_reason FROM ref.tms_closure_reason WHERE id = COALESCE(s.closure_reason_id, s.resolution_reason_id);
      IF s.resolved_at IS NULL OR NOT COALESCE(v_reason.is_ratable, false) THEN
        RAISE EXCEPTION 'tms.ticket_event: only a resolved ticket is rated' USING ERRCODE = 'check_violation';
      END IF;
      IF v_now > s.resolved_at + make_interval(days => c.rating_window_days) THEN
        RAISE EXCEPTION 'tms.ticket_event: the rating window of % days has passed', c.rating_window_days USING ERRCODE = 'check_violation';
      END IF;
    ELSE
      NULL;
  END CASE;

  -- what does not belong to this kind of event is not kept
  IF NOT v_et.sets_assignee THEN
    NEW.assignee_employee_id := NULL; NEW.assignment_basis_id := NULL; NEW.level_id := NULL; NEW.level_category_id := NULL;
    NEW.forum_id := NULL; NEW.academic_body_id := NULL;
  ELSIF v_et.code NOT IN ('REFERRED', 'AUTO_REFERRED', 'APPEALED', 'FORUM_FORWARDED') THEN
    NEW.forum_id := NULL; NEW.academic_body_id := NULL;
  END IF;
  IF NOT v_et.starts_clock THEN NEW.due_at := NULL; END IF;
  IF NOT v_et.pauses_clock THEN NEW.sla_remaining_minutes := NULL; END IF;
  IF v_et.code <> 'TRANSFERRED' THEN NEW.priority_id := NULL; NEW.route_id := NULL; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ticket_event_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.ticket_event
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_event_validate();

-- At commit: an event that needs a reply or a file has one of them.
CREATE OR REPLACE FUNCTION tms.ticket_event_complete()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (SELECT needs_remark_or_file FROM ref.tms_event_type WHERE id = NEW.event_type_id)
     AND COALESCE(btrim(NEW.remarks), '') = ''
     AND NOT EXISTS (SELECT 1 FROM tms.ticket_event_file WHERE ticket_event_id = NEW.id) THEN
    RAISE EXCEPTION 'tms.ticket_event: % needs a reply or a document', (SELECT code FROM ref.tms_event_type WHERE id = NEW.event_type_id)
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER trg_ticket_event_complete AFTER INSERT ON tms.ticket_event
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION tms.ticket_event_complete();

-- Files go on an event that takes files, in the transaction that recorded
-- it, up to the configured number, of an allowed type and size, and a file
-- belongs to one ticket only (nobody attaches somebody else's upload).
CREATE OR REPLACE FUNCTION tms.ticket_event_file_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_ev record; v_file people.file_object;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'tms.ticket_event_file: attachments are part of the timeline and never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT e.occurred_at, e.ticket_id, et.allows_files, et.code INTO v_ev FROM tms.ticket_event e JOIN ref.tms_event_type et ON et.id = e.event_type_id
  WHERE e.id = NEW.ticket_event_id;
  SELECT * INTO v_file FROM people.file_object WHERE id = NEW.file_object_id;
  IF NOT EXISTS (SELECT 1 FROM tms.helpdesk_file_type WHERE mime_type = v_file.mime_type) THEN
    RAISE EXCEPTION 'tms.ticket_event_file: files of type % are not accepted', v_file.mime_type USING ERRCODE = 'check_violation';
  END IF;
  IF v_file.byte_size > (tms.config()).max_file_bytes THEN
    RAISE EXCEPTION 'tms.ticket_event_file: the file is larger than % bytes', (tms.config()).max_file_bytes USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM tms.ticket_event_file f JOIN tms.ticket_event e ON e.id = f.ticket_event_id
             WHERE f.file_object_id = NEW.file_object_id AND e.ticket_id <> v_ev.ticket_id) THEN
    RAISE EXCEPTION 'tms.ticket_event_file: the file belongs to another ticket' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT v_ev.allows_files THEN
    RAISE EXCEPTION 'tms.ticket_event_file: % takes no files', v_ev.code USING ERRCODE = 'check_violation';
  END IF;
  IF v_ev.occurred_at < transaction_timestamp() THEN
    RAISE EXCEPTION 'tms.ticket_event_file: files are attached when the event is recorded' USING ERRCODE = 'check_violation';
  END IF;
  IF (SELECT count(*) FROM tms.ticket_event_file WHERE ticket_event_id = NEW.ticket_event_id) >= (tms.config()).max_files_per_event THEN
    RAISE EXCEPTION 'tms.ticket_event_file: at most % files per entry', (tms.config()).max_files_per_event USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ticket_event_file_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.ticket_event_file
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_event_file_validate();

-- A respondent is named by the requester or by someone who can act, on an
-- open ticket whose category takes complaints against a person; never the
-- requester; kept for good.
CREATE OR REPLACE FUNCTION tms.ticket_respondent_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE s record;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'tms.ticket_respondent: a respondent stays on record' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO s FROM tms.v_ticket_state WHERE ticket_id = NEW.ticket_id;
  IF s.is_closed THEN
    RAISE EXCEPTION 'tms.ticket_respondent: the ticket is closed' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT (SELECT allows_respondent FROM tms.v_ticket_category WHERE category_id = s.category_id) THEN
    RAISE EXCEPTION 'tms.ticket_respondent: this category does not take complaints against a person' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.person_id = tms.person_of_account(s.requester_account_id) THEN
    RAISE EXCEPTION 'tms.ticket_respondent: the requester cannot be the respondent' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.added_by_account_id <> s.requester_account_id AND NOT tms.can_act(NEW.added_by_account_id, NEW.ticket_id) THEN
    RAISE EXCEPTION 'tms.ticket_respondent: only the requester or the handling side names a respondent' USING ERRCODE = 'insufficient_privilege';
  END IF;
  NEW.added_at := clock_timestamp();
  RETURN NEW;
END $$;
CREATE TRIGGER trg_ticket_respondent_validate BEFORE INSERT OR UPDATE OR DELETE ON tms.ticket_respondent
  FOR EACH ROW EXECUTE FUNCTION tms.ticket_respondent_validate();

-- Naming the current assignee moves the ticket on (conflict of interest).
CREATE OR REPLACE FUNCTION tms.ticket_respondent_recuse()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM tms.v_ticket_state s WHERE s.ticket_id = NEW.ticket_id AND s.status IN ('OPEN', 'ESCALATED')
               AND tms.person_of_employee(s.assignee_employee_id) = NEW.person_id) THEN
    INSERT INTO tms.ticket_event (ticket_id, event_type_id, actor_account_id, remarks)
    VALUES (NEW.ticket_id, ref.id_of('tms_event_type', 'RECUSED'), NEW.added_by_account_id,
            'The assignee is named in the complaint (conflict of interest)');
  END IF;
  RETURN NULL;
END $$;
