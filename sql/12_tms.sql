-- The raised facts. Immutable: everything that happens later is a ticket_event.
-- Set by the trigger, never by the caller: number, priority (the leaf's: the
-- SLA terms the requester got), route (the leaf's: the ladder it climbs), the
-- requester's unit when raised (what "relative to the requester" means for
-- this ticket — a later transfer of the student does not re-route it).
CREATE TABLE tms.ticket (
  id                              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_no                      citext NOT NULL UNIQUE CHECK (request_no ~ '^TMS-[0-9]{4}-[0-9]{5,}$'),
  requester_account_id            uuid NOT NULL REFERENCES iam.user_account(id),
  requester_org_unit_id           uuid REFERENCES org.org_unit(id),
  raised_by_account_id            uuid REFERENCES iam.user_account(id),          -- the intake desk that recorded it (NULL = the requester)
  intake_channel_id               smallint NOT NULL REFERENCES ref.tms_intake_channel(id),
  raised_category_id              uuid NOT NULL REFERENCES tms.ticket_category(id),
  route_id                        smallint REFERENCES tms.ticket_route(id),      -- NULL = filed straight with a forum
  priority_id                     smallint NOT NULL REFERENCES ref.tms_priority(id),
  message_type_id                 smallint NOT NULL REFERENCES ref.tms_message_type(id),
  subject                         text NOT NULL CHECK (length(btrim(subject)) BETWEEN 3 AND 256),
  description                     text NOT NULL CHECK (length(btrim(description)) BETWEEN 10 AND 5000),
  relief_sought                   text CHECK (relief_sought IS NULL OR length(btrim(relief_sought)) BETWEEN 3 AND 2000),
  incident_on                     date,
  is_anonymous                    boolean NOT NULL DEFAULT false,                -- identity withheld from the people handling it
  contact_phone_id                uuid REFERENCES pii.person_phone(id) ON DELETE SET NULL,   -- required when raised; erasable later
  declaration_id                  uuid REFERENCES tms.helpdesk_declaration(id),
  requested_assignee_employee_id  uuid REFERENCES people.employee(id),
  idempotency_key                 text CHECK (idempotency_key ~ '^[A-Za-z0-9_-]{8,64}$'),
  created_at                      timestamptz NOT NULL DEFAULT clock_timestamp(),
  UNIQUE (requester_account_id, idempotency_key),
  CHECK (raised_by_account_id IS DISTINCT FROM requester_account_id)
);
