  updated_at                     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (event_id, person_id),
  CHECK ((decided_at IS NULL) = (is_approved IS NULL)),
  CHECK ((cancelled_at IS NULL) = (registration_cancel_reason_id IS NULL)),
  CHECK (promoted_at IS NULL OR waitlisted_at IS NOT NULL)
);
