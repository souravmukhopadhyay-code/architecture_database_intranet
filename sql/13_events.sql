-- System job: cancel registrations of individual paid events that were not
-- paid within event_setting.unpaid_registration_expiry (NULL = never), unless a
-- payment is under way, and move the waiting list up into the freed seats.
CREATE OR REPLACE FUNCTION events.expire_unpaid_registrations()
RETURNS int LANGUAGE plpgsql AS $$
DECLARE v_after interval; r record; v_n int := 0;
BEGIN
  IF current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'expire_unpaid_registrations: runs as a system job only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT unpaid_registration_expiry INTO v_after FROM events.event_setting;
  IF v_after IS NULL THEN RETURN 0; END IF;
  FOR r IN
    SELECT reg.id, reg.event_id FROM events.event_registration reg
    JOIN events.event e ON e.id = reg.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
    JOIN ref.participation_type pt ON pt.id = p.participation_type_id AND NOT pt.is_team
    WHERE reg.cancelled_at IS NULL AND reg.registered_at < clock_timestamp() - v_after AND events.registration_state(reg.id) = 'PENDING_PAYMENT'
      AND NOT EXISTS (SELECT 1 FROM events.event_payment pm JOIN ref.payment_status ps ON ps.id = pm.payment_status_id AND ps.is_open
                      WHERE pm.registration_id = reg.id AND pm.created_at >= clock_timestamp() - v_after)
  LOOP
    UPDATE events.event_registration SET cancelled_at = clock_timestamp(), registration_cancel_reason_id = ref.id_of('registration_cancel_reason', 'UNPAID') WHERE id = r.id;
    PERFORM events.promote_waitlist(r.event_id);
    v_n := v_n + 1;
  END LOOP;
  RETURN v_n;
END $$;

-- Send a message: resolve the audience into recipients (a selection already
-- has them), take one credit each, and hand the queue to the mail sender. By an
-- organiser for an unscheduled message, by the scheduler for a scheduled one.
CREATE OR REPLACE FUNCTION events.dispatch_mail(p_mail uuid, p_account uuid DEFAULT NULL)
RETURNS int LANGUAGE plpgsql AS $$
DECLARE m record; a record; v_n int; v_avail int;
BEGIN
  SELECT * INTO m FROM events.event_mail WHERE id = p_mail FOR UPDATE;
  IF m.id IS NULL OR m.dispatch_started_at IS NOT NULL OR m.cancelled_at IS NOT NULL OR m.failed_at IS NOT NULL THEN
    RAISE EXCEPTION 'dispatch_mail: nothing to send (unknown, already sent, cancelled or failed)' USING ERRCODE = 'check_violation';
  END IF;
  IF current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN
    IF p_account IS NULL OR NOT events.can_manage(p_account, m.event_id) THEN
      RAISE EXCEPTION 'dispatch_mail: sent by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF m.scheduled_at IS NOT NULL AND m.scheduled_at > clock_timestamp() THEN
      RAISE EXCEPTION 'dispatch_mail: this message is scheduled for %', m.scheduled_at USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  SELECT * INTO a FROM ref.mail_audience WHERE id = m.mail_audience_id;
  PERFORM set_config('events.mail_dispatch', 'on', true);
  IF NOT a.is_selection THEN
    INSERT INTO events.event_mail_recipient (event_mail_id, registration_id, mail_delivery_status_id)
    SELECT m.id, r.id, (SELECT id FROM ref.mail_delivery_status WHERE NOT is_final ORDER BY sort_order LIMIT 1)
    FROM events.event_registration r
    WHERE r.event_id = m.event_id
      AND CASE events.registration_state(r.id) WHEN 'CONFIRMED' THEN a.includes_confirmed
                                               WHEN 'CANCELLED' THEN a.includes_cancelled WHEN 'REJECTED' THEN a.includes_cancelled
                                               ELSE a.includes_pending END
    ON CONFLICT (event_mail_id, registration_id) DO NOTHING;
  END IF;
  SELECT count(*) INTO v_n FROM events.event_mail_recipient WHERE event_mail_id = m.id;
  v_avail := events.mail_credits_total(m.event_id) - events.mail_credits_used(m.event_id);
  IF v_n = 0 THEN
    RAISE EXCEPTION 'dispatch_mail: the message has no recipients' USING ERRCODE = 'check_violation';
  END IF;
  IF v_n > v_avail THEN
    RAISE EXCEPTION 'dispatch_mail: % mail credits needed, % left', v_n, v_avail USING ERRCODE = 'check_violation';
  END IF;
  UPDATE events.event_mail SET dispatch_started_at = clock_timestamp() WHERE id = m.id;
  PERFORM set_config('events.mail_dispatch', 'off', true);
  RETURN v_n;
END $$;

-- System job: send the scheduled messages that are due; one that cannot be
-- sent (no recipients, no credits) is marked failed with the reason.
CREATE OR REPLACE FUNCTION events.run_mail_scheduler()
RETURNS int LANGUAGE plpgsql AS $$
DECLARE r record; v_n int := 0; v_msg text;
BEGIN
  IF current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'run_mail_scheduler: runs as a system job only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  FOR r IN SELECT id FROM events.event_mail
           WHERE scheduled_at <= clock_timestamp() AND dispatch_started_at IS NULL AND cancelled_at IS NULL AND failed_at IS NULL ORDER BY scheduled_at LOOP
    BEGIN
      PERFORM events.dispatch_mail(r.id);
      v_n := v_n + 1;
    EXCEPTION WHEN check_violation THEN
      GET STACKED DIAGNOSTICS v_msg = MESSAGE_TEXT;
      PERFORM set_config('events.mail_dispatch', 'on', true);
      UPDATE events.event_mail SET failed_at = clock_timestamp(), failure_reason = v_msg WHERE id = r.id;
      PERFORM set_config('events.mail_dispatch', 'off', true);
    END;
  END LOOP;
  RETURN v_n;
END $$;

-- An open of a message (the tracking pixel). Off unless event_setting
-- .mail_open_tracking is on, and never recorded for a minor (DPDP s.9(3)).
CREATE OR REPLACE FUNCTION events.mail_opened(p_recipient uuid)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF NOT (SELECT mail_open_tracking FROM events.event_setting) THEN RETURN; END IF;
  IF EXISTS (SELECT 1 FROM events.event_mail_recipient x JOIN events.event_registration r ON r.id = x.registration_id
             JOIN pii.v_person_age pa ON pa.person_id = r.person_id AND pa.is_minor WHERE x.id = p_recipient) THEN
    RETURN;
  END IF;
  UPDATE events.event_mail_recipient
     SET open_count = open_count + 1, first_opened_at = COALESCE(first_opened_at, clock_timestamp()), last_opened_at = clock_timestamp()
   WHERE id = p_recipient;
END $$;

-- Feedback on a stall from its public form: one or more scores on the
-- feedback scale and an optional comment. No login, no person.
CREATE OR REPLACE FUNCTION events.submit_stall_feedback(p_stall_code text, p_scores int[], p_comment text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_stall uuid; v_id uuid; v_set record;
BEGIN
  SELECT s.id INTO v_stall FROM events.event_stall s JOIN events.event e ON e.id = s.event_id
  WHERE s.stall_code = p_stall_code::citext AND s.is_active AND e.published_at IS NOT NULL AND e.cancelled_at IS NULL;
  IF v_stall IS NULL THEN
    RAISE EXCEPTION 'submit_stall_feedback: no such active stall' USING ERRCODE = 'no_data_found';
  END IF;
  SELECT * INTO v_set FROM events.event_setting;
  IF COALESCE(cardinality(p_scores), 0) NOT BETWEEN 1 AND v_set.stall_feedback_max_points
     OR EXISTS (SELECT 1 FROM unnest(p_scores) s WHERE s IS NULL OR s NOT BETWEEN 1 AND v_set.feedback_rating_max) THEN
    RAISE EXCEPTION 'submit_stall_feedback: 1 to % scores, each from 1 to %', v_set.stall_feedback_max_points, v_set.feedback_rating_max USING ERRCODE = 'check_violation';
  END IF;
  PERFORM set_config('events.stall_feedback_ok', 'on', true);
  INSERT INTO events.stall_feedback (event_stall_id, comment) VALUES (v_stall, left(p_comment, 2000)) RETURNING id INTO v_id;
  INSERT INTO events.stall_feedback_point (stall_feedback_id, point_no, score) SELECT v_id, o, s FROM unnest(p_scores) WITH ORDINALITY u(s, o);
  PERFORM set_config('events.stall_feedback_ok', 'off', true);
END $$;


-- Submit a drafted event change: opens its EVENT_CHANGE round at the
-- organising unit (flags say what changes) and, for new dates, the venue
-- package for them on the same round.
CREATE OR REPLACE FUNCTION events.submit_event_change(p_request uuid, p_account uuid)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE v record; v_instance uuid; v_package uuid; v_flags text[] := '{}';
BEGIN
  SELECT c.id, c.instance_id, c.requested_by_account_id, c.reason, c.new_during, c.new_venue_text, c.new_approx_capacity, c.new_capacity_fixed,
         p.organising_org_unit_id, p.title, p.approx_capacity, t.event_kind_id INTO v
  FROM events.event_change_request c JOIN events.event e ON e.id = c.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
  JOIN ref.event_type t ON t.id = p.event_type_id WHERE c.id = p_request;
  IF v.id IS NULL OR v.instance_id IS NOT NULL OR v.requested_by_account_id IS DISTINCT FROM p_account THEN
    RAISE EXCEPTION 'submit_event_change: only its requester submits a draft, once' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF v.new_during IS NOT NULL THEN v_flags := array_append(v_flags, 'EVENT_RESCHEDULE'); END IF;
  IF v.new_venue_text IS NOT NULL THEN v_flags := array_append(v_flags, 'EVENT_VENUE_CHANGE'); END IF;
  IF v.new_approx_capacity IS NOT NULL OR v.new_capacity_fixed IS NOT NULL THEN v_flags := array_append(v_flags, 'EVENT_CAPACITY_CHANGE'); END IF;
  v_instance := wf.submit('EVENT_CHANGE', v.organising_org_unit_id, p_account, v.reason, NULL, v_flags);
  IF v.new_during IS NOT NULL THEN
    INSERT INTO facility.event_request (title, organiser_person_id, on_behalf_org_unit_id, event_kind_id, during, expected_attendance, instance_id)
    VALUES (v.title, (SELECT person_id FROM iam.user_account WHERE id = p_account), v.organising_org_unit_id, v.event_kind_id, v.new_during,
            COALESCE(v.new_approx_capacity, v.approx_capacity), v_instance)
    RETURNING id INTO v_package;
  END IF;
  UPDATE events.event_change_request SET instance_id = v_instance, facility_event_request_id = v_package WHERE id = p_request;
  RETURN v_instance;
END $$;

