-- Live members of a team.
CREATE OR REPLACE FUNCTION events.team_size(p_team uuid)
RETURNS int LANGUAGE sql STABLE AS $$ SELECT count(*)::int FROM events.event_team_member WHERE event_team_id = p_team AND left_at IS NULL $$;

CREATE OR REPLACE FUNCTION events.event_team_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT r.event_id, r.cancelled_at, pt.is_team INTO v
    FROM events.event_registration r JOIN events.event e ON e.id = r.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
    JOIN ref.participation_type pt ON pt.id = p.participation_type_id WHERE r.id = NEW.leader_registration_id;
    IF v.event_id IS DISTINCT FROM NEW.event_id OR v.cancelled_at IS NOT NULL OR NOT v.is_team THEN
      RAISE EXCEPTION 'event_team: a team is formed by a live registration of that team event' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.event_id <> OLD.event_id OR NEW.leader_registration_id <> OLD.leader_registration_id THEN
    RAISE EXCEPTION 'event_team: the event and leader never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.locked_at IS NOT NULL AND OLD.locked_at IS NULL AND events.team_size(NEW.id) < (
       SELECT p.min_team_size FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = NEW.event_id) THEN
    RAISE EXCEPTION 'event_team: a team below the minimum size cannot be finalised' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.disqualified_at IS NOT NULL AND OLD.disqualified_at IS NULL AND NOT events.can_manage(NEW.disqualified_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'event_team: only the organisers disqualify a team' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_team_validate BEFORE INSERT OR UPDATE ON events.event_team
  FOR EACH ROW EXECUTE FUNCTION events.event_team_validate();

