-- An event proposal: what, when, for whom, at what cost — by a club (its
-- officers / advisors propose) or by a department / school / central
-- department. A draft while instance_id is NULL (its parts may be edited);
-- events.submit_proposal() opens the EVENT_PROPOSAL round with the budget
-- total as the amount and the flags (PAID_EVENT, EXTERNAL_GUESTS, SPONSORED)
-- the chain's conditions read, and creates the facility package. Once
-- submitted nothing changes: a returned proposal is revised as a NEW proposal
-- (revises_proposal_id). The approved proposal is the event's fixed facts.
CREATE TABLE events.event_proposal (
  id                         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  proposal_code              citext NOT NULL UNIQUE CHECK (proposal_code ~ '^EP-[0-9]{4}-[0-9]{3,}$'),
  organising_org_unit_id     uuid NOT NULL REFERENCES org.org_unit(id),
  proposed_by_account_id     uuid NOT NULL REFERENCES iam.user_account(id),
  event_type_id              smallint NOT NULL REFERENCES ref.event_type(id),
  title                      text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 3 AND 256),
  during                     tsrange NOT NULL,
  event_level_id             smallint NOT NULL REFERENCES ref.event_level(id),
  event_mode_id              smallint NOT NULL REFERENCES ref.event_mode(id),
  theme                      text NOT NULL CHECK (btrim(theme) <> ''),
  objective                  text NOT NULL CHECK (btrim(objective) <> ''),
