-- Seats taken: registrations neither cancelled, refused nor waiting in the queue.
CREATE OR REPLACE FUNCTION events.seats_taken(p_event uuid)
RETURNS int LANGUAGE sql STABLE AS $$
  SELECT count(*)::int FROM events.event_registration r
  WHERE r.event_id = p_event AND r.cancelled_at IS NULL AND r.is_approved IS DISTINCT FROM false
    AND (r.waitlisted_at IS NULL OR r.promoted_at IS NOT NULL)
$$;
CREATE OR REPLACE FUNCTION events.seat_limit(p_event uuid)
RETURNS int LANGUAGE sql STABLE AS $$
  SELECT COALESCE(e.registration_cap, p.capacity_fixed) FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = p_event
$$;

CREATE OR REPLACE FUNCTION events.registration_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_event record; v_limit int; v_raw bytea;
BEGIN
  SELECT e.*, p.is_paid, p.during AS event_during INTO v_event
  FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = NEW.event_id FOR UPDATE OF e;
  IF TG_OP = 'INSERT' THEN
    IF v_event.published_at IS NULL OR v_event.cancelled_at IS NOT NULL OR v_event.completed_at IS NOT NULL THEN
      RAISE EXCEPTION 'registration: the event is not open' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT (v_event.registration_window @> NEW.registered_at) THEN
      RAISE EXCEPTION 'registration: outside the registration window' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT events.can_see(NEW.event_id, NEW.person_id) THEN
      RAISE EXCEPTION 'registration: this event is not open to this person' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.cancelled_at IS NOT NULL OR NEW.decided_at IS NOT NULL OR NEW.promoted_at IS NOT NULL THEN
      RAISE EXCEPTION 'registration: a registration starts plain' USING ERRCODE = 'check_violation';
    END IF;
    NEW.registration_code := COALESCE(NEW.registration_code, format('REG-%s-%s', split_part(v_event.event_code, '-', 3) || split_part(v_event.event_code, '-', 2),
                                                                    lpad(nextval('events.registration_seq')::text, 6, '0')));
    NEW.qr_token_hash := digest(gen_random_bytes(32), 'sha256');   -- a placeholder nobody knows: the ticket comes from events.issue_ticket()
    NEW.ticket_issued_at := NULL;
    v_limit := events.seat_limit(NEW.event_id);
    NEW.waitlisted_at := CASE WHEN v_limit IS NOT NULL AND events.seats_taken(NEW.event_id) >= v_limit THEN NEW.registered_at END;
    IF NOT v_event.requires_approval THEN
      NEW.decided_at := NEW.registered_at; NEW.is_approved := true;       -- approved by rule; no deciding account
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.event_id <> OLD.event_id OR NEW.person_id <> OLD.person_id OR NEW.registration_code <> OLD.registration_code
     OR NEW.registered_at <> OLD.registered_at OR NEW.waitlisted_at IS DISTINCT FROM OLD.waitlisted_at THEN
    RAISE EXCEPTION 'registration: who registered for what, and when, never changes' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF (NEW.qr_token_hash <> OLD.qr_token_hash OR NEW.ticket_issued_at IS DISTINCT FROM OLD.ticket_issued_at)
     AND current_setting('events.ticket_issue', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'registration: a ticket is issued only through events.issue_ticket()' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF OLD.cancelled_at IS NOT NULL THEN
    RAISE EXCEPTION 'registration: already cancelled' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.decided_at IS DISTINCT FROM OLD.decided_at THEN
    IF OLD.decided_at IS NOT NULL OR NOT events.can_manage(NEW.decided_by_account_id, NEW.event_id) THEN
      RAISE EXCEPTION 'registration: decided once, by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  IF NEW.promoted_at IS NOT NULL AND OLD.promoted_at IS NULL AND events.seats_taken(NEW.event_id) >= events.seat_limit(NEW.event_id) THEN
    RAISE EXCEPTION 'registration: no seat is free to promote into' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.cancelled_at IS NOT NULL THEN
    -- the participant withdraws (if the event allows it, before it starts); organisers and the event's own cancellation always can
    IF NEW.cancelled_by_account_id IS NOT NULL AND NOT events.can_manage(NEW.cancelled_by_account_id, NEW.event_id) THEN
      IF NOT EXISTS (SELECT 1 FROM iam.user_account WHERE id = NEW.cancelled_by_account_id AND person_id = NEW.person_id) THEN
        RAISE EXCEPTION 'registration: cancelled by the participant or the organisers' USING ERRCODE = 'insufficient_privilege';
      END IF;
      IF NOT v_event.allow_withdraw OR clock_timestamp()::timestamp >= lower(v_event.event_during) THEN
        RAISE EXCEPTION 'registration: withdrawal is not allowed for this event (or it has started)' USING ERRCODE = 'check_violation';
      END IF;
    ELSIF NEW.cancelled_by_account_id IS NULL AND v_event.cancelled_at IS NULL AND current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN   -- the expiry job cancels without an account
      RAISE EXCEPTION 'registration: a cancellation names who cancelled' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_registration_validate BEFORE INSERT OR UPDATE ON events.event_registration
  FOR EACH ROW EXECUTE FUNCTION events.registration_validate();

