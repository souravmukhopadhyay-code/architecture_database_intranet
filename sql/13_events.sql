-- A proposal to found a club: where it will sit (a school, department, central
-- department or the university), its name and objective, the faculty advisor
-- and co-advisor, the first student officers and members. A draft until it is
-- submitted (instance_id): then a CLUB_PROPOSAL round. Its approval creates the
-- org unit, the club, the advisor appointments, the officers and the members.
CREATE TABLE events.club_proposal (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  proposal_code            citext NOT NULL UNIQUE CHECK (proposal_code ~ '^CP-[0-9]{4}-[0-9]{3,}$'),
  proposed_by_account_id   uuid NOT NULL REFERENCES iam.user_account(id),
  parent_org_unit_id       uuid NOT NULL REFERENCES org.org_unit(id),
  club_name                text NOT NULL CHECK (btrim(club_name) <> ''),      -- length limits: event_setting
  objective                text NOT NULL CHECK (btrim(objective) <> ''),      -- minimum length: event_setting
  advisor_employee_id      uuid NOT NULL REFERENCES people.employee(id),
  co_advisor_employee_id   uuid REFERENCES people.employee(id),
  club_category_id         smallint REFERENCES ref.club_category(id),         -- what kind of club; required before submission
  instance_id              uuid UNIQUE REFERENCES wf.approval_instance(id),     -- NULL = draft
  club_org_unit_id         uuid UNIQUE REFERENCES org.org_unit(id),             -- set when the approval creates the club
  created_at               timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now(),
  CHECK (co_advisor_employee_id IS DISTINCT FROM advisor_employee_id)
);
