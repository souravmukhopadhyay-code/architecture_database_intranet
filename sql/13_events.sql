CREATE OR REPLACE FUNCTION events.event_team_member_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_team record; v_max int;
BEGIN
  SELECT t.*, p.max_team_size INTO v_team
  FROM events.event_team t JOIN events.event e ON e.id = t.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
  WHERE t.id = NEW.event_team_id FOR UPDATE OF t;
  IF TG_OP = 'UPDATE' THEN
    IF NEW.event_team_id <> OLD.event_team_id OR NEW.registration_id <> OLD.registration_id OR OLD.left_at IS NOT NULL THEN
      RAISE EXCEPTION 'event_team_member: a member only ever leaves' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.registration_id = v_team.leader_registration_id AND v_team.withdrawn_at IS NULL THEN
      RAISE EXCEPTION 'event_team_member: the leader leaves by withdrawing the team' USING ERRCODE = 'check_violation';
    END IF;
    IF v_team.locked_at IS NOT NULL AND v_team.withdrawn_at IS NULL THEN
      RAISE EXCEPTION 'event_team_member: the team is finalised' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF v_team.locked_at IS NOT NULL OR v_team.withdrawn_at IS NOT NULL OR v_team.disqualified_at IS NOT NULL THEN
    RAISE EXCEPTION 'event_team_member: the team is closed' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM events.event_registration r WHERE r.id = NEW.registration_id AND r.event_id = v_team.event_id AND r.cancelled_at IS NULL) THEN
    RAISE EXCEPTION 'event_team_member: a member has a live registration for the team''s event' USING ERRCODE = 'check_violation';
  END IF;
  IF events.team_size(NEW.event_team_id) >= v_team.max_team_size THEN
    RAISE EXCEPTION 'event_team_member: the team is full (% members)', v_team.max_team_size USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
