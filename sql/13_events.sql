-- Payments that must be given back: money was captured but cannot (any longer)
-- settle what it was paid for. Derived — nothing is flagged by hand.
CREATE OR REPLACE VIEW events.v_refund_queue AS
SELECT q.* FROM (
  SELECT pm.id AS event_payment_id, pm.receipt_no, COALESCE(r.event_id, sa.event_id) AS event_id, pm.registration_id, pm.stall_application_id,
         pm.amount, pm.currency_code, pm.captured_at,
         CASE WHEN pm.superseded_at IS NOT NULL THEN 'SUPERSEDED_ORDER'
              WHEN ev.cancelled_at IS NOT NULL THEN 'EVENT_CANCELLED'
              WHEN r.cancelled_at IS NOT NULL THEN 'REGISTRATION_CANCELLED'
              WHEN r.is_approved IS FALSE THEN 'REGISTRATION_REJECTED'
              WHEN sa.is_approved IS FALSE THEN 'STALL_REJECTED'
              WHEN tm.withdrawn_at IS NOT NULL OR tm.disqualified_at IS NOT NULL THEN 'TEAM_WITHDRAWN'
              WHEN EXISTS (SELECT 1 FROM events.event_payment o JOIN ref.payment_status os ON os.id = o.payment_status_id AND os.is_settled
                           WHERE o.id <> pm.id AND o.superseded_at IS NULL AND o.captured_at < pm.captured_at
                             AND (o.registration_id = pm.registration_id OR o.stall_application_id = pm.stall_application_id)) THEN 'DUPLICATE_PAYMENT'
         END AS reason
  FROM events.event_payment pm
  JOIN ref.payment_status ps ON ps.id = pm.payment_status_id AND ps.is_settled
  LEFT JOIN events.event_registration r ON r.id = pm.registration_id
  LEFT JOIN events.stall_application sa ON sa.id = pm.stall_application_id
  LEFT JOIN events.event_team tm ON tm.id = pm.event_team_id
  JOIN events.event ev ON ev.id = COALESCE(r.event_id, sa.event_id)) q
WHERE q.reason IS NOT NULL;

-- A message with its derived status and delivery counts:
--   CANCELLED · FAILED · SCHEDULED · DRAFT (not yet sent) · SENDING · SENT · PARTIAL · UNDELIVERED
CREATE OR REPLACE VIEW events.v_event_mail AS
SELECT m.id AS event_mail_id, m.event_id, m.subject, a.code AS audience, m.created_by_account_id, m.created_at, m.scheduled_at, m.dispatch_started_at,
       COALESCE(c.recipients, 0)::int AS recipients, COALESCE(c.delivered, 0)::int AS delivered, COALESCE(c.failed, 0)::int AS failed,
       COALESCE(c.queued, 0)::int AS queued, COALESCE(c.opened, 0)::int AS opened,
       CASE WHEN m.cancelled_at IS NOT NULL THEN 'CANCELLED'
            WHEN m.failed_at IS NOT NULL THEN 'FAILED'
            WHEN m.dispatch_started_at IS NULL THEN CASE WHEN m.scheduled_at IS NOT NULL THEN 'SCHEDULED' ELSE 'DRAFT' END
            WHEN COALESCE(c.queued, 0) > 0 THEN 'SENDING'
            WHEN COALESCE(c.failed, 0) = 0 THEN 'SENT'
            WHEN COALESCE(c.delivered, 0) = 0 THEN 'UNDELIVERED'
            ELSE 'PARTIAL' END AS status,
       m.failure_reason
FROM events.event_mail m
JOIN ref.mail_audience a ON a.id = m.mail_audience_id
LEFT JOIN (SELECT x.event_mail_id, count(*) AS recipients, count(*) FILTER (WHERE s.is_delivered) AS delivered,
                  count(*) FILTER (WHERE s.is_final AND NOT s.is_delivered) AS failed, count(*) FILTER (WHERE NOT s.is_final) AS queued,
                  count(*) FILTER (WHERE x.open_count > 0) AS opened
           FROM events.event_mail_recipient x JOIN ref.mail_delivery_status s ON s.id = x.mail_delivery_status_id GROUP BY x.event_mail_id) c ON c.event_mail_id = m.id;

-- Mail credits of an event: an allowance per registration (event_setting)
-- plus what an administrator granted, less one per recipient written to
-- (a failed delivery gives its credit back).
CREATE OR REPLACE VIEW events.v_event_mail_credit AS
SELECT e.id AS event_id,
       (SELECT count(*) FROM events.event_registration r WHERE r.event_id = e.id)::int AS registrations,
       (SELECT mail_credits_per_registration FROM events.event_setting)::int AS credits_per_registration,
       COALESCE((SELECT sum(g.credits) FROM events.event_mail_credit_grant g WHERE g.event_id = e.id), 0)::int AS granted,
       events.mail_credits_total(e.id) AS total, events.mail_credits_used(e.id) AS used,
       events.mail_credits_total(e.id) - events.mail_credits_used(e.id) AS available
FROM events.event e;

-- Stall applications with what is due and paid: PENDING · APPROVED · REJECTED.
CREATE OR REPLACE VIEW events.v_stall_application AS
SELECT a.id AS stall_application_id, a.event_id, a.applicant_person_id, a.stall_name, st.code AS stall_type, sc.code AS stall_category, a.applied_at,
       CASE WHEN a.is_approved IS NULL THEN 'PENDING' WHEN a.is_approved THEN 'APPROVED' ELSE 'REJECTED' END AS status,
       events.stall_fee(a.id) AS fee,
       COALESCE((SELECT sum(pm.amount) FROM events.event_payment pm JOIN ref.payment_status ps ON ps.id = pm.payment_status_id AND ps.is_settled
                 WHERE pm.stall_application_id = a.id), 0) AS fee_paid,
       s.id AS event_stall_id, s.stall_code
FROM events.stall_application a
JOIN ref.stall_type st ON st.id = a.stall_type_id
JOIN ref.stall_category sc ON sc.id = a.stall_category_id
LEFT JOIN events.event_stall s ON s.stall_application_id = a.id;

-- Stalls with their visitors' feedback (no person in it).
CREATE OR REPLACE VIEW events.v_stall AS
SELECT s.id AS event_stall_id, s.event_id, s.stall_code, COALESCE(a.stall_name, s.stall_name) AS stall_name, st.code AS stall_type, sc.code AS stall_category,
       COALESCE(a.applicant_person_id, s.owner_person_id) AS owner_person_id, sz.code AS stall_size, COALESCE(a.custom_size, s.custom_size) AS custom_size,
       COALESCE(a.electricity_required, s.electricity_required) AS electricity_required, s.location, s.is_active,
       (s.stall_application_id IS NOT NULL) AS from_application,
       (SELECT count(*) FROM events.stall_feedback f WHERE f.event_stall_id = s.id)::int AS feedback_count,
       (SELECT round(avg(p.score), 2) FROM events.stall_feedback f JOIN events.stall_feedback_point p ON p.stall_feedback_id = f.id WHERE f.event_stall_id = s.id) AS feedback_avg
FROM events.event_stall s
LEFT JOIN events.stall_application a ON a.id = s.stall_application_id
LEFT JOIN ref.stall_type st ON st.id = COALESCE(a.stall_type_id, s.stall_type_id)
LEFT JOIN ref.stall_category sc ON sc.id = COALESCE(a.stall_category_id, s.stall_category_id)
LEFT JOIN ref.stall_size sz ON sz.id = COALESCE(a.stall_size_id, s.stall_size_id);


