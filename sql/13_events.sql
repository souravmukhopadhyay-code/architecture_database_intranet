-- One payment of a registration fee (in a team event: the team's flat fee,
-- paid by its leader) or of a stall fee. Online: an order of the gateway that
-- is captured or fails. Offline (UPI, bank transfer, cash): claimed by the
-- payer with a reference and proof, then verified by an organiser — or
-- recorded as received by an organiser. The gateway itself (signatures, the
-- webhook, reconciliation) is the application's; here are the facts. A captured
-- payment is never changed except to record its refund; who must be refunded
-- is derived (v_refund_queue).
CREATE TABLE events.event_payment (
  id                             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  receipt_no                     citext NOT NULL UNIQUE CHECK (receipt_no ~ '^RCP-[0-9]{4}-[0-9]{6,}$'),
  registration_id                uuid REFERENCES events.event_registration(id),
  stall_application_id           uuid REFERENCES events.stall_application(id),
  event_team_id                  uuid REFERENCES events.event_team(id),          -- the team paid for (team events)
  amount                         numeric(10,2) NOT NULL CHECK (amount > 0),
  currency_code                  char(3) NOT NULL,
  payment_channel_id             smallint NOT NULL REFERENCES ref.payment_channel(id),
  payment_status_id              smallint NOT NULL REFERENCES ref.payment_status(id),
  gateway_order_id               text UNIQUE,
  gateway_payment_id             text UNIQUE,
  payment_reference              text,                     -- offline: the transaction id the payer quotes
  proof_file_id                  uuid REFERENCES people.file_object(id),
  attempts                       smallint NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  webhook_verified               boolean NOT NULL DEFAULT false,
  recorded_by_account_id         uuid REFERENCES iam.user_account(id),   -- offline: who entered it (the payer, or an organiser)
  verified_by_account_id         uuid REFERENCES iam.user_account(id),   -- offline: the organiser who confirmed the money arrived
  superseded_at                  timestamptz,              -- an open order replaced by a newer one
  captured_at                    timestamptz,
  failed_at                      timestamptz,
  refunded_at                    timestamptz,
  refund_reference               text,
  refund_note                    text,
  refund_recorded_by_account_id  uuid REFERENCES iam.user_account(id),
  created_at                     timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at                     timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(registration_id, stall_application_id) = 1),
  CHECK (event_team_id IS NULL OR registration_id IS NOT NULL),
  CHECK ((refunded_at IS NULL) = (refund_recorded_by_account_id IS NULL) AND (refunded_at IS NULL) = (refund_reference IS NULL))
);
