-- The event: created (unpublished) by the approval of its proposal, which
-- stays the source of its fixed facts (type, dates, fees, participation,
-- capacity, prizes, sponsors, audience). Here is only what the organisers
-- settle afterwards: descriptions, contact person, the registration window
-- and settings, images and links — and the three moments of its life:
-- published, completed, cancelled. Its status is derived (v_event).
CREATE TABLE events.event (
  id                          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_code                  citext NOT NULL UNIQUE CHECK (event_code ~ '^EVT-[0-9]{4}-[0-9]{4,}$'),
  event_proposal_id           uuid NOT NULL UNIQUE REFERENCES events.event_proposal(id),
  short_description           text CHECK (char_length(short_description) <= 200),
  long_description            text,
  contact_person_id           uuid REFERENCES people.person(id),
  registration_window         tstzrange,
  registration_cap            int CHECK (registration_cap >= 1),
  requires_approval           boolean NOT NULL DEFAULT false,     -- registrations wait for an organiser's decision
  allow_withdraw              boolean NOT NULL DEFAULT true,
  accepts_volunteer_applications boolean NOT NULL DEFAULT false,  -- people may offer to volunteer (events.volunteer_application)
  stall_applications_open     boolean NOT NULL DEFAULT false,     -- stalls may be applied for (events.stall_application)
  stall_application_deadline  timestamptz,
  max_applied_stalls          int CHECK (max_applied_stalls >= 1),
  website_url                 text CHECK (website_url ~ '^https?://'),
  logo_file_id                uuid REFERENCES people.file_object(id),
  banner_file_id              uuid REFERENCES people.file_object(id),
  eligibility_text            text,
  rules_text                  text,
  published_at                timestamptz,
  published_by_account_id     uuid REFERENCES iam.user_account(id),
  completed_at                timestamptz,
  completed_by_account_id     uuid REFERENCES iam.user_account(id),
  cancelled_at                timestamptz,
  cancelled_by_account_id     uuid REFERENCES iam.user_account(id),
  cancel_reason               text,
  created_at                  timestamptz NOT NULL DEFAULT now(),
  updated_at                  timestamptz NOT NULL DEFAULT now(),
  CHECK (registration_window IS NULL OR (NOT isempty(registration_window) AND NOT lower_inf(registration_window) AND NOT upper_inf(registration_window))),
  CHECK ((published_at IS NULL) = (published_by_account_id IS NULL)),
  CHECK ((completed_at IS NULL) = (completed_by_account_id IS NULL)),
  CHECK ((cancelled_at IS NULL) = (cancelled_by_account_id IS NULL) AND (cancelled_at IS NULL) = (cancel_reason IS NULL)),
  CHECK (completed_at IS NULL OR published_at IS NOT NULL)
);
