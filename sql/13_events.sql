CREATE OR REPLACE FUNCTION events.club_change_request_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_set record; t record;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.instance_id IS NOT NULL THEN
      RAISE EXCEPTION 'club_change_request: a submitted request is a record; withdraw it instead' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;
  IF TG_OP = 'INSERT' THEN
    NEW.request_code := COALESCE(NEW.request_code, format('CCR-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.club_change_seq')::text, 3, '0')));
    IF NEW.applied_at IS NOT NULL OR NEW.instance_id IS NOT NULL THEN
      RAISE EXCEPTION 'club_change_request: a request starts as a draft' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF OLD.instance_id IS NOT NULL THEN
    -- once submitted only the application of the approved change is recorded, by the database
    IF (to_jsonb(NEW) - 'applied_at' - 'updated_at') <> (to_jsonb(OLD) - 'applied_at' - 'updated_at') OR OLD.applied_at IS NOT NULL
       OR current_setting('events.club_change_apply', true) IS DISTINCT FROM 'on' THEN
      RAISE EXCEPTION 'club_change_request: a submitted request is never edited' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  ELSIF NEW.club_org_unit_id <> OLD.club_org_unit_id OR NEW.requested_by_account_id <> OLD.requested_by_account_id OR NEW.request_code <> OLD.request_code THEN
    RAISE EXCEPTION 'club_change_request: the club, the requester and the code of a draft never change' USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF NOT events.is_club_officer(NEW.requested_by_account_id, NEW.club_org_unit_id)
     AND NOT authz.has_permission(NEW.requested_by_account_id, 'events.club.update', NEW.club_org_unit_id) THEN
    RAISE EXCEPTION 'club_change_request: requested by an officer or advisor of the club, or its administrator' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NOT events.club_is_active(NEW.club_org_unit_id) THEN
    RAISE EXCEPTION 'club_change_request: the club is suspended or closed' USING ERRCODE = 'check_violation';
  END IF;
  SELECT * INTO t FROM ref.club_change_type WHERE id = NEW.club_change_type_id;
  SELECT * INTO v_set FROM events.event_setting;
  -- the request carries exactly what its type changes
  IF t.sets_name <> (NEW.new_name IS NOT NULL) OR t.sets_objective <> (NEW.new_objective IS NOT NULL)
     OR t.sets_category <> (NEW.new_club_category_id IS NOT NULL)
     OR (t.sets_advisor AND NEW.new_employee_id IS NULL)
     OR (NOT t.sets_advisor AND NOT t.sets_co_advisor AND NEW.new_employee_id IS NOT NULL) THEN
    RAISE EXCEPTION 'club_change_request: a % request states exactly what it changes', t.code USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.new_name IS NOT NULL THEN
    IF char_length(btrim(NEW.new_name)) NOT BETWEEN v_set.club_name_min_length AND v_set.club_name_max_length THEN
      RAISE EXCEPTION 'club_change_request: the club name has % to % characters', v_set.club_name_min_length, v_set.club_name_max_length USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM events.club c JOIN org.org_unit u ON u.id = c.org_unit_id AND u.is_active
               WHERE lower(u.name) = lower(btrim(NEW.new_name)) AND c.org_unit_id <> NEW.club_org_unit_id) THEN
      RAISE EXCEPTION 'club_change_request: a club named "%" already exists', NEW.new_name USING ERRCODE = 'unique_violation';
    END IF;
  END IF;
  IF NEW.new_objective IS NOT NULL AND char_length(btrim(NEW.new_objective)) < v_set.club_objective_min_length THEN
    RAISE EXCEPTION 'club_change_request: the objective has at least % characters', v_set.club_objective_min_length USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.new_employee_id IS NOT NULL THEN
    IF (v_set.advisor_must_be_faculty AND NOT events.is_teaching_employee(NEW.new_employee_id))
       OR NOT events.is_current_employee(NEW.new_employee_id) THEN
      RAISE EXCEPTION 'club_change_request: the incoming advisor is not eligible (current %)', CASE WHEN v_set.advisor_must_be_faculty THEN 'faculty' ELSE 'employee' END
        USING ERRCODE = 'check_violation';
    END IF;
    -- one person is not both advisor and co-advisor
    IF EXISTS (SELECT 1 FROM org.appointment ap JOIN org.position_type pt ON pt.id = ap.position_type_id
               WHERE ap.org_unit_id = NEW.club_org_unit_id AND ap.employee_id = NEW.new_employee_id AND ap.valid @> current_date
                 AND pt.code = CASE WHEN t.sets_advisor THEN 'CLUB_CO_ADVISOR' ELSE 'CLUB_ADVISOR' END) THEN
      RAISE EXCEPTION 'club_change_request: that person already holds the other advisory post of the club' USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  IF NEW.instance_id IS NOT NULL THEN       -- being submitted
    IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'CLUB_CHANGE'
                   WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = NEW.club_org_unit_id AND i.submitted_by_account_id = NEW.requested_by_account_id) THEN
      RAISE EXCEPTION 'club_change_request: the round is not the requester''s CLUB_CHANGE round of the club' USING ERRCODE = 'check_violation';
    END IF;
    IF (t.sets_officers AND NOT EXISTS (SELECT 1 FROM events.club_change_officer o WHERE o.club_change_request_id = NEW.id))
       OR (t.sets_members AND NOT EXISTS (SELECT 1 FROM events.club_change_member m WHERE m.club_change_request_id = NEW.id)) THEN
      RAISE EXCEPTION 'club_change_request: name the officers / members the request changes before submitting' USING ERRCODE = 'check_violation';
    END IF;
    IF v_set.max_open_club_changes IS NOT NULL AND
       (SELECT count(*) FROM events.club_change_request r JOIN wf.v_instance_state s ON s.instance_id = r.instance_id AND s.status = 'IN_PROGRESS'
        WHERE r.club_org_unit_id = NEW.club_org_unit_id AND r.id <> NEW.id) >= v_set.max_open_club_changes THEN
      RAISE EXCEPTION 'club_change_request: the club already has % change request(s) under approval', v_set.max_open_club_changes USING ERRCODE = 'exclusion_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_club_change_request_validate BEFORE INSERT OR UPDATE OR DELETE ON events.club_change_request
  FOR EACH ROW EXECUTE FUNCTION events.club_change_request_validate();

-- The officer / member lines change only while the request is a draft, belong
-- to a request of the right type, and name current students.
CREATE OR REPLACE FUNCTION events.club_change_part_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_id uuid := CASE WHEN TG_OP = 'DELETE' THEN OLD.club_change_request_id ELSE NEW.club_change_request_id END;
        v_req record; v_student uuid;
BEGIN
  SELECT r.instance_id, r.club_org_unit_id, t.sets_officers, t.sets_members INTO v_req
  FROM events.club_change_request r JOIN ref.club_change_type t ON t.id = r.club_change_type_id WHERE r.id = v_id;
  IF v_req.instance_id IS NOT NULL THEN
    RAISE EXCEPTION '%: the request has been submitted; its lines are frozen', TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  IF (TG_TABLE_NAME = 'club_change_officer' AND NOT v_req.sets_officers) OR (TG_TABLE_NAME = 'club_change_member' AND NOT v_req.sets_members) THEN
    RAISE EXCEPTION '%: this kind of request does not change that', TG_TABLE_NAME USING ERRCODE = 'check_violation';
  END IF;
  v_student := (to_jsonb(NEW) ->> 'student_id')::uuid;
  IF TG_TABLE_NAME = 'club_change_member' THEN
    IF NEW.is_removal <> EXISTS (SELECT 1 FROM events.club_member m WHERE m.club_org_unit_id = v_req.club_org_unit_id AND m.student_id = NEW.student_id AND m.valid @> current_date) THEN
      RAISE EXCEPTION 'club_change_member: only a current member leaves, only a non-member joins' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.is_removal THEN RETURN NEW; END IF;
  END IF;
  IF v_student IS NOT NULL AND NOT events.is_current_student(v_student) THEN
    RAISE EXCEPTION '%: not a current student', TG_TABLE_NAME USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_club_change_officer_guard BEFORE INSERT OR UPDATE OR DELETE ON events.club_change_officer FOR EACH ROW EXECUTE FUNCTION events.club_change_part_guard();
CREATE TRIGGER trg_club_change_member_guard  BEFORE INSERT OR UPDATE OR DELETE ON events.club_change_member  FOR EACH ROW EXECUTE FUNCTION events.club_change_part_guard();

-- Apply an approved change. Called by the approval hook only.
CREATE OR REPLACE FUNCTION events.apply_club_change(p_request uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v record; t record; v_pos smallint;
BEGIN
  SELECT * INTO v FROM events.club_change_request WHERE id = p_request FOR UPDATE;
  IF v.id IS NULL OR v.applied_at IS NOT NULL THEN RETURN; END IF;
  IF NOT EXISTS (SELECT 1 FROM wf.v_instance_state s WHERE s.instance_id = v.instance_id AND s.status = 'APPROVED') THEN
    RAISE EXCEPTION 'apply_club_change: the request is not approved' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO t FROM ref.club_change_type WHERE id = v.club_change_type_id;
  IF t.sets_name THEN
    UPDATE org.org_unit SET name = btrim(v.new_name) WHERE id = v.club_org_unit_id;
  END IF;
  IF t.sets_category THEN
    UPDATE events.club SET club_category_id = v.new_club_category_id WHERE org_unit_id = v.club_org_unit_id;
  END IF;
  IF t.sets_objective THEN
    UPDATE events.club SET objective = v.new_objective WHERE org_unit_id = v.club_org_unit_id;
  END IF;
  IF t.sets_advisor OR t.sets_co_advisor THEN
    SELECT id INTO v_pos FROM org.position_type WHERE code = CASE WHEN t.sets_advisor THEN 'CLUB_ADVISOR' ELSE 'CLUB_CO_ADVISOR' END;
    -- the outgoing holder's appointment ends today (one that began today is withdrawn)
    DELETE FROM org.appointment WHERE org_unit_id = v.club_org_unit_id AND position_type_id = v_pos AND valid @> current_date AND lower(valid) >= current_date;
    UPDATE org.appointment SET valid = daterange(lower(valid), current_date)
    WHERE org_unit_id = v.club_org_unit_id AND position_type_id = v_pos AND valid @> current_date;
    IF v.new_employee_id IS NOT NULL THEN
      INSERT INTO org.appointment (org_unit_id, position_type_id, employee_id) VALUES (v.club_org_unit_id, v_pos, v.new_employee_id);
    END IF;
  END IF;
  IF t.sets_officers THEN
    -- the named offices fall vacant, and an incoming student leaves any other office of the club
    DELETE FROM events.club_officer co
    WHERE co.club_org_unit_id = v.club_org_unit_id AND co.valid @> current_date AND lower(co.valid) >= current_date
      AND EXISTS (SELECT 1 FROM events.club_change_officer x WHERE x.club_change_request_id = v.id AND (x.club_office_id = co.club_office_id OR x.student_id = co.student_id));
    UPDATE events.club_officer co SET valid = daterange(lower(co.valid), current_date)
    WHERE co.club_org_unit_id = v.club_org_unit_id AND co.valid @> current_date
      AND EXISTS (SELECT 1 FROM events.club_change_officer x WHERE x.club_change_request_id = v.id AND (x.club_office_id = co.club_office_id OR x.student_id = co.student_id));
    INSERT INTO events.club_officer (club_org_unit_id, club_office_id, student_id)
    SELECT v.club_org_unit_id, x.club_office_id, x.student_id FROM events.club_change_officer x WHERE x.club_change_request_id = v.id AND x.student_id IS NOT NULL;
    -- an officer is a member
    INSERT INTO events.club_member (club_org_unit_id, student_id, club_member_role_id, added_by_account_id)
    SELECT v.club_org_unit_id, x.student_id, ref.id_of('club_member_role', 'MEMBER'), v.requested_by_account_id
    FROM events.club_change_officer x
    WHERE x.club_change_request_id = v.id AND x.student_id IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM events.club_member m WHERE m.club_org_unit_id = v.club_org_unit_id AND m.student_id = x.student_id AND m.valid @> current_date);
  END IF;
  IF t.sets_members THEN
    DELETE FROM events.club_member m
    WHERE m.club_org_unit_id = v.club_org_unit_id AND m.valid @> current_date AND lower(m.valid) >= current_date
      AND EXISTS (SELECT 1 FROM events.club_change_member x WHERE x.club_change_request_id = v.id AND x.is_removal AND x.student_id = m.student_id);
    UPDATE events.club_member m SET valid = daterange(lower(m.valid), current_date)
    WHERE m.club_org_unit_id = v.club_org_unit_id AND m.valid @> current_date
      AND EXISTS (SELECT 1 FROM events.club_change_member x WHERE x.club_change_request_id = v.id AND x.is_removal AND x.student_id = m.student_id);
    INSERT INTO events.club_member (club_org_unit_id, student_id, club_member_role_id, added_by_account_id)
    SELECT v.club_org_unit_id, x.student_id, x.club_member_role_id, v.requested_by_account_id
    FROM events.club_change_member x WHERE x.club_change_request_id = v.id AND NOT x.is_removal;
  END IF;
  PERFORM set_config('events.club_change_apply', 'on', true);
  UPDATE events.club_change_request SET applied_at = clock_timestamp() WHERE id = v.id;
  PERFORM set_config('events.club_change_apply', 'off', true);
END $$;

-- A student's primary club (the one shown first on their profile). By default
-- only a club in which they hold an office (event_setting.primary_club_requires_office).
CREATE TABLE events.primary_club (
  student_id        uuid PRIMARY KEY REFERENCES people.student(id) ON DELETE CASCADE,
  club_org_unit_id  uuid NOT NULL REFERENCES events.club(org_unit_id) ON DELETE CASCADE,
  set_at            timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION events.primary_club_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.set_at := now();
  IF (SELECT primary_club_requires_office FROM events.event_setting) THEN
    IF NOT EXISTS (SELECT 1 FROM events.club_officer o WHERE o.club_org_unit_id = NEW.club_org_unit_id AND o.student_id = NEW.student_id AND o.valid @> current_date) THEN
      RAISE EXCEPTION 'primary_club: only a club in which the student holds an office' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NOT EXISTS (SELECT 1 FROM events.club_member m WHERE m.club_org_unit_id = NEW.club_org_unit_id AND m.student_id = NEW.student_id AND m.valid @> current_date) THEN
    RAISE EXCEPTION 'primary_club: only a club the student is a member of' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_primary_club_validate BEFORE INSERT OR UPDATE ON events.primary_club
  FOR EACH ROW EXECUTE FUNCTION events.primary_club_validate();

-- ################################################## VOLUNTEER SIGN-UP ##

-- Someone offers to volunteer at an event that takes applications
-- (event.accepts_volunteer_applications); an organiser decides, and acceptance
-- makes the volunteer (gate and scanning right are then given by the organiser).
CREATE TABLE events.volunteer_application (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id               uuid NOT NULL REFERENCES events.event(id) ON DELETE CASCADE,
  person_id              uuid NOT NULL REFERENCES people.person(id),
  note                   text,
  applied_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
  decided_at             timestamptz,
  decided_by_account_id  uuid REFERENCES iam.user_account(id),
  is_accepted            boolean,
  decision_note          text,
  UNIQUE (event_id, person_id),
  CHECK ((decided_at IS NULL) = (is_accepted IS NULL) AND (decided_at IS NULL) = (decided_by_account_id IS NULL))
);
CREATE OR REPLACE FUNCTION events.volunteer_application_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT e.accepts_volunteer_applications, e.published_at, e.cancelled_at, e.completed_at, upper(p.during) AS ends INTO v
    FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = NEW.event_id;
    IF NEW.decided_at IS NOT NULL THEN
      RAISE EXCEPTION 'volunteer_application: an application starts undecided' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT v.accepts_volunteer_applications OR v.published_at IS NULL OR v.cancelled_at IS NOT NULL OR v.completed_at IS NOT NULL
       OR clock_timestamp()::timestamp >= v.ends THEN
      RAISE EXCEPTION 'volunteer_application: this event takes no volunteer applications (now)' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM people.v_person_principal_kind k WHERE k.person_id = NEW.person_id AND k.principal_kind IN ('STUDENT', 'EMPLOYEE')) THEN
      RAISE EXCEPTION 'volunteer_application: volunteers are students or employees of the university' USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM events.event_volunteer ev WHERE ev.event_id = NEW.event_id AND ev.person_id = NEW.person_id AND ev.removed_at IS NULL) THEN
      RAISE EXCEPTION 'volunteer_application: already a volunteer of this event' USING ERRCODE = 'unique_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.decided_at IS NOT NULL OR NEW.event_id <> OLD.event_id OR NEW.person_id <> OLD.person_id OR NEW.applied_at <> OLD.applied_at
     OR NEW.note IS DISTINCT FROM OLD.note THEN
    RAISE EXCEPTION 'volunteer_application: only the decision is recorded, once' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.decided_at IS NOT NULL AND NOT events.can_manage(NEW.decided_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'volunteer_application: decided by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_volunteer_application_validate BEFORE INSERT OR UPDATE ON events.volunteer_application
  FOR EACH ROW EXECUTE FUNCTION events.volunteer_application_validate();
CREATE OR REPLACE FUNCTION events.volunteer_application_effects()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.is_accepted AND OLD.decided_at IS NULL THEN
    UPDATE events.event_volunteer SET removed_at = NULL WHERE event_id = NEW.event_id AND person_id = NEW.person_id;
    IF NOT FOUND THEN
      INSERT INTO events.event_volunteer (event_id, person_id, volunteer_role_id, can_scan, assigned_by_account_id)
      VALUES (NEW.event_id, NEW.person_id, (SELECT id FROM ref.volunteer_role WHERE NOT is_manager AND is_active ORDER BY sort_order LIMIT 1), false, NEW.decided_by_account_id);
    END IF;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_volunteer_application_effects AFTER UPDATE OF decided_at ON events.volunteer_application
  FOR EACH ROW EXECUTE FUNCTION events.volunteer_application_effects();

-- ################################################# COUPONS · PAYMENTS ##

CREATE SEQUENCE events.receipt_seq;

-- A discount coupon of a paid event: percentage (with an optional cap) or a
-- fixed amount, with a minimum amount, total and per-person limits and an expiry.
CREATE TABLE events.event_coupon (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id                 uuid NOT NULL REFERENCES events.event(id) ON DELETE CASCADE,
  code                     citext NOT NULL CHECK (code = upper(btrim(code)) AND code <> ''),
  coupon_discount_type_id  smallint NOT NULL REFERENCES ref.coupon_discount_type(id),
  discount_value           numeric(10,2) NOT NULL CHECK (discount_value > 0),
  max_discount             numeric(10,2) CHECK (max_discount > 0),          -- cap on a percentage discount
  min_amount               numeric(10,2) CHECK (min_amount >= 0),           -- the fee must be at least this
  max_uses                 int CHECK (max_uses >= 1),                       -- NULL = unlimited
  max_uses_per_person      int DEFAULT 1 CHECK (max_uses_per_person >= 1),  -- NULL = unlimited
  expires_at               timestamptz,
  is_active                boolean NOT NULL DEFAULT true,
  description              text,
  created_by_account_id    uuid NOT NULL REFERENCES iam.user_account(id),
  created_at               timestamptz NOT NULL DEFAULT now(),
  updated_at               timestamptz NOT NULL DEFAULT now(),
  UNIQUE (event_id, code)
);
SELECT util.attach_updated_at('events.event_coupon');

-- A coupon used on a registration: one per registration; the discount is fixed
-- at that moment (the coupon's terms may change later).
CREATE TABLE events.coupon_redemption (
  id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_coupon_id  uuid NOT NULL REFERENCES events.event_coupon(id),
  registration_id  uuid NOT NULL UNIQUE REFERENCES events.event_registration(id) ON DELETE CASCADE,
  discount_amount  numeric(10,2) NOT NULL CHECK (discount_amount >= 0),
  redeemed_at      timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX coupon_redemption_coupon_idx ON events.coupon_redemption(event_coupon_id);

CREATE OR REPLACE FUNCTION events.event_coupon_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF EXISTS (SELECT 1 FROM events.coupon_redemption WHERE event_coupon_id = OLD.id) THEN
      RAISE EXCEPTION 'event_coupon: a coupon that was used is deactivated, not deleted' USING ERRCODE = 'foreign_key_violation';
    END IF;
    RETURN OLD;
  END IF;
  NEW.code := upper(btrim(NEW.code));
  IF TG_OP = 'UPDATE' AND (NEW.event_id <> OLD.event_id OR NEW.created_by_account_id <> OLD.created_by_account_id) THEN
    RAISE EXCEPTION 'event_coupon: the event and the creator never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NOT (SELECT p.is_paid FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = NEW.event_id) THEN
    RAISE EXCEPTION 'event_coupon: this event is free — no coupon is needed' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'INSERT' AND NOT events.can_manage(NEW.created_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'event_coupon: coupons are created by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF (SELECT is_percentage FROM ref.coupon_discount_type WHERE id = NEW.coupon_discount_type_id) THEN
    IF NEW.discount_value > 100 THEN
      RAISE EXCEPTION 'event_coupon: a percentage is at most 100' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.max_discount IS NOT NULL THEN
    RAISE EXCEPTION 'event_coupon: a cap belongs to a percentage discount' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_coupon_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_coupon
  FOR EACH ROW EXECUTE FUNCTION events.event_coupon_validate();

-- Redeeming: the coupon is of the same event, active, not expired, within its
-- limits (a cancelled registration's use is free again) and the fee reaches
-- its minimum; the discount is computed here. Whatever remains payable is
-- either nothing or at least event_setting.min_payable_amount.
CREATE OR REPLACE FUNCTION events.coupon_redemption_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c record; r record; v_base numeric; v_discount numeric; v_min numeric;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION 'coupon_redemption: a redemption is never edited' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF events.amount_settled(OLD.registration_id) > 0 THEN
      RAISE EXCEPTION 'coupon_redemption: the fee was paid with this coupon applied' USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
  END IF;
  SELECT cp.*, dt.is_percentage INTO c FROM events.event_coupon cp JOIN ref.coupon_discount_type dt ON dt.id = cp.coupon_discount_type_id
  WHERE cp.id = NEW.event_coupon_id FOR UPDATE OF cp;
  SELECT reg.event_id, reg.person_id, reg.cancelled_at INTO r FROM events.event_registration reg WHERE reg.id = NEW.registration_id FOR UPDATE;
  IF r.event_id <> c.event_id THEN
    RAISE EXCEPTION 'coupon_redemption: the coupon belongs to another event' USING ERRCODE = 'check_violation';
  END IF;
  IF r.cancelled_at IS NOT NULL THEN
    RAISE EXCEPTION 'coupon_redemption: the registration is cancelled' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT c.is_active OR (c.expires_at IS NOT NULL AND c.expires_at <= clock_timestamp()) THEN
    RAISE EXCEPTION 'coupon_redemption: the coupon is inactive or has expired' USING ERRCODE = 'check_violation';
  END IF;
  IF events.payer_registration(NEW.registration_id) IS DISTINCT FROM NEW.registration_id THEN
    RAISE EXCEPTION 'coupon_redemption: in a team event the coupon is applied by the team''s leader' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF events.amount_settled(NEW.registration_id) > 0 THEN
    RAISE EXCEPTION 'coupon_redemption: the fee is already paid' USING ERRCODE = 'check_violation';
  END IF;
  IF c.max_uses IS NOT NULL AND
     (SELECT count(*) FROM events.coupon_redemption x JOIN events.event_registration xr ON xr.id = x.registration_id AND xr.cancelled_at IS NULL
      WHERE x.event_coupon_id = c.id) >= c.max_uses THEN
    RAISE EXCEPTION 'coupon_redemption: the coupon has been used % time(s) — its limit', c.max_uses USING ERRCODE = 'check_violation';
  END IF;
  IF c.max_uses_per_person IS NOT NULL AND
     (SELECT count(*) FROM events.coupon_redemption x JOIN events.event_registration xr ON xr.id = x.registration_id AND xr.cancelled_at IS NULL
      WHERE x.event_coupon_id = c.id AND xr.person_id = r.person_id) >= c.max_uses_per_person THEN
    RAISE EXCEPTION 'coupon_redemption: this person has used the coupon as often as it allows' USING ERRCODE = 'check_violation';
  END IF;
  v_base := events.amount_due(NEW.registration_id);
  IF v_base <= 0 THEN
    RAISE EXCEPTION 'coupon_redemption: nothing is due on this registration' USING ERRCODE = 'check_violation';
  END IF;
  IF c.min_amount IS NOT NULL AND v_base < c.min_amount THEN
    RAISE EXCEPTION 'coupon_redemption: the fee (%) is below the coupon''s minimum (%)', v_base, c.min_amount USING ERRCODE = 'check_violation';
  END IF;
  v_discount := CASE WHEN c.is_percentage THEN least(round(v_base * c.discount_value / 100, 2), COALESCE(c.max_discount, v_base)) ELSE c.discount_value END;
  v_discount := least(v_discount, v_base);
  SELECT min_payable_amount INTO v_min FROM events.event_setting;
  IF v_base - v_discount > 0 AND v_base - v_discount < v_min THEN
    v_discount := v_base - v_min;       -- what remains is either nothing or a payable amount
  END IF;
  NEW.discount_amount := greatest(v_discount, 0);
  NEW.redeemed_at := clock_timestamp();
  RETURN NEW;
END $$;
CREATE TRIGGER trg_coupon_redemption_validate BEFORE INSERT OR UPDATE OR DELETE ON events.coupon_redemption
  FOR EACH ROW EXECUTE FUNCTION events.coupon_redemption_validate();

