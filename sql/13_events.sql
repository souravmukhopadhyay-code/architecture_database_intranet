-- Module settings: the one row an events administrator edits
-- (events.setting.update). No policy value of this module is written into a
-- function or a CHECK. Each is one of:
--   * a column of this row;
--   * a row of a lookup (ref.event_type, ref.event_level, ref.club_office
--     .is_required / .may_propose, ref.event_audience_kind.is_external ...);
--   * a dated row (events.event_type_points, events.club_tier);
--   * a row of the approval engine (wf.approval_chain / approval_chain_stage:
--     levels, approvers, conditions, deadlines, timeout actions);
--   * the retention period of a privacy.processing_purpose;
--   * which unit types may have clubs (org.org_unit_type_rule).
-- The defaults below are the old system's rules (POLICY).
CREATE TABLE events.event_setting (
  id                                boolean PRIMARY KEY DEFAULT true CHECK (id),      -- exactly one row
  club_name_min_length              smallint NOT NULL DEFAULT 3   CHECK (club_name_min_length >= 1),
  club_name_max_length              smallint NOT NULL DEFAULT 100,
  club_objective_min_length         smallint NOT NULL DEFAULT 50  CHECK (club_objective_min_length >= 1),
  advisor_must_be_faculty           boolean  NOT NULL DEFAULT true,                   -- false: any current employee may advise a club
  proposal_min_lead_time            interval NOT NULL DEFAULT interval '0' CHECK (proposal_min_lead_time >= interval '0'),   -- submitted at least this long before the start
  proposal_needs_audience           boolean  NOT NULL DEFAULT true,
  proposal_needs_coordinator        boolean  NOT NULL DEFAULT true,
  proposal_needs_sdg                boolean  NOT NULL DEFAULT true,
  max_open_proposals_per_proposer   smallint DEFAULT 1 CHECK (max_open_proposals_per_proposer >= 1),   -- per organising unit; NULL = no limit
  max_extra_passes_per_participant  smallint NOT NULL DEFAULT 20  CHECK (max_extra_passes_per_participant >= 0),   -- the most a proposal may ask for
  publish_needs_description         boolean  NOT NULL DEFAULT true,
  publish_needs_contact             boolean  NOT NULL DEFAULT true,
  publish_needs_round               boolean  NOT NULL DEFAULT true,
  feedback_rating_max               smallint NOT NULL DEFAULT 10  CHECK (feedback_rating_max >= 2),   -- ratings run from 1 to this
  max_open_club_changes             smallint DEFAULT 1 CHECK (max_open_club_changes >= 1),             -- change requests of one club under approval; NULL = no limit
  primary_club_requires_office      boolean  NOT NULL DEFAULT true,                   -- false: any club the student is a member of
  currency_code                     char(3)  NOT NULL DEFAULT 'INR' CHECK (currency_code ~ '^[A-Z]{3}$'),
  min_payable_amount                numeric(10,2) NOT NULL DEFAULT 1 CHECK (min_payable_amount >= 0),   -- after a coupon: nothing, or at least this
  unpaid_registration_expiry        interval CHECK (unpaid_registration_expiry > interval '0'),         -- NULL = unpaid registrations never expire
  mail_credits_per_registration     smallint NOT NULL DEFAULT 3   CHECK (mail_credits_per_registration >= 0),
  mail_subject_max_length           int      NOT NULL DEFAULT 256   CHECK (mail_subject_max_length >= 1),
  mail_body_max_length              int      NOT NULL DEFAULT 50000 CHECK (mail_body_max_length >= 1),
  mail_open_tracking                boolean  NOT NULL DEFAULT false,                  -- opens are recorded only when on, and never for a minor
  stall_feedback_max_points         smallint NOT NULL DEFAULT 10  CHECK (stall_feedback_max_points >= 1),
  round_checkin_opens_before        interval NOT NULL DEFAULT interval '30 minutes' CHECK (round_checkin_opens_before >= interval '0'),   -- how long before a session its check-in opens
  expense_bill_required_above       numeric(12,2) CHECK (expense_bill_required_above >= 0),             -- an expense above this needs its bill before settlement; NULL = never
  updated_by_account_id             uuid REFERENCES iam.user_account(id),
  created_at                        timestamptz NOT NULL DEFAULT now(),
  updated_at                        timestamptz NOT NULL DEFAULT now(),
  CHECK (club_name_max_length >= club_name_min_length)
);
