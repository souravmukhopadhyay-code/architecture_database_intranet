  revises_proposal_id        uuid REFERENCES events.event_proposal(id),
  instance_id                uuid UNIQUE REFERENCES wf.approval_instance(id),   -- NULL = draft
  created_at                 timestamptz NOT NULL DEFAULT now(),
  updated_at                 timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT isempty(during) AND NOT lower_inf(during) AND NOT upper_inf(during)),
  CHECK (max_team_size IS NULL OR max_team_size >= COALESCE(min_team_size, 1)),
  CHECK (allow_extra_passes = (max_extra_passes > 0)),
  CHECK ((instance_id IS NULL) = (facility_event_request_id IS NULL))
);
