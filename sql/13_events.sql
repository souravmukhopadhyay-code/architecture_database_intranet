-- =============================================================================
-- 13_events.sql — Event Management & Academic Clubs (schema: events)
--
-- A module on top of the foundation (runs after 00–12). Rebuilt from the old
-- SGT UMS academic-clubs and event-management modules, keeping their
-- behaviour; approval is NOT built here — it is configuration on the wf
-- engine (06b): document types CLUB_PROPOSAL, EVENT_PROPOSAL and CLUB_CHANGE,
-- a default chain each, and any number of overrides per school / club as chain
-- rows. No policy value is hard-coded: see events.event_setting.
--
-- What the foundation already knows is referenced, never copied:
--   a club                   an org.org_unit of type CLUB (under a school, a
--                            department, a central department or the
--                            university); its advisor / co-advisor are
--                            org.appointment rows (positions CLUB_ADVISOR /
--                            CLUB_CO_ADVISOR); student officers and members
--                            are dated rows here
--   who proposes / registers people.person / student / employee,
--                            iam.user_account — no name, e-mail or phone copies
--   approval                 wf (stages, conditions, deadlines, delegation …)
--   venue, equipment, cabs   the facility package: the proposal owns a
--                            facility.event_request sharing its round, so
--                            rooms are held from submission and go to their
--                            custodians on approval; vehicles through
--                            facility.request_trip()
--   duty leave               academic.attendance_leave (DUTY_LEAVE)
--   files                    people.file_object
--
--   CLUBS       club, club_officer, club_member, club_application,
--               club_suspension, club_calendar_item; club_proposal (+ officers,
--               members, attachments) → approved → the club exists
--   PROPOSALS   event_proposal (draft → submitted round → approved) with its
--               audience, SDGs, partner clubs, speakers, coordinators, budget
--               items, funding sources, prizes, attachments, visibility;
--               sponsor, sponsorship (+ receipts, in-kind items)
--   EVENTS      event (created by the approval; what the organiser edits
--               afterwards), event_round, event_faq, event_link,
--               event_custom_field (+ options), event_volunteer,
--               post_event_report
--   TAKING PART registration (+ field_response, extra_pass), event_team
--               (+ members, invitations, join requests), entry_scan (in / out,
--               append-only), prize_award, feedback_token / feedback
--               (anonymous by construction), certificate_template, certificate
--   POINTS      event_type_points (config as data), club_point_award (written
--               when a club event completes), club_tier
--   CLUB LIFE   club_change_request (+ officer / member lines; applied by the
--               database on approval), primary_club, volunteer_application
--   MONEY       event_coupon, coupon_redemption, event_payment (online order
--               or offline claim; captured / failed / refunded) — what is
--               owed, paid and to be refunded is derived
--   STALLS      event_stall_fee, stall_application (+ set-ups, documents),
--               event_stall (+ products), stall_feedback (+ points; anonymous)
--   MAIL        event_mail, event_mail_recipient (no address stored),
--               event_mail_credit_grant
--
-- Clock: "has it started / ended" is asked of the wall clock (clock_timestamp),
-- not of the transaction's start, so a long transaction cannot act on stale time.
-- Nothing stores a status: club, proposal, event, registration, team and
-- attendance states are views. With the application, not here: the
-- conversation with the payment gateway (order creation, signature and webhook
-- verification, reconciliation), the sending of mail, rendering QR codes and
-- certificate files. The database records their outcome and enforces the rules.
-- =============================================================================

