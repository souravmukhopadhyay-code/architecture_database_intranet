CREATE OR REPLACE FUNCTION events.event_expense_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_event uuid := CASE WHEN TG_OP = 'DELETE' THEN OLD.event_id ELSE NEW.event_id END;
BEGIN
  IF EXISTS (SELECT 1 FROM events.event_settlement st JOIN wf.v_instance_state s ON s.instance_id = st.instance_id AND s.status IN ('IN_PROGRESS', 'APPROVED', 'SIGNED')
             WHERE st.event_id = v_event) THEN
    RAISE EXCEPTION 'event_expense: the settlement has been submitted; the expenses are frozen' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  IF TG_OP = 'UPDATE' AND NEW.event_id <> OLD.event_id THEN
    RAISE EXCEPTION 'event_expense: an expense stays with its event' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NOT events.can_manage(NEW.recorded_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'event_expense: expenses are recorded by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.incurred_on > current_date THEN
    RAISE EXCEPTION 'event_expense: an expense is recorded once it is incurred' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.proposal_budget_item_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM events.proposal_budget_item b JOIN events.event e ON e.event_proposal_id = b.event_proposal_id
       WHERE b.id = NEW.proposal_budget_item_id AND e.id = NEW.event_id AND b.budget_item_type_id = NEW.budget_item_type_id) THEN
    RAISE EXCEPTION 'event_expense: the budget line belongs to this event''s approved budget, under the same head' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_expense_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_expense
  FOR EACH ROW EXECUTE FUNCTION events.event_expense_validate();

CREATE OR REPLACE FUNCTION events.event_settlement_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record; v_limit numeric;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'event_settlement: a settlement is a record' USING ERRCODE = 'insufficient_privilege';
  END IF;
  NEW.settlement_code := COALESCE(NEW.settlement_code, format('EST-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.settlement_seq')::text, 3, '0')));
  SELECT e.cancelled_at, p.during, p.organising_org_unit_id INTO v
  FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = NEW.event_id;
  IF NOT events.can_manage(NEW.submitted_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'event_settlement: the accounts are settled by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF v.cancelled_at IS NULL AND clock_timestamp()::timestamp < upper(v.during) THEN
    RAISE EXCEPTION 'event_settlement: an event is settled after it is over (or cancelled)' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'EVENT_SETTLEMENT'
                 WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = v.organising_org_unit_id AND i.submitted_by_account_id = NEW.submitted_by_account_id) THEN
    RAISE EXCEPTION 'event_settlement: the round is not the submitter''s EVENT_SETTLEMENT round of the organising unit' USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM events.event_settlement st JOIN wf.v_instance_state s ON s.instance_id = st.instance_id AND s.status IN ('IN_PROGRESS', 'APPROVED', 'SIGNED')
             WHERE st.event_id = NEW.event_id) THEN
    RAISE EXCEPTION 'event_settlement: this event already has a settlement under approval or approved' USING ERRCODE = 'exclusion_violation';
  END IF;
  SELECT expense_bill_required_above INTO v_limit FROM events.event_setting;
  IF v_limit IS NOT NULL AND EXISTS (SELECT 1 FROM events.event_expense x WHERE x.event_id = NEW.event_id AND x.amount > v_limit AND x.bill_file_id IS NULL) THEN
    RAISE EXCEPTION 'event_settlement: every expense above % needs its bill attached', v_limit USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_settlement_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_settlement
  FOR EACH ROW EXECUTE FUNCTION events.event_settlement_validate();

