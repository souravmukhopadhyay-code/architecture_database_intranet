-- The event as people see it: the proposal's fixed facts, the organisers'
-- settings and the derived status
--   DRAFT · PUBLISHED · ONGOING · ENDED (over, not yet closed) · COMPLETED · CANCELLED
CREATE OR REPLACE VIEW events.v_event AS
SELECT e.id AS event_id, e.event_code, p.id AS event_proposal_id, p.organising_org_unit_id, t.code AS event_type, p.title, p.during,
       m.code AS event_mode, pt.code AS participation_type, pt.is_team, p.min_team_size, p.max_team_size,
       p.is_paid, p.fee_individual, p.fee_team, p.approx_capacity, events.seat_limit(e.id) AS seat_limit, p.gives_certificates,
       e.short_description, e.long_description, e.contact_person_id, e.registration_window, e.requires_approval, e.allow_withdraw,
       e.published_at, e.completed_at, e.cancelled_at,
