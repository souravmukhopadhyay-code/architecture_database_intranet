-- Attendance, derived from the gate log and the session check-ins.
CREATE OR REPLACE VIEW events.v_attendance AS
SELECT r.id AS registration_id, r.event_id, r.person_id,
       COALESCE(sum(s.people_count) FILTER (WHERE d.is_entry), 0)::int AS entered,
       COALESCE(sum(s.people_count) FILTER (WHERE NOT d.is_entry), 0)::int AS exited,
       (COALESCE(sum(s.people_count) FILTER (WHERE d.is_entry), 0) - COALESCE(sum(s.people_count) FILTER (WHERE NOT d.is_entry), 0))::int AS inside,
       (count(*) FILTER (WHERE d.is_entry) > 0 OR EXISTS (SELECT 1 FROM events.round_attendance ra WHERE ra.registration_id = r.id)) AS attended,
       min(s.scanned_at) FILTER (WHERE d.is_entry) AS first_entry_at,
       max(s.scanned_at) FILTER (WHERE NOT d.is_entry) AS last_exit_at,
       (SELECT count(*) FROM events.round_attendance ra WHERE ra.registration_id = r.id)::int AS sessions_attended
FROM events.event_registration r
LEFT JOIN events.entry_scan s ON s.registration_id = r.id
LEFT JOIN ref.entry_direction d ON d.id = s.entry_direction_id
GROUP BY r.id;

-- Teams: FORMING · COMPLETE · FINAL (locked) · WITHDRAWN · DISQUALIFIED
-- The ticket as its holder sees it: the event, the registration's state and
-- the size of the pass (holder + guests). The QR itself is the token returned
-- once by events.issue_ticket(); it is not stored.
CREATE OR REPLACE VIEW events.v_ticket AS
