-- May this account manage the event: its proposer, the officers / advisors
-- (or staff) of the organising unit, an event-manager volunteer, or whoever
-- holds events.event.update there.
CREATE OR REPLACE FUNCTION events.can_manage(p_account uuid, p_event uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id
    WHERE e.id = p_event
      AND (p.proposed_by_account_id = p_account
           OR events.may_propose_for(p_account, p.organising_org_unit_id)
           OR EXISTS (SELECT 1 FROM events.event_volunteer v JOIN ref.volunteer_role r ON r.id = v.volunteer_role_id AND r.is_manager
                      JOIN iam.user_account ua ON ua.person_id = v.person_id AND ua.id = p_account
                      WHERE v.event_id = e.id AND v.removed_at IS NULL)))
$$;

CREATE OR REPLACE FUNCTION events.event_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_prop record; v_set record;
BEGIN
  SELECT p.*, s.status AS round_status INTO v_prop
  FROM events.event_proposal p LEFT JOIN wf.v_instance_state s ON s.instance_id = p.instance_id WHERE p.id = NEW.event_proposal_id;
  IF TG_OP = 'INSERT' THEN
    IF v_prop.round_status IS DISTINCT FROM 'APPROVED' THEN
      RAISE EXCEPTION 'event: an event exists only for an approved proposal' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.event_code IS NULL THEN
      NEW.event_code := format('EVT-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.event_code_seq')::text, 4, '0'));
    END IF;
    IF NEW.published_at IS NOT NULL OR NEW.completed_at IS NOT NULL OR NEW.cancelled_at IS NOT NULL THEN
      RAISE EXCEPTION 'event: an event starts unpublished' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.event_proposal_id <> OLD.event_proposal_id OR NEW.event_code <> OLD.event_code THEN
    RAISE EXCEPTION 'event: the proposal and code never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF OLD.cancelled_at IS NOT NULL OR (OLD.completed_at IS NOT NULL AND NEW.cancelled_at IS NULL) THEN
    RAISE EXCEPTION 'event: a % event is closed', CASE WHEN OLD.cancelled_at IS NOT NULL THEN 'cancelled' ELSE 'completed' END USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.registration_window IS NOT NULL AND upper(NEW.registration_window)::timestamp > lower(v_prop.during) THEN
    RAISE EXCEPTION 'event: registration closes before the event starts' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.registration_cap IS NOT NULL AND v_prop.capacity_fixed IS NOT NULL AND NEW.registration_cap > v_prop.capacity_fixed THEN
    RAISE EXCEPTION 'event: the registration cap exceeds the approved capacity (%)', v_prop.capacity_fixed USING ERRCODE = 'check_violation';
  END IF;

  -- publishing: by an organiser, with everything a participant needs
  IF NEW.published_at IS NOT NULL AND OLD.published_at IS NULL THEN
    IF NOT events.can_manage(NEW.published_by_account_id, NEW.id) THEN
      RAISE EXCEPTION 'event: only its organisers publish an event' USING ERRCODE = 'insufficient_privilege';
    END IF;
    SELECT * INTO v_set FROM events.event_setting;
    IF NEW.registration_window IS NULL THEN
      RAISE EXCEPTION 'event: publishing needs the registration window' USING ERRCODE = 'check_violation';
    END IF;
    IF (v_set.publish_needs_description AND (NEW.short_description IS NULL OR NEW.long_description IS NULL))
       OR (v_set.publish_needs_contact AND NEW.contact_person_id IS NULL) THEN
      RAISE EXCEPTION 'event: publishing needs what the settings ask for (descriptions: %, contact person: %)',
        v_set.publish_needs_description, v_set.publish_needs_contact USING ERRCODE = 'check_violation';
    END IF;
    IF v_set.publish_needs_round AND NOT EXISTS (SELECT 1 FROM events.event_round WHERE event_id = NEW.id) THEN
      RAISE EXCEPTION 'event: publishing needs at least one round' USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM events.club WHERE org_unit_id = v_prop.organising_org_unit_id) AND NOT events.club_is_active(v_prop.organising_org_unit_id) THEN
      RAISE EXCEPTION 'event: the club is suspended or closed' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.published_at IS NULL AND OLD.published_at IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM events.event_registration r WHERE r.event_id = NEW.id AND r.cancelled_at IS NULL) THEN
      RAISE EXCEPTION 'event: cannot unpublish an event people have registered for' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  IF NEW.completed_at IS NOT NULL AND OLD.completed_at IS NULL THEN
    IF clock_timestamp()::timestamp < upper(v_prop.during) THEN
      RAISE EXCEPTION 'event: an event is completed only after it has ended' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT events.can_manage(NEW.completed_by_account_id, NEW.id) THEN
      RAISE EXCEPTION 'event: only its organisers complete an event' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  IF NEW.cancelled_at IS NOT NULL AND OLD.cancelled_at IS NULL AND NOT events.can_manage(NEW.cancelled_by_account_id, NEW.id) THEN
    RAISE EXCEPTION 'event: only its organisers cancel an event' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
