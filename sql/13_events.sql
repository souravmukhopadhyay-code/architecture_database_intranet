       events.registration_state(r.id) AS status, r.ticket_issued_at,
       (SELECT count(*) FROM events.extra_pass x WHERE x.registration_id = r.id)::int AS guests,
       1 + (SELECT count(*) FROM events.extra_pass x WHERE x.registration_id = r.id)::int AS pass_size,
       events.people_inside(r.id) AS inside,
       (SELECT t.name FROM events.event_team_member m JOIN events.event_team t ON t.id = m.event_team_id
        WHERE m.registration_id = r.id AND m.left_at IS NULL) AS team_name
FROM events.event_registration r
JOIN events.v_event e ON e.event_id = r.event_id
JOIN events.event_proposal p ON p.id = e.event_proposal_id;

