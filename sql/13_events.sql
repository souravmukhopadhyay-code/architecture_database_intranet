CREATE OR REPLACE FUNCTION events.certificate_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF NEW.certificate_template_id <> OLD.certificate_template_id OR NEW.registration_id IS DISTINCT FROM OLD.registration_id
       OR NEW.event_volunteer_id IS DISTINCT FROM OLD.event_volunteer_id OR NEW.serial_no <> OLD.serial_no OR NEW.verification_code <> OLD.verification_code
       OR OLD.revoked_at IS NOT NULL THEN
      RAISE EXCEPTION 'certificate: an issued certificate is only ever revoked' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  END IF;
  SELECT t.event_id, ct.code AS kind, p.gives_certificates, e.cancelled_at, p.during INTO v
  FROM events.event_certificate_template t JOIN ref.event_certificate_type ct ON ct.id = t.event_certificate_type_id
  JOIN events.event e ON e.id = t.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
  WHERE t.id = NEW.certificate_template_id;
  IF NOT v.gives_certificates OR v.cancelled_at IS NOT NULL OR clock_timestamp()::timestamp < lower(v.during) THEN
    RAISE EXCEPTION 'certificate: this event gives no certificates (or has not started, or was cancelled)' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT events.can_manage(NEW.issued_by_account_id, v.event_id) THEN
    RAISE EXCEPTION 'certificate: issued by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF v.kind = 'VOLUNTEER' THEN
    IF NOT EXISTS (SELECT 1 FROM events.event_volunteer ev WHERE ev.id = NEW.event_volunteer_id AND ev.event_id = v.event_id AND ev.removed_at IS NULL) THEN
      RAISE EXCEPTION 'certificate: a volunteer certificate goes to a volunteer of the event' USING ERRCODE = 'check_violation';
    END IF;
  ELSE
    IF NOT EXISTS (SELECT 1 FROM events.event_registration r WHERE r.id = NEW.registration_id AND r.event_id = v.event_id) OR NOT events.attended(NEW.registration_id) THEN
      RAISE EXCEPTION 'certificate: goes to a participant of the event who attended' USING ERRCODE = 'check_violation';
    END IF;
    IF v.kind = 'WINNER' AND NOT EXISTS (
         SELECT 1 FROM events.event_prize_award a
         WHERE a.registration_id = NEW.registration_id
            OR a.event_team_id IN (SELECT m.event_team_id FROM events.event_team_member m WHERE m.registration_id = NEW.registration_id AND m.left_at IS NULL)) THEN
      RAISE EXCEPTION 'certificate: a winner certificate needs a prize' USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  NEW.serial_no := COALESCE(NEW.serial_no, format('EC-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.certificate_seq')::text, 6, '0')));
  NEW.verification_code := COALESCE(NEW.verification_code, encode(gen_random_bytes(8), 'hex'));
  RETURN NEW;
END $$;
CREATE TRIGGER trg_certificate_validate BEFORE INSERT OR UPDATE ON events.event_certificate
  FOR EACH ROW EXECUTE FUNCTION events.certificate_validate();

