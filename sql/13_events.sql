       COALESCE(s.status, 'DRAFT') AS status, s.current_step, s.current_due_at, s.is_overdue,
       (r.new_during IS NOT NULL) AS changes_dates, (r.new_venue_text IS NOT NULL) AS changes_venue,
       (r.new_approx_capacity IS NOT NULL OR r.new_capacity_fixed IS NOT NULL) AS changes_capacity,
       r.new_during, r.previous_during, r.applied_at
FROM events.event_change_request r
