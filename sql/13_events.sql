CREATE OR REPLACE FUNCTION events.event_stall_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.stall_application_id IS NOT NULL OR EXISTS (SELECT 1 FROM events.stall_feedback f WHERE f.event_stall_id = OLD.id) THEN
      RAISE EXCEPTION 'event_stall: a stall from an application, or one with feedback, is deactivated, not deleted' USING ERRCODE = 'check_violation';
    END IF;
    RETURN OLD;
  END IF;
  IF TG_OP = 'INSERT' THEN
    NEW.stall_code := COALESCE(NEW.stall_code, 'ST' || nextval('events.stall_code_seq'));
    IF NOT events.can_manage(NEW.created_by_account_id, NEW.event_id) THEN
      RAISE EXCEPTION 'event_stall: stalls are set up by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.stall_application_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM events.stall_application a
         WHERE a.id = NEW.stall_application_id AND a.event_id = NEW.event_id AND a.is_approved) THEN
      RAISE EXCEPTION 'event_stall: the application is an approved one of the same event' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.event_id <> OLD.event_id OR NEW.stall_code <> OLD.stall_code OR NEW.stall_application_id IS DISTINCT FROM OLD.stall_application_id THEN
    RAISE EXCEPTION 'event_stall: the event, the code and the application never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  -- a stall that came from an application keeps what was applied for: only its place and whether it is active change
  IF OLD.stall_application_id IS NOT NULL
     AND (to_jsonb(NEW) - 'location' - 'is_active' - 'updated_at') <> (to_jsonb(OLD) - 'location' - 'is_active' - 'updated_at') THEN
    RAISE EXCEPTION 'event_stall: only the location and the active flag of an applied stall change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_stall_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_stall
  FOR EACH ROW EXECUTE FUNCTION events.event_stall_validate();

