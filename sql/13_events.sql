  granted_by_account_id  uuid NOT NULL REFERENCES iam.user_account(id),
  granted_at             timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION events.event_mail_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_set record;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.dispatch_started_at IS NOT NULL THEN
      RAISE EXCEPTION 'event_mail: a message that was sent is a record' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;
  SELECT * INTO v_set FROM events.event_setting;
  IF char_length(NEW.subject) > v_set.mail_subject_max_length OR char_length(NEW.body) > v_set.mail_body_max_length THEN
    RAISE EXCEPTION 'event_mail: the subject has at most % characters and the body at most %', v_set.mail_subject_max_length, v_set.mail_body_max_length
      USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NOT events.can_manage(NEW.created_by_account_id, NEW.event_id) THEN
      RAISE EXCEPTION 'event_mail: only the event''s organisers write to its registrants' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.scheduled_at IS NOT NULL AND NEW.scheduled_at <= clock_timestamp() THEN
      RAISE EXCEPTION 'event_mail: a scheduled time lies in the future' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.dispatch_started_at IS NOT NULL OR NEW.cancelled_at IS NOT NULL OR NEW.failed_at IS NOT NULL THEN
      RAISE EXCEPTION 'event_mail: a message starts unsent' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.event_id <> OLD.event_id OR NEW.created_by_account_id <> OLD.created_by_account_id OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'event_mail: the event and the author never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF OLD.cancelled_at IS NOT NULL OR OLD.failed_at IS NOT NULL THEN
    RAISE EXCEPTION 'event_mail: a cancelled or failed message is closed' USING ERRCODE = 'check_violation';
  END IF;
  IF OLD.dispatch_started_at IS NOT NULL THEN
    -- once sending has started only its completion is recorded
    IF NEW.subject <> OLD.subject OR NEW.body <> OLD.body OR NEW.mail_audience_id <> OLD.mail_audience_id OR NEW.scheduled_at IS DISTINCT FROM OLD.scheduled_at
       OR NEW.cancelled_at IS NOT NULL OR NEW.dispatch_started_at <> OLD.dispatch_started_at THEN
      RAISE EXCEPTION 'event_mail: sending has started — it can no longer be changed or cancelled' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.cancelled_at IS NOT NULL AND NOT events.can_manage(NEW.cancelled_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'event_mail: cancelled by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF (NEW.dispatch_started_at IS DISTINCT FROM OLD.dispatch_started_at OR NEW.failed_at IS DISTINCT FROM OLD.failed_at)
     AND current_setting('events.mail_dispatch', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'event_mail: sending is recorded by events.dispatch_mail() and the scheduler' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_mail_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_mail
  FOR EACH ROW EXECUTE FUNCTION events.event_mail_validate();

-- Recipients: picked by the organisers before sending (a selection), or
-- resolved by the dispatch; afterwards only the delivery outcome and the opens
-- are recorded, and a final outcome never changes.
CREATE OR REPLACE FUNCTION events.event_mail_recipient_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE m record; v_old record; v_new record;
BEGIN
  SELECT em.event_id, em.dispatch_started_at, em.cancelled_at, em.failed_at, a.is_selection INTO m
  FROM events.event_mail em JOIN ref.mail_audience a ON a.id = em.mail_audience_id
  WHERE em.id = CASE WHEN TG_OP = 'DELETE' THEN OLD.event_mail_id ELSE NEW.event_mail_id END;
  IF TG_OP = 'DELETE' THEN
    IF m.dispatch_started_at IS NOT NULL THEN
      RAISE EXCEPTION 'event_mail_recipient: the delivery log is a record' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;
  SELECT * INTO v_new FROM ref.mail_delivery_status WHERE id = NEW.mail_delivery_status_id;
  IF TG_OP = 'INSERT' THEN
    IF (SELECT r.event_id FROM events.event_registration r WHERE r.id = NEW.registration_id) <> m.event_id THEN
      RAISE EXCEPTION 'event_mail_recipient: the recipient registered for another event' USING ERRCODE = 'check_violation';
    END IF;
    IF v_new.is_final OR NEW.open_count <> 0 THEN
      RAISE EXCEPTION 'event_mail_recipient: a recipient starts queued' USING ERRCODE = 'check_violation';
    END IF;
    IF current_setting('events.mail_dispatch', true) IS DISTINCT FROM 'on'
       AND (NOT m.is_selection OR m.dispatch_started_at IS NOT NULL OR m.cancelled_at IS NOT NULL) THEN
      RAISE EXCEPTION 'event_mail_recipient: recipients are hand-picked only for a selection, before it is sent' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.event_mail_id <> OLD.event_mail_id OR NEW.registration_id <> OLD.registration_id OR NEW.open_count < OLD.open_count THEN
    RAISE EXCEPTION 'event_mail_recipient: who was written to never changes' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO v_old FROM ref.mail_delivery_status WHERE id = OLD.mail_delivery_status_id;
  IF NEW.mail_delivery_status_id <> OLD.mail_delivery_status_id THEN
    IF v_old.is_final THEN
      RAISE EXCEPTION 'event_mail_recipient: a final delivery outcome never changes' USING ERRCODE = 'check_violation';
    END IF;
    IF v_new.is_delivered THEN NEW.delivered_at := clock_timestamp();
    ELSIF v_new.is_final THEN NEW.failed_at := clock_timestamp();
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_mail_recipient_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_mail_recipient
  FOR EACH ROW EXECUTE FUNCTION events.event_mail_recipient_validate();

