  participation_type_id      smallint NOT NULL REFERENCES ref.participation_type(id),
  min_team_size              smallint CHECK (min_team_size >= 1),
  max_team_size              smallint,
  is_paid                    boolean NOT NULL DEFAULT false,
  fee_individual             numeric(10,2) CHECK (fee_individual > 0),
  fee_team                   numeric(10,2) CHECK (fee_team > 0),
  approx_capacity            int NOT NULL CHECK (approx_capacity >= 1),
