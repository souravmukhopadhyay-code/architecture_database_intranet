-- Move the waiting list up into the seats that have come free (oldest first).
CREATE OR REPLACE FUNCTION events.promote_waitlist(p_event uuid)
RETURNS int LANGUAGE plpgsql AS $$
DECLARE r record; v_n int := 0; v_limit int;
BEGIN
  PERFORM 1 FROM events.event WHERE id = p_event FOR UPDATE;
  v_limit := events.seat_limit(p_event);
  FOR r IN SELECT id FROM events.event_registration WHERE event_id = p_event AND waitlisted_at IS NOT NULL AND promoted_at IS NULL AND cancelled_at IS NULL
           AND is_approved IS DISTINCT FROM false ORDER BY waitlisted_at, registered_at LOOP
    EXIT WHEN v_limit IS NOT NULL AND events.seats_taken(p_event) >= v_limit;
    UPDATE events.event_registration SET promoted_at = now() WHERE id = r.id;
    v_n := v_n + 1;
  END LOOP;
  RETURN v_n;
END $$;

-- Ticket generation. The QR of a registration carries a random token; the
-- database keeps only its hash, so a copy of the table is not a stack of valid
-- tickets. The token is returned once — to the holder, or to an organiser who
-- hands it over; issuing again replaces it (a lost phone: the old QR stops
-- working).
CREATE OR REPLACE FUNCTION events.issue_ticket(p_registration uuid, p_account uuid)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE v record; v_token text;
BEGIN
  SELECT r.event_id, r.person_id, r.cancelled_at INTO v FROM events.event_registration r WHERE r.id = p_registration FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'issue_ticket: unknown registration' USING ERRCODE = 'no_data_found';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM iam.user_account a WHERE a.id = p_account AND a.person_id = v.person_id)
     AND NOT events.can_manage(p_account, v.event_id) THEN
    RAISE EXCEPTION 'issue_ticket: a ticket goes to its holder, or is issued by the organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF v.cancelled_at IS NOT NULL THEN
    RAISE EXCEPTION 'issue_ticket: the registration is cancelled' USING ERRCODE = 'check_violation';
  END IF;
  v_token := 'TKT-' || upper(encode(gen_random_bytes(20), 'hex'));
  PERFORM set_config('events.ticket_issue', 'on', true);
  UPDATE events.event_registration SET qr_token_hash = digest(v_token, 'sha256'), ticket_issued_at = clock_timestamp() WHERE id = p_registration;
  PERFORM set_config('events.ticket_issue', 'off', true);
  RETURN v_token;
END $$;

-- What the volunteer's scanner shows before letting anyone in: whose pass, its
-- state, how many it admits, how many are inside, how many may still enter.
CREATE OR REPLACE FUNCTION events.ticket_check(p_token text, p_account uuid)
RETURNS TABLE (registration_id uuid, registration_code citext, event_id uuid, person_id uuid, status text,
               pass_size int, entered int, exited int, inside int, may_enter int)
LANGUAGE plpgsql STABLE AS $$
DECLARE v_reg uuid; v_event uuid;
BEGIN
  SELECT r.id, r.event_id INTO v_reg, v_event FROM events.event_registration r
  WHERE r.qr_token_hash = digest(p_token, 'sha256') AND r.ticket_issued_at IS NOT NULL;
  IF v_reg IS NULL THEN
    RAISE EXCEPTION 'ticket_check: unknown pass' USING ERRCODE = 'no_data_found';
  END IF;
  IF NOT events.can_manage(p_account, v_event)
     AND NOT EXISTS (SELECT 1 FROM events.event_volunteer v JOIN iam.user_account a ON a.person_id = v.person_id AND a.id = p_account
                     WHERE v.event_id = v_event AND v.can_scan AND v.removed_at IS NULL) THEN
    RAISE EXCEPTION 'ticket_check: only a scanning volunteer or an organiser of this event checks its passes' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN QUERY
  SELECT t.registration_id, t.registration_code, t.event_id, t.person_id, t.status, t.pass_size, att.entered, att.exited, att.inside,
         CASE WHEN t.status = 'CONFIRMED' THEN greatest(t.pass_size - att.inside, 0) ELSE 0 END
  FROM events.v_ticket t JOIN events.v_attendance att ON att.registration_id = t.registration_id
  WHERE t.registration_id = v_reg;
END $$;

-- A gate scan: the token read from the QR, in or out, with the head-count.
CREATE OR REPLACE FUNCTION events.scan(p_token text, p_direction text, p_account uuid, p_people int DEFAULT 1, p_gate text DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE v_reg uuid; v_id bigint;
BEGIN
  SELECT id INTO v_reg FROM events.event_registration WHERE qr_token_hash = digest(p_token, 'sha256') AND ticket_issued_at IS NOT NULL;
  IF v_reg IS NULL THEN
    RAISE EXCEPTION 'scan: unknown pass' USING ERRCODE = 'no_data_found';
  END IF;
  INSERT INTO events.entry_scan (registration_id, entry_direction_id, people_count, scanned_by_account_id, scan_source_id, gate)
  VALUES (v_reg, ref.id_of('entry_direction', p_direction), p_people, p_account, ref.id_of('scan_source', 'LIVE'), p_gate) RETURNING id INTO v_id;
  RETURN v_id;
END $$;

-- The one feedback token of an attendee (returned once; only its hash is kept).
CREATE OR REPLACE FUNCTION events.feedback_token_for(p_registration uuid)
RETURNS text LANGUAGE plpgsql AS $$
DECLARE v_token text := encode(gen_random_bytes(16), 'hex');
BEGIN
  IF NOT events.attended(p_registration) THEN
    RAISE EXCEPTION 'feedback_token_for: only someone who attended gives feedback' USING ERRCODE = 'check_violation';
  END IF;
  INSERT INTO events.event_feedback_token (registration_id, token_hash) VALUES (p_registration, digest(v_token, 'sha256'));
  RETURN v_token;
END $$;

-- Anonymous feedback against an unused token.
CREATE OR REPLACE FUNCTION events.submit_feedback(p_token text, p_rating int, p_comment text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_event uuid;
BEGIN
  UPDATE events.event_feedback_token ft SET used_at = now()
  FROM events.event_registration r
  WHERE ft.token_hash = digest(p_token, 'sha256') AND ft.used_at IS NULL AND r.id = ft.registration_id
  RETURNING r.event_id INTO v_event;
  IF v_event IS NULL THEN
    RAISE EXCEPTION 'submit_feedback: unknown or used token' USING ERRCODE = 'insufficient_privilege';
  END IF;
  PERFORM set_config('events.feedback_token_ok', 'on', true);
  INSERT INTO events.event_feedback (event_id, rating, comment) VALUES (v_event, p_rating, p_comment);
  PERFORM set_config('events.feedback_token_ok', 'off', true);
END $$;

-- Issue the certificates of one kind to everyone entitled who has none yet.
CREATE OR REPLACE FUNCTION events.issue_certificates(p_event uuid, p_kind text, p_account uuid)
RETURNS int LANGUAGE plpgsql AS $$
DECLARE v_template uuid; v_n int;
BEGIN
  SELECT t.id INTO v_template FROM events.event_certificate_template t JOIN ref.event_certificate_type k ON k.id = t.event_certificate_type_id AND k.code = upper(p_kind)
  WHERE t.event_id = p_event;
  IF v_template IS NULL THEN
    RAISE EXCEPTION 'issue_certificates: the event has no % template', p_kind USING ERRCODE = 'no_data_found';
  END IF;
  IF upper(p_kind) = 'VOLUNTEER' THEN
    INSERT INTO events.event_certificate (certificate_template_id, event_volunteer_id, issued_by_account_id)
    SELECT v_template, v.id, p_account FROM events.event_volunteer v
    WHERE v.event_id = p_event AND v.removed_at IS NULL
      AND NOT EXISTS (SELECT 1 FROM events.event_certificate c WHERE c.certificate_template_id = v_template AND c.event_volunteer_id = v.id);
  ELSE
    INSERT INTO events.event_certificate (certificate_template_id, registration_id, issued_by_account_id)
    SELECT v_template, r.id, p_account FROM events.event_registration r
    WHERE r.event_id = p_event AND events.attended(r.id)
      AND (upper(p_kind) <> 'WINNER' OR EXISTS (
             SELECT 1 FROM events.event_prize_award a WHERE a.registration_id = r.id
                OR a.event_team_id IN (SELECT m.event_team_id FROM events.event_team_member m WHERE m.registration_id = r.id AND m.left_at IS NULL)))
      AND NOT EXISTS (SELECT 1 FROM events.event_certificate c WHERE c.certificate_template_id = v_template AND c.registration_id = r.id);
  END IF;
  GET DIAGNOSTICS v_n = ROW_COUNT;
  RETURN v_n;
END $$;

-- The attendance office turns an event's duty-leave list into leave requests
-- (each goes through the ATTENDANCE_LEAVE chain of the student's department);
-- students already covered, or outside the caller's reach, are skipped.
CREATE OR REPLACE FUNCTION events.grant_duty_leave(p_event uuid, p_account uuid)
RETURNS int LANGUAGE plpgsql AS $$
DECLARE r record; v_n int := 0; v_title text;
BEGIN
  SELECT p.title INTO v_title FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = p_event;
  FOR r IN SELECT DISTINCT student_enrollment_id, period FROM events.v_duty_leave_eligible WHERE event_id = p_event LOOP
    BEGIN
      PERFORM academic.request_attendance_leave(r.student_enrollment_id, 'DUTY_LEAVE', r.period, 'Event: ' || v_title, NULL, p_account);
      v_n := v_n + 1;
    EXCEPTION WHEN insufficient_privilege OR exclusion_violation THEN NULL;
    END;
  END LOOP;
  RETURN v_n;
END $$;

