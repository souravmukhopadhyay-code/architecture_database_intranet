CREATE OR REPLACE FUNCTION events.stall_application_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT e.stall_applications_open, e.stall_application_deadline, e.max_applied_stalls, e.published_at, e.cancelled_at, e.completed_at INTO v
    FROM events.event e WHERE e.id = NEW.event_id FOR UPDATE;
    IF NEW.decided_at IS NOT NULL THEN
      RAISE EXCEPTION 'stall_application: an application starts undecided' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT v.stall_applications_open OR v.published_at IS NULL OR v.cancelled_at IS NOT NULL OR v.completed_at IS NOT NULL
       OR (v.stall_application_deadline IS NOT NULL AND clock_timestamp() > v.stall_application_deadline) THEN
      RAISE EXCEPTION 'stall_application: this event takes no stall applications (now)' USING ERRCODE = 'check_violation';
    END IF;
    IF v.max_applied_stalls IS NOT NULL AND
       (SELECT count(*) FROM events.stall_application a WHERE a.event_id = NEW.event_id AND a.is_approved IS NOT FALSE) >= v.max_applied_stalls THEN
      RAISE EXCEPTION 'stall_application: the event takes at most % applied stalls', v.max_applied_stalls USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM people.v_person_principal_kind k WHERE k.person_id = NEW.applicant_person_id AND k.principal_kind IN ('STUDENT', 'EMPLOYEE')) THEN
      RAISE EXCEPTION 'stall_application: stalls are applied for by students or employees of the university' USING ERRCODE = 'check_violation';
    END IF;
  ELSE
    IF OLD.decided_at IS NOT NULL THEN
      RAISE EXCEPTION 'stall_application: a decided application is a record' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.event_id <> OLD.event_id OR NEW.applicant_person_id <> OLD.applicant_person_id OR NEW.applied_at <> OLD.applied_at THEN
      RAISE EXCEPTION 'stall_application: who applied for which event, and when, never changes' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.decided_at IS NOT NULL AND NOT events.can_manage(NEW.decided_by_account_id, NEW.event_id) THEN
      RAISE EXCEPTION 'stall_application: decided by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  IF (SELECT is_custom FROM ref.stall_size WHERE id = NEW.stall_size_id) <> (NEW.custom_size IS NOT NULL) THEN
    RAISE EXCEPTION 'stall_application: a custom size is described, a standard size is not' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_stall_application_validate BEFORE INSERT OR UPDATE ON events.stall_application
  FOR EACH ROW EXECUTE FUNCTION events.stall_application_validate();

