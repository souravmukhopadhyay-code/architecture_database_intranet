-- What completing / cancelling an event sets in motion: points for the
-- organising club; on cancellation the registrations and teams are cancelled,
-- the facility package is cancelled (which cancels its bookings), and the
-- points taken back.
CREATE OR REPLACE FUNCTION events.event_effects()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_prop record;
BEGIN
  SELECT p.organising_org_unit_id, p.event_type_id, p.facility_event_request_id INTO v_prop
  FROM events.event_proposal p WHERE p.id = NEW.event_proposal_id;
  IF NEW.completed_at IS NOT NULL AND OLD.completed_at IS NULL AND EXISTS (SELECT 1 FROM events.club WHERE org_unit_id = v_prop.organising_org_unit_id) THEN
    INSERT INTO events.club_point_award (event_id, points)
    SELECT NEW.id, tp.points FROM events.event_type_points tp
    WHERE tp.event_type_id = v_prop.event_type_id AND tp.valid @> NEW.completed_at::date
    ON CONFLICT (event_id) DO NOTHING;
  END IF;
  IF NEW.cancelled_at IS NOT NULL AND OLD.cancelled_at IS NULL THEN
    DELETE FROM events.club_point_award WHERE event_id = NEW.id;
    UPDATE events.event_team SET withdrawn_at = NEW.cancelled_at WHERE event_id = NEW.id AND withdrawn_at IS NULL;
    UPDATE events.event_registration SET cancelled_at = NEW.cancelled_at, registration_cancel_reason_id = ref.id_of('registration_cancel_reason', 'EVENT_CANCELLED')
    WHERE event_id = NEW.id AND cancelled_at IS NULL;
    UPDATE facility.event_request SET cancelled_at = NEW.cancelled_at, cancelled_by_account_id = NEW.cancelled_by_account_id
    WHERE id = v_prop.facility_event_request_id AND cancelled_at IS NULL;
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_event_effects AFTER UPDATE OF completed_at, cancelled_at ON events.event
  FOR EACH ROW EXECUTE FUNCTION events.event_effects();

