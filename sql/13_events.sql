-- May the account propose for the unit: for a club, its officers (posts that
-- may propose) and advisors; for any other unit, its own current employees
-- (primary unit inside it) or whoever may update events there.
CREATE OR REPLACE FUNCTION events.may_propose_for(p_account uuid, p_unit uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN EXISTS (SELECT 1 FROM events.club WHERE org_unit_id = p_unit)
              THEN events.is_club_officer(p_account, p_unit, true)
              ELSE EXISTS (SELECT 1 FROM iam.user_account ua JOIN people.v_employee_current e ON e.person_id = ua.person_id
                           WHERE ua.id = p_account AND e.primary_org_unit_id IN (SELECT org_unit_id FROM org.descendants(p_unit)))
         END
      OR authz.has_permission(p_account, 'events.event.update', p_unit)
$$;

CREATE OR REPLACE FUNCTION events.event_proposal_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_part record; v_set record;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.instance_id IS NOT NULL THEN
      RAISE EXCEPTION 'event_proposal: a submitted proposal is a record; withdraw it instead' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;
  IF TG_OP = 'INSERT' AND NEW.proposal_code IS NULL THEN
    NEW.proposal_code := format('EP-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.event_proposal_seq')::text, 3, '0'));
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.instance_id IS NOT NULL AND current_setting('events.proposal_change_apply', true) = 'on'
     AND (to_jsonb(NEW) - 'during' - 'venue_text' - 'approx_capacity' - 'capacity_fixed' - 'facility_event_request_id' - 'updated_at')
       = (to_jsonb(OLD) - 'during' - 'venue_text' - 'approx_capacity' - 'capacity_fixed' - 'facility_event_request_id' - 'updated_at') THEN
    RETURN NEW;       -- an approved event change being applied (events.apply_event_change)
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.instance_id IS NOT NULL THEN
    RAISE EXCEPTION 'event_proposal: a submitted proposal is never edited; revise it as a new proposal, or change the approved event through an event change request' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP = 'UPDATE' AND (NEW.proposal_code <> OLD.proposal_code OR NEW.proposed_by_account_id <> OLD.proposed_by_account_id
                           OR NEW.organising_org_unit_id <> OLD.organising_org_unit_id) THEN
    RAISE EXCEPTION 'event_proposal: the code, proposer and organising unit of a draft never change' USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF NOT events.may_propose_for(NEW.proposed_by_account_id, NEW.organising_org_unit_id) THEN
    RAISE EXCEPTION 'event_proposal: the proposer is not an officer / advisor of that club, nor of that unit' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF EXISTS (SELECT 1 FROM events.club WHERE org_unit_id = NEW.organising_org_unit_id) AND NOT events.club_is_active(NEW.organising_org_unit_id) THEN
    RAISE EXCEPTION 'event_proposal: the club is suspended or closed' USING ERRCODE = 'check_violation';
  END IF;
  SELECT * INTO v_part FROM ref.participation_type WHERE id = NEW.participation_type_id;
  IF v_part.is_team AND (NEW.min_team_size IS NULL OR NEW.max_team_size IS NULL) THEN
    RAISE EXCEPTION 'event_proposal: a team event states its minimum and maximum team size' USING ERRCODE = 'check_violation';
  ELSIF NOT v_part.is_team AND (NEW.min_team_size IS NOT NULL OR NEW.max_team_size IS NOT NULL OR NEW.fee_team IS NOT NULL) THEN
    RAISE EXCEPTION 'event_proposal: team sizes and a team fee belong to team events' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.is_paid AND (CASE WHEN v_part.is_team THEN NEW.fee_team ELSE NEW.fee_individual END) IS NULL THEN
    RAISE EXCEPTION 'event_proposal: a paid event states its fee' USING ERRCODE = 'check_violation';
  ELSIF NOT NEW.is_paid AND (NEW.fee_individual IS NOT NULL OR NEW.fee_team IS NOT NULL) THEN
    RAISE EXCEPTION 'event_proposal: a free event has no fee' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.capacity_fixed IS NOT NULL AND NEW.capacity_fixed < NEW.approx_capacity THEN
    RAISE EXCEPTION 'event_proposal: the fixed capacity cannot be below the expected attendance' USING ERRCODE = 'check_violation';
  END IF;
  SELECT * INTO v_set FROM events.event_setting;
  IF NEW.max_extra_passes > v_set.max_extra_passes_per_participant THEN
    RAISE EXCEPTION 'event_proposal: at most % guest passes per participant may be asked for', v_set.max_extra_passes_per_participant USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.revises_proposal_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM events.event_proposal p JOIN wf.v_instance_state s ON s.instance_id = p.instance_id AND s.status IN ('RETURNED', 'WITHDRAWN')
       WHERE p.id = NEW.revises_proposal_id AND p.organising_org_unit_id = NEW.organising_org_unit_id) THEN
    RAISE EXCEPTION 'event_proposal: only a returned or withdrawn proposal of the same unit is revised' USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.instance_id IS NOT NULL THEN       -- being submitted
    IF lower(NEW.during) <= clock_timestamp()::timestamp + v_set.proposal_min_lead_time THEN
      RAISE EXCEPTION 'event_proposal: the event must start more than % from now', v_set.proposal_min_lead_time USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'EVENT_PROPOSAL'
                   WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = NEW.organising_org_unit_id AND i.submitted_by_account_id = NEW.proposed_by_account_id) THEN
      RAISE EXCEPTION 'event_proposal: the round is not the proposer''s EVENT_PROPOSAL round of the organising unit' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM facility.event_request e WHERE e.id = NEW.facility_event_request_id AND e.instance_id = NEW.instance_id) THEN
      RAISE EXCEPTION 'event_proposal: the facility package must share the proposal''s round' USING ERRCODE = 'check_violation';
    END IF;
    -- the sections the settings ask for
    IF (v_set.proposal_needs_audience AND NOT EXISTS (SELECT 1 FROM events.proposal_audience WHERE event_proposal_id = NEW.id))
       OR (v_set.proposal_needs_coordinator AND NOT EXISTS (SELECT 1 FROM events.proposal_coordinator WHERE event_proposal_id = NEW.id))
       OR (v_set.proposal_needs_sdg AND NOT EXISTS (SELECT 1 FROM events.proposal_sdg WHERE event_proposal_id = NEW.id)) THEN
      RAISE EXCEPTION 'event_proposal: complete the required sections before submitting (audience: %, coordinator: %, SDG: %)',
        v_set.proposal_needs_audience, v_set.proposal_needs_coordinator, v_set.proposal_needs_sdg USING ERRCODE = 'check_violation';
    END IF;
    IF v_set.max_open_proposals_per_proposer IS NOT NULL AND
       (SELECT count(*) FROM events.event_proposal p JOIN wf.v_instance_state s ON s.instance_id = p.instance_id AND s.status = 'IN_PROGRESS'
        WHERE p.organising_org_unit_id = NEW.organising_org_unit_id AND p.proposed_by_account_id = NEW.proposed_by_account_id AND p.id <> NEW.id)
       >= v_set.max_open_proposals_per_proposer THEN
      RAISE EXCEPTION 'event_proposal: this proposer already has % proposal(s) of the unit under approval', v_set.max_open_proposals_per_proposer USING ERRCODE = 'exclusion_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_proposal_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_proposal
  FOR EACH ROW EXECUTE FUNCTION events.event_proposal_validate();

-- The parts of a proposal change only while it is a draft (what was approved
-- is what was submitted).
CREATE OR REPLACE FUNCTION events.proposal_part_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_id uuid := CASE WHEN TG_OP = 'DELETE' THEN OLD.event_proposal_id ELSE NEW.event_proposal_id END;
BEGIN
  IF (SELECT instance_id FROM events.event_proposal WHERE id = v_id) IS NOT NULL THEN
    RAISE EXCEPTION '%: the proposal has been submitted; its parts are frozen', TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['proposal_audience','proposal_sdg','proposal_partner','proposal_speaker','proposal_coordinator','proposal_budget_item',
                           'proposal_funding','proposal_prize','proposal_attachment','proposal_visibility_role','proposal_visibility_scope','event_sponsorship'] LOOP
    EXECUTE format('CREATE TRIGGER trg_%s_guard BEFORE INSERT OR UPDATE OR DELETE ON events.%I FOR EACH ROW EXECUTE FUNCTION events.proposal_part_guard()', t, t);
  END LOOP;
END $$;

