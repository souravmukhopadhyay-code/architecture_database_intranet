-- Is the registration confirmed (may enter): approved, in a seat, paid if the
-- event is paid, in a complete team if it is a team event, not cancelled.
-- Money (plpgsql: coupons, payments and stalls are created further down).
-- Who pays for a registration: the participant — or, in a team event, the
-- leader of their complete team (NULL while there is none).
CREATE OR REPLACE FUNCTION events.payer_registration(p_registration uuid)
RETURNS uuid LANGUAGE plpgsql STABLE AS $$
DECLARE v_is_team boolean; v_leader uuid;
BEGIN
  SELECT pt.is_team INTO v_is_team FROM events.event_registration r JOIN events.event e ON e.id = r.event_id
  JOIN events.event_proposal p ON p.id = e.event_proposal_id JOIN ref.participation_type pt ON pt.id = p.participation_type_id WHERE r.id = p_registration;
  IF NOT COALESCE(v_is_team, false) THEN RETURN p_registration; END IF;
  SELECT t.leader_registration_id INTO v_leader
  FROM events.event_team_member m JOIN events.event_team t ON t.id = m.event_team_id
  JOIN events.event e ON e.id = t.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
  WHERE m.registration_id = p_registration AND m.left_at IS NULL AND t.withdrawn_at IS NULL AND t.disqualified_at IS NULL
    AND events.team_size(t.id) >= p.min_team_size;
  RETURN v_leader;
END $$;
-- What a registration owes: the fee (a team's flat fee is owed by its leader
-- alone) less its coupon. 0 for a free event and for a team's other members.
CREATE OR REPLACE FUNCTION events.amount_due(p_registration uuid)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
DECLARE v record;
BEGIN
  SELECT p.is_paid, pt.is_team, p.fee_individual, p.fee_team INTO v
  FROM events.event_registration r JOIN events.event e ON e.id = r.event_id JOIN events.event_proposal p ON p.id = e.event_proposal_id
  JOIN ref.participation_type pt ON pt.id = p.participation_type_id WHERE r.id = p_registration;
  IF NOT FOUND OR NOT v.is_paid OR events.payer_registration(p_registration) IS DISTINCT FROM p_registration THEN RETURN 0; END IF;
  RETURN greatest(CASE WHEN v.is_team THEN v.fee_team ELSE v.fee_individual END
                  - COALESCE((SELECT sum(x.discount_amount) FROM events.coupon_redemption x WHERE x.registration_id = p_registration), 0), 0);
END $$;
-- What was captured (and not refunded) on a registration.
CREATE OR REPLACE FUNCTION events.amount_settled(p_registration uuid)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN COALESCE((SELECT sum(pm.amount) FROM events.event_payment pm JOIN ref.payment_status ps ON ps.id = pm.payment_status_id AND ps.is_settled
                   WHERE pm.registration_id = p_registration), 0);
END $$;
-- Is the fee covering this registration paid?
CREATE OR REPLACE FUNCTION events.is_paid(p_registration uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE v_payer uuid := events.payer_registration(p_registration);
BEGIN
  RETURN v_payer IS NOT NULL AND events.amount_settled(v_payer) >= events.amount_due(v_payer);
END $$;
-- The fee of a stall application: its category's fee at the event (none set = free).
CREATE OR REPLACE FUNCTION events.stall_fee(p_application uuid)
RETURNS numeric LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN COALESCE((SELECT f.fee FROM events.stall_application a JOIN events.event_stall_fee f ON f.event_id = a.event_id AND f.stall_category_id = a.stall_category_id
                   WHERE a.id = p_application), 0);
END $$;
-- Mail credits (plpgsql for the same reason).
CREATE OR REPLACE FUNCTION events.mail_credits_total(p_event uuid)
RETURNS int LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN (SELECT mail_credits_per_registration FROM events.event_setting) * (SELECT count(*) FROM events.event_registration r WHERE r.event_id = p_event)
         + COALESCE((SELECT sum(g.credits) FROM events.event_mail_credit_grant g WHERE g.event_id = p_event), 0);
END $$;
CREATE OR REPLACE FUNCTION events.mail_credits_used(p_event uuid)
RETURNS int LANGUAGE plpgsql STABLE AS $$
BEGIN
  RETURN (SELECT count(*) FROM events.event_mail_recipient x JOIN events.event_mail m ON m.id = x.event_mail_id
          JOIN ref.mail_delivery_status s ON s.id = x.mail_delivery_status_id
          WHERE m.event_id = p_event AND m.dispatch_started_at IS NOT NULL AND (NOT s.is_final OR s.is_delivered));
END $$;

CREATE OR REPLACE FUNCTION events.registration_state(p_registration uuid)
RETURNS text LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN r.cancelled_at IS NOT NULL THEN 'CANCELLED'
              WHEN r.is_approved IS FALSE THEN 'REJECTED'
              WHEN r.waitlisted_at IS NOT NULL AND r.promoted_at IS NULL THEN 'WAITLISTED'
              WHEN r.is_approved IS NULL THEN 'PENDING'
              WHEN pt.is_team AND NOT EXISTS (SELECT 1 FROM events.event_team_member m JOIN events.event_team t ON t.id = m.event_team_id
                                              WHERE m.registration_id = r.id AND m.left_at IS NULL AND t.withdrawn_at IS NULL AND t.disqualified_at IS NULL
                                                AND events.team_size(t.id) >= p.min_team_size) THEN 'INCOMPLETE_TEAM'
              WHEN p.is_paid AND NOT events.is_paid(r.id) THEN 'PENDING_PAYMENT'
              ELSE 'CONFIRMED' END
  FROM events.event_registration r
  JOIN events.event e ON e.id = r.event_id
  JOIN events.event_proposal p ON p.id = e.event_proposal_id
  JOIN ref.participation_type pt ON pt.id = p.participation_type_id
  WHERE r.id = p_registration
$$;

-- The gate log: every scan in or out of a participant (with their guests),
-- append-only. Who is inside, who attended, first entry and last exit are
-- derived (v_attendance). An offline attendance sheet is imported as scans
-- with source IMPORT (no scanner) by an organiser.
CREATE TABLE events.entry_scan (
  id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration_id        uuid NOT NULL REFERENCES events.event_registration(id),
  entry_direction_id     smallint NOT NULL REFERENCES ref.entry_direction(id),
  people_count           smallint NOT NULL DEFAULT 1 CHECK (people_count >= 1),          -- the pass size is the ceiling (trigger)
  scanned_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
  scanned_by_account_id  uuid NOT NULL REFERENCES iam.user_account(id),
  scan_source_id         smallint NOT NULL REFERENCES ref.scan_source(id),
  gate                   text,
  remarks                text
);
CREATE INDEX entry_scan_registration_idx ON events.entry_scan(registration_id);

CREATE OR REPLACE FUNCTION events.people_inside(p_registration uuid)
RETURNS int LANGUAGE sql STABLE AS $$
  SELECT COALESCE(sum(CASE WHEN d.is_entry THEN s.people_count ELSE -s.people_count END), 0)::int
  FROM events.entry_scan s JOIN ref.entry_direction d ON d.id = s.entry_direction_id WHERE s.registration_id = p_registration
$$;

CREATE OR REPLACE FUNCTION events.entry_scan_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_event uuid; v_person uuid; v_is_entry boolean; v_inside int; v_allowed int; v_source text;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'entry_scan: the gate log is append-only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT event_id INTO v_event FROM events.event_registration WHERE id = NEW.registration_id FOR UPDATE;
  SELECT code INTO v_source FROM ref.scan_source WHERE id = NEW.scan_source_id;
  SELECT person_id INTO v_person FROM iam.user_account WHERE id = NEW.scanned_by_account_id;
  IF NOT events.can_manage(NEW.scanned_by_account_id, v_event)
     AND (v_source = 'IMPORT' OR NOT EXISTS (SELECT 1 FROM events.event_volunteer v WHERE v.event_id = v_event AND v.person_id = v_person
                                             AND v.can_scan AND v.removed_at IS NULL)) THEN
    RAISE EXCEPTION 'entry_scan: only a scanning volunteer or an organiser scans (an import: an organiser)' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF events.registration_state(NEW.registration_id) <> 'CONFIRMED' THEN
    RAISE EXCEPTION 'entry_scan: the registration is not confirmed (%)', events.registration_state(NEW.registration_id) USING ERRCODE = 'check_violation';
  END IF;
  SELECT is_entry INTO v_is_entry FROM ref.entry_direction WHERE id = NEW.entry_direction_id;
  v_inside := events.people_inside(NEW.registration_id);
  v_allowed := 1 + (SELECT count(*) FROM events.extra_pass x WHERE x.registration_id = NEW.registration_id);
  IF v_is_entry AND v_inside + NEW.people_count > v_allowed THEN
    RAISE EXCEPTION 'entry_scan: % inside + % entering exceeds the % allowed on this pass', v_inside, NEW.people_count, v_allowed USING ERRCODE = 'check_violation';
  ELSIF NOT v_is_entry AND NEW.people_count > v_inside THEN
    RAISE EXCEPTION 'entry_scan: % leaving but only % inside', NEW.people_count, v_inside USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_entry_scan_validate BEFORE INSERT OR UPDATE OR DELETE ON events.entry_scan
  FOR EACH ROW EXECUTE FUNCTION events.entry_scan_validate();

-- Attendance at one session (round) of an event: one check-in per
-- registration and round, by a scanning volunteer or an organiser — or
-- imported from a sheet by an organiser. Append-only. The gate log says who
-- was on the premises; this says which sessions they sat in.
CREATE TABLE events.round_attendance (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_round_id        uuid NOT NULL REFERENCES events.event_round(id),
  registration_id       uuid NOT NULL REFERENCES events.event_registration(id),
  marked_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
  marked_by_account_id  uuid NOT NULL REFERENCES iam.user_account(id),
  scan_source_id        smallint NOT NULL REFERENCES ref.scan_source(id),
  UNIQUE (event_round_id, registration_id)
);
CREATE INDEX round_attendance_registration_idx ON events.round_attendance(registration_id);
CREATE OR REPLACE FUNCTION events.round_attendance_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_round record; v_event uuid; v_person uuid; v_source text;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'round_attendance: session attendance is append-only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT rd.event_id, rd.during INTO v_round FROM events.event_round rd WHERE rd.id = NEW.event_round_id;
  SELECT r.event_id INTO v_event FROM events.event_registration r WHERE r.id = NEW.registration_id;
  IF v_round.event_id IS DISTINCT FROM v_event THEN
    RAISE EXCEPTION 'round_attendance: the registration is for another event' USING ERRCODE = 'check_violation';
  END IF;
  SELECT code INTO v_source FROM ref.scan_source WHERE id = NEW.scan_source_id;
  SELECT person_id INTO v_person FROM iam.user_account WHERE id = NEW.marked_by_account_id;
  IF NOT events.can_manage(NEW.marked_by_account_id, v_event)
     AND (v_source = 'IMPORT' OR NOT EXISTS (SELECT 1 FROM events.event_volunteer v WHERE v.event_id = v_event AND v.person_id = v_person
                                             AND v.can_scan AND v.removed_at IS NULL)) THEN
    RAISE EXCEPTION 'round_attendance: only a scanning volunteer or an organiser marks a session (an import: an organiser)' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF events.registration_state(NEW.registration_id) <> 'CONFIRMED' THEN
    RAISE EXCEPTION 'round_attendance: the registration is not confirmed (%)', events.registration_state(NEW.registration_id) USING ERRCODE = 'check_violation';
  END IF;
  IF clock_timestamp()::timestamp < lower(v_round.during) - (SELECT round_checkin_opens_before FROM events.event_setting) THEN
    RAISE EXCEPTION 'round_attendance: check-in for this session has not opened yet' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_round_attendance_validate BEFORE INSERT OR UPDATE OR DELETE ON events.round_attendance
  FOR EACH ROW EXECUTE FUNCTION events.round_attendance_validate();


-- Did the participant attend: at least one entry at the gate, or a check-in to a session.
CREATE OR REPLACE FUNCTION events.attended(p_registration uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM events.entry_scan s JOIN ref.entry_direction d ON d.id = s.entry_direction_id AND d.is_entry WHERE s.registration_id = p_registration)
      OR EXISTS (SELECT 1 FROM events.round_attendance ra WHERE ra.registration_id = p_registration)
$$;

