-- Submit a drafted club proposal: opens its CLUB_PROPOSAL round.
CREATE OR REPLACE FUNCTION events.submit_club_proposal(p_proposal uuid, p_account uuid)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE v record; v_instance uuid;
BEGIN
  SELECT * INTO v FROM events.club_proposal WHERE id = p_proposal;
  IF v.instance_id IS NOT NULL OR v.proposed_by_account_id IS DISTINCT FROM p_account THEN
    RAISE EXCEPTION 'submit_club_proposal: only its proposer submits a draft, once' USING ERRCODE = 'insufficient_privilege';
  END IF;
  -- the category travels as a flag (CLUBCAT_<code>, where registered), so a chain can send e.g. sports clubs past the sports officer
  v_instance := wf.submit('CLUB_PROPOSAL', v.parent_org_unit_id, p_account, v.club_name, NULL,
                          (SELECT array_agg(f.code::text) FROM ref.club_category c JOIN ref.wf_flag f ON f.code = ('CLUBCAT_' || c.code)::citext
                           WHERE c.id = v.club_category_id));
  UPDATE events.club_proposal SET instance_id = v_instance WHERE id = p_proposal;
  RETURN v_instance;
END $$;

-- Submit a drafted event proposal: the round gets the budget total as its
-- amount and the flags the chain's conditions read (PAID_EVENT,
-- EXTERNAL_GUESTS, SPONSORED); the facility package is created on the same
-- round so rooms, equipment and vehicles can be requested under it.
CREATE OR REPLACE FUNCTION events.submit_proposal(p_proposal uuid, p_account uuid)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE v record; v_instance uuid; v_package uuid; v_flags text[] := '{}'; v_amount numeric;
BEGIN
  SELECT p.*, t.event_kind_id INTO v FROM events.event_proposal p JOIN ref.event_type t ON t.id = p.event_type_id WHERE p.id = p_proposal;
  IF v.instance_id IS NOT NULL OR v.proposed_by_account_id IS DISTINCT FROM p_account THEN
    RAISE EXCEPTION 'submit_proposal: only its proposer submits a draft, once' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT COALESCE(sum(unit_cost * quantity), 0) INTO v_amount FROM events.proposal_budget_item WHERE event_proposal_id = p_proposal;
  IF v.is_paid THEN v_flags := array_append(v_flags, 'PAID_EVENT'); END IF;
  IF EXISTS (SELECT 1 FROM events.proposal_audience a JOIN ref.event_audience_kind k ON k.id = a.event_audience_kind_id AND k.is_external WHERE a.event_proposal_id = p_proposal)
     OR EXISTS (SELECT 1 FROM events.proposal_speaker s WHERE s.event_proposal_id = p_proposal AND s.person_id IS NULL) THEN
    v_flags := array_append(v_flags, 'EXTERNAL_GUESTS');
  END IF;
  IF EXISTS (SELECT 1 FROM events.event_sponsorship WHERE event_proposal_id = p_proposal) THEN v_flags := array_append(v_flags, 'SPONSORED'); END IF;
  -- an event of a club carries the club's category too
  SELECT array_cat(v_flags, COALESCE(array_agg(f.code::text), '{}')) INTO v_flags
  FROM events.club cl JOIN ref.club_category c ON c.id = cl.club_category_id JOIN ref.wf_flag f ON f.code = ('CLUBCAT_' || c.code)::citext
  WHERE cl.org_unit_id = v.organising_org_unit_id;
  v_instance := wf.submit('EVENT_PROPOSAL', v.organising_org_unit_id, p_account, v.title, v_amount, v_flags, NULL, NULL,
                          (SELECT instance_id FROM events.event_proposal WHERE id = v.revises_proposal_id));
  INSERT INTO facility.event_request (title, organiser_person_id, on_behalf_org_unit_id, event_kind_id, during, expected_attendance, instance_id)
  VALUES (v.title, (SELECT person_id FROM iam.user_account WHERE id = p_account), v.organising_org_unit_id, v.event_kind_id, v.during, v.approx_capacity, v_instance)
  RETURNING id INTO v_package;
  UPDATE events.event_proposal SET instance_id = v_instance, facility_event_request_id = v_package WHERE id = p_proposal;
  RETURN v_instance;
END $$;

-- What the approval of a round creates: the club (unit, advisors, officers,
-- members) for a CLUB_PROPOSAL; the unpublished event, with its proposer as
-- event manager, for an EVENT_PROPOSAL.
CREATE OR REPLACE FUNCTION events.approval_action_effects()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_state record; v_cp record; v_ep record; v_unit uuid; v_code text; v_event uuid; v_person uuid;
BEGIN
  SELECT * INTO v_state FROM wf.v_instance_state WHERE instance_id = NEW.instance_id;
  IF v_state.status <> 'APPROVED' THEN RETURN NULL; END IF;
  IF v_state.document_type = 'CLUB_PROPOSAL' THEN
    SELECT * INTO v_cp FROM events.club_proposal WHERE instance_id = NEW.instance_id;
    IF v_cp.id IS NULL OR v_cp.club_org_unit_id IS NOT NULL THEN RETURN NULL; END IF;
    v_code := format('CLB-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.club_code_seq')::text, 5, '0'));
    INSERT INTO org.org_unit (org_unit_type_id, parent_id, code, name)
    VALUES (ref.id_of('org_unit_type', 'CLUB'), v_cp.parent_org_unit_id, v_code, btrim(v_cp.club_name)) RETURNING id INTO v_unit;
    INSERT INTO events.club (org_unit_id, club_code, objective, club_category_id, club_proposal_id) VALUES (v_unit, v_code, v_cp.objective, v_cp.club_category_id, v_cp.id);
    INSERT INTO org.appointment (org_unit_id, position_type_id, employee_id)
    VALUES (v_unit, (SELECT id FROM org.position_type WHERE code = 'CLUB_ADVISOR'), v_cp.advisor_employee_id);
    IF v_cp.co_advisor_employee_id IS NOT NULL THEN
      INSERT INTO org.appointment (org_unit_id, position_type_id, employee_id)
      VALUES (v_unit, (SELECT id FROM org.position_type WHERE code = 'CLUB_CO_ADVISOR'), v_cp.co_advisor_employee_id);
    END IF;
    INSERT INTO events.club_officer (club_org_unit_id, club_office_id, student_id)
    SELECT v_unit, o.club_office_id, o.student_id FROM events.club_proposal_officer o WHERE o.club_proposal_id = v_cp.id;
    INSERT INTO events.club_member (club_org_unit_id, student_id, club_member_role_id, added_by_account_id)
    SELECT v_unit, s.student_id, ref.id_of('club_member_role', 'MEMBER'), v_cp.proposed_by_account_id
    FROM (SELECT student_id FROM events.club_proposal_member WHERE club_proposal_id = v_cp.id
          UNION SELECT student_id FROM events.club_proposal_officer WHERE club_proposal_id = v_cp.id) s;
    UPDATE events.club_proposal SET club_org_unit_id = v_unit WHERE id = v_cp.id;
  ELSIF v_state.document_type = 'EVENT_PROPOSAL' THEN
    SELECT * INTO v_ep FROM events.event_proposal WHERE instance_id = NEW.instance_id;
    IF v_ep.id IS NULL OR EXISTS (SELECT 1 FROM events.event WHERE event_proposal_id = v_ep.id) THEN RETURN NULL; END IF;
    INSERT INTO events.event (event_proposal_id) VALUES (v_ep.id) RETURNING id INTO v_event;
    SELECT person_id INTO v_person FROM iam.user_account WHERE id = v_ep.proposed_by_account_id;
    INSERT INTO events.event_volunteer (event_id, person_id, volunteer_role_id, can_scan, assigned_by_account_id)
    VALUES (v_event, v_person, ref.id_of('volunteer_role', 'EVENT_MANAGER'), true, v_ep.proposed_by_account_id);
  ELSIF v_state.document_type = 'CLUB_CHANGE' THEN
    PERFORM events.apply_club_change((SELECT id FROM events.club_change_request WHERE instance_id = NEW.instance_id));
  ELSIF v_state.document_type = 'EVENT_CHANGE' THEN
    PERFORM events.apply_event_change((SELECT id FROM events.event_change_request WHERE instance_id = NEW.instance_id));
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_events_action_effects AFTER INSERT ON wf.approval_action
  FOR EACH ROW EXECUTE FUNCTION events.approval_action_effects();

