-- May this person see (and so register for) the event: no visibility rows =
-- everyone; else their kind (student / employee / guardian) must be listed,
-- and a student must match one of the scopes if any are set.
CREATE OR REPLACE FUNCTION events.can_see(p_event uuid, p_person uuid)
RETURNS boolean LANGUAGE plpgsql STABLE AS $$
DECLARE v_prop uuid;
BEGIN
  SELECT event_proposal_id INTO v_prop FROM events.event WHERE id = p_event;
  IF NOT EXISTS (SELECT 1 FROM events.proposal_visibility_role WHERE event_proposal_id = v_prop) THEN RETURN true; END IF;
  IF NOT EXISTS (SELECT 1 FROM events.proposal_visibility_role vr JOIN people.v_person_principal_kind k ON k.principal_kind_id = vr.principal_kind_id
                 WHERE vr.event_proposal_id = v_prop AND k.person_id = p_person) THEN RETURN false; END IF;
  IF NOT EXISTS (SELECT 1 FROM events.proposal_visibility_scope WHERE event_proposal_id = v_prop)
     OR NOT EXISTS (SELECT 1 FROM people.v_student_current sc WHERE sc.person_id = p_person) THEN RETURN true; END IF;   -- scopes narrow students only
  RETURN EXISTS (
    SELECT 1 FROM events.proposal_visibility_scope vs JOIN people.v_student_current sc ON sc.person_id = p_person
    WHERE vs.event_proposal_id = v_prop
      AND (vs.batch_id = sc.batch_id OR vs.program_id = sc.program_id
           OR (vs.org_unit_id IS NOT NULL AND sc.home_org_unit_id IN (SELECT org_unit_id FROM org.descendants(vs.org_unit_id)))));
END $$;

-- One person's registration for one event. Seats are counted under a lock on
-- the event: when the event is full the registration is waitlisted and
-- events.promote_waitlist() moves the queue up as seats free. The organiser's
-- decision (where the event requires approval) and the withdrawal are dated
-- facts; what is owed and paid is derived from coupons and payments
-- (events.amount_due, events.is_paid); the status is derived (v_registration).
CREATE TABLE events.event_registration (
  id                             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id                       uuid NOT NULL REFERENCES events.event(id),
  person_id                      uuid NOT NULL REFERENCES people.person(id),
  registration_code              citext NOT NULL UNIQUE,
  qr_token_hash                  bytea NOT NULL UNIQUE CHECK (octet_length(qr_token_hash) = 32),   -- hash of the ticket's token; until a ticket is issued, of random bytes nobody knows
  ticket_issued_at               timestamptz,                         -- set by events.issue_ticket(); NULL = no ticket yet, no QR works
  registered_at                  timestamptz NOT NULL DEFAULT clock_timestamp(),
  waitlisted_at                  timestamptz,
  promoted_at                    timestamptz,
  decided_at                     timestamptz,
  decided_by_account_id          uuid REFERENCES iam.user_account(id),
