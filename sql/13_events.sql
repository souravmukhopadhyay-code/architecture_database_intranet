-- Invitations (leader → participant) and join requests (participant → team):
-- an acceptance in time makes the member.
CREATE OR REPLACE FUNCTION events.team_offer_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_reg uuid := COALESCE(to_jsonb(NEW) ->> 'invitee_registration_id', to_jsonb(NEW) ->> 'registration_id')::uuid;   -- one function, two tables
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.responded_at IS NOT NULL THEN
      RAISE EXCEPTION '%: starts unanswered', TG_TABLE_NAME USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM events.event_team t JOIN events.event_registration r ON r.event_id = t.event_id AND r.id = v_reg AND r.cancelled_at IS NULL
                   WHERE t.id = NEW.event_team_id AND t.locked_at IS NULL AND t.withdrawn_at IS NULL AND t.disqualified_at IS NULL) THEN
      RAISE EXCEPTION '%: needs an open team and a live registration for its event', TG_TABLE_NAME USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM events.event_team_member m WHERE m.registration_id = v_reg AND m.left_at IS NULL) THEN
      RAISE EXCEPTION '%: that participant is already in a team', TG_TABLE_NAME USING ERRCODE = 'unique_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.responded_at IS NOT NULL OR NEW.event_team_id <> OLD.event_team_id THEN
    RAISE EXCEPTION '%: answered once', TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.is_accepted AND NEW.responded_at > (to_jsonb(NEW) ->> 'expires_at')::timestamptz THEN
    RAISE EXCEPTION 'team_invitation: the invitation has expired' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
