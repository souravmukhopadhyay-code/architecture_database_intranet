-- Feedback, anonymous by construction: an attendee gets ONE token (its hash
-- here, with whether it was used); the feedback row carries the event, the
-- rating and the comment — and nothing about who wrote it. The two tables
-- share no key, so feedback cannot be traced, yet nobody votes twice.
CREATE TABLE events.event_feedback_token (
  registration_id  uuid PRIMARY KEY REFERENCES events.event_registration(id) ON DELETE CASCADE,
  token_hash       bytea NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
  issued_at        timestamptz NOT NULL DEFAULT now(),
  used_at          timestamptz
);
CREATE TABLE events.event_feedback (
  id            bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id      uuid NOT NULL REFERENCES events.event(id),
  rating        smallint NOT NULL CHECK (rating >= 1),      -- upper end: event_setting.feedback_rating_max
  comment       text CHECK (char_length(comment) <= 2000),
  submitted_on  date NOT NULL DEFAULT current_date        -- the day only: a timestamp could be matched to the token's
);
CREATE OR REPLACE FUNCTION events.feedback_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'INSERT' OR current_setting('events.feedback_token_ok', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'feedback: written only through events.submit_feedback() with an unused token' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.rating > (SELECT feedback_rating_max FROM events.event_setting) THEN
    RAISE EXCEPTION 'feedback: the rating runs from 1 to %', (SELECT feedback_rating_max FROM events.event_setting) USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_feedback_guard BEFORE INSERT OR UPDATE OR DELETE ON events.event_feedback
  FOR EACH ROW EXECUTE FUNCTION events.feedback_guard();

