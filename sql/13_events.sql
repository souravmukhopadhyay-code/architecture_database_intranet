-- The row is edited, never removed; the feedback scale cannot be cut below a
-- rating already given.
CREATE OR REPLACE FUNCTION events.event_setting_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'event_setting: the settings row is edited, never removed' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.feedback_rating_max < OLD.feedback_rating_max AND EXISTS (SELECT 1 FROM events.event_feedback WHERE rating > NEW.feedback_rating_max) THEN
    RAISE EXCEPTION 'event_setting: feedback already holds ratings above %', NEW.feedback_rating_max USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_setting_guard BEFORE UPDATE OR DELETE ON events.event_setting
  FOR EACH ROW EXECUTE FUNCTION events.event_setting_guard();

