-- Submit the settlement of an event: the expenses as they stand become the
-- statement; the round's amount is their total and it is flagged OVER_BUDGET
-- when that exceeds the approved budget.
CREATE OR REPLACE FUNCTION events.submit_settlement(p_event uuid, p_account uuid, p_remarks text DEFAULT NULL)
RETURNS uuid LANGUAGE plpgsql AS $$
DECLARE v record; v_instance uuid;
BEGIN
  SELECT p.organising_org_unit_id, p.title, s.budget_total, s.expense_total INTO v
  FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id JOIN events.v_event_settlement s ON s.event_id = e.id WHERE e.id = p_event;
  IF NOT FOUND OR NOT events.can_manage(p_account, p_event) THEN
    RAISE EXCEPTION 'submit_settlement: the accounts are settled by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  v_instance := wf.submit('EVENT_SETTLEMENT', v.organising_org_unit_id, p_account, 'Settlement: ' || v.title, v.expense_total,
                          CASE WHEN v.expense_total > v.budget_total THEN ARRAY['OVER_BUDGET'] END);
  INSERT INTO events.event_settlement (event_id, remarks, submitted_by_account_id, instance_id) VALUES (p_event, p_remarks, p_account, v_instance);
  RETURN v_instance;
END $$;


