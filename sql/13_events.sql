-- Apply a coupon code to one's own registration.
CREATE OR REPLACE FUNCTION events.redeem_coupon(p_registration uuid, p_code text, p_account uuid)
RETURNS numeric LANGUAGE plpgsql AS $$
DECLARE v_coupon uuid; v_discount numeric;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM events.event_registration r JOIN iam.user_account a ON a.person_id = r.person_id AND a.id = p_account WHERE r.id = p_registration) THEN
    RAISE EXCEPTION 'redeem_coupon: a coupon is applied by the participant, on their own registration' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT c.id INTO v_coupon FROM events.event_coupon c JOIN events.event_registration r ON r.event_id = c.event_id AND r.id = p_registration
