CREATE OR REPLACE FUNCTION events.event_payment_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_new record; v_old record; v_ch record; v_event uuid; v_person uuid; v_cancelled timestamptz; v_due numeric; v_settled numeric; v_unit uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'event_payment: payments are a record' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO v_new FROM ref.payment_status WHERE id = NEW.payment_status_id;
  SELECT * INTO v_ch FROM ref.payment_channel WHERE id = NEW.payment_channel_id;
  IF NEW.registration_id IS NOT NULL THEN
    SELECT r.event_id, r.person_id, r.cancelled_at INTO v_event, v_person, v_cancelled FROM events.event_registration r WHERE r.id = NEW.registration_id FOR UPDATE;
  ELSE
    SELECT a.event_id, a.applicant_person_id, NULL::timestamptz INTO v_event, v_person, v_cancelled FROM events.stall_application a WHERE a.id = NEW.stall_application_id FOR UPDATE;
  END IF;

  IF TG_OP = 'INSERT' THEN
    NEW.receipt_no := format('RCP-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.receipt_seq')::text, 6, '0'));
    NEW.currency_code := (SELECT currency_code FROM events.event_setting);
    NEW.attempts := 0; NEW.superseded_at := NULL; NEW.failed_at := NULL; NEW.captured_at := NULL; NEW.verified_by_account_id := NULL;
    IF NEW.refunded_at IS NOT NULL THEN
      RAISE EXCEPTION 'event_payment: a payment does not start refunded' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.registration_id IS NOT NULL THEN
      IF v_cancelled IS NOT NULL THEN
        RAISE EXCEPTION 'event_payment: the registration is cancelled' USING ERRCODE = 'check_violation';
      END IF;
      IF events.payer_registration(NEW.registration_id) IS DISTINCT FROM NEW.registration_id THEN
        RAISE EXCEPTION 'event_payment: in a team event the fee is paid by the leader of a complete team' USING ERRCODE = 'insufficient_privilege';
      END IF;
      NEW.event_team_id := (SELECT m.event_team_id FROM events.event_team_member m JOIN events.event_team t ON t.id = m.event_team_id
                            WHERE m.registration_id = NEW.registration_id AND m.left_at IS NULL AND t.withdrawn_at IS NULL AND t.disqualified_at IS NULL
                              AND t.leader_registration_id = NEW.registration_id);
      v_due := events.amount_due(NEW.registration_id);
      v_settled := events.amount_settled(NEW.registration_id);
    ELSE
      v_due := events.stall_fee(NEW.stall_application_id);
      v_settled := COALESCE((SELECT sum(pm.amount) FROM events.event_payment pm JOIN ref.payment_status ps ON ps.id = pm.payment_status_id AND ps.is_settled
                             WHERE pm.stall_application_id = NEW.stall_application_id), 0);
    END IF;
    IF v_due - v_settled <= 0 THEN
      RAISE EXCEPTION 'event_payment: nothing is due (free, fully discounted or already paid)' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.amount <> v_due - v_settled THEN
      RAISE EXCEPTION 'event_payment: the amount due is %', v_due - v_settled USING ERRCODE = 'check_violation';
    END IF;
    IF v_ch.is_online THEN
      IF NEW.gateway_order_id IS NULL OR NOT v_new.is_open THEN
        RAISE EXCEPTION 'event_payment: an online payment starts as an open order with the gateway''s order id' USING ERRCODE = 'check_violation';
      END IF;
    ELSE
      IF NEW.recorded_by_account_id IS NULL THEN
        RAISE EXCEPTION 'event_payment: an offline payment names who recorded it' USING ERRCODE = 'check_violation';
      END IF;
      IF v_new.is_settled THEN
        IF NOT events.can_manage(NEW.recorded_by_account_id, v_event) THEN
          RAISE EXCEPTION 'event_payment: money received is recorded by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
        END IF;
        NEW.verified_by_account_id := NEW.recorded_by_account_id; NEW.captured_at := clock_timestamp();
      ELSIF v_new.is_open THEN
        IF NOT events.can_manage(NEW.recorded_by_account_id, v_event)
           AND NOT EXISTS (SELECT 1 FROM iam.user_account a WHERE a.id = NEW.recorded_by_account_id AND a.person_id = v_person) THEN
          RAISE EXCEPTION 'event_payment: an offline payment is claimed by the payer or recorded by the organisers' USING ERRCODE = 'insufficient_privilege';
        END IF;
        IF NEW.payment_reference IS NULL THEN
          RAISE EXCEPTION 'event_payment: an offline payment quotes its transaction reference' USING ERRCODE = 'check_violation';
        END IF;
      END IF;
    END IF;
    IF NOT v_new.is_open AND NOT (v_new.is_settled AND NOT v_ch.is_online) THEN
      RAISE EXCEPTION 'event_payment: a payment starts open (or, offline, as received)' USING ERRCODE = 'check_violation';
    END IF;
    -- one open order at a time: a newer one supersedes the older
    PERFORM set_config('events.payment_supersede', 'on', true);
    UPDATE events.event_payment pm SET superseded_at = clock_timestamp(),
           payment_status_id = (SELECT id FROM ref.payment_status WHERE NOT is_open AND NOT is_settled AND NOT is_refunded ORDER BY sort_order LIMIT 1)
    WHERE (pm.registration_id = NEW.registration_id OR pm.stall_application_id = NEW.stall_application_id)
      AND pm.payment_status_id IN (SELECT id FROM ref.payment_status WHERE is_open);
    PERFORM set_config('events.payment_supersede', 'off', true);
    RETURN NEW;
  END IF;

  -- UPDATE: the order itself never changes; only its outcome is recorded
  IF NEW.registration_id IS DISTINCT FROM OLD.registration_id OR NEW.stall_application_id IS DISTINCT FROM OLD.stall_application_id
     OR NEW.event_team_id IS DISTINCT FROM OLD.event_team_id OR NEW.amount <> OLD.amount OR NEW.currency_code <> OLD.currency_code
     OR NEW.payment_channel_id <> OLD.payment_channel_id OR NEW.receipt_no <> OLD.receipt_no OR NEW.gateway_order_id IS DISTINCT FROM OLD.gateway_order_id
     OR NEW.recorded_by_account_id IS DISTINCT FROM OLD.recorded_by_account_id OR NEW.created_at <> OLD.created_at OR NEW.attempts < OLD.attempts THEN
    RAISE EXCEPTION 'event_payment: what was ordered never changes' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT * INTO v_old FROM ref.payment_status WHERE id = OLD.payment_status_id;
  IF NEW.superseded_at IS DISTINCT FROM OLD.superseded_at AND current_setting('events.payment_supersede', true) IS DISTINCT FROM 'on' THEN
    RAISE EXCEPTION 'event_payment: an order is superseded only by a newer order' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.payment_status_id <> OLD.payment_status_id THEN
    IF v_old.is_refunded THEN
      RAISE EXCEPTION 'event_payment: a refunded payment is final' USING ERRCODE = 'check_violation';
    END IF;
    IF v_old.is_settled AND NOT v_new.is_refunded THEN
      RAISE EXCEPTION 'event_payment: a captured payment is only ever refunded' USING ERRCODE = 'check_violation';
    END IF;
    IF v_new.is_refunded THEN
      IF NOT v_old.is_settled THEN
        RAISE EXCEPTION 'event_payment: only a captured payment is refunded' USING ERRCODE = 'check_violation';
      END IF;
      SELECT p.organising_org_unit_id INTO v_unit FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = v_event;
      IF NEW.refund_recorded_by_account_id IS NULL OR NEW.refund_reference IS NULL
         OR NOT authz.has_permission(NEW.refund_recorded_by_account_id, 'events.refund.create', v_unit) THEN
        RAISE EXCEPTION 'event_payment: a refund is recorded, with its reference, by someone who may record refunds' USING ERRCODE = 'insufficient_privilege';
      END IF;
      NEW.refunded_at := clock_timestamp();
    ELSIF v_new.is_settled THEN
      IF NOT v_ch.is_online AND (NEW.verified_by_account_id IS NULL OR NOT events.can_manage(NEW.verified_by_account_id, v_event)) THEN
        RAISE EXCEPTION 'event_payment: an offline payment is verified by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
      END IF;
      NEW.captured_at := clock_timestamp();
    ELSIF NOT v_new.is_open THEN
      NEW.failed_at := clock_timestamp();
    END IF;
  ELSIF NEW.refunded_at IS DISTINCT FROM OLD.refunded_at OR NEW.captured_at IS DISTINCT FROM OLD.captured_at OR NEW.failed_at IS DISTINCT FROM OLD.failed_at
        OR NEW.refund_reference IS DISTINCT FROM OLD.refund_reference THEN
    RAISE EXCEPTION 'event_payment: outcome times follow the status' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_payment_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_payment
  FOR EACH ROW EXECUTE FUNCTION events.event_payment_validate();

