CREATE SEQUENCE events.event_change_seq;
CREATE SEQUENCE events.settlement_seq;

-- A change to an approved event that has not started: new dates, another
-- venue, another capacity. A draft until submitted as an EVENT_CHANGE round
-- (levels by configuration; the kind of change travels as flags); on approval
-- the database applies it — the proposal's facts are rewritten, the rounds
-- move with the dates, and for new dates the venue package of the old dates is
-- released in favour of the one opened with the request. What it was before
-- stays on the request.
CREATE TABLE events.event_change_request (
  id                         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_code               citext NOT NULL UNIQUE CHECK (request_code ~ '^ECR-[0-9]{4}-[0-9]{3,}$'),
  event_id                   uuid NOT NULL REFERENCES events.event(id),
  reason                     text NOT NULL CHECK (btrim(reason) <> ''),
  new_during                 tsrange,
  new_venue_text             text CHECK (btrim(new_venue_text) <> ''),
  new_approx_capacity        int CHECK (new_approx_capacity >= 1),
  new_capacity_fixed         int CHECK (new_capacity_fixed >= 1),
  previous_during            tsrange,              -- what the event was before, recorded when the change is applied
  previous_venue_text        text,
  previous_approx_capacity   int,
  previous_capacity_fixed    int,
  facility_event_request_id  uuid REFERENCES facility.event_request(id),   -- new dates: the venue package for them, on this request's round
  requested_by_account_id    uuid NOT NULL REFERENCES iam.user_account(id),
  instance_id                uuid UNIQUE REFERENCES wf.approval_instance(id),   -- NULL = draft
  applied_at                 timestamptz,
  created_at                 timestamptz NOT NULL DEFAULT now(),
  updated_at                 timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(new_during, new_venue_text, new_approx_capacity, new_capacity_fixed) >= 1),
  CHECK (new_during IS NULL OR (NOT isempty(new_during) AND NOT lower_inf(new_during) AND NOT upper_inf(new_during)))
);
CREATE INDEX event_change_request_event_idx ON events.event_change_request(event_id);
SELECT util.attach_updated_at('events.event_change_request');

CREATE OR REPLACE FUNCTION events.event_change_request_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record; v_approx int; v_fixed int; v_offset interval;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.instance_id IS NOT NULL THEN
      RAISE EXCEPTION 'event_change_request: a submitted request is a record; withdraw it instead' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;
  IF TG_OP = 'INSERT' THEN
    NEW.request_code := COALESCE(NEW.request_code, format('ECR-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.event_change_seq')::text, 3, '0')));
    IF NEW.instance_id IS NOT NULL OR NEW.applied_at IS NOT NULL OR NEW.facility_event_request_id IS NOT NULL
       OR num_nonnulls(NEW.previous_during, NEW.previous_venue_text, NEW.previous_approx_capacity, NEW.previous_capacity_fixed) > 0 THEN
      RAISE EXCEPTION 'event_change_request: a request starts as a draft' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF OLD.instance_id IS NOT NULL THEN
    -- once submitted only its application is recorded, by the database
    IF OLD.applied_at IS NOT NULL OR current_setting('events.event_change_apply', true) IS DISTINCT FROM 'on'
       OR (to_jsonb(NEW) - 'applied_at' - 'previous_during' - 'previous_venue_text' - 'previous_approx_capacity' - 'previous_capacity_fixed' - 'updated_at')
          <> (to_jsonb(OLD) - 'applied_at' - 'previous_during' - 'previous_venue_text' - 'previous_approx_capacity' - 'previous_capacity_fixed' - 'updated_at') THEN
      RAISE EXCEPTION 'event_change_request: a submitted request is never edited' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  ELSIF NEW.event_id <> OLD.event_id OR NEW.requested_by_account_id <> OLD.requested_by_account_id OR NEW.request_code <> OLD.request_code THEN
    RAISE EXCEPTION 'event_change_request: the event, the requester and the code of a draft never change' USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT e.registration_window, e.registration_cap, e.cancelled_at, e.completed_at, p.during, p.approx_capacity, p.capacity_fixed, p.organising_org_unit_id INTO v
  FROM events.event e JOIN events.event_proposal p ON p.id = e.event_proposal_id WHERE e.id = NEW.event_id;
  IF NOT events.can_manage(NEW.requested_by_account_id, NEW.event_id) THEN
    RAISE EXCEPTION 'event_change_request: a change is requested by the event''s organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF v.cancelled_at IS NOT NULL OR v.completed_at IS NOT NULL OR clock_timestamp()::timestamp >= lower(v.during) THEN
    RAISE EXCEPTION 'event_change_request: only an event that has not started (and is not cancelled) is changed' USING ERRCODE = 'check_violation';
  END IF;
  v_approx := COALESCE(NEW.new_approx_capacity, v.approx_capacity);
  v_fixed  := COALESCE(NEW.new_capacity_fixed, v.capacity_fixed);
  IF v_fixed IS NOT NULL AND v_fixed < v_approx THEN
    RAISE EXCEPTION 'event_change_request: the fixed capacity cannot be below the expected attendance' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.new_capacity_fixed IS NOT NULL AND (NEW.new_capacity_fixed < events.seats_taken(NEW.event_id)
                                             OR (v.registration_cap IS NOT NULL AND v.registration_cap > NEW.new_capacity_fixed)) THEN
    RAISE EXCEPTION 'event_change_request: the new capacity is below the seats already taken (or the registration cap)' USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.instance_id IS NOT NULL THEN       -- being submitted
    IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'EVENT_CHANGE'
                   WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = v.organising_org_unit_id AND i.submitted_by_account_id = NEW.requested_by_account_id) THEN
      RAISE EXCEPTION 'event_change_request: the round is not the requester''s EVENT_CHANGE round of the organising unit' USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM events.event_change_request r JOIN wf.v_instance_state s ON s.instance_id = r.instance_id AND s.status = 'IN_PROGRESS'
               WHERE r.event_id = NEW.event_id AND r.id <> NEW.id) THEN
      RAISE EXCEPTION 'event_change_request: another change of this event is under approval' USING ERRCODE = 'exclusion_violation';
    END IF;
    IF NEW.new_during IS NOT NULL THEN
      IF lower(NEW.new_during) <= clock_timestamp()::timestamp + (SELECT proposal_min_lead_time FROM events.event_setting) THEN
        RAISE EXCEPTION 'event_change_request: the new start is too soon (or in the past)' USING ERRCODE = 'check_violation';
      END IF;
      IF v.registration_window IS NOT NULL AND upper(v.registration_window)::timestamp > lower(NEW.new_during) THEN
        RAISE EXCEPTION 'event_change_request: registration would close after the new start — shorten the registration window first' USING ERRCODE = 'check_violation';
      END IF;
      v_offset := lower(NEW.new_during) - lower(v.during);
      IF EXISTS (SELECT 1 FROM events.event_round rd WHERE rd.event_id = NEW.event_id
                 AND NOT (NEW.new_during @> tsrange(lower(rd.during) + v_offset, upper(rd.during) + v_offset))) THEN
        RAISE EXCEPTION 'event_change_request: a round would fall outside the new dates — adjust the rounds first' USING ERRCODE = 'check_violation';
      END IF;
      IF NOT EXISTS (SELECT 1 FROM facility.event_request f WHERE f.id = NEW.facility_event_request_id AND f.instance_id = NEW.instance_id) THEN
        RAISE EXCEPTION 'event_change_request: new dates carry their venue package on the request''s round' USING ERRCODE = 'check_violation';
      END IF;
    ELSIF NEW.facility_event_request_id IS NOT NULL THEN
      RAISE EXCEPTION 'event_change_request: a venue package belongs to a change of dates' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.facility_event_request_id IS NOT NULL THEN
    RAISE EXCEPTION 'event_change_request: the venue package is opened at submission' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_event_change_request_validate BEFORE INSERT OR UPDATE OR DELETE ON events.event_change_request
  FOR EACH ROW EXECUTE FUNCTION events.event_change_request_validate();

-- Apply an approved change. Called by the approval hook only.
CREATE OR REPLACE FUNCTION events.apply_event_change(p_request uuid)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v record; p record; v_offset interval;
BEGIN
  SELECT * INTO v FROM events.event_change_request WHERE id = p_request FOR UPDATE;
  IF v.id IS NULL OR v.applied_at IS NOT NULL THEN RETURN; END IF;
  IF NOT EXISTS (SELECT 1 FROM wf.v_instance_state s WHERE s.instance_id = v.instance_id AND s.status = 'APPROVED') THEN
    RAISE EXCEPTION 'apply_event_change: the request is not approved' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT pr.id, pr.during, pr.venue_text, pr.approx_capacity, pr.capacity_fixed, pr.facility_event_request_id INTO p
  FROM events.event e JOIN events.event_proposal pr ON pr.id = e.event_proposal_id WHERE e.id = v.event_id;
  PERFORM set_config('events.proposal_change_apply', 'on', true);
  UPDATE events.event_proposal
     SET during = COALESCE(v.new_during, during), venue_text = COALESCE(v.new_venue_text, venue_text),
         approx_capacity = COALESCE(v.new_approx_capacity, approx_capacity), capacity_fixed = COALESCE(v.new_capacity_fixed, capacity_fixed),
         facility_event_request_id = COALESCE(v.facility_event_request_id, facility_event_request_id)
   WHERE id = p.id;
  PERFORM set_config('events.proposal_change_apply', 'off', true);
  IF v.new_during IS NOT NULL THEN
    v_offset := lower(v.new_during) - lower(p.during);
    UPDATE events.event_round SET during = tsrange(lower(during) + v_offset, upper(during) + v_offset) WHERE event_id = v.event_id;
    -- the venue package of the old dates is released; rooms for the new dates are on the request's own package
    UPDATE facility.event_request SET cancelled_at = clock_timestamp(), cancelled_by_account_id = v.requested_by_account_id
    WHERE id = p.facility_event_request_id AND cancelled_at IS NULL;
  END IF;
  PERFORM set_config('events.event_change_apply', 'on', true);
  UPDATE events.event_change_request
     SET applied_at = clock_timestamp(), previous_during = p.during, previous_venue_text = p.venue_text,
         previous_approx_capacity = p.approx_capacity, previous_capacity_fixed = p.capacity_fixed
   WHERE id = v.id;
  PERFORM set_config('events.event_change_apply', 'off', true);
END $$;

