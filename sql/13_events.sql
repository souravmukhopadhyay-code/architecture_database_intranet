-- Attendance per session: how many confirmed participants, how many checked in.
CREATE OR REPLACE VIEW events.v_round_attendance AS
SELECT rd.id AS event_round_id, rd.event_id, rd.name, rd.during,
       (SELECT count(*) FROM events.event_registration r WHERE r.event_id = rd.event_id AND events.registration_state(r.id) = 'CONFIRMED')::int AS confirmed,
       (SELECT count(*) FROM events.round_attendance ra WHERE ra.event_round_id = rd.id)::int AS attended
FROM events.event_round rd;

-- Budget against actual spending, per budget head of an event.
CREATE OR REPLACE VIEW events.v_event_budget_actual AS
SELECT e.id AS event_id, t.code AS budget_item_type, COALESCE(b.budgeted, 0) AS budgeted, COALESCE(x.actual, 0) AS actual,
       COALESCE(x.actual, 0) - COALESCE(b.budgeted, 0) AS variance
FROM events.event e
CROSS JOIN ref.budget_item_type t
LEFT JOIN (SELECT event_proposal_id, budget_item_type_id, sum(unit_cost * quantity) AS budgeted FROM events.proposal_budget_item GROUP BY 1, 2) b
       ON b.event_proposal_id = e.event_proposal_id AND b.budget_item_type_id = t.id
LEFT JOIN (SELECT event_id, budget_item_type_id, sum(amount) AS actual FROM events.event_expense GROUP BY 1, 2) x
       ON x.event_id = e.id AND x.budget_item_type_id = t.id
WHERE b.budgeted IS NOT NULL OR x.actual IS NOT NULL;

-- The accounts of an event on one row: approved budget, what was spent, what
-- came in (fees, sponsorship), and where its settlement stands
--   NOT_SUBMITTED · IN_PROGRESS · RETURNED · REJECTED · WITHDRAWN · APPROVED
CREATE OR REPLACE VIEW events.v_event_settlement AS
SELECT e.id AS event_id, e.event_code,
       (SELECT COALESCE(sum(b.unit_cost * b.quantity), 0) FROM events.proposal_budget_item b WHERE b.event_proposal_id = e.event_proposal_id) AS budget_total,
       (SELECT COALESCE(sum(x.amount), 0) FROM events.event_expense x WHERE x.event_id = e.id) AS expense_total,
       (SELECT COALESCE(sum(x.amount), 0) FROM events.event_expense x WHERE x.event_id = e.id)
         - (SELECT COALESCE(sum(b.unit_cost * b.quantity), 0) FROM events.proposal_budget_item b WHERE b.event_proposal_id = e.event_proposal_id) AS variance,
       (SELECT COALESCE(sum(pm.amount), 0) FROM events.event_payment pm JOIN ref.payment_status ps ON ps.id = pm.payment_status_id AND ps.is_settled
        JOIN events.event_registration r ON r.id = pm.registration_id WHERE r.event_id = e.id) AS fees_collected,
       (SELECT COALESCE(sum(rc.amount), 0) FROM events.sponsorship_receipt rc JOIN events.event_sponsorship sp ON sp.id = rc.sponsorship_id
        WHERE sp.event_proposal_id = e.event_proposal_id) AS sponsorship_received,
       st.settlement_code, COALESCE(s.status, 'NOT_SUBMITTED') AS status, st.instance_id, s.amount AS settled_amount
FROM events.event e
LEFT JOIN LATERAL (SELECT x.* FROM events.event_settlement x WHERE x.event_id = e.id ORDER BY x.created_at DESC, x.settlement_code DESC LIMIT 1) st ON true
LEFT JOIN wf.v_instance_state s ON s.instance_id = st.instance_id;


