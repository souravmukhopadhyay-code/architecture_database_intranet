-- A message from the organisers to an event's registrants: everyone, those
-- confirmed, pending or cancelled, or a hand-picked selection; sent now or at
-- a scheduled time. Addresses are never stored — a recipient is a registration
-- and the address is looked up when sending. Each recipient costs one credit
-- (see v_event_mail_credit). The status is derived (v_event_mail).
CREATE TABLE events.event_mail (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_id                 uuid NOT NULL REFERENCES events.event(id) ON DELETE CASCADE,
  subject                  text NOT NULL CHECK (btrim(subject) <> '' AND subject !~ '[\r\n]'),
  body                     text NOT NULL CHECK (btrim(body) <> ''),
  mail_audience_id         smallint NOT NULL REFERENCES ref.mail_audience(id),
  created_by_account_id    uuid NOT NULL REFERENCES iam.user_account(id),
  created_at               timestamptz NOT NULL DEFAULT clock_timestamp(),
  scheduled_at             timestamptz,                -- NULL = send as soon as it is dispatched
  dispatch_started_at      timestamptz,               -- recipients resolved and credits taken; completion is derived from the recipients
  failed_at                timestamptz,
  failure_reason           text,
  cancelled_at             timestamptz,
  cancelled_by_account_id  uuid REFERENCES iam.user_account(id),
  CHECK ((cancelled_at IS NULL) = (cancelled_by_account_id IS NULL)),
  CHECK ((failed_at IS NULL) = (failure_reason IS NULL))
);
CREATE INDEX event_mail_event_idx ON events.event_mail(event_id);

CREATE TABLE events.event_mail_recipient (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_mail_id            uuid NOT NULL REFERENCES events.event_mail(id) ON DELETE CASCADE,
  registration_id          uuid NOT NULL REFERENCES events.event_registration(id),
  mail_delivery_status_id  smallint NOT NULL REFERENCES ref.mail_delivery_status(id),
  failure_reason           text,
  delivered_at             timestamptz,
  failed_at                timestamptz,
  open_count               int NOT NULL DEFAULT 0 CHECK (open_count >= 0),
  first_opened_at          timestamptz,
  last_opened_at           timestamptz,
  UNIQUE (event_mail_id, registration_id)
);
CREATE INDEX event_mail_recipient_registration_idx ON events.event_mail_recipient(registration_id);

-- Extra credits an administrator gives an event beyond its allowance.
CREATE TABLE events.event_mail_credit_grant (
