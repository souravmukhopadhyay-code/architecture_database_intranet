CREATE OR REPLACE FUNCTION events.sponsorship_receipt_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'sponsorship_receipt: receipts are append-only' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT s.cash_amount, p.organising_org_unit_id,
         COALESCE((SELECT sum(amount) FROM events.sponsorship_receipt r WHERE r.sponsorship_id = s.id), 0) AS received
    INTO v
  FROM events.event_sponsorship s JOIN events.event_proposal p ON p.id = s.event_proposal_id WHERE s.id = NEW.sponsorship_id;
  IF v.cash_amount IS NULL OR v.received + NEW.amount > v.cash_amount THEN
    RAISE EXCEPTION 'sponsorship_receipt: more than the committed cash' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT events.may_propose_for(NEW.recorded_by_account_id, v.organising_org_unit_id) THEN
    RAISE EXCEPTION 'sponsorship_receipt: recorded by the organisers' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
