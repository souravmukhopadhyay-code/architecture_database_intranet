-- Is the club running at a moment (its unit active, not suspended)?
CREATE OR REPLACE FUNCTION events.club_is_active(p_club uuid, p_at timestamptz DEFAULT now())
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM events.club c JOIN org.org_unit u ON u.id = c.org_unit_id AND u.is_active WHERE c.org_unit_id = p_club)
     AND NOT EXISTS (SELECT 1 FROM events.club_suspension s WHERE s.club_org_unit_id = p_club AND s.during @> p_at)
$$;

-- Is this account's person an officer (student post) or an advisor / co-advisor
-- (appointment) of the club today? Row-level ownership, like
-- academic.is_program_coordinator().
CREATE OR REPLACE FUNCTION events.is_club_officer(p_account uuid, p_club uuid, p_must_propose boolean DEFAULT false)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
           SELECT 1 FROM iam.user_account ua
           JOIN people.student s ON s.person_id = ua.person_id
           JOIN events.club_officer o ON o.student_id = s.id AND o.club_org_unit_id = p_club AND o.valid @> current_date
           JOIN ref.club_office f ON f.id = o.club_office_id AND (f.may_propose OR NOT p_must_propose)
           WHERE ua.id = p_account)
      OR EXISTS (
           SELECT 1 FROM iam.user_account ua
           JOIN people.employee e ON e.person_id = ua.person_id
           JOIN org.appointment ap ON ap.employee_id = e.id AND ap.org_unit_id = p_club AND ap.valid @> current_date
           JOIN org.position_type pt ON pt.id = ap.position_type_id AND pt.code IN ('CLUB_ADVISOR', 'CLUB_CO_ADVISOR')
           WHERE ua.id = p_account)
$$;

CREATE OR REPLACE FUNCTION events.is_current_student(p_student uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM people.student s JOIN ref.student_status ss ON ss.id = s.student_status_id AND ss.is_current_member WHERE s.id = p_student)
$$;

CREATE OR REPLACE FUNCTION events.is_teaching_employee(p_employee uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM people.employee e
                 JOIN ref.employee_category c ON c.id = e.employee_category_id AND c.code = 'TEACHING'
                 JOIN ref.employment_status es ON es.id = e.employment_status_id AND es.is_current_member
                 WHERE e.id = p_employee)
$$;

CREATE OR REPLACE FUNCTION events.is_current_employee(p_employee uuid)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (SELECT 1 FROM people.employee e
                 JOIN ref.employment_status es ON es.id = e.employment_status_id AND es.is_current_member
                 WHERE e.id = p_employee)
$$;

CREATE OR REPLACE FUNCTION events.club_proposal_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_set record; v_missing text;
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF OLD.instance_id IS NOT NULL THEN
      RAISE EXCEPTION 'club_proposal: a submitted proposal is a record; withdraw it instead' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN OLD;
  END IF;
  IF TG_OP = 'INSERT' AND NEW.proposal_code IS NULL THEN
    NEW.proposal_code := format('CP-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.club_proposal_seq')::text, 3, '0'));
  END IF;
  IF TG_OP = 'UPDATE' AND OLD.instance_id IS NOT NULL THEN
    -- once submitted only the created club may be recorded
    IF (to_jsonb(NEW) - 'club_org_unit_id' - 'updated_at') <> (to_jsonb(OLD) - 'club_org_unit_id' - 'updated_at') OR OLD.club_org_unit_id IS NOT NULL THEN
      RAISE EXCEPTION 'club_proposal: a submitted proposal is never edited; withdraw it and propose again' USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
  END IF;
  SELECT * INTO v_set FROM events.event_setting;
  IF char_length(btrim(NEW.club_name)) NOT BETWEEN v_set.club_name_min_length AND v_set.club_name_max_length THEN
    RAISE EXCEPTION 'club_proposal: the club name has % to % characters', v_set.club_name_min_length, v_set.club_name_max_length USING ERRCODE = 'check_violation';
  END IF;
  IF char_length(btrim(NEW.objective)) < v_set.club_objective_min_length THEN
    RAISE EXCEPTION 'club_proposal: the objective has at least % characters', v_set.club_objective_min_length USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM org.org_unit u JOIN org.org_unit_type_rule r ON r.parent_type_id = u.org_unit_type_id
                 AND r.child_type_id = ref.id_of('org_unit_type', 'CLUB') WHERE u.id = NEW.parent_org_unit_id AND u.is_active) THEN
    RAISE EXCEPTION 'club_proposal: a club cannot sit under that unit' USING ERRCODE = 'check_violation';
  END IF;
  IF v_set.advisor_must_be_faculty THEN
    IF NOT events.is_teaching_employee(NEW.advisor_employee_id)
       OR (NEW.co_advisor_employee_id IS NOT NULL AND NOT events.is_teaching_employee(NEW.co_advisor_employee_id)) THEN
      RAISE EXCEPTION 'club_proposal: the advisor and co-advisor are current faculty' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NOT events.is_current_employee(NEW.advisor_employee_id)
        OR (NEW.co_advisor_employee_id IS NOT NULL AND NOT events.is_current_employee(NEW.co_advisor_employee_id)) THEN
    RAISE EXCEPTION 'club_proposal: the advisor and co-advisor are current employees' USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM events.club c JOIN org.org_unit u ON u.id = c.org_unit_id AND u.is_active WHERE lower(u.name) = lower(btrim(NEW.club_name))) THEN
    RAISE EXCEPTION 'club_proposal: a club named "%" already exists', NEW.club_name USING ERRCODE = 'unique_violation';
  END IF;
  IF NEW.instance_id IS NOT NULL THEN       -- being submitted
    IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'CLUB_PROPOSAL'
                   WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = NEW.parent_org_unit_id AND i.submitted_by_account_id = NEW.proposed_by_account_id) THEN
      RAISE EXCEPTION 'club_proposal: the round is not the proposer''s CLUB_PROPOSAL round of the parent unit' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.club_category_id IS NULL THEN
      RAISE EXCEPTION 'club_proposal: say what kind of club it is (its category) before submitting' USING ERRCODE = 'check_violation';
    END IF;
    -- every office marked required (ref.club_office.is_required) is named
    SELECT string_agg(f.label, ', ' ORDER BY f.sort_order) INTO v_missing
    FROM ref.club_office f
    WHERE f.is_required AND f.is_active
      AND NOT EXISTS (SELECT 1 FROM events.club_proposal_officer o WHERE o.club_proposal_id = NEW.id AND o.club_office_id = f.id);
    IF v_missing IS NOT NULL THEN
      RAISE EXCEPTION 'club_proposal: name the required officers before submitting (%)', v_missing USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_club_proposal_validate BEFORE INSERT OR UPDATE OR DELETE ON events.club_proposal
  FOR EACH ROW EXECUTE FUNCTION events.club_proposal_validate();

-- The parts of a club proposal change only while it is a draft; the students
-- named are current students.
CREATE OR REPLACE FUNCTION events.club_proposal_part_guard()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_id uuid := CASE WHEN TG_OP = 'DELETE' THEN OLD.club_proposal_id ELSE NEW.club_proposal_id END;
BEGIN
  IF (SELECT instance_id FROM events.club_proposal WHERE id = v_id) IS NOT NULL THEN
    RAISE EXCEPTION '%: the proposal has been submitted; its parts are frozen', TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF TG_OP <> 'DELETE' AND TG_TABLE_NAME IN ('club_proposal_officer', 'club_proposal_member')
     AND NOT events.is_current_student((to_jsonb(NEW) ->> 'student_id')::uuid) THEN
    RAISE EXCEPTION '%: not a current student', TG_TABLE_NAME USING ERRCODE = 'check_violation';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER trg_club_proposal_officer_guard BEFORE INSERT OR UPDATE OR DELETE ON events.club_proposal_officer FOR EACH ROW EXECUTE FUNCTION events.club_proposal_part_guard();
CREATE TRIGGER trg_club_proposal_member_guard  BEFORE INSERT OR UPDATE OR DELETE ON events.club_proposal_member  FOR EACH ROW EXECUTE FUNCTION events.club_proposal_part_guard();
CREATE TRIGGER trg_club_proposal_attachment_guard BEFORE INSERT OR UPDATE OR DELETE ON events.club_proposal_attachment FOR EACH ROW EXECUTE FUNCTION events.club_proposal_part_guard();

CREATE OR REPLACE FUNCTION events.club_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' AND NEW.club_code IS NULL THEN
    NEW.club_code := format('CLB-%s-%s', to_char(current_date, 'YYYY'), lpad(nextval('events.club_code_seq')::text, 5, '0'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM org.org_unit u JOIN ref.org_unit_type t ON t.id = u.org_unit_type_id AND t.code = 'CLUB' WHERE u.id = NEW.org_unit_id) THEN
    RAISE EXCEPTION 'club: the org unit is not of type CLUB' USING ERRCODE = 'check_violation';
  END IF;
  IF TG_OP = 'UPDATE' AND (NEW.org_unit_id <> OLD.org_unit_id OR NEW.club_code <> OLD.club_code OR NEW.club_proposal_id IS DISTINCT FROM OLD.club_proposal_id) THEN
    RAISE EXCEPTION 'club: the unit, code and founding proposal never change' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_club_validate BEFORE INSERT OR UPDATE ON events.club
  FOR EACH ROW EXECUTE FUNCTION events.club_validate();

-- Officers and members are current students of a running club.
CREATE OR REPLACE FUNCTION events.club_person_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.student_id <> OLD.student_id THEN
    IF NOT events.is_current_student(NEW.student_id) THEN
      RAISE EXCEPTION '%: not a current student', TG_TABLE_NAME USING ERRCODE = 'check_violation';
    END IF;
    IF NOT events.club_is_active(NEW.club_org_unit_id) THEN
      RAISE EXCEPTION '%: the club is suspended or closed', TG_TABLE_NAME USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_club_officer_validate BEFORE INSERT OR UPDATE ON events.club_officer FOR EACH ROW EXECUTE FUNCTION events.club_person_validate();
CREATE TRIGGER trg_club_member_validate  BEFORE INSERT OR UPDATE ON events.club_member  FOR EACH ROW EXECUTE FUNCTION events.club_person_validate();

CREATE OR REPLACE FUNCTION events.club_application_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.decided_at IS NOT NULL THEN
      RAISE EXCEPTION 'club_application: an application starts undecided' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT events.is_current_student(NEW.student_id) OR NOT events.club_is_active(NEW.club_org_unit_id) THEN
      RAISE EXCEPTION 'club_application: only current students apply, and only to a running club' USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM events.club_member m WHERE m.club_org_unit_id = NEW.club_org_unit_id AND m.student_id = NEW.student_id AND m.valid @> current_date) THEN
      RAISE EXCEPTION 'club_application: already a member' USING ERRCODE = 'unique_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF OLD.decided_at IS NOT NULL OR NEW.club_org_unit_id <> OLD.club_org_unit_id OR NEW.student_id <> OLD.student_id OR NEW.applied_at <> OLD.applied_at THEN
    RAISE EXCEPTION 'club_application: only the decision is recorded, once' USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.decided_at IS NOT NULL AND NOT events.is_club_officer(NEW.decided_by_account_id, NEW.club_org_unit_id)
     AND NOT authz.has_permission(NEW.decided_by_account_id, 'events.club_member.update', NEW.club_org_unit_id) THEN
    RAISE EXCEPTION 'club_application: decided by the club''s advisors, officers or its administrators' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_club_application_validate BEFORE INSERT OR UPDATE ON events.club_application
  FOR EACH ROW EXECUTE FUNCTION events.club_application_validate();

-- An approved application becomes a membership.
CREATE OR REPLACE FUNCTION events.club_application_effects()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.is_approved AND OLD.decided_at IS NULL THEN
    INSERT INTO events.club_member (club_org_unit_id, student_id, club_member_role_id, added_by_account_id)
    VALUES (NEW.club_org_unit_id, NEW.student_id, ref.id_of('club_member_role', 'VOLUNTEER'), NEW.decided_by_account_id);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_club_application_effects AFTER UPDATE OF decided_at ON events.club_application
  FOR EACH ROW EXECUTE FUNCTION events.club_application_effects();

