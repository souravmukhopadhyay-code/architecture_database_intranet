-- =============================================================================
-- 06_authz.sql — Role-based access control with org-unit scoping (schema: authz)
--
-- Model: NIST RBAC1 (hierarchical roles) + static separation of duties
--        + grants scoped to a subtree of the org tree.
--
--   app_module ─< resource ─< permission >─ action
--   role ─< role_permission >─ permission
--   role ─< role_inheritance (senior inherits junior)
--
-- Who gets a role:
--   1. EXPLICIT   authz.account_role / authz.account_permission (scoped, time-bound)
--   2. DERIVED    from facts, never copied onto users:
--        designation_role    : designation of an active employee_assignment -> role @ that unit
--        position_role       : active org.appointment (e.g. HEAD)           -> role @ that unit
--        principal_kind_role : being an employee / student / guardian       -> baseline role
--   Resolution happens in views/functions (09_views_functions.sql).
--
-- A permission code is DERIVED as  <module>.<resource>.<action>  (never stored).
-- Module access = permission <module>._module.access
-- "Reviewer for Schools A and B" = two account_role rows scoped to A and B.
-- =============================================================================

SET client_encoding = 'UTF8';   -- files are UTF-8; psql on Windows may default to WIN1252

SET search_path = authz, iam, org, people, ref, public;

-- ---------------------------------------------------------------- catalogue --
CREATE TABLE authz.app_module (
  id           smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         citext NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{1,40}$'),
  name         text   NOT NULL,
  description  text,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
SELECT util.attach_updated_at('authz.app_module');

CREATE TABLE authz.resource (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  app_module_id  smallint NOT NULL REFERENCES authz.app_module(id),
  code           citext NOT NULL CHECK (code ~ '^_?[a-z][a-z0-9_]{0,40}$'),
  label          text NOT NULL,
  UNIQUE (app_module_id, code)
);

CREATE TABLE authz.action (
  id     smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code   citext NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{1,30}$'),
  label  text NOT NULL
);

CREATE TABLE authz.permission (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  resource_id  int      NOT NULL REFERENCES authz.resource(id),
  action_id    smallint NOT NULL REFERENCES authz.action(id),
  description  text,
  is_scopable  boolean NOT NULL DEFAULT true,  -- false = only meaningful as a global grant
  UNIQUE (resource_id, action_id)
);

-- --------------------------------------------------------------------- roles --
CREATE TABLE authz.role (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           citext NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]{1,60}$'),
  name           text NOT NULL UNIQUE,
  description    text,
  is_system      boolean NOT NULL DEFAULT false,  -- seeded, not deletable from UI
  requires_mfa   boolean NOT NULL DEFAULT false,  -- holders must complete MFA
  is_active      boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
SELECT util.attach_updated_at('authz.role');

CREATE TABLE authz.role_permission (
  role_id        int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  permission_id  int NOT NULL REFERENCES authz.permission(id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX role_permission_permission_idx ON authz.role_permission(permission_id);

-- senior role inherits every permission of the junior role (transitively)
CREATE TABLE authz.role_inheritance (
  senior_role_id  int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  junior_role_id  int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  PRIMARY KEY (senior_role_id, junior_role_id),
  CHECK (senior_role_id <> junior_role_id)
);

CREATE OR REPLACE FUNCTION authz.role_inheritance_no_cycle()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_cycle boolean;
BEGIN
  -- would junior (transitively) inherit senior? then adding senior->junior cycles
  WITH RECURSIVE down AS (
    SELECT junior_role_id AS role_id FROM authz.role_inheritance WHERE senior_role_id = NEW.junior_role_id
    UNION
    SELECT ri.junior_role_id FROM authz.role_inheritance ri JOIN down d ON ri.senior_role_id = d.role_id
  )
  SELECT EXISTS (SELECT 1 FROM down WHERE role_id = NEW.senior_role_id) INTO v_cycle;
  IF v_cycle THEN
    RAISE EXCEPTION 'role inheritance % -> % would create a cycle',
      NEW.senior_role_id, NEW.junior_role_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_role_inheritance_no_cycle
  BEFORE INSERT OR UPDATE ON authz.role_inheritance
  FOR EACH ROW EXECUTE FUNCTION authz.role_inheritance_no_cycle();

-- static separation of duties: nobody may hold both roles at the same time
CREATE TABLE authz.role_conflict (
  role_a_id  int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  role_b_id  int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  reason     text,
  PRIMARY KEY (role_a_id, role_b_id),
  CHECK (role_a_id < role_b_id)                 -- store each pair once
);

-- =========================================================== explicit grants ==
-- scope_org_unit_id NULL = global (whole university). For a global grant
-- include_descendants must be true (global already means "everything").
CREATE TABLE authz.account_role (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id             uuid NOT NULL REFERENCES iam.user_account(id) ON DELETE CASCADE,
  role_id                int  NOT NULL REFERENCES authz.role(id),
  scope_org_unit_id      uuid REFERENCES org.org_unit(id),
  include_descendants    boolean NOT NULL DEFAULT true,
  valid                  tstzrange NOT NULL DEFAULT tstzrange(now(), NULL),
  granted_by_account_id  uuid REFERENCES iam.user_account(id),
  reason                 text,
  created_at             timestamptz NOT NULL DEFAULT now(),
  CHECK (scope_org_unit_id IS NOT NULL OR include_descendants),
  CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  CONSTRAINT account_role_no_overlap EXCLUDE USING gist (
    account_id WITH =, role_id WITH =,
    (COALESCE(scope_org_unit_id, '00000000-0000-0000-0000-000000000000'::uuid)) WITH =,
    valid WITH &&)
);
CREATE INDEX account_role_account_idx ON authz.account_role(account_id);
CREATE INDEX account_role_scope_idx   ON authz.account_role(scope_org_unit_id);

-- Ad-hoc single-permission grants (prefer roles; kept for exceptional cases).
CREATE TABLE authz.account_permission (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  account_id             uuid NOT NULL REFERENCES iam.user_account(id) ON DELETE CASCADE,
  permission_id          int  NOT NULL REFERENCES authz.permission(id),
  scope_org_unit_id      uuid REFERENCES org.org_unit(id),
  include_descendants    boolean NOT NULL DEFAULT true,
  valid                  tstzrange NOT NULL DEFAULT tstzrange(now(), NULL),
  granted_by_account_id  uuid REFERENCES iam.user_account(id),
  reason                 text NOT NULL,          -- ad-hoc grants must be justified
  created_at             timestamptz NOT NULL DEFAULT now(),
  CHECK (scope_org_unit_id IS NOT NULL OR include_descendants),
  CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  CONSTRAINT account_permission_no_overlap EXCLUDE USING gist (
    account_id WITH =, permission_id WITH =,
    (COALESCE(scope_org_unit_id, '00000000-0000-0000-0000-000000000000'::uuid)) WITH =,
    valid WITH &&)
);
CREATE INDEX account_permission_account_idx ON authz.account_permission(account_id);

-- Guard rails on explicit grants: inactive role, non-scopable permission
-- granted with a scope, and static separation-of-duty conflicts.
CREATE OR REPLACE FUNCTION authz.account_role_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT (SELECT is_active FROM authz.role WHERE id = NEW.role_id) THEN
    RAISE EXCEPTION 'role % is inactive', NEW.role_id USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (
    SELECT 1 FROM authz.account_role ar
    JOIN authz.role_conflict rc
      ON (rc.role_a_id = ar.role_id AND rc.role_b_id = NEW.role_id)
      OR (rc.role_b_id = ar.role_id AND rc.role_a_id = NEW.role_id)
    WHERE ar.account_id = NEW.account_id AND ar.id <> NEW.id AND ar.valid && NEW.valid) THEN
    RAISE EXCEPTION 'role % conflicts with a role already held by account % (separation of duties)',
      NEW.role_id, NEW.account_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_account_role_validate
  BEFORE INSERT OR UPDATE ON authz.account_role
  FOR EACH ROW EXECUTE FUNCTION authz.account_role_validate();

CREATE OR REPLACE FUNCTION authz.account_permission_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.scope_org_unit_id IS NOT NULL
     AND NOT (SELECT is_scopable FROM authz.permission WHERE id = NEW.permission_id) THEN
    RAISE EXCEPTION 'permission % is not scopable; grant it globally', NEW.permission_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_account_permission_validate
  BEFORE INSERT OR UPDATE ON authz.account_permission
  FOR EACH ROW EXECUTE FUNCTION authz.account_permission_validate();

-- ========================================================= derivation rules ==
-- Templates only. Effective grants are computed in 09_views_functions.sql.

-- designation held in an active employee_assignment => role.
--   scope_to_assignment_unit = true  : scoped to the assignment's unit (e.g. HOD-like)
--   scope_to_assignment_unit = false : global (e.g. HR Manager manages all staff)
CREATE TABLE authz.designation_role (
  designation_id            smallint NOT NULL REFERENCES people.designation(id) ON DELETE CASCADE,
  role_id                   int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  scope_to_assignment_unit  boolean NOT NULL DEFAULT true,
  include_descendants       boolean NOT NULL DEFAULT true,
  PRIMARY KEY (designation_id, role_id),
  CHECK (scope_to_assignment_unit OR include_descendants)   -- global implies everything
);

-- active appointment to a position => role scoped to the appointed unit
CREATE TABLE authz.position_role (
  position_type_id     smallint NOT NULL REFERENCES org.position_type(id) ON DELETE CASCADE,
  role_id              int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  include_descendants  boolean NOT NULL DEFAULT true,
  PRIMARY KEY (position_type_id, role_id)
);

-- baseline role for every principal of a kind (optionally narrowed to an
-- employee category). scope_to_home_unit: true => scoped to the person's primary
-- unit (employee primary assignment / student affiliation), false => global.
CREATE TABLE authz.principal_kind_role (
  id                    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  principal_kind_id     smallint NOT NULL REFERENCES ref.principal_kind(id),
  employee_category_id  smallint REFERENCES ref.employee_category(id),
  role_id               int NOT NULL REFERENCES authz.role(id) ON DELETE CASCADE,
  scope_to_home_unit    boolean NOT NULL DEFAULT false,
  CONSTRAINT principal_kind_role_uq UNIQUE NULLS NOT DISTINCT (principal_kind_id, employee_category_id, role_id)
);
