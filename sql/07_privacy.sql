SET client_encoding = 'UTF8';   -- files are UTF-8; psql on Windows may default to WIN1252

SET search_path = privacy, people, pii, iam, ref, public;

-- --------------------------------------------------------- processing_purpose --
CREATE TABLE privacy.processing_purpose (
  id                smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              citext NOT NULL UNIQUE,
  label             text   NOT NULL,
  description       text   NOT NULL,
  legal_basis_id    smallint NOT NULL REFERENCES ref.legal_basis(id),
  retention_period  interval NOT NULL CHECK (retention_period > interval '0'),
  is_active         boolean NOT NULL DEFAULT true,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);
SELECT util.attach_updated_at('privacy.processing_purpose');

CREATE TABLE privacy.purpose_data_category (
  purpose_id        smallint NOT NULL REFERENCES privacy.processing_purpose(id) ON DELETE CASCADE,
  data_category_id  smallint NOT NULL REFERENCES ref.data_category(id),
  PRIMARY KEY (purpose_id, data_category_id)
);

-- ---------------------------------------------------------------- data_element --
-- Personal-data inventory: which column holds which category of personal data
-- and what erasure does to it. Drives access-summary exports, erasure jobs and
-- audit redaction (sensitivity comes from ref.data_category.is_sensitive).
CREATE TABLE privacy.data_element (
  id                 int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schema_name        name NOT NULL,
  table_name         name NOT NULL,
  column_name        name NOT NULL,
  data_category_id   smallint NOT NULL REFERENCES ref.data_category(id),
  erasure_action_id  smallint NOT NULL REFERENCES ref.erasure_action(id),
  UNIQUE (schema_name, table_name, column_name)
);

CREATE OR REPLACE FUNCTION privacy.data_element_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema = NEW.schema_name AND table_name = NEW.table_name
                   AND column_name = NEW.column_name) THEN
    RAISE EXCEPTION 'data_element: column %.%.% does not exist',
      NEW.schema_name, NEW.table_name, NEW.column_name USING ERRCODE = 'foreign_key_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_data_element_validate BEFORE INSERT OR UPDATE ON privacy.data_element
  FOR EACH ROW EXECUTE FUNCTION privacy.data_element_validate();

-- ------------------------------------------------------------ privacy_notice --
-- One row per (version, language). DPDP §5(3): notice available in English
-- and any 8th-Schedule language.
CREATE TABLE privacy.privacy_notice (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  version         varchar(20) NOT NULL,
  language_id     smallint NOT NULL REFERENCES ref.language(id),
  content_sha256  bytea NOT NULL CHECK (octet_length(content_sha256) = 32),
  file_object_id  uuid REFERENCES people.file_object(id),
  published_at    timestamptz,
  retired_at      timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (version, language_id),
  CHECK (retired_at IS NULL OR (published_at IS NOT NULL AND retired_at > published_at))
);

CREATE TABLE privacy.notice_purpose (
  notice_id   uuid     NOT NULL REFERENCES privacy.privacy_notice(id) ON DELETE CASCADE,
  purpose_id  smallint NOT NULL REFERENCES privacy.processing_purpose(id),
  PRIMARY KEY (notice_id, purpose_id)
);

-- ------------------------------------------------------------------- consent --
-- One row per consent act; withdrawal closes it. A purpose can only be
-- consented to under a notice that actually lists it (composite FK).
-- given_by_person_id = the principal, or a lawful guardian for a child.
CREATE TABLE privacy.consent (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  principal_person_id  uuid NOT NULL REFERENCES people.person(id) ON DELETE CASCADE,
  notice_id            uuid NOT NULL,
  purpose_id           smallint NOT NULL,
  given_by_person_id   uuid NOT NULL REFERENCES people.person(id),
  consent_channel_id   smallint NOT NULL REFERENCES ref.consent_channel(id),
  consent_manager_ref  text,                       -- artefact id from a registered Consent Manager
  ip                   inet,
  granted_at           timestamptz NOT NULL DEFAULT now(),
  withdrawn_at         timestamptz,
  FOREIGN KEY (notice_id, purpose_id) REFERENCES privacy.notice_purpose(notice_id, purpose_id),
  CHECK (withdrawn_at IS NULL OR withdrawn_at >= granted_at),
  CONSTRAINT consent_one_active_per_purpose EXCLUDE USING gist (
    principal_person_id WITH =, purpose_id WITH =,
    tstzrange(granted_at, withdrawn_at) WITH &&)
);
CREATE INDEX consent_principal_idx ON privacy.consent(principal_person_id);

-- consent given by someone else must come from a recorded guardian
CREATE OR REPLACE FUNCTION privacy.consent_validate_giver()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.given_by_person_id <> NEW.principal_person_id AND NOT EXISTS (
       SELECT 1 FROM people.person_relationship
       WHERE person_id = NEW.principal_person_id
         AND related_person_id = NEW.given_by_person_id
         AND is_guardian) THEN
    RAISE EXCEPTION 'consent: % is not a recorded guardian of %',
      NEW.given_by_person_id, NEW.principal_person_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_consent_validate_giver BEFORE INSERT OR UPDATE ON privacy.consent
  FOR EACH ROW EXECUTE FUNCTION privacy.consent_validate_giver();

-- §9: verifiable consent of the parent/guardian for a child (the guardian is
-- consent.given_by_person_id — not repeated here).
CREATE TABLE privacy.verifiable_parental_consent (
  consent_id              uuid PRIMARY KEY REFERENCES privacy.consent(id) ON DELETE CASCADE,
  verification_method_id  smallint NOT NULL REFERENCES ref.verification_method(id),
  verified_at             timestamptz NOT NULL DEFAULT now(),
  evidence_file_id        uuid REFERENCES people.file_object(id)
);

-- -------------------------------------------------------------------- nominee --
-- §14: a principal may nominate someone to exercise rights on death/incapacity.
CREATE TABLE privacy.nominee (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  principal_person_id  uuid NOT NULL REFERENCES people.person(id) ON DELETE CASCADE,
  nominee_person_id    uuid NOT NULL REFERENCES people.person(id),
  valid                daterange NOT NULL DEFAULT daterange(current_date, NULL),
  created_at           timestamptz NOT NULL DEFAULT now(),
  CHECK (principal_person_id <> nominee_person_id),
  CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  CONSTRAINT nominee_one_active EXCLUDE USING gist (principal_person_id WITH =, valid WITH &&)
);

-- ---------------------------------------------------- data principal requests --
-- Current status, due date and closure are DERIVED (latest event; submitted_at
-- + ref.dpr_request_type.response_days) — see privacy.v_dpr_request_status.
CREATE TABLE privacy.data_principal_request (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  person_id               uuid NOT NULL REFERENCES people.person(id) ON DELETE CASCADE,
  dpr_request_type_id     smallint NOT NULL REFERENCES ref.dpr_request_type(id),
  submitted_by_person_id  uuid NOT NULL REFERENCES people.person(id),  -- principal, guardian or nominee
  details                 text,
  submitted_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX data_principal_request_person_idx ON privacy.data_principal_request(person_id);

CREATE TABLE privacy.dpr_request_event (
  id                bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  request_id        uuid NOT NULL REFERENCES privacy.data_principal_request(id) ON DELETE CASCADE,
  dpr_status_id     smallint NOT NULL REFERENCES ref.dpr_status(id),
  actor_account_id  uuid REFERENCES iam.user_account(id),
  note              text,
  occurred_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dpr_request_event_request_idx ON privacy.dpr_request_event(request_id, occurred_at DESC);

-- ------------------------------------------------------------ data_processor --
CREATE TABLE privacy.data_processor (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name           text NOT NULL UNIQUE,
  country_id     smallint NOT NULL REFERENCES ref.country(id),  -- where data is processed
  dpa_signed_on  date,                                          -- data processing agreement
  is_active      boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);
SELECT util.attach_updated_at('privacy.data_processor');

CREATE TABLE privacy.processor_purpose (
  processor_id  uuid     NOT NULL REFERENCES privacy.data_processor(id) ON DELETE CASCADE,
  purpose_id    smallint NOT NULL REFERENCES privacy.processing_purpose(id),
  PRIMARY KEY (processor_id, purpose_id)
);

-- --------------------------------------------------------------- erasure_log --
-- Evidence of retention-driven or request-driven erasure. Persons are
-- anonymised rather than deleted, so person_id normally survives.
CREATE TABLE privacy.erasure_log (
  id                      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  person_id               uuid REFERENCES people.person(id) ON DELETE SET NULL,
  data_element_id         int  NOT NULL REFERENCES privacy.data_element(id),
  erasure_action_id       smallint NOT NULL REFERENCES ref.erasure_action(id),
  request_id              uuid REFERENCES privacy.data_principal_request(id) ON DELETE SET NULL,
  executed_by_account_id  uuid REFERENCES iam.user_account(id),
  executed_at             timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX erasure_log_person_idx ON privacy.erasure_log(person_id);

-- ------------------------------------------------------------ personal data breach --
CREATE TABLE privacy.breach_incident (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title               text NOT NULL,
  description         text NOT NULL,
  breach_severity_id  smallint NOT NULL REFERENCES ref.breach_severity(id),
  breach_status_id    smallint NOT NULL REFERENCES ref.breach_status(id),
  occurred_from       timestamptz,
  detected_at         timestamptz NOT NULL,
  board_notified_at   timestamptz,               -- intimation to the Data Protection Board
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  CHECK (occurred_from IS NULL OR occurred_from <= detected_at),
  CHECK (board_notified_at IS NULL OR board_notified_at >= detected_at)
);
SELECT util.attach_updated_at('privacy.breach_incident');

CREATE TABLE privacy.breach_affected_person (
  incident_id  uuid NOT NULL REFERENCES privacy.breach_incident(id) ON DELETE CASCADE,
  person_id    uuid NOT NULL REFERENCES people.person(id) ON DELETE CASCADE,
  PRIMARY KEY (incident_id, person_id)
);

CREATE TABLE privacy.breach_notification (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  incident_id         uuid NOT NULL,
  person_id           uuid NOT NULL,
  contact_channel_id  smallint NOT NULL REFERENCES ref.contact_channel(id),
  sent_at             timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (incident_id, person_id)
    REFERENCES privacy.breach_affected_person(incident_id, person_id) ON DELETE CASCADE
);

-- ------------------------------------------------------------ pii_access_log --
-- Who viewed/exported whose personal data, for which purpose (partitioned).
CREATE TABLE privacy.pii_access_log (
  id                   bigint GENERATED ALWAYS AS IDENTITY,
  accessed_at          timestamptz NOT NULL DEFAULT now(),
  accessor_account_id  uuid REFERENCES iam.user_account(id) ON DELETE SET NULL,
  person_id            uuid REFERENCES people.person(id) ON DELETE SET NULL,
  data_category_id     smallint NOT NULL REFERENCES ref.data_category(id),
  purpose_id           smallint NOT NULL REFERENCES privacy.processing_purpose(id),
  request_id           uuid,                          -- HTTP correlation id
  PRIMARY KEY (id, accessed_at)
) PARTITION BY RANGE (accessed_at);
CREATE INDEX pii_access_log_person_idx   ON privacy.pii_access_log(person_id, accessed_at DESC);
CREATE INDEX pii_access_log_accessor_idx ON privacy.pii_access_log(accessor_account_id, accessed_at DESC);
CREATE TABLE privacy.pii_access_log_default PARTITION OF privacy.pii_access_log DEFAULT;
SELECT util.create_monthly_partitions('privacy.pii_access_log', current_date, 13);
