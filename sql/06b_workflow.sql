-- Schemes of examination are shared between curricula: a scheme used by an
-- APPROVED / SIGNED curriculum is frozen (a new regulation = a new scheme).
-- Same for a course's credits and L-T-P hours once a signed curriculum uses it.
CREATE OR REPLACE FUNCTION academic.guard_scheme_edit()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_row jsonb := to_jsonb(CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END); v_scheme int;
BEGIN
  IF TG_TABLE_NAME = 'evaluation_scheme' AND TG_OP = 'UPDATE'
     AND (to_jsonb(NEW) - 'is_active' - 'updated_at') = (to_jsonb(OLD) - 'is_active' - 'updated_at') THEN
    RETURN NEW;
  END IF;
  v_scheme := CASE WHEN TG_TABLE_NAME = 'evaluation_scheme' THEN (v_row ->> 'id')::int
                   ELSE (v_row ->> 'evaluation_scheme_id')::int END;
  IF EXISTS (SELECT 1 FROM academic.v_curriculum_item ci
             JOIN academic.v_curriculum_status cs ON cs.curriculum_id = ci.curriculum_id AND cs.status IN ('APPROVED', 'SIGNED')
             WHERE ci.evaluation_scheme_id = v_scheme) THEN
    RAISE EXCEPTION '%.%: this scheme of examination is part of an approved curriculum version and frozen — create a new scheme',
      TG_TABLE_SCHEMA, TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER trg_evaluation_scheme_freeze BEFORE UPDATE OR DELETE ON academic.evaluation_scheme
  FOR EACH ROW EXECUTE FUNCTION academic.guard_scheme_edit();
CREATE TRIGGER trg_evaluation_component_freeze BEFORE INSERT OR UPDATE OR DELETE ON academic.evaluation_component
  FOR EACH ROW EXECUTE FUNCTION academic.guard_scheme_edit();
CREATE TRIGGER trg_evaluation_component_group_freeze BEFORE INSERT OR UPDATE OR DELETE ON academic.evaluation_component_group
  FOR EACH ROW EXECUTE FUNCTION academic.guard_scheme_edit();
CREATE TRIGGER trg_evaluation_part_rule_freeze BEFORE INSERT OR UPDATE OR DELETE ON academic.evaluation_part_rule
  FOR EACH ROW EXECUTE FUNCTION academic.guard_scheme_edit();

CREATE OR REPLACE FUNCTION academic.guard_course_edit()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_course uuid;
BEGIN
  IF TG_TABLE_NAME = 'course' THEN
    IF NEW.credits = OLD.credits THEN RETURN NEW; END IF;
    v_course := NEW.id;
  ELSE
    v_course := CASE WHEN TG_OP = 'DELETE' THEN OLD.course_id ELSE NEW.course_id END;
  END IF;
  IF EXISTS (SELECT 1 FROM academic.v_curriculum_item ci
             JOIN academic.v_curriculum_status cs ON cs.curriculum_id = ci.curriculum_id AND cs.status IN ('APPROVED', 'SIGNED')
             WHERE ci.course_id = v_course) THEN
    RAISE EXCEPTION '%.%: the course is part of an approved curriculum version — its credits and L-T-P are frozen',
      TG_TABLE_SCHEMA, TG_TABLE_NAME USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;
CREATE TRIGGER trg_course_credits_freeze BEFORE UPDATE OF credits ON academic.course
  FOR EACH ROW EXECUTE FUNCTION academic.guard_course_edit();
CREATE TRIGGER trg_course_component_hours_freeze BEFORE INSERT OR UPDATE OR DELETE ON academic.course_component_hours
  FOR EACH ROW EXECUTE FUNCTION academic.guard_course_edit();

-- ################################## user 2: INTERNAL-MARKS REVISION ##
-- Where the curriculum allows it (curriculum.allows_internal_marks_revision),
-- a PUBLISHED internal mark (continuous assessment, not a scheduled paper) can
-- be revised through the INTERNAL_MARKS_REVISION chain (e.g. the Faculty
-- Moderation Committee at school level). The original mark is never touched;
-- once the round completes, the revised mark is what exam.v_component_score
-- uses, and a revised result publication follows (as for revaluation).
CREATE TABLE exam.internal_mark_revision (
  id                        uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  component_mark_id         uuid NOT NULL REFERENCES exam.component_mark(id),
  revised_marks             numeric(6,2) NOT NULL CHECK (revised_marks >= 0),
  reason                    text NOT NULL CHECK (btrim(reason) <> ''),
  requested_by_employee_id  uuid NOT NULL REFERENCES people.employee(id),
  instance_id               uuid NOT NULL UNIQUE REFERENCES wf.approval_instance(id),
  created_at                timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX internal_mark_revision_mark_idx ON exam.internal_mark_revision(component_mark_id);

CREATE OR REPLACE FUNCTION exam.internal_mark_revision_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v record;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    RAISE EXCEPTION 'internal_mark_revision: a revision request is never edited; raise a new one' USING ERRCODE = 'insufficient_privilege';
  END IF;
  SELECT c.allows_internal_marks_revision AS allowed, ep.code AS part, at.is_scheduled_exam AS scheduled, ec.max_marks,
         o.offering_org_unit_id, cm.course_registration_id, cm.exam_registration_id
    INTO v
  FROM exam.component_mark cm
  JOIN academic.evaluation_component ec ON ec.id = cm.evaluation_component_id
  JOIN ref.assessment_type at           ON at.id = ec.assessment_type_id
  JOIN ref.evaluation_part ep           ON ep.id = at.evaluation_part_id
  JOIN academic.course_registration r   ON r.id = cm.course_registration_id
  JOIN academic.course_offering o       ON o.id = r.course_offering_id
  JOIN academic.student_enrollment e    ON e.id = r.student_enrollment_id
  JOIN academic.batch_curriculum bc     ON bc.batch_id = e.batch_id
  JOIN academic.curriculum c            ON c.id = bc.curriculum_id
  WHERE cm.id = NEW.component_mark_id;
  IF NOT v.allowed THEN
    RAISE EXCEPTION 'internal_mark_revision: the student''s curriculum does not allow internal-marks revision' USING ERRCODE = 'check_violation';
  END IF;
  IF v.part <> 'INTERNAL' OR v.scheduled THEN
    RAISE EXCEPTION 'internal_mark_revision: only continuous internal marks can be revised this way' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.revised_marks > v.max_marks THEN
    RAISE EXCEPTION 'internal_mark_revision: % exceeds the maximum of %', NEW.revised_marks, v.max_marks USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM exam.exam_registration er JOIN exam.course_result cr ON cr.exam_registration_id = er.id
                 WHERE er.course_registration_id = v.course_registration_id
                   AND (v.exam_registration_id IS NULL OR er.id = v.exam_registration_id)) THEN
    RAISE EXCEPTION 'internal_mark_revision: no result is published on this mark yet — correct the mark directly' USING ERRCODE = 'check_violation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'INTERNAL_MARKS_REVISION'
                 WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = v.offering_org_unit_id) THEN
    RAISE EXCEPTION 'internal_mark_revision: the round is not an INTERNAL_MARKS_REVISION round of the offering''s department'
      USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM exam.internal_mark_revision imr JOIN wf.v_instance_state s ON s.instance_id = imr.instance_id
             WHERE imr.component_mark_id = NEW.component_mark_id AND s.current_seq IS NOT NULL) THEN
    RAISE EXCEPTION 'internal_mark_revision: a revision of this mark is already under review' USING ERRCODE = 'unique_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_internal_mark_revision_validate BEFORE INSERT OR UPDATE OR DELETE ON exam.internal_mark_revision
  FOR EACH ROW EXECUTE FUNCTION exam.internal_mark_revision_validate();
