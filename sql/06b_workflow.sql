-- =============================================================================
-- 06b_workflow.sql — Generic, permission-based approval workflow (schema: wf)
--                    + its first two users: curriculum (SOE) approval and
--                    internal-marks revision
--
-- THE approval engine of the intranet: every approval of every module is
-- CONFIGURATION here (a document type, a chain, its levels) — no module builds
-- its own approval, status or reviewer tables.
--
-- A document (a curriculum version, a marks revision, a leave, a room
-- booking, a trip, an event proposal, a noting, an IPR filing …) is sent
-- through a CHAIN of STAGES (levels). What is configurable per level: who
-- approves (a permission at an org level, a position holder, the requester's
-- manager, named people, a committee with a quorum), how many must approve,
-- when the level applies (amount band, flags), what happens when the
-- requester is the approver, what must be supplied (note, file, signature,
-- checklist), whether it can be forwarded or sent back, and its deadline with
-- reminder / escalation / automatic decision. Standing delegations cover
-- absence; consultations ask outsiders without blocking; an outbox carries the
-- notices. The classic stage is a PERMISSION required at an ORG-UNIT LEVEL
-- relative to the document's owning unit — e.g.
--   1. DEPARTMENT  academics.curriculum_department_review.approve
--   2. SCHOOL      academics.curriculum_school_review.approve
--   3. UNIVERSITY  academics.curriculum_university_review.approve
--   4. (signature) academics.curriculum.sign
-- Whoever holds that permission at that unit — through an appointment (HOD,
-- Dean …), a designation, or a dated scoped grant (acting HOD, leave cover) —
-- may act. Nothing here names a role.
--
--   document_type ─< chain (optionally scoped to a subtree, dated) ─< chain_stage
--   instance  = one approval round of one document; steps are SNAPSHOTTED
--               (instance_step) at submission with the anchor unit resolved
--   action    = APPROVE / SIGN / RETURN / RETURN_TO / REJECT / WITHDRAW /
--               FORWARD / DELEGATE and the system actions AUTO_APPROVE /
--               AUTO_REJECT / ESCALATE — append-only; the status of a round
--               (IN_PROGRESS / APPROVED / SIGNED / RETURNED / REJECTED /
--               WITHDRAWN) is derived (wf.v_instance_state [09]), never stored
--   comment   = reviewer remark, optionally on a table / row / column with a
--               suggested value; resolved (accepted / rejected) by the submitter
--
-- A RETURN, REJECT or WITHDRAW closes the round; resubmission opens a new
-- instance (revises_instance_id), so the full history is every instance of the
-- document.
--
-- TO PUT A NEW KIND OF APPROVAL ON THE ENGINE (no engine change):
--   1. INSERT wf.approval_document_type (module, author permission, link table)
--   2. INSERT wf.approval_chain (default; more rows = overrides per org subtree)
--      + wf.approval_chain_stage rows (+ checklist rows, ref.wf_flag rows)
--   3. give the document an instance_id column (or a link table for several
--      rounds) with the standard validate trigger (see academic.attendance_leave)
--   4. submit with wf.submit(), act with wf.act(); read wf.v_instance_state
--   5. optional: an AFTER INSERT trigger on wf.approval_action for side effects
-- Functions (09): wf.submit(), wf.act(), wf.can_act(), wf.can_view(),
-- wf.is_eligible(), wf.pending_for(), wf.run_timeouts(), wf.document_of(),
-- academic.submit_curriculum(), academic.is_program_coordinator().
-- =============================================================================

SET client_encoding = 'UTF8';   -- files are UTF-8; psql on Windows may default to WIN1252

SET search_path = wf, authz, org, people, iam, academic, exam, ref, public;

-- ------------------------------------------------------------- catalogue --
-- A kind of document that goes through approval. link_table / link_document_
-- column say where the document of a round lives (a table with an instance_id
-- column, and the column holding the document's id) so one inbox can point at
-- any module's document (wf.document_of()).
CREATE TABLE wf.approval_document_type (
  id                    smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code                  citext NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]{1,60}$'),
  label                 text NOT NULL,
  app_module_id         smallint NOT NULL REFERENCES authz.app_module(id),
  author_permission_id  int NOT NULL REFERENCES authz.permission(id),   -- who may submit (at the owning unit)
  viewer_permission_id  int REFERENCES authz.permission(id),            -- who may see rounds in flight at the owning unit (besides the people involved)
  allows_empty_chain    boolean NOT NULL DEFAULT false,                 -- no stage applies → approved on submission (auto-approval by configuration)
  link_table            text CHECK (link_table ~ '^[a-z_]+\.[a-z_0-9]+$'),
  link_document_column  text CHECK (link_document_column ~ '^[a-z_0-9]+$'),
  is_active             boolean NOT NULL DEFAULT true,
  CHECK ((link_table IS NULL) = (link_document_column IS NULL))
);

-- The approval chain of a document type. scope_org_unit_id NULL = the default
-- chain; a scoped chain overrides it for that subtree (e.g. medical programmes
-- add a council-liaison stage; one block adds the Registrar). One chain per
-- type × scope at a time.
CREATE TABLE wf.approval_chain (
  id                 int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_type_id   smallint NOT NULL REFERENCES wf.approval_document_type(id),
  scope_org_unit_id  uuid REFERENCES org.org_unit(id),
  valid              daterange NOT NULL DEFAULT daterange(current_date, NULL),
  note               text,
  -- A higher level may approve out of turn; the pending lower levels are then
  -- passed over (a Dean's approval makes the HOD's unnecessary) — but never so
  -- that fewer than min_approved_levels levels were approved by people. A
  -- chain that must take every level in order switches the first off; a single
  -- level that must always decide itself is approval_chain_stage.is_mandatory.
  allows_level_override  boolean NOT NULL DEFAULT true,
  min_approved_levels    smallint NOT NULL DEFAULT 2 CHECK (min_approved_levels >= 1),
  created_at         timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT isempty(valid) AND NOT lower_inf(valid)),
  UNIQUE (id, document_type_id),            -- so that a round can be tied to the chain AND its document type together
  CONSTRAINT chain_one_per_scope EXCLUDE USING gist (
    document_type_id WITH =,
    (COALESCE(scope_org_unit_id, '00000000-0000-0000-0000-000000000000'::uuid)) WITH =,
    valid WITH &&)
);

-- One level of a chain — everything about it is configuration:
--   WHO      wf_approver_kind: PERMISSION (held at the anchor unit), POSITION
--            (the holder at the anchor unit), MANAGER (reporting / reviewing
--            manager of the round's subject person, N levels up), NAMED (a
--            fixed account, or chosen at submission / by forwarding),
--            COMMITTEE (current members of an academic body; quorum)
--   WHERE    anchor: a unit type above the owner, the owner itself, or the
--            university (root) — for PERMISSION / POSITION
--   HOW MANY required_approvals: 1 = any one, N, NULL = every assignee (the
--            committee's quorum for COMMITTEE; 1 for the pool kinds)
--   WHEN     min_amount / max_amount on the round's amount; a flag present
--            (or absent) on the round
--   SELF     the submitter is the approver: BLOCK (someone else must act) or
--            SKIP (the level is left out)
--   WHAT     a file, a signature (always the last level), ticked checklist
--   MOVES    may the approver forward it to someone else / send it back to an
--            earlier level
--   CLOCK    due_within + what happens then: NONE / REMIND / ESCALATE (one
--            org level up, or the next manager) / AUTO_APPROVE / AUTO_REJECT
--   ORDER    is_mandatory: this level always decides itself — a higher level
--            approving out of turn (approval_chain.allows_level_override)
--            cannot pass it over
CREATE TABLE wf.approval_chain_stage (
  chain_id                 int NOT NULL REFERENCES wf.approval_chain(id) ON DELETE CASCADE,
  seq                      smallint NOT NULL CHECK (seq >= 1),
  code                     citext NOT NULL,
  label                    text NOT NULL,
  wf_approver_kind_id      smallint NOT NULL REFERENCES ref.wf_approver_kind(id),     -- default PERMISSION (trigger)
  permission_id            int REFERENCES authz.permission(id),                        -- PERMISSION: required; other kinds: an extra requirement
  anchor_org_unit_type_id  smallint REFERENCES ref.org_unit_type(id),
  anchor_is_owner          boolean NOT NULL DEFAULT false,   -- held at the owning unit itself (its head), whatever its type
  position_type_id         smallint REFERENCES org.position_type(id),
  reporting_line_type_id   smallint REFERENCES ref.reporting_line_type(id),
  manager_level            smallint CHECK (manager_level BETWEEN 1 AND 5),
  academic_body_id         uuid REFERENCES academic.academic_body(id),
  named_account_id         uuid REFERENCES iam.user_account(id),
  required_approvals       smallint CHECK (required_approvals >= 1),
  min_amount               numeric(14,2) CHECK (min_amount >= 0),
  max_amount               numeric(14,2),
  wf_flag_id               smallint REFERENCES ref.wf_flag(id),
  flag_must_be_absent      boolean NOT NULL DEFAULT false,
  wf_self_action_id        smallint NOT NULL REFERENCES ref.wf_self_action(id),      -- default BLOCK (trigger)
  needs_file               boolean NOT NULL DEFAULT false,
  allows_forward           boolean NOT NULL DEFAULT false,
  allows_return_to         boolean NOT NULL DEFAULT false,
  due_within               interval CHECK (due_within > interval '0'),
  wf_timeout_action_id     smallint NOT NULL REFERENCES ref.wf_timeout_action(id),   -- default NONE (trigger)
  is_signature             boolean NOT NULL DEFAULT false,
  is_mandatory             boolean NOT NULL DEFAULT false,   -- never passed over by a higher level
  PRIMARY KEY (chain_id, seq),
  UNIQUE (chain_id, code),
  CHECK (NOT (anchor_is_owner AND anchor_org_unit_type_id IS NOT NULL)),
  CHECK (max_amount IS NULL OR max_amount > COALESCE(min_amount, 0)),
  CHECK (NOT flag_must_be_absent OR wf_flag_id IS NOT NULL)
);

CREATE OR REPLACE FUNCTION wf.chain_stage_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_kind text; v_timeout text;
BEGIN
  NEW.wf_approver_kind_id  := COALESCE(NEW.wf_approver_kind_id, ref.id_of('wf_approver_kind', 'PERMISSION'));
  NEW.wf_self_action_id    := COALESCE(NEW.wf_self_action_id, ref.id_of('wf_self_action', 'BLOCK'));
  NEW.wf_timeout_action_id := COALESCE(NEW.wf_timeout_action_id, ref.id_of('wf_timeout_action', 'NONE'));
  SELECT code INTO v_kind FROM ref.wf_approver_kind WHERE id = NEW.wf_approver_kind_id;
  SELECT code INTO v_timeout FROM ref.wf_timeout_action WHERE id = NEW.wf_timeout_action_id;
  IF v_kind = 'PERMISSION' AND NEW.permission_id IS NULL THEN
    RAISE EXCEPTION 'chain_stage %: a PERMISSION stage needs the permission', NEW.code USING ERRCODE = 'check_violation';
  ELSIF v_kind = 'POSITION' AND NEW.position_type_id IS NULL THEN
    RAISE EXCEPTION 'chain_stage %: a POSITION stage needs the position type', NEW.code USING ERRCODE = 'check_violation';
  ELSIF v_kind = 'MANAGER' THEN
    NEW.reporting_line_type_id := COALESCE(NEW.reporting_line_type_id, ref.id_of('reporting_line_type', 'REPORTING'));
    NEW.manager_level := COALESCE(NEW.manager_level, 1);
  ELSIF v_kind = 'COMMITTEE' AND NEW.academic_body_id IS NULL THEN
    RAISE EXCEPTION 'chain_stage %: a COMMITTEE stage needs the body', NEW.code USING ERRCODE = 'check_violation';
  END IF;
  IF (v_kind <> 'POSITION' AND NEW.position_type_id IS NOT NULL) OR (v_kind <> 'MANAGER' AND (NEW.reporting_line_type_id IS NOT NULL OR NEW.manager_level IS NOT NULL))
     OR (v_kind <> 'COMMITTEE' AND NEW.academic_body_id IS NOT NULL) OR (v_kind <> 'NAMED' AND NEW.named_account_id IS NOT NULL) THEN
    RAISE EXCEPTION 'chain_stage %: approver settings that do not belong to a % stage', NEW.code, v_kind USING ERRCODE = 'check_violation';
  END IF;
  IF v_timeout <> 'NONE' AND NEW.due_within IS NULL THEN
    RAISE EXCEPTION 'chain_stage %: a timeout action needs due_within', NEW.code USING ERRCODE = 'check_violation';
  END IF;
  IF v_timeout = 'ESCALATE' AND v_kind NOT IN ('PERMISSION', 'POSITION', 'MANAGER') THEN
    RAISE EXCEPTION 'chain_stage %: only PERMISSION / POSITION / MANAGER stages can escalate', NEW.code USING ERRCODE = 'check_violation';
  END IF;
  IF EXISTS (SELECT 1 FROM wf.approval_chain_stage s WHERE s.chain_id = NEW.chain_id AND s.seq <> NEW.seq
               AND ((s.is_signature AND s.seq < NEW.seq) OR (NEW.is_signature AND s.seq > NEW.seq))) THEN
    RAISE EXCEPTION 'chain_stage: the signature stage must be the last stage of the chain' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_chain_stage_validate BEFORE INSERT OR UPDATE ON wf.approval_chain_stage
  FOR EACH ROW EXECUTE FUNCTION wf.chain_stage_validate();

-- What the approver of a level must confirm before approving ("budget head
-- available", "documents verified"). Mandatory items must be ticked
-- (wf.approval_step_check) by whoever approves.
CREATE TABLE wf.approval_chain_stage_check (
  chain_id      int NOT NULL,
  seq           smallint NOT NULL,
  check_no      smallint NOT NULL CHECK (check_no >= 1),
  label         text NOT NULL CHECK (btrim(label) <> ''),
  is_mandatory  boolean NOT NULL DEFAULT true,
  PRIMARY KEY (chain_id, seq, check_no),
  FOREIGN KEY (chain_id, seq) REFERENCES wf.approval_chain_stage(chain_id, seq) ON DELETE CASCADE
);

-- ------------------------------------------------------------- instances --
-- One approval round. Created only through wf.submit(), which checks the
-- author's permission, picks the chain, keeps the levels that apply (amount,
-- flags, self-skip) and snapshots them. amount and flags are what the
-- conditions are evaluated on; subject_person is whose managers approve
-- (default: the submitter); revises = the earlier round of the same document
-- this one replaces (re-approval after a change).
CREATE TABLE wf.approval_instance (
  id                       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  document_type_id         smallint NOT NULL REFERENCES wf.approval_document_type(id),
  chain_id                 int NOT NULL REFERENCES wf.approval_chain(id),
  owner_org_unit_id        uuid NOT NULL REFERENCES org.org_unit(id),
  submitted_by_account_id  uuid NOT NULL REFERENCES iam.user_account(id),
  submitted_at             timestamptz NOT NULL DEFAULT clock_timestamp(),
  note                     text,
  amount                   numeric(14,2) CHECK (amount >= 0),
  subject_person_id        uuid REFERENCES people.person(id),
  revises_instance_id      uuid REFERENCES wf.approval_instance(id),
  allows_level_override    boolean NOT NULL DEFAULT false,   -- the chain's settings as they were at submission
  min_approved_levels      smallint NOT NULL DEFAULT 2 CHECK (min_approved_levels >= 1),
  -- document_type_id repeats what the chain says (kept for the many reads by type); this key makes the two unable to disagree
  FOREIGN KEY (chain_id, document_type_id) REFERENCES wf.approval_chain(id, document_type_id)
);
CREATE INDEX instance_owner_idx ON wf.approval_instance(owner_org_unit_id);
CREATE INDEX instance_submitter_idx ON wf.approval_instance(submitted_by_account_id);

CREATE TABLE wf.approval_instance_flag (
  instance_id  uuid NOT NULL REFERENCES wf.approval_instance(id),
  wf_flag_id   smallint NOT NULL REFERENCES ref.wf_flag(id),
  PRIMARY KEY (instance_id, wf_flag_id)
);

-- The levels of one round as they were at submission, with the anchor unit
-- resolved. Later changes to the chain do not affect rounds already in
-- flight. seq is the configured stage's seq (levels that did not apply leave
-- gaps), so a step's checklist is the stage's.
CREATE TABLE wf.approval_step (
  instance_id           uuid NOT NULL REFERENCES wf.approval_instance(id) ON DELETE CASCADE,
  seq                   smallint NOT NULL,
  code                  citext NOT NULL,
  wf_approver_kind_id   smallint NOT NULL REFERENCES ref.wf_approver_kind(id),
  permission_id         int REFERENCES authz.permission(id),
  anchor_org_unit_id    uuid NOT NULL REFERENCES org.org_unit(id),
  position_type_id      smallint REFERENCES org.position_type(id),
  required_approvals    smallint CHECK (required_approvals >= 1),     -- NULL = every (unreleased) assignee
  needs_file            boolean NOT NULL DEFAULT false,
  allows_forward        boolean NOT NULL DEFAULT false,
  allows_return_to      boolean NOT NULL DEFAULT false,
  due_within            interval,
  wf_timeout_action_id  smallint NOT NULL REFERENCES ref.wf_timeout_action(id),
  is_signature          boolean NOT NULL,
  is_mandatory          boolean NOT NULL DEFAULT false,
  PRIMARY KEY (instance_id, seq)
);

-- What happened, append-only. step_seq is the step acted on (NULL for
-- WITHDRAW). target_account = whom it was forwarded / delegated / escalated
-- to; target_org_unit = the unit an escalation moved the step up to;
-- return_to_seq = the earlier level a RETURN_TO sends the round back to;
-- on_behalf_of = the absent approver a delegate acted for.
CREATE TABLE wf.approval_action (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id               uuid NOT NULL REFERENCES wf.approval_instance(id),
  step_seq                  smallint,
  wf_action_type_id         smallint NOT NULL REFERENCES ref.wf_action_type(id),
  actor_account_id          uuid REFERENCES iam.user_account(id),      -- NULL only for a system action (a scheduled job)
  acted_at                  timestamptz NOT NULL DEFAULT clock_timestamp(),
  note                      text,
  file_object_id            uuid REFERENCES people.file_object(id),   -- the signed document / supporting file
  target_account_id         uuid REFERENCES iam.user_account(id),
  target_org_unit_id        uuid REFERENCES org.org_unit(id),
  return_to_seq             smallint,
  on_behalf_of_account_id   uuid REFERENCES iam.user_account(id),
  FOREIGN KEY (instance_id, step_seq) REFERENCES wf.approval_step(instance_id, seq),
  FOREIGN KEY (instance_id, return_to_seq) REFERENCES wf.approval_step(instance_id, seq),
  CHECK (on_behalf_of_account_id IS NULL OR on_behalf_of_account_id <> actor_account_id)
);
CREATE INDEX action_instance_idx ON wf.approval_action(instance_id);
CREATE INDEX action_actor_idx ON wf.approval_action(actor_account_id);

-- The named approvers of a step: resolved at submission (MANAGER, NAMED,
-- COMMITTEE) or added later by FORWARD / DELEGATE / ESCALATE. A step that has
-- assignees is decided by them alone (a forwarded pool step is closed to the
-- pool). released_by = the action with which this person handed it on.
CREATE TABLE wf.approval_step_assignee (
  instance_id            uuid NOT NULL,
  seq                    smallint NOT NULL,
  account_id             uuid NOT NULL REFERENCES iam.user_account(id),
  added_by_action_id     bigint REFERENCES wf.approval_action(id),
  released_by_action_id  bigint REFERENCES wf.approval_action(id),
  PRIMARY KEY (instance_id, seq, account_id),
  FOREIGN KEY (instance_id, seq) REFERENCES wf.approval_step(instance_id, seq) ON DELETE CASCADE
);
CREATE INDEX step_assignee_account_idx ON wf.approval_step_assignee(account_id);

-- Checklist items ticked by an approver on a step (before approving).
CREATE TABLE wf.approval_step_check (
  instance_id          uuid NOT NULL,
  seq                  smallint NOT NULL,
  check_no             smallint NOT NULL,
  checked_by_account_id uuid NOT NULL REFERENCES iam.user_account(id),
  checked_at           timestamptz NOT NULL DEFAULT clock_timestamp(),
  PRIMARY KEY (instance_id, seq, check_no, checked_by_account_id),
  FOREIGN KEY (instance_id, seq) REFERENCES wf.approval_step(instance_id, seq) ON DELETE CASCADE
);

-- Standing delegation (out of office, leave cover): for a period, the
-- delegate may act wherever the delegator could — for one document type or
-- for all. The action records both (actor + on_behalf_of). Always bounded.
CREATE TABLE wf.approval_delegation (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  delegator_account_id   uuid NOT NULL REFERENCES iam.user_account(id),
  delegate_account_id    uuid NOT NULL REFERENCES iam.user_account(id),
  document_type_id       smallint REFERENCES wf.approval_document_type(id),   -- NULL = every document type
  valid                  tstzrange NOT NULL,
  reason                 text,
  created_at             timestamptz NOT NULL DEFAULT now(),
  CHECK (delegator_account_id <> delegate_account_id),
  CHECK (NOT isempty(valid) AND NOT lower_inf(valid) AND NOT upper_inf(valid)),
  CONSTRAINT approval_delegation_one EXCLUDE USING gist (
    delegator_account_id WITH =, (COALESCE(document_type_id, 0)) WITH =, valid WITH &&)
);
CREATE INDEX approval_delegation_delegate_idx ON wf.approval_delegation(delegate_account_id);

-- A question to someone outside the chain ("copy to accounts for comments"),
-- with their reply. Never blocks the round.
CREATE TABLE wf.approval_consultation (
  id                    uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  instance_id           uuid NOT NULL REFERENCES wf.approval_instance(id),
  asked_by_account_id   uuid NOT NULL REFERENCES iam.user_account(id),
  asked_account_id      uuid NOT NULL REFERENCES iam.user_account(id),
  question              text NOT NULL CHECK (btrim(question) <> ''),
  asked_at              timestamptz NOT NULL DEFAULT clock_timestamp(),
  reply                 text,
  replied_at            timestamptz,
  reply_file_object_id  uuid REFERENCES people.file_object(id),
  CHECK (asked_by_account_id <> asked_account_id),
  CHECK ((reply IS NULL) = (replied_at IS NULL))
);
CREATE INDEX approval_consultation_instance_idx ON wf.approval_consultation(instance_id);
CREATE INDEX approval_consultation_asked_idx ON wf.approval_consultation(asked_account_id);

-- Outbox of what the application must tell people (a level is waiting, a
-- reminder, returned / rejected / approved, forwarded to you, a question for
-- you). account NULL = everyone who can act on the step (a pool). One of a
-- kind per step, account and day.
CREATE TABLE wf.approval_notice (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  instance_id        uuid NOT NULL REFERENCES wf.approval_instance(id),
  step_seq           smallint,
  wf_notice_kind_id  smallint NOT NULL REFERENCES ref.wf_notice_kind(id),
  account_id         uuid REFERENCES iam.user_account(id),
  notice_date        date NOT NULL DEFAULT current_date,
  created_at         timestamptz NOT NULL DEFAULT now(),
  dispatched_at      timestamptz
);
CREATE UNIQUE INDEX approval_notice_once ON wf.approval_notice
  (instance_id, COALESCE(step_seq, 0), wf_notice_kind_id, COALESCE(account_id, '00000000-0000-0000-0000-000000000000'::uuid), notice_date);

-- Instances, their steps and actions are a record: never edited or deleted.
CREATE OR REPLACE FUNCTION wf.append_only()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'wf.%: workflow records are append-only (% refused)', TG_TABLE_NAME, TG_OP
    USING ERRCODE = 'insufficient_privilege';
END $$;
CREATE TRIGGER trg_instance_append_only BEFORE UPDATE OR DELETE ON wf.approval_instance
  FOR EACH ROW EXECUTE FUNCTION wf.append_only();
CREATE TRIGGER trg_instance_step_append_only BEFORE UPDATE OR DELETE ON wf.approval_step
  FOR EACH ROW EXECUTE FUNCTION wf.append_only();
CREATE TRIGGER trg_action_append_only BEFORE UPDATE OR DELETE ON wf.approval_action
  FOR EACH ROW EXECUTE FUNCTION wf.append_only();
CREATE TRIGGER trg_instance_flag_append_only BEFORE UPDATE OR DELETE ON wf.approval_instance_flag
  FOR EACH ROW EXECUTE FUNCTION wf.append_only();
CREATE TRIGGER trg_step_check_append_only BEFORE UPDATE ON wf.approval_step_check
  FOR EACH ROW EXECUTE FUNCTION wf.append_only();

-- Steps are written once, at submission, before anyone acts.
CREATE OR REPLACE FUNCTION wf.instance_step_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.wf_approver_kind_id  := COALESCE(NEW.wf_approver_kind_id, ref.id_of('wf_approver_kind', 'PERMISSION'));
  NEW.wf_timeout_action_id := COALESCE(NEW.wf_timeout_action_id, ref.id_of('wf_timeout_action', 'NONE'));
  IF EXISTS (SELECT 1 FROM wf.approval_action WHERE instance_id = NEW.instance_id) THEN
    RAISE EXCEPTION 'wf.approval_step: steps cannot be added once the round has started' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_instance_step_validate BEFORE INSERT ON wf.approval_step
  FOR EACH ROW EXECUTE FUNCTION wf.instance_step_validate();

-- An assignee is never edited except to be released (by the FORWARD /
-- DELEGATE / ESCALATE that hands the step on).
CREATE OR REPLACE FUNCTION wf.step_assignee_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' OR NEW.instance_id <> OLD.instance_id OR NEW.seq <> OLD.seq OR NEW.account_id <> OLD.account_id
     OR NEW.added_by_action_id IS DISTINCT FROM OLD.added_by_action_id OR OLD.released_by_action_id IS NOT NULL THEN
    RAISE EXCEPTION 'wf.approval_step_assignee: an assignee is only ever released' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_step_assignee_validate BEFORE UPDATE OR DELETE ON wf.approval_step_assignee
  FOR EACH ROW EXECUTE FUNCTION wf.step_assignee_validate();

-- A checklist item is ticked by someone who can act on the round's current step.
CREATE OR REPLACE FUNCTION wf.step_check_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i JOIN wf.approval_chain_stage_check c ON c.chain_id = i.chain_id
                 WHERE i.id = NEW.instance_id AND c.seq = NEW.seq AND c.check_no = NEW.check_no) THEN
    RAISE EXCEPTION 'wf.approval_step_check: the stage has no such checklist item' USING ERRCODE = 'foreign_key_violation';
  END IF;
  IF NOT ((NEW.seq IS NOT DISTINCT FROM (SELECT current_seq FROM wf.v_instance_state WHERE instance_id = NEW.instance_id)
           AND wf.can_act(NEW.checked_by_account_id, NEW.instance_id))
          OR NEW.seq IS NOT DISTINCT FROM wf.override_step(NEW.checked_by_account_id, NEW.instance_id)) THEN
    RAISE EXCEPTION 'wf.approval_step_check: only an approver of the current step (or of a higher level deciding out of turn) ticks its checklist' USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_step_check_validate BEFORE INSERT ON wf.approval_step_check
  FOR EACH ROW EXECUTE FUNCTION wf.step_check_validate();

-- A consultation is asked by the submitter or someone who can act on the
-- round, of anyone else; only the person asked replies, once.
CREATE OR REPLACE FUNCTION wf.consultation_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.reply IS NOT NULL THEN
      RAISE EXCEPTION 'wf.approval_consultation: a question starts unanswered' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM wf.approval_instance WHERE id = NEW.instance_id AND submitted_by_account_id = NEW.asked_by_account_id)
       AND NOT wf.can_act(NEW.asked_by_account_id, NEW.instance_id) THEN
      RAISE EXCEPTION 'wf.approval_consultation: only the submitter or a current approver may consult' USING ERRCODE = 'insufficient_privilege';
    END IF;
  ELSE
    IF OLD.reply IS NOT NULL OR NEW.instance_id <> OLD.instance_id OR NEW.asked_by_account_id <> OLD.asked_by_account_id
       OR NEW.asked_account_id <> OLD.asked_account_id OR NEW.question <> OLD.question OR NEW.asked_at <> OLD.asked_at THEN
      RAISE EXCEPTION 'wf.approval_consultation: only the reply may be added, once' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF current_setting('app.account_id', true) IS DISTINCT FROM NEW.asked_account_id::text THEN
      RAISE EXCEPTION 'wf.approval_consultation: only the person asked replies' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_consultation_validate BEFORE INSERT OR UPDATE ON wf.approval_consultation
  FOR EACH ROW EXECUTE FUNCTION wf.consultation_validate();

-- The rules of acting (state comes from wf.v_instance_state [09]):
--   * only an open round, only its current step (WITHDRAW: submitter only);
--   * a system action (AUTO_APPROVE, AUTO_REJECT, ESCALATE, SKIP) has no actor
--     and is written only under app.system_job;
--   * the actor — or the absent approver a delegate acts for — must be
--     eligible for the step (wf.is_eligible): hold its permission / position
--     at its unit, or be one of its assignees;
--   * APPROVE on a review step, SIGN (with the signed file) on the signature
--     step; a step that needs a file gets one; mandatory checklist items are
--     ticked; RETURN / REJECT / RETURN_TO need a note;
--   * RETURN_TO only where the step allows it, to an earlier step of the round;
--   * FORWARD / DELEGATE only where the step allows forwarding, to someone
--     who is not the submitter and holds the step's permission (if it has one);
--   * separation of duties: never the submitter, one step per person, one
--     approval per person on a step.
CREATE OR REPLACE FUNCTION wf.action_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_type record; v_state record; v_step record; v_perm text; v_principal uuid; v_doc smallint; v_chain int; v_refusal text;
BEGIN
  SELECT * INTO v_type FROM ref.wf_action_type WHERE id = NEW.wf_action_type_id;
  SELECT * INTO v_state FROM wf.v_instance_state WHERE instance_id = NEW.instance_id;
  IF v_state.current_seq IS NULL THEN
    RAISE EXCEPTION 'wf.approval_action: this round is closed (%)', v_state.status USING ERRCODE = 'check_violation';
  END IF;
  IF v_type.needs_note AND COALESCE(btrim(NEW.note), '') = '' THEN
    RAISE EXCEPTION 'wf.approval_action: % needs a note', v_type.code USING ERRCODE = 'check_violation';
  END IF;

  IF v_type.is_system THEN
    IF NEW.actor_account_id IS NOT NULL THEN
      RAISE EXCEPTION 'wf.approval_action: a system action has no actor' USING ERRCODE = 'check_violation';
    END IF;
    IF current_setting('app.system_job', true) IS DISTINCT FROM 'on' THEN
      RAISE EXCEPTION 'wf.approval_action: % may only be taken by a system job', v_type.code USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF NEW.step_seq IS DISTINCT FROM v_state.current_seq THEN
      RAISE EXCEPTION 'wf.approval_action: step % is not the current step (%)', NEW.step_seq, v_state.current_seq
        USING ERRCODE = 'check_violation';
    END IF;
    IF v_type.code = 'ESCALATE' AND num_nonnulls(NEW.target_account_id, NEW.target_org_unit_id) <> 1 THEN
      RAISE EXCEPTION 'wf.approval_action: an escalation names the unit or the person it goes up to' USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
  END IF;
  IF NEW.actor_account_id IS NULL THEN
    RAISE EXCEPTION 'wf.approval_action: an actor is required' USING ERRCODE = 'not_null_violation';
  END IF;

  IF v_type.code = 'WITHDRAW' THEN
    IF NEW.actor_account_id <> v_state.submitted_by_account_id THEN
      RAISE EXCEPTION 'wf.approval_action: only the submitter may withdraw' USING ERRCODE = 'insufficient_privilege';
    END IF;
    NEW.step_seq := NULL;
    RETURN NEW;
  END IF;

  IF NEW.step_seq IS DISTINCT FROM v_state.current_seq THEN
    -- a higher level deciding out of turn (APPROVE only): its approval passes
    -- over the pending lower levels, where the chain allows it
    IF v_type.code <> 'APPROVE' OR NEW.step_seq IS NULL OR NEW.step_seq < v_state.current_seq THEN
      RAISE EXCEPTION 'wf.approval_action: step % is not the current step (%)', NEW.step_seq, v_state.current_seq
        USING ERRCODE = 'check_violation';
    END IF;
    v_refusal := wf.override_refusal(NEW.instance_id, NEW.step_seq);
    IF v_refusal IS NOT NULL THEN
      RAISE EXCEPTION 'wf.approval_action: step % is not the current step (%): %', NEW.step_seq, v_state.current_seq, v_refusal
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  SELECT * INTO v_step FROM wf.approval_step WHERE instance_id = NEW.instance_id AND seq = NEW.step_seq;
  SELECT document_type_id, chain_id INTO v_doc, v_chain FROM wf.approval_instance WHERE id = NEW.instance_id;

  -- who is really deciding: the actor, or the absent approver they stand in for
  v_principal := COALESCE(NEW.on_behalf_of_account_id, NEW.actor_account_id);
  IF NEW.on_behalf_of_account_id IS NOT NULL AND NOT EXISTS (
       SELECT 1 FROM wf.approval_delegation d
       WHERE d.delegator_account_id = NEW.on_behalf_of_account_id AND d.delegate_account_id = NEW.actor_account_id
         AND d.valid @> now() AND (d.document_type_id IS NULL OR d.document_type_id = v_doc)) THEN
    RAISE EXCEPTION 'wf.approval_action: the actor holds no delegation from that approver for this kind of document'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF v_type.code = 'SIGN' AND NOT v_step.is_signature THEN
    RAISE EXCEPTION 'wf.approval_action: this step is a review, approve it instead of signing' USING ERRCODE = 'check_violation';
  END IF;
  IF v_type.code = 'APPROVE' AND v_step.is_signature THEN
    RAISE EXCEPTION 'wf.approval_action: this step needs a signature' USING ERRCODE = 'check_violation';
  END IF;
  IF v_type.code = 'SIGN' AND NEW.file_object_id IS NULL THEN
    RAISE EXCEPTION 'wf.approval_action: a signature needs the signed file' USING ERRCODE = 'check_violation';
  END IF;
  IF v_type.completes_step AND v_step.needs_file AND NEW.file_object_id IS NULL THEN
    RAISE EXCEPTION 'wf.approval_action: this step needs a file with the approval' USING ERRCODE = 'check_violation';
  END IF;

  IF NOT wf.is_eligible(v_principal, NEW.instance_id, NEW.step_seq) THEN
    SELECT code INTO v_perm FROM authz.v_permission_code WHERE permission_id = v_step.permission_id;
    RAISE EXCEPTION 'wf.approval_action: the actor does not hold % at this step''s unit', COALESCE(v_perm, 'the approver''s place')
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  IF NEW.actor_account_id = v_state.submitted_by_account_id OR v_principal = v_state.submitted_by_account_id THEN
    RAISE EXCEPTION 'wf.approval_action: the submitter cannot act on their own submission' USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF v_type.returns_to_step THEN
    IF NOT v_step.allows_return_to THEN
      RAISE EXCEPTION 'wf.approval_action: this step cannot send the round back to an earlier level' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.return_to_seq IS NULL OR NEW.return_to_seq >= NEW.step_seq THEN
      RAISE EXCEPTION 'wf.approval_action: RETURN_TO names an earlier step of the round' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.return_to_seq IS NOT NULL THEN
    RAISE EXCEPTION 'wf.approval_action: return_to_seq belongs to RETURN_TO only' USING ERRCODE = 'check_violation';
  END IF;

  IF v_type.reassigns THEN
    IF NOT v_step.allows_forward THEN
      RAISE EXCEPTION 'wf.approval_action: this step cannot be forwarded or delegated' USING ERRCODE = 'check_violation';
    END IF;
    IF NEW.target_account_id IS NULL OR NEW.target_account_id IN (NEW.actor_account_id, v_state.submitted_by_account_id) THEN
      RAISE EXCEPTION 'wf.approval_action: forward to someone else who is not the submitter' USING ERRCODE = 'check_violation';
    END IF;
    IF v_step.permission_id IS NOT NULL THEN
      SELECT code INTO v_perm FROM authz.v_permission_code WHERE permission_id = v_step.permission_id;
      IF NOT authz.has_permission(NEW.target_account_id, v_perm, wf.step_anchor(NEW.instance_id, NEW.step_seq)) THEN
        RAISE EXCEPTION 'wf.approval_action: the person it is forwarded to does not hold % there', v_perm USING ERRCODE = 'insufficient_privilege';
      END IF;
    ELSIF NOT EXISTS (SELECT 1 FROM iam.user_account a JOIN ref.account_status s ON s.id = a.account_status_id AND s.can_login WHERE a.id = NEW.target_account_id) THEN
      RAISE EXCEPTION 'wf.approval_action: the person it is forwarded to has no active account' USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM wf.approval_step_assignee sa WHERE sa.instance_id = NEW.instance_id AND sa.seq = NEW.step_seq
               AND sa.account_id = NEW.target_account_id) THEN
      RAISE EXCEPTION 'wf.approval_action: that person is (or was) already an approver of this step' USING ERRCODE = 'unique_violation';
    END IF;
  ELSIF NEW.target_account_id IS NOT NULL OR NEW.target_org_unit_id IS NOT NULL THEN
    RAISE EXCEPTION 'wf.approval_action: a target belongs to FORWARD / DELEGATE / ESCALATE only' USING ERRCODE = 'check_violation';
  END IF;

  IF v_type.completes_step THEN
    IF EXISTS (SELECT 1 FROM wf.approval_chain_stage_check c
               WHERE c.chain_id = v_chain AND c.seq = NEW.step_seq AND c.is_mandatory
                 AND NOT EXISTS (SELECT 1 FROM wf.approval_step_check k WHERE k.instance_id = NEW.instance_id AND k.seq = c.seq
                                 AND k.check_no = c.check_no AND k.checked_by_account_id IN (NEW.actor_account_id, v_principal))) THEN
      RAISE EXCEPTION 'wf.approval_action: tick every mandatory checklist item of this step first' USING ERRCODE = 'check_violation';
    END IF;
    IF EXISTS (SELECT 1 FROM wf.v_effective_action e
               WHERE e.instance_id = NEW.instance_id AND e.step_seq <> NEW.step_seq
                 AND v_principal IN (e.actor_account_id, e.on_behalf_of_account_id)) THEN
      RAISE EXCEPTION 'wf.approval_action: one person may complete only one step of a round' USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF EXISTS (SELECT 1 FROM wf.v_effective_action e
               WHERE e.instance_id = NEW.instance_id AND e.step_seq = NEW.step_seq
                 AND v_principal = COALESCE(e.on_behalf_of_account_id, e.actor_account_id)) THEN
      RAISE EXCEPTION 'wf.approval_action: this person has already approved this step' USING ERRCODE = 'unique_violation';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_action_validate BEFORE INSERT ON wf.approval_action
  FOR EACH ROW EXECUTE FUNCTION wf.action_validate();

-- What an action sets in motion inside the engine: a forward / delegation /
-- personal escalation hands the step to the named person (the one who handed
-- it on — or, on escalation, everyone before — is released), and the outbox
-- gets the notices.
CREATE OR REPLACE FUNCTION wf.action_effects()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_type record; v_state record;
BEGIN
  SELECT * INTO v_type FROM ref.wf_action_type WHERE id = NEW.wf_action_type_id;
  IF NEW.target_account_id IS NOT NULL THEN
    IF v_type.code = 'ESCALATE' THEN
      UPDATE wf.approval_step_assignee SET released_by_action_id = NEW.id
      WHERE instance_id = NEW.instance_id AND seq = NEW.step_seq AND released_by_action_id IS NULL;
    ELSE
      UPDATE wf.approval_step_assignee SET released_by_action_id = NEW.id
      WHERE instance_id = NEW.instance_id AND seq = NEW.step_seq AND released_by_action_id IS NULL
        AND account_id = COALESCE(NEW.on_behalf_of_account_id, NEW.actor_account_id);
    END IF;
    INSERT INTO wf.approval_step_assignee (instance_id, seq, account_id, added_by_action_id)
    VALUES (NEW.instance_id, NEW.step_seq, NEW.target_account_id, NEW.id);
    INSERT INTO wf.approval_notice (instance_id, step_seq, wf_notice_kind_id, account_id)
    VALUES (NEW.instance_id, NEW.step_seq, ref.id_of('wf_notice_kind', CASE WHEN v_type.code = 'ESCALATE' THEN 'ESCALATED' ELSE 'FORWARDED' END), NEW.target_account_id)
    ON CONFLICT DO NOTHING;
    RETURN NULL;
  END IF;
  SELECT * INTO v_state FROM wf.v_instance_state WHERE instance_id = NEW.instance_id;
  IF v_type.completes_step THEN       -- the levels a higher level's approval has just passed over are told
    PERFORM wf.notify_step(NEW.instance_id, s.seq, 'SUPERSEDED')
    FROM wf.v_step_state s WHERE s.instance_id = NEW.instance_id AND s.seq < NEW.step_seq AND s.superseded;
  END IF;
  IF v_state.status IN ('RETURNED', 'REJECTED', 'APPROVED', 'SIGNED') THEN
    INSERT INTO wf.approval_notice (instance_id, step_seq, wf_notice_kind_id, account_id)
    VALUES (NEW.instance_id, NULL, ref.id_of('wf_notice_kind', CASE v_state.status WHEN 'RETURNED' THEN 'RETURNED' WHEN 'REJECTED' THEN 'REJECTED' ELSE 'APPROVED' END),
            v_state.submitted_by_account_id)
    ON CONFLICT DO NOTHING;
  ELSIF v_state.current_seq IS NOT NULL AND (v_type.completes_step OR v_type.returns_to_step OR v_type.code = 'ESCALATE') THEN
    PERFORM wf.notify_step(NEW.instance_id, v_state.current_seq, CASE WHEN v_type.code = 'ESCALATE' THEN 'ESCALATED' ELSE 'STEP_PENDING' END);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_action_effects AFTER INSERT ON wf.approval_action
  FOR EACH ROW EXECUTE FUNCTION wf.action_effects();

-- A notice that a step is waiting: one per assignee, or one for the pool.
CREATE OR REPLACE FUNCTION wf.notify_step(p_instance uuid, p_seq smallint, p_kind text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM wf.approval_step_assignee WHERE instance_id = p_instance AND seq = p_seq AND released_by_action_id IS NULL) THEN
    INSERT INTO wf.approval_notice (instance_id, step_seq, wf_notice_kind_id, account_id)
    SELECT p_instance, p_seq, ref.id_of('wf_notice_kind', p_kind), sa.account_id
    FROM wf.approval_step_assignee sa WHERE sa.instance_id = p_instance AND sa.seq = p_seq AND sa.released_by_action_id IS NULL
    ON CONFLICT DO NOTHING;
  ELSE
    INSERT INTO wf.approval_notice (instance_id, step_seq, wf_notice_kind_id) VALUES (p_instance, p_seq, ref.id_of('wf_notice_kind', p_kind))
    ON CONFLICT DO NOTHING;
  END IF;
END $$;

-- ------------------------------------------------------------- comments --
-- A reviewer's remark on the round — general, or on one table / row / column
-- (target_table = 'schema.table'), with an optional suggested value. Written
-- by someone who may act on the current step; accepted or rejected by the
-- submitter. The remark itself is never edited.
CREATE TABLE wf.approval_comment (
  id                      uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  instance_id             uuid NOT NULL REFERENCES wf.approval_instance(id),
  step_seq                smallint NOT NULL,
  author_account_id       uuid NOT NULL REFERENCES iam.user_account(id),
  target_table            text,
  target_row_id           uuid,
  target_column           text,
  body                    text NOT NULL CHECK (btrim(body) <> ''),
  suggested_value         text,
  wf_comment_status_id    smallint NOT NULL REFERENCES ref.wf_comment_status(id),
  resolved_by_account_id  uuid REFERENCES iam.user_account(id),
  resolved_at             timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (instance_id, step_seq) REFERENCES wf.approval_step(instance_id, seq),
  CHECK (target_row_id IS NULL OR target_table IS NOT NULL),
  CHECK (target_column IS NULL OR target_table IS NOT NULL),
  CHECK (suggested_value IS NULL OR target_column IS NOT NULL),
  CHECK ((resolved_at IS NULL) = (resolved_by_account_id IS NULL))
);
CREATE INDEX comment_instance_idx ON wf.approval_comment(instance_id);

CREATE OR REPLACE FUNCTION wf.comment_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_resolved boolean; v_submitter uuid;
BEGIN
  SELECT is_resolved INTO v_resolved FROM ref.wf_comment_status WHERE id = NEW.wf_comment_status_id;
  SELECT submitted_by_account_id INTO v_submitter FROM wf.approval_instance WHERE id = NEW.instance_id;
  IF TG_OP = 'INSERT' THEN
    IF NEW.target_table IS NOT NULL AND NOT EXISTS (
         SELECT 1 FROM information_schema.columns
         WHERE table_schema || '.' || table_name = NEW.target_table
           AND (NEW.target_column IS NULL OR column_name = NEW.target_column)) THEN
      RAISE EXCEPTION 'wf.approval_comment: % % does not exist', NEW.target_table, COALESCE(NEW.target_column, '')
        USING ERRCODE = 'foreign_key_violation';
    END IF;
    IF v_resolved OR NEW.resolved_at IS NOT NULL THEN
      RAISE EXCEPTION 'wf.approval_comment: a new comment starts unresolved' USING ERRCODE = 'check_violation';
    END IF;
    IF NOT wf.can_act(NEW.author_account_id, NEW.instance_id)
       OR NEW.step_seq IS DISTINCT FROM (SELECT current_seq FROM wf.v_instance_state WHERE instance_id = NEW.instance_id) THEN
      RAISE EXCEPTION 'wf.approval_comment: only the reviewer of the current step may comment' USING ERRCODE = 'insufficient_privilege';
    END IF;
  ELSE
    IF (to_jsonb(NEW) - 'wf_comment_status_id' - 'resolved_by_account_id' - 'resolved_at')
       <> (to_jsonb(OLD) - 'wf_comment_status_id' - 'resolved_by_account_id' - 'resolved_at') THEN
      RAISE EXCEPTION 'wf.approval_comment: a comment is never edited, only resolved' USING ERRCODE = 'check_violation';
    END IF;
    IF v_resolved <> (NEW.resolved_at IS NOT NULL) THEN
      RAISE EXCEPTION 'wf.approval_comment: a resolved status needs who resolved it and when' USING ERRCODE = 'check_violation';
    END IF;
    IF v_resolved AND NEW.resolved_by_account_id <> v_submitter THEN
      RAISE EXCEPTION 'wf.approval_comment: only the submitter resolves a comment' USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_comment_validate BEFORE INSERT OR UPDATE ON wf.approval_comment
  FOR EACH ROW EXECUTE FUNCTION wf.comment_validate();

-- ################################################ user 1: CURRICULUM (SOE) ##
-- The Statement of Examination = a curriculum version sent through the
-- CURRICULUM chain. Each round is linked here; the curriculum's status is
-- derived from its latest round (academic.v_curriculum_status [09]).
CREATE TABLE academic.curriculum_approval (
  instance_id    uuid PRIMARY KEY REFERENCES wf.approval_instance(id),
  curriculum_id  uuid NOT NULL REFERENCES academic.curriculum(id)
);
CREATE INDEX curriculum_approval_curriculum_idx ON academic.curriculum_approval(curriculum_id);

CREATE OR REPLACE FUNCTION academic.curriculum_approval_validate()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM wf.approval_instance i
                 JOIN wf.approval_document_type dt ON dt.id = i.document_type_id AND dt.code = 'CURRICULUM'
                 JOIN academic.curriculum c ON c.id = NEW.curriculum_id
                 JOIN academic.program p ON p.id = c.program_id
                 WHERE i.id = NEW.instance_id AND i.owner_org_unit_id = p.offering_org_unit_id) THEN
    RAISE EXCEPTION 'curriculum_approval: the round is not a CURRICULUM round owned by the programme''s department'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_curriculum_approval_validate BEFORE INSERT OR UPDATE ON academic.curriculum_approval
  FOR EACH ROW EXECUTE FUNCTION academic.curriculum_approval_validate();

-- FREEZE. Once a curriculum version is APPROVED or SIGNED nothing in it may
-- change (a change = a new curriculum version). While IN_REVIEW, only an
-- account that can act on the current step may edit (reviewer in-place edit,
-- identified by SET LOCAL app.account_id and captured by the audit trail).
-- DRAFT / RETURNED / WITHDRAWN: editable. Retiring a version (is_active) is
-- always allowed.
CREATE OR REPLACE FUNCTION academic.assert_curriculum_editable(p_curriculum uuid, p_what text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_state record; v_account uuid;
BEGIN
  IF p_curriculum IS NULL THEN RETURN; END IF;
  SELECT status, instance_id INTO v_state FROM academic.v_curriculum_status WHERE curriculum_id = p_curriculum;
  IF v_state.status IN ('APPROVED', 'SIGNED') THEN
    RAISE EXCEPTION '%: the curriculum version is % and frozen — create a new curriculum version', p_what, v_state.status
      USING ERRCODE = 'insufficient_privilege';
  ELSIF v_state.status = 'IN_REVIEW' THEN
    v_account := NULLIF(current_setting('app.account_id', true), '')::uuid;
    IF v_account IS NULL OR NOT wf.can_act(v_account, v_state.instance_id) THEN
      RAISE EXCEPTION '%: the curriculum is under review — only the reviewer of the current stage may edit it', p_what
        USING ERRCODE = 'insufficient_privilege';
    END IF;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION academic.guard_curriculum_edit()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_row jsonb := to_jsonb(CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END);
        v_old jsonb := CASE WHEN TG_OP = 'UPDATE' THEN to_jsonb(OLD) END;
        v_id uuid;
BEGIN
  IF TG_TABLE_NAME = 'curriculum' AND TG_OP = 'UPDATE'
     AND (to_jsonb(NEW) - 'is_active' - 'updated_at') = (to_jsonb(OLD) - 'is_active' - 'updated_at') THEN
    RETURN NEW;
  END IF;
  v_id := CASE TG_TABLE_NAME
            WHEN 'curriculum' THEN (v_row ->> 'id')::uuid
            WHEN 'elective_basket_course' THEN (SELECT curriculum_id FROM academic.elective_basket WHERE id = (v_row ->> 'elective_basket_id')::uuid)
            WHEN 'award_rule_course' THEN (SELECT curriculum_id FROM academic.award_rule WHERE id = (v_row ->> 'award_rule_id')::uuid)
            ELSE (v_row ->> 'curriculum_id')::uuid END;
  PERFORM academic.assert_curriculum_editable(v_id, TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME);
  IF v_old ? 'curriculum_id' AND (v_old ->> 'curriculum_id') IS DISTINCT FROM (v_row ->> 'curriculum_id') THEN
    PERFORM academic.assert_curriculum_editable((v_old ->> 'curriculum_id')::uuid, TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME);
  END IF;
  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END $$;

